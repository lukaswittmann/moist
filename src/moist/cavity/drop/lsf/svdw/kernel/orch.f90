   pure module subroutine svdw_normalized_eval(f0, f1_r, f1_rA, f2_r_rA, norm0, norm1_rA)
      !> Level-set value
      real(wp), intent(in) :: f0
      !> Spatial gradient
      real(wp), intent(in) :: f1_r(3)
      !> Nuclear gradient of this atom
      real(wp), intent(in) :: f1_rA(3)
      !> Mixed spatial/nuclear derivative of this atom
      real(wp), intent(in) :: f2_r_rA(3, 3)
      !> Normalized level-set value
      real(wp), intent(out) :: norm0
      !> Nuclear gradient of the normalized level-set value
      real(wp), intent(out) :: norm1_rA(3)

      !> Smallest gradient norm treated as non-degenerate
      real(wp), parameter :: eps = 1.0e-14_wp
      !> Gradient norm and its reciprocal powers
      real(wp) :: g, inv_g, inv_g3
      !> Contraction of the spatial gradient with the mixed derivative
      real(wp) :: gd(3)
      !> Loop index
      integer :: j

      g = sqrt(f1_r(1)*f1_r(1) + f1_r(2)*f1_r(2) + f1_r(3)*f1_r(3))
      if (g < eps) then
         norm0 = 0.0_wp
         norm1_rA = 0.0_wp
         return
      end if

      inv_g = 1.0_wp/g
      inv_g3 = inv_g*inv_g*inv_g
      norm0 = f0*inv_g

      gd = 0.0_wp
      do j = 1, ndim
         gd = gd + f1_r(j)*f2_r_rA(j, :)
      end do
      norm1_rA = f1_rA*inv_g - f0*gd*inv_g3
   end subroutine svdw_normalized_eval

