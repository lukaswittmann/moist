                            hvp_f3_rr_rA(:, :, :, ia))
      end do
   end subroutine svdw_lsf_hvp

   pure module subroutine svdw_lsf_radius_hvp(d, radii, v, vrad, blend_k, s_1, s_2, s_3, &
                                       max_deriv, hvp_f1_rad, hvp_f2_r_rad, &
                                       hvp_f3_rr_rad)
      !> Displacements r - R_A
      real(wp), intent(in) :: d(:, :)
      !> Radii of the active atoms
      real(wp), intent(in) :: radii(:)
      !> Displacement directions
      real(wp), intent(in) :: v(:, :)
      !> Radius directions
      real(wp), intent(in) :: vrad(:)
      !> Blending sharpness k
      real(wp), intent(in) :: blend_k
      !> One-body weight
      real(wp), intent(in) :: s_1
      !> Two-body weight
      real(wp), intent(in) :: s_2
      !> Three-body weight
      real(wp), intent(in) :: s_3
      !> Highest spatial-derivative order
      integer, intent(in) :: max_deriv
      !> Contracted radius Hessian row
      real(wp), intent(out) :: hvp_f1_rad(:)
      !> Contracted mixed third derivative
      real(wp), intent(out) :: hvp_f2_r_rad(:, :)
      !> Contracted mixed fourth derivative
      real(wp), intent(out) :: hvp_f3_rr_rad(:, :, :)

      !> Accumulated power-sum tensors
      real(wp) :: ps0(nkind), ps1(3, nkind), ps2(3, 3, nkind)
      real(wp) :: ps3(3, 3, 3, nkind), ps4(3, 3, 3, 3, nkind)
      !> Accumulated contracted tensors
      real(wp) :: ws0(nkind), ws1(3, nkind), ws2(3, 3, nkind), ws3(3, 3, 3, nkind)
      !> Per-atom radius tensors and the radius derivative of the joint contraction
      real(wp) :: atd0(nkind), atd1(3, nkind), atd2(3, 3, nkind), atd3(3, 3, 3, nkind)
      real(wp) :: awd0(nkind), awd1(3, nkind), awd2(3, 3, nkind)
      !> Geometry of one atom
      real(wp) :: x, ix, u
      !> Active-atom index
      integer :: ia

      call svdw_powersums(d, radii, blend_k, s_2 /= 0.0_wp, max_deriv, &
                          ps0, ps1, ps2, ps3, ps4)
      call svdw_powersums_tangent(d, radii, v, blend_k, max_deriv, ws0, ws1, ws2, &
                                  ws3, vrad)
      do ia = 1, size(radii)
         call svdw_atom_geometry(d(:, ia), radii(ia), blend_k, x, ix, u)
         call svdw_atom_rad_eval(d(:, ia), radii(ia), blend_k, max_deriv, &
                                 atd0, atd1, atd2, atd3, x, ix, u, ref_fade_start, &
                                 ref_fade_width)
         call svdw_atom_tangent_rad_eval(d(:, ia), radii(ia), blend_k, v(:, ia), &
                                         vrad(ia), max_deriv, awd0, awd1, awd2, x, ix, &
                                         u, ref_fade_start, ref_fade_width)
         call svdw_radius_hvp_eval(blend_k, s_1, s_2, s_3, ps0, ps1, ps2, &
                                   ws0, ws1, ws2, atd0, atd1, atd2, awd0, awd1, awd2, &
                                   max_deriv, hvp_f1_rad(ia), &
                                   hvp_f2_r_rad(:, ia), hvp_f3_rr_rad(:, :, ia))
      end do
   end subroutine svdw_lsf_radius_hvp

   pure module subroutine svdw_lsf_normalized(d, radii, blend_k, s_1, s_2, s_3, &
                                       norm0, norm1_rA)
      !> Displacements r - R_A
      real(wp), intent(in) :: d(:, :)
      !> Radii of the active atoms
      real(wp), intent(in) :: radii(:)
      !> Blending sharpness k
      real(wp), intent(in) :: blend_k
      !> One-body weight
      real(wp), intent(in) :: s_1
      !> Two-body weight
      real(wp), intent(in) :: s_2
      !> Three-body weight
      real(wp), intent(in) :: s_3
      !> Normalized level-set value
      real(wp), intent(out) :: norm0
      !> Nuclear gradient of the normalized level-set value
      real(wp), intent(out) :: norm1_rA(:, :)

      !> Spatial results
      real(wp) :: f0, f1_r(3), f2_rr(3, 3), f3_rrr(3, 3, 3), f4_rrrr(3, 3, 3, 3)
      !> One-nuclear-index results.  Only orders 0 and 1 are used, but the two
      !> higher-order buffers must still be full size: `svdw_lsf_nuclear` slices
      !> them per atom on every call, whatever `max_deriv` says.  A caller that
      !> minds the stack should inline this driver's two calls instead.
      real(wp) :: f1_rA(3, size(radii)), f2_r_rA(3, 3, size(radii))
      real(wp) :: f3_rr_rA(3, 3, 3, size(radii)), f4_rrr_rA(3, 3, 3, 3, size(radii))
      !> Active-atom index
      integer :: ia

      call svdw_lsf_spatial(d, radii, blend_k, s_1, s_2, s_3, 1, &
                            f0, f1_r, f2_rr, f3_rrr, f4_rrrr)
      call svdw_lsf_nuclear(d, radii, blend_k, s_1, s_2, s_3, 1, &
                            f1_rA, f2_r_rA, f3_rr_rA, f4_rrr_rA)
      do ia = 1, size(radii)
         call svdw_normalized_eval(f0, f1_r, f1_rA(:, ia), f2_r_rA(:, :, ia), &
                                   norm0, norm1_rA(:, ia))
      end do
   end subroutine svdw_lsf_normalized

