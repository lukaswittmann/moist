                                   ca0(:, ia), ca1(:, :, ia), ca2(:, :, :, ia), &
                                   ca3(:, :, :, :, ia), &
                                   ca0(:, ib), ca1(:, :, ib), ca2(:, :, :, ib), &
                                   ca3(:, :, :, :, ib), max_deriv, b2, b3, b4)
            end if
            do t = 1, ndim
