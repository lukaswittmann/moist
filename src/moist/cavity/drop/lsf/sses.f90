   !> Prepare the spatial Taylor jet
   !>
   !> @param[in,out] self Level set instance
   !> @param[in] point Evaluation point in Bohr
   !> @param[out] error Invalid parameters, geometry or numerical accessibility
   subroutine prepare(self, point, error)
      !> Level set instance
      class(moist_cavity_drop_lsf_sses_type), intent(inout) :: self
      !> Evaluation point in Bohr
      real(wp), intent(in) :: point(3)
      !> Invalid parameters, geometry or numerical accessibility
      type(error_type), allocatable, intent(out) :: error
      logical :: valid

      self%prepared_deriv = -1
      if (self%ncenters <= 0 .or. .not. allocated(self%radii)) then
         call fatal_error(error, "SSES: update with nonempty geometry before prepare")
         return
      end if
      if (.not. all(ieee_is_finite([self%param%probe_radius, self%param%smoothing_length, self%param%scale])) &
          .or. self%param%probe_radius < 0.0_wp .or. self%param%smoothing_length <= 0.0_wp .or. self%param%scale <= 0.0_wp) then
         call fatal_error(error, "SSES: require finite probe >= 0, smoothing length > 0 and scale > 0")
         return
      end if
      if (.not. all(ieee_is_finite(self%radii)) .or. any(self%radii <= 0.0_wp) &
          .or. .not. all(ieee_is_finite(point)) .or. .not. all(ieee_is_finite(self%mol%xyz))) then
         call fatal_error(error, "SSES: require finite geometry and positive radii")
         return
      end if
      self%point = point
      if (.not. sses_cache_matches(self%cache, self%mol%xyz, self%radii, &
                                   self%param%probe_radius, self%param%smoothing_length, &
                                   self%param%temperature())) then
         call sses_cache_build(self%cache, self%mol%xyz, self%radii, &
                               self%param%probe_radius, self%param%smoothing_length, &
                               self%param%temperature(), valid)
         if (.not. valid) then
            call fatal_error(error, "SSES: invalid moment geometry")
            return
         end if
      end if
      call sses_cached_evaluate(self%cache, point, self%max_deriv, self%spatial, valid)
      if (.not. valid .or. .not. all(ieee_is_finite(self%spatial%c))) then
         call fatal_error(error, "SSES: moment optimizer failed to converge")
         return
      end if
      self%spatial%c = self%param%scale*self%spatial%c
      self%prepared_deriv = self%max_deriv
   end subroutine prepare

   !> Prepare with all atoms retained by the global smooth weights
