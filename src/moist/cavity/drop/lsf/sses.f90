   !> Add the normalized optimized Boltzmann shares
   !>
   !> @param[in,out] self Level set instance
   !> @param[in] scale Point weight
   !> @param[in,out] acc Per-atom accumulator in user order
   subroutine atom_partition(self, scale, acc)
      !> Level set instance
      class(moist_cavity_drop_lsf_sses_type), intent(inout) :: self
      !> Point weight
      real(wp), intent(in) :: scale
      !> Per-atom accumulator in user order
      real(wp), intent(inout) :: acc(:)
      type(sses_jet_type) :: temporary
      real(wp) :: weights(self%ncenters)
      logical :: valid
      integer :: n

      call self%require_deriv(0, "atom_partition")
      n = self%ncenters
      if (n == 1) then
         acc(1) = acc(1) + scale
         return
      end if
      call sses_cached_evaluate(self%cache, self%point, 0, temporary, valid)
      if (.not. valid) error stop "SSES: atomic partition evaluation failed"
      weights = self%cache%state%w
      acc(1:n) = acc(1:n) + scale*weights/sum(weights)
   end subroutine atom_partition

   !> Field and envelope atom-derivative jets at the prepared point
   !>
   !> Variables 1-3 are spatial when spatial_order > 0; variable 5 carries one
   !> optional direction: a center axis or radius of atom b, or a joint nuclear
   !> and radius direction. Atom derivatives are not jet variables: gc(k, a) and
   !> gr(a) are jets of dF/dc(k, a) and dF/dr(a), so one O(N) Taylor solve
   !> serves every atom.
   !>
   !> @param[in] self Prepared level set
   !> @param[in] spatial_order Highest spatial derivative order
   !> @param[out] field Field jet
   !> @param[out] gc Atom-center derivative jets
   !> @param[out] gr Radius derivative jets
   !> @param[in] b Direction atom
   !> @param[in] axis_b Direction axis of atom b, zero for its radius
   !> @param[in] v Nuclear direction in user order
   !> @param[in] vrad Radius direction in user order
   subroutine derivative_jets(self, spatial_order, field, gc, gr, b, axis_b, v, vrad)
      !> Prepared level set
      class(moist_cavity_drop_lsf_sses_type), intent(in) :: self
      !> Highest spatial derivative order
      integer, intent(in) :: spatial_order
      !> Field jet
      type(sses_jet_type), intent(out) :: field
      !> Atom-center derivative jets
      type(sses_jet_type), intent(out), optional :: gc(:, :)
      !> Radius derivative jets
      type(sses_jet_type), intent(out), optional :: gr(:)
      !> Direction atom
      integer, intent(in), optional :: b
      !> Direction axis of atom b, zero for its radius
      integer, intent(in), optional :: axis_b
      !> Nuclear direction in user order
      real(wp), intent(in), optional :: v(:, :)
      !> Radius direction in user order
      real(wp), intent(in), optional :: vrad(:)
      real(wp) :: ps(3, 5), cs(3, self%ncenters, 5), rs(self%ncenters, 5), y0(3)
      logical :: valid
      integer :: k, a, order

      ps = 0.0_wp
      cs = 0.0_wp
      rs = 0.0_wp
      order = spatial_order
      if (spatial_order > 0) then
         do k = 1, 3
            ps(k, k) = 1.0_wp
         end do
      end if
      if (present(b) .or. present(v) .or. present(vrad)) order = order + 1
      if (present(b) .and. present(axis_b)) then
         if (axis_b == 0) then
            rs(b, 5) = 1.0_wp
         else
            cs(axis_b, b, 5) = 1.0_wp
         end if
      end if
      if (present(v)) cs(:, :, 5) = v(:, 1:self%ncenters)
      if (present(vrad)) rs(:, 5) = vrad(1:self%ncenters)
      if (.not. sses_cache_moment(self%cache, self%point, y0)) then
         call sses_moment(self%point, self%mol%xyz, self%radii, self%param%probe_radius, &
                          self%param%smoothing_length, self%param%temperature(), y0, valid)
         if (.not. valid) error stop "SSES: moment optimizer failed to converge"
      end if
      call sses_jets(self%point, self%mol%xyz, self%radii, self%param%probe_radius, &
                     self%param%smoothing_length, self%param%temperature(), ps, cs, rs, order, y0, &
                     field, valid, gc, gr)
      if (.not. valid) error stop "SSES: analytic derivative evaluation failed"
      field%c = self%param%scale*field%c
      if (present(gc)) then
         do a = 1, self%ncenters
            do k = 1, 3
               gc(k, a)%c = self%param%scale*gc(k, a)%c
            end do
         end do
      end if
      if (present(gr)) then
         do a = 1, self%ncenters
            gr(a)%c = self%param%scale*gr(a)%c
         end do
      end if
   end subroutine derivative_jets

   !> Envelope atom derivatives in closed form from the converged point state
   !>
   !> Available for several atoms when the prepared point owns the native cache
   !> with its moment sensitivity; otherwise the caller falls back to jets.
   !>
   !> @param[in] self Prepared level set
   !> @param[in] order Highest spatial derivative order, at most two
   !> @param[out] gc0 dF/dR(s, a)
   !> @param[out] gc1 d2F/dr(i) dR(s, a)
   !> @param[out] gc2 d3F/dr(i) dr(j) dR(s, a)
   !> @param[out] gr0 dF/drad(a)
   !> @param[out] gr1 d2F/dr(i) drad(a)
   !> @param[out] gr2 d3F/dr(i) dr(j) drad(a)
   function native_atoms(self, order, gc0, gc1, gc2, gr0, gr1, gr2) result(done)
      !> Prepared level set
      class(moist_cavity_drop_lsf_sses_type), intent(in) :: self
      !> Highest spatial derivative order, at most two
      integer, intent(in) :: order
      !> dF/dR(s, a)
      real(wp), intent(out), optional :: gc0(:, :)
      !> d2F/dr(i) dR(s, a)
      real(wp), intent(out), optional :: gc1(:, :, :)
      !> d3F/dr(i) dr(j) dR(s, a)
      real(wp), intent(out), optional :: gc2(:, :, :, :)
      !> dF/drad(a)
      real(wp), intent(out), optional :: gr0(:)
      !> d2F/dr(i) drad(a)
      real(wp), intent(out), optional :: gr1(:, :)
      !> d3F/dr(i) dr(j) drad(a)
      real(wp), intent(out), optional :: gr2(:, :, :)
      !> Closed-form derivatives were written
      logical :: done
      real(wp) :: y0(3), scale
      integer :: n

      done = .false.
      n = self%ncenters
      if (n < 2) return
      if (.not. sses_cache_moment(self%cache, self%point, y0)) return
      call moment_atom_native(self%cache%state, order, done, gc0, gc1, gc2, gr0, gr1, gr2)
      if (.not. done) return
      scale = self%param%scale
      if (present(gc0)) gc0(:, 1:n) = scale*gc0(:, 1:n)
      if (present(gc1)) gc1(:, :, 1:n) = scale*gc1(:, :, 1:n)
      if (present(gc2)) gc2(:, :, :, 1:n) = scale*gc2(:, :, :, 1:n)
      if (present(gr0)) gr0(1:n) = scale*gr0(1:n)
      if (present(gr1)) gr1(:, 1:n) = scale*gr1(:, 1:n)
      if (present(gr2)) gr2(:, :, 1:n) = scale*gr2(:, :, 1:n)
   end function native_atoms

   !> Analytic SSES f0 accessor
   !>
   !> @param[in] self Prepared level set
   !> @param[out] val val
   subroutine f0(self, val)
      !> Accessor argument
      class(moist_cavity_drop_lsf_sses_type), intent(in) :: self
      !> Accessor argument
      real(wp), intent(out) :: val

      call self%require_deriv(0, "f0")
      val = self%spatial%c(0)
   end subroutine f0

   !> Analytic SSES f012_r accessor
   !>
   !> @param[in] self Prepared level set
   !> @param[out] lsf0 lsf0
   !> @param[out] lsf1_r lsf1_r
   !> @param[out] lsf2_rr lsf2_rr
   subroutine f012_r(self, lsf0, lsf1_r, lsf2_rr)
      !> Accessor argument
      class(moist_cavity_drop_lsf_sses_type), intent(in) :: self
      !> Accessor argument
      real(wp), intent(out), optional :: lsf0
      !> Accessor argument
      real(wp), intent(out), optional :: lsf1_r(:)
      !> Accessor argument
      real(wp), intent(out), optional :: lsf2_rr(:, :)
      !> Cartesian and atom indices
      integer :: i, j

      call self%require_deriv(0, "f012_r")
      if (present(lsf1_r)) call self%require_deriv(1, "f012_r")
      if (present(lsf2_rr)) call self%require_deriv(2, "f012_r")
      if (present(lsf0)) then
         lsf0 = self%spatial%c(0)
      end if
      if (present(lsf1_r)) then
      do i = 1, 3
         lsf1_r(i) = jet_derivative(self%spatial, [i])
      end do
      end if
      if (present(lsf2_rr)) then
      do j = 1, 3
      do i = 1, 3
         lsf2_rr(i, j) = jet_derivative(self%spatial, [i, j])
      end do
      end do
      end if
   end subroutine f012_r

   !> Analytic SSES f3_rrr accessor
   !>
   !> @param[in] self Prepared level set
   !> @param[out] lsf0 lsf0
   !> @param[out] lsf1_r lsf1_r
   !> @param[out] lsf2_rr lsf2_rr
   !> @param[out] lsf3_rrr lsf3_rrr
   subroutine f3_rrr(self, lsf0, lsf1_r, lsf2_rr, lsf3_rrr)
      !> Accessor argument
      class(moist_cavity_drop_lsf_sses_type), intent(in) :: self
      !> Accessor argument
      real(wp), intent(out), optional :: lsf0
      !> Accessor argument
      real(wp), intent(out), optional :: lsf1_r(:)
      !> Accessor argument
      real(wp), intent(out), optional :: lsf2_rr(:, :)
      !> Accessor argument
      real(wp), intent(out) :: lsf3_rrr(:, :, :)
      !> Cartesian and atom indices
      integer :: i, j, k

      call self%require_deriv(3, "f3_rrr")
      if (present(lsf0)) then
         lsf0 = self%spatial%c(0)
      end if
      if (present(lsf1_r)) then
      do i = 1, 3
         lsf1_r(i) = jet_derivative(self%spatial, [i])
      end do
      end if
      if (present(lsf2_rr)) then
      do j = 1, 3
      do i = 1, 3
         lsf2_rr(i, j) = jet_derivative(self%spatial, [i, j])
      end do
      end do
      end if
      do k = 1, 3
      do j = 1, 3
      do i = 1, 3
         lsf3_rrr(i, j, k) = jet_derivative(self%spatial, [i, j, k])
      end do
      end do
      end do
   end subroutine f3_rrr

   !> Analytic SSES f4_rrrr accessor
   !>
   !> @param[in] self Prepared level set
   !> @param[out] lsf4_rrrr lsf4_rrrr
   subroutine f4_rrrr(self, lsf4_rrrr)
      !> Accessor argument
      class(moist_cavity_drop_lsf_sses_type), intent(in) :: self
      !> Accessor argument
      real(wp), intent(out) :: lsf4_rrrr(:, :, :, :)
      !> Cartesian and atom indices
      integer :: i, j, k, l

      call self%require_deriv(4, "f4_rrrr")
      do l = 1, 3
      do k = 1, 3
      do j = 1, 3
      do i = 1, 3
         lsf4_rrrr(i, j, k, l) = jet_derivative(self%spatial, [i, j, k, l])
      end do
      end do
      end do
      end do
   end subroutine f4_rrrr

   !> Center derivatives of the field, gradient and Hessian
   !>
   !> @param[in] self Prepared level set
   !> @param[out] lsf1_rA dF/dR(s, a)
   !> @param[out] lsf2_r_rA d2F/dr(i) dR(s, a)
   !> @param[out] lsf3_rr_rA d3F/dr(i) dr(j) dR(s, a)
   subroutine f3_rr_rA(self, lsf1_rA, lsf2_r_rA, lsf3_rr_rA)
