   end subroutine hvp_f3_rr_rA

   !> Joint nuclear-radius direction derivative of radius blocks, spatial order 2
   !>
   !> @param[in] self Prepared level set
   !> @param[in] v Nuclear direction in user order
   !> @param[in] vrad Radius direction in user order
   !> @param[out] res Directional radius derivatives
   subroutine hvp_f3_rr_rad(self, v, vrad, res)
      !> Prepared level set
      class(moist_cavity_drop_lsf_sses_type), intent(in) :: self
      !> Nuclear direction in user order
      real(wp), intent(in) :: v(:, :)
      !> Radius direction in user order
      real(wp), intent(in) :: vrad(:)
      !> Directional radius derivatives
      real(wp), intent(out) :: res(:, :, :)
      type(sses_jet_type) :: field
      type(sses_jet_type), allocatable :: gr(:)
      integer :: i, j, a

      call self%require_deriv(2, "hvp_f3_rr_rad")
      allocate (gr(self%ncenters))
      call derivative_jets(self, 2, field, gr=gr, v=v, vrad=vrad)
      do a = 1, self%ncenters
         do j = 1, 3
         do i = 1, 3
            res(i, j, a) = jet_derivative(gr(a), [i, j, 5])
         end do
         end do
      end do
   end subroutine hvp_f3_rr_rad

   !> Weighted center derivatives of field, gradient and Hessian
   !>
   !> @param[in] self Prepared level set
   !> @param[in] w0 Field weight
   !> @param[in] w1 Gradient weights
   !> @param[in] w2 Hessian weights
   !> @param[out] res Weighted atom derivatives
   subroutine vjp_f1_rA(self, w0, w1, w2, res)
      !> Prepared level set
      class(moist_cavity_drop_lsf_sses_type), intent(in) :: self
      !> Field weight
      real(wp), intent(in) :: w0
      !> Gradient weights
      real(wp), intent(in) :: w1(3)
      !> Hessian weights
      real(wp), intent(in) :: w2(3, 3)
      !> Weighted atom derivatives
      real(wp), intent(out) :: res(:, :)
      real(wp), allocatable :: n0(:, :), n1(:, :, :), n2(:, :, :, :)
      integer :: a, s

      call self%require_deriv(2, "vjp_f1_rA")
      allocate (n0(3, self%ncenters), n1(3, 3, self%ncenters), n2(3, 3, 3, self%ncenters))
      call self%f3_rr_rA(n0, n1, n2)
      do a = 1, self%ncenters
         do s = 1, 3
            res(s, a) = w0*n0(s, a) + sum(w1*n1(:, s, a)) + sum(w2*n2(:, :, s, a))
         end do
      end do
   end subroutine vjp_f1_rA

   !> Weighted radius derivatives of field, gradient and Hessian
   !>
   !> @param[in] self Prepared level set
   !> @param[in] w0 Field weight
   !> @param[in] w1 Gradient weights
   !> @param[in] w2 Hessian weights
   !> @param[out] res Weighted atom derivatives
   subroutine vjp_f1_rad(self, w0, w1, w2, res)
      !> Prepared level set
      class(moist_cavity_drop_lsf_sses_type), intent(in) :: self
      !> Field weight
      real(wp), intent(in) :: w0
      !> Gradient weights
      real(wp), intent(in) :: w1(3)
      !> Hessian weights
      real(wp), intent(in) :: w2(3, 3)
      !> Weighted atom derivatives
      real(wp), intent(out) :: res(:)
      real(wp), allocatable :: n0(:), n1(:, :), n2(:, :, :)
      integer :: a

      call self%require_deriv(2, "vjp_f1_rad")
      allocate (n0(self%ncenters), n1(3, self%ncenters), n2(3, 3, self%ncenters))
      call self%f3_rr_rad(n0, n1, n2)
      do a = 1, self%ncenters
         res(a) = w0*n0(a) + sum(w1*n1(:, a)) + sum(w2*n2(:, :, a))
      end do
   end subroutine vjp_f1_rad

   !> Gradient-normalized field and its center derivatives
   !>
   !> @param[in] self Prepared level set
   !> @param[out] val F/|grad F|
   !> @param[out] deriv_rA d(F/|grad F|)/dR(s, a)
   subroutine normalized_f01_rA(self, val, deriv_rA)
      !> Prepared level set
      class(moist_cavity_drop_lsf_sses_type), intent(in) :: self
      !> F/|grad F|
      real(wp), intent(out) :: val
      !> d(F/|grad F|)/dR(s, a)
      real(wp), intent(out), optional :: deriv_rA(:, :)
      type(sses_jet_type) :: field
      type(sses_jet_type), allocatable :: gc(:, :)
      real(wp), allocatable :: n0(:, :), n1(:, :, :)
      integer :: i, a, s
      !> Normalization intermediates
      real(wp) :: g(3), f, norm

      call self%require_deriv(1, "normalized_f01_rA")
      do i = 1, 3
         g(i) = self%spatial%c(i)
      end do
      f = self%spatial%c(0)
      norm = sqrt(sum(g*g))
      val = 0.0_wp
      if (present(deriv_rA)) deriv_rA(:, 1:self%ncenters) = 0.0_wp
      if (norm <= tiny(0.0_wp)) return
      val = f/norm
      if (.not. present(deriv_rA)) return
      allocate (n0(3, self%ncenters), n1(3, 3, self%ncenters))
      if (.not. native_atoms(self, 1, gc0=n0, gc1=n1)) then
         allocate (gc(3, self%ncenters))
         call derivative_jets(self, 1, field, gc=gc)
         do a = 1, self%ncenters
            do s = 1, 3
               n0(s, a) = gc(s, a)%c(0)
               do i = 1, 3
                  n1(i, s, a) = jet_derivative(gc(s, a), [i])
               end do
            end do
         end do
      end if
      do a = 1, self%ncenters
         do s = 1, 3
            deriv_rA(s, a) = n0(s, a)/norm - f*sum(g*n1(:, s, a))/(norm*norm*norm)
         end do
      end do
   end subroutine normalized_f01_rA

end module moist_cavity_drop_lsf_sses
