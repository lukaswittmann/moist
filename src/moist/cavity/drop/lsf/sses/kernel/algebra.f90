      !> Scalar operand
      real(wp), intent(in) :: a
      !> Taylor jet
      type(sses_jet_type), intent(in) :: b
      !> Function result
      type(sses_jet_type) :: r

      r = (-b) + a
   end function sub_rj

   !> Multiply Taylor jets with generated sparse convolution indices
   !>
   !> @param[in] a First operand
   !> @param[in] b Second operand
   pure recursive function mul_jj(a, b) result(r)
      !> First operand
      type(sses_jet_type), intent(in) :: a
      !> Second operand
      type(sses_jet_type), intent(in) :: b
      !> Function result
      type(sses_jet_type) :: r
      integer :: i, k

      if (a%constant) then
         r = b*a%c(0)
         r%order = max(a%order, b%order)
         return
      else if (b%constant) then
         r = a*b%c(0)
         r%order = max(a%order, b%order)
         return
      end if
      r%order = max(a%order, b%order)
      r%constant = .false.
      do i = 1, size(products, 2)
         k = products(3, i)
         if (k >= counts(r%order)) exit
         if (a%c(products(1, i)) == 0.0_wp) cycle
         if (b%c(products(2, i)) == 0.0_wp) cycle
         r%c(k) = r%c(k) + a%c(products(1, i))*b%c(products(2, i))
      end do
   end function mul_jj

   !> Scale a Taylor jet
   !>
   !> @param[in] a Taylor jet
   !> @param[in] b Scalar factor
   pure recursive function mul_jr(a, b) result(r)
      !> Taylor jet
      type(sses_jet_type), intent(in) :: a
      !> Scalar factor
      real(wp), intent(in) :: b
      !> Function result
      type(sses_jet_type) :: r

      r%order = a%order
      r%constant = a%constant .or. abs(b) <= 0.0_wp
      r%c(0:counts(r%order) - 1) = a%c(0:counts(r%order) - 1)*b
   end function mul_jr

   !> Scale a Taylor jet from the left
   !>
   !> @param[in] a Scalar factor
   !> @param[in] b Taylor jet
   pure recursive function mul_rj(a, b) result(r)
      !> Scalar factor
      real(wp), intent(in) :: a
      !> Taylor jet
      type(sses_jet_type), intent(in) :: b
      !> Function result
      type(sses_jet_type) :: r

      r = b*a
   end function mul_rj

   !> Scalar division of a Taylor jet
   !>
   !> @param[in] a Taylor jet
   !> @param[in] b Nonzero scalar divisor
   pure recursive function div_jr(a, b) result(r)
      !> Taylor jet
      type(sses_jet_type), intent(in) :: a
      !> Nonzero scalar divisor
      real(wp), intent(in) :: b
      !> Function result
      type(sses_jet_type) :: r

      r = a*(1.0_wp/b)
   end function div_jr

   !> Reciprocal Taylor series from the coefficient recurrence of a r = 1
   !>
   !> @param[in] a Taylor jet with nonzero scalar part
   pure recursive function inverse(a) result(r)
      !> Taylor jet with nonzero scalar part
      type(sses_jet_type), intent(in) :: a
      !> Function result
      type(sses_jet_type) :: r
      real(wp) :: scale
      integer :: p, i, k

      scale = 1.0_wp/a%c(0)
      r = jet_constant(scale, a%order)
      if (a%constant) return
      r%constant = .false.
      do p = 1, size(products, 2)
         k = products(3, p)
         if (k >= counts(a%order)) exit
         i = products(1, p)
         if (i == 0) cycle
         if (a%c(i) == 0.0_wp) cycle
         r%c(k) = r%c(k) - scale*a%c(i)*r%c(products(2, p))
      end do
   end function inverse

   !> Divide Taylor jets from the coefficient recurrence of b r = a
   !>
   !> @param[in] a Numerator
   !> @param[in] b Denominator with nonzero scalar part
   pure recursive function div_jj(a, b) result(r)
      !> Numerator
      type(sses_jet_type), intent(in) :: a
      !> Denominator with nonzero scalar part
      type(sses_jet_type), intent(in) :: b
      !> Function result
      type(sses_jet_type) :: r
      real(wp) :: scale
      integer :: p, i, k, n

      if (b%constant) then
         r = a*(1.0_wp/b%c(0))
         r%order = max(a%order, b%order)
         return
      end if
      scale = 1.0_wp/b%c(0)
      r%order = max(a%order, b%order)
      r%constant = .false.
      n = counts(r%order)
      r%c(0:n - 1) = scale*a%c(0:n - 1)
      do p = 1, size(products, 2)
         k = products(3, p)
         if (k >= n) exit
         i = products(1, p)
         if (i == 0) cycle
         if (b%c(i) == 0.0_wp) cycle
         r%c(k) = r%c(k) - scale*b%c(i)*r%c(products(2, p))
      end do
   end function div_jj

   !> Divide a scalar by a Taylor jet
   !>
   !> @param[in] a Scalar numerator
   !> @param[in] b Taylor denominator
   pure recursive function div_rj(a, b) result(r)
      !> Scalar numerator
      real(wp), intent(in) :: a
      !> Taylor denominator
      type(sses_jet_type), intent(in) :: b
      !> Function result
      type(sses_jet_type) :: r

      r = a*inverse(b)
   end function div_rj

   !> Exponential Taylor series from the coefficient recurrence of r' = a' r
   !>
   !> @param[in] a Taylor jet
   pure recursive function exp_j(a) result(r)
      !> Taylor jet
      type(sses_jet_type), intent(in) :: a
      !> Function result
      type(sses_jet_type) :: r
      integer :: p, i, k

      r = jet_constant(exp(a%c(0)), a%order)
      if (a%constant) return
      r%constant = .false.
      do p = 1, size(products, 2)
         k = products(3, p)
         if (k >= counts(a%order)) exit
         i = products(1, p)
         if (leading_share(p) == 0.0_wp) cycle
         if (a%c(i) == 0.0_wp) cycle
         r%c(k) = r%c(k) + leading_share(p)*a%c(i)*r%c(products(2, p))
      end do
   end function exp_j

   !> Logarithmic Taylor series from the coefficient recurrence of a r' = a'
   !>
   !> @param[in] a Taylor jet with positive scalar part
   pure recursive function log_j(a) result(r)
      !> Taylor jet with positive scalar part
      type(sses_jet_type), intent(in) :: a
      !> Function result
      type(sses_jet_type) :: r
      real(wp) :: scale
      integer :: p, i, j, k, n

      r = jet_constant(log(a%c(0)), a%order)
      if (a%constant) return
      r%constant = .false.
      scale = 1.0_wp/a%c(0)
      n = counts(a%order)
      r%c(1:n - 1) = scale*a%c(1:n - 1)
      do p = 1, size(products, 2)
         k = products(3, p)
         if (k >= n) exit
         i = products(1, p)
         j = products(2, p)
         if (i == 0 .or. j == 0) cycle
         if (a%c(i) == 0.0_wp) cycle
         r%c(k) = r%c(k) - (1.0_wp - leading_share(p))*scale*a%c(i)*r%c(j)
      end do
   end function log_j

   !> Real power of a positive Taylor jet from the recurrence of a r' = b a' r
   !>
   !> @param[in] a Taylor jet with positive scalar part
   !> @param[in] b Scalar exponent
   pure recursive function pow_jr(a, b) result(r)
      !> Taylor jet with positive scalar part
      type(sses_jet_type), intent(in) :: a
      !> Scalar exponent
      real(wp), intent(in) :: b
      !> Function result
      type(sses_jet_type) :: r
      real(wp) :: scale
      integer :: p, i, k

      r = jet_constant(a%c(0)**b, a%order)
      if (a%constant) return
      r%constant = .false.
      scale = 1.0_wp/a%c(0)
      do p = 1, size(products, 2)
         k = products(3, p)
         if (k >= counts(a%order)) exit
         i = products(1, p)
         if (i == 0) cycle
         if (a%c(i) == 0.0_wp) cycle
         r%c(k) = r%c(k) + ((b + 1.0_wp)*leading_share(p) - 1.0_wp)*scale*a%c(i)*r%c(products(2, p))
      end do
   end function pow_jr

