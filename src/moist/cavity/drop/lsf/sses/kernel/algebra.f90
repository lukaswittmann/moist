contains

   !> Constant Taylor jet
   !>
   !> @param[in] value Scalar value
   !> @param[in] order Highest total derivative order
   pure recursive function jet_constant(value, order) result(r)
      !> Scalar value
      real(wp), intent(in) :: value
      !> Highest total derivative order
      integer, intent(in) :: order
      !> Function result
      type(sses_jet_type) :: r

      r%order = order
      r%c(0) = value
   end function jet_constant

   !> Seed five linear perturbations
   !>
   !> @param[in] value Scalar value
   !> @param[in] seeds Linear derivatives in five variables
   !> @param[in] order Highest total derivative order
   pure recursive function jet_seed(value, seeds, order) result(r)
      !> Scalar value
      real(wp), intent(in) :: value
      !> Linear derivatives in five variables
      real(wp), intent(in) :: seeds(:)
      !> Highest total derivative order
      integer, intent(in) :: order
      !> Function result
      type(sses_jet_type) :: r

      r = jet_constant(real(value, wp), order)
      if (order >= 1) r%c(1:5) = real(seeds(1:5), wp)
      r%constant = order == 0 .or. maxval(abs(seeds)) <= 0.0_wp
   end function jet_seed

   !> Extract an unnormalized mixed derivative
   !>
   !> @param[in] a Taylor jet
   !> @param[in] indices Variable indices, including repetitions
   pure recursive function jet_derivative(a, indices) result(r)
      !> Taylor jet
      type(sses_jet_type), intent(in) :: a
      !> Variable indices, including repetitions
      integer, intent(in) :: indices(:)
      !> Function result
      real(wp) :: r
      integer :: alpha(5), i, j, factorial

      r = 0.0_wp
      if (size(indices) > a%order) return
      alpha = 0
      do i = 1, size(indices)
         alpha(indices(i)) = alpha(indices(i)) + 1
      end do
      factorial = 1
      do i = 1, 5
         do j = 2, alpha(i)
            factorial = factorial*j
         end do
      end do
      r = a%c(slots(alpha(1), alpha(2), alpha(3), alpha(4), alpha(5)))*real(factorial, wp)
   end function jet_derivative

   !> Add two Taylor jets
   !>
   !> @param[in] a First operand
   !> @param[in] b Second operand
   pure recursive function add_jj(a, b) result(r)
      !> First operand
      type(sses_jet_type), intent(in) :: a
      !> Second operand
      type(sses_jet_type), intent(in) :: b
      !> Function result
      type(sses_jet_type) :: r

      r%order = max(a%order, b%order)
      r%constant = a%constant .and. b%constant
      r%c(0:counts(r%order) - 1) = a%c(0:counts(r%order) - 1) + b%c(0:counts(r%order) - 1)
   end function add_jj

   !> Add a scalar to a Taylor jet
   !>
   !> @param[in] a Taylor jet
   !> @param[in] b Scalar operand
   pure recursive function add_jr(a, b) result(r)
      !> Taylor jet
      type(sses_jet_type), intent(in) :: a
      !> Scalar operand
      real(wp), intent(in) :: b
      !> Function result
      type(sses_jet_type) :: r

      r = a
      r%c(0) = r%c(0) + b
   end function add_jr

   !> Add a Taylor jet to a scalar
   !>
   !> @param[in] a Scalar operand
   !> @param[in] b Taylor jet
   pure recursive function add_rj(a, b) result(r)
      !> Scalar operand
      real(wp), intent(in) :: a
      !> Taylor jet
      type(sses_jet_type), intent(in) :: b
      !> Function result
      type(sses_jet_type) :: r

      r = b + a
   end function add_rj

   !> Negate a Taylor jet
   !>
   !> @param[in] a Taylor jet
   pure recursive function neg_j(a) result(r)
      !> Taylor jet
      type(sses_jet_type), intent(in) :: a
      !> Function result
      type(sses_jet_type) :: r

      r%order = a%order
      r%constant = a%constant
      r%c(0:counts(r%order) - 1) = -a%c(0:counts(r%order) - 1)
   end function neg_j

   !> Subtract two Taylor jets
   !>
   !> @param[in] a First operand
   !> @param[in] b Second operand
   pure recursive function sub_jj(a, b) result(r)
      !> First operand
      type(sses_jet_type), intent(in) :: a
      !> Second operand
      type(sses_jet_type), intent(in) :: b
      !> Function result
      type(sses_jet_type) :: r

      r = a + (-b)
   end function sub_jj

   !> Subtract a scalar from a Taylor jet
   !>
   !> @param[in] a Taylor jet
   !> @param[in] b Scalar operand
