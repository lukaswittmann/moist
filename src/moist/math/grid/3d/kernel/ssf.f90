   !> @param[out] error Invalid geometry, allocation or non-finite contraction
   !> @param[in] nthreads Optional worker count; enclosing teams use one worker
   subroutine ssf_grid_gradient(self, points, xyz, numbers, owners, atomic_w, adjoint_xyz, &
      & adjoint_w, gradient, error, nthreads)
      !> Configured partition scheme
      class(ssf_partition_type), intent(in) :: self
      !> Sample positions (3, ng), bohr
      real(wp), intent(in) :: points(:, :)
      !> Nuclear positions (3, nat), bohr
      real(wp), intent(in) :: xyz(:, :)
      !> Atomic numbers (nat)
      integer, intent(in) :: numbers(:)
      !> Point owners (ng), in [1, nat]
      integer, intent(in) :: owners(:)
      !> Fixed atomic quadrature weights (ng), bohr**3
      real(wp), intent(in) :: atomic_w(:)
      !> Point-position adjoints (3, ng)
      real(wp), intent(in) :: adjoint_xyz(:, :)
      !> Integration-weight adjoints (ng)
      real(wp), intent(in) :: adjoint_w(:)
      !> Nuclear-gradient accumulator (3, nat)
      real(wp), intent(inout) :: gradient(:, :)
      !> Invalid geometry, allocation or non-finite contraction
      type(error_type), intent(out), allocatable :: error
      !> Optional worker count; enclosing teams use one worker
      integer, intent(in), optional :: nthreads

      real(wp), allocatable :: pair_r(:, :), pair_a(:, :), dist(:, :), probs(:, :), workers(:, :, &
         & :), local(:, :)
      real(wp) :: point(3), seed, point_response(3)
      integer :: nat, ng, nt, slot, ip, owner, stat

      nat = size(numbers)
      ng = size(owners)
      if (ng == 0) return
      nt = 1
!$    if (.not. omp_in_parallel()) then
!$       nt = omp_get_max_threads()
!$       if (present(nthreads)) then
!$          if (nthreads > 0) nt = nthreads
!$       end if
!$       nt = min(nt, ng)
!$    end if
      allocate (pair_r(nat, nat), stat=stat)
      if (stat == 0) allocate (pair_a(nat, nat), stat=stat)
      if (stat == 0) allocate (dist(nat, nt), stat=stat)
      if (stat == 0) allocate (probs(nat, nt), stat=stat)
      if (stat == 0) allocate (workers(3, nat, nt), stat=stat)
      if (stat == 0) allocate (local(3, nat), stat=stat)
      if (stat /= 0) then
         call fatal_error(error, "ssf grid: cannot allocate gradient scratch")
         return
      end if
      block
         real(wp) :: radius(size(numbers))
         real(wp) :: chi, u
         integer :: ia, ja

         radius = covalent_rad(numbers)
         pair_r = 0.0_wp
         pair_a = 0.0_wp
         do ia = 1, size(numbers)
            do ja = 1, ia - 1
               pair_r(ja, ia) = norm2(xyz(:, ia) - xyz(:, ja))
               chi = radius(ia)/radius(ja)
               u = (chi - 1.0_wp)/(chi + 1.0_wp)
               pair_a(ja, ia) = max(-0.5_wp, min(0.5_wp, u/(u*u - 1.0_wp)))
               pair_r(ia, ja) = pair_r(ja, ia)
               pair_a(ia, ja) = -pair_a(ja, ia)
            end do
         end do
      end block
      workers = 0.0_wp
      !$omp parallel num_threads(nt) default(none) &
      !$omp shared(points, xyz, owners, atomic_w, pair_a, dist, probs, nat, ng, pair_r, self, adjoint_w, &
      !$omp    & workers, adjoint_xyz) private(slot, ip, owner, point, seed, point_response)
      slot = 1
!$    slot = omp_get_thread_num() + 1
      !$omp do schedule(static, 64)
      do ip = 1, ng
         owner = owners(ip)
         point = points(:, ip)
         seed = atomic_w(ip)*adjoint_w(ip)
         point_response = 0.0_wp
         if (seed /= 0.0_wp .and. nat > 1) then
            point_math: block
               real(wp) :: peak, owner_seed, log_seed, mu, nu, s, ds, factor
               real(wp) :: ui(3), uj(3), axis(3)
               integer :: i, j

               associate (dist => dist(:, slot), probs => probs(:, slot), gradient => workers(:, :, slot), &
                  & point_gradient => point_response)
                  point_gradient = 0.0_wp
                  dist = 0.0_wp
                  do i = 1, size(dist)
                     dist(i) = norm2(point - xyz(:, i))
                  end do
                  do i = 1, size(dist)
                     probs(i) = ssf_cell_log(i, dist, pair_r, pair_a, self)
                  end do
                  if (probs(owner) == -huge(1.0_wp)) exit point_math
                  peak = maxval(probs)
                  probs = exp(probs - peak)
                  probs = probs/sum(probs)
                  owner_seed = seed*probs(owner)
                  do i = 1, size(dist)
                     log_seed = -owner_seed*probs(i)
                     if (i == owner) then
                        ! Sum other probabilities to retain derivatives of tiny partition tails
                        log_seed = owner_seed*(sum(probs(:i - 1)) + sum(probs(i + 1:)))
                     end if
                     if (log_seed == 0.0_wp) cycle
                     do j = 1, size(dist)
                        if (j == i) cycle
                        if (pair_r(j, i) <= 0.0_wp) cycle
                        mu = max(-1.0_wp, min(1.0_wp, (dist(i) - dist(j))/pair_r(j, i)))
                        nu = mu + pair_a(j, i)*(1.0_wp - mu*mu)
                        block
                           real(wp) :: t

                           s = 0.0_wp
                           ds = 0.0_wp
                           if (abs((nu/self%a)) >= 1.0_wp) then
                              if ((nu/self%a) < 0.0_wp) s = 1.0_wp
                           else
                              t = 0.5_wp*(1.0_wp - abs((nu/self%a)))
                              s = t**4*(35.0_wp + t*(-84.0_wp + t*(70.0_wp - 20.0_wp*t)))
                              ds = 70.0_wp*t**3*(-1.0_wp + t)**3
                              if ((nu/self%a) < 0.0_wp) then
                                 s = 1.0_wp - s
                              end if
                           end if
                           ds = ds/self%a
                        end block
                        if (s <= 0.0_wp .or. ds == 0.0_wp) cycle
                        factor = (log_seed/s)*ds
                        if (abs(mu) >= 1.0_wp) cycle
                        factor = factor*(1.0_wp - 2.0_wp*pair_a(j, i)*mu)/pair_r(j, i)
                        ui = 0.0_wp
                        uj = 0.0_wp
                        if (dist(i) > 0.0_wp) ui = (point - xyz(:, i))/dist(i)
                        if (dist(j) > 0.0_wp) uj = (point - xyz(:, j))/dist(j)
                        axis = (xyz(:, i) - xyz(:, j))/pair_r(j, i)
                        point_gradient = point_gradient + factor*(ui - uj)
                        gradient(:, i) = gradient(:, i) - factor*(ui + mu*axis)
                        gradient(:, j) = gradient(:, j) + factor*(uj + mu*axis)
                     end do
                  end do
               end associate
            end block point_math
         end if
         workers(:, owner, slot) = workers(:, owner, slot) + point_response + adjoint_xyz(:, ip)
      end do
      !$omp end do
      !$omp end parallel
      local = 0.0_wp
      do slot = 1, nt
         local = local + workers(:, :, slot)
      end do
      if (.not. all(ieee_is_finite(local))) then
         call fatal_error(error, "ssf grid: non-finite gradient contraction")
         return
      end if
      gradient = gradient + local
   end subroutine ssf_grid_gradient

