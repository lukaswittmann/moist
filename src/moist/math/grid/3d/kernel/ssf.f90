   subroutine ssf_grid_weights(self, points, xyz, numbers, owners, atomic_w, w, partition_w, error, &
      & nthreads)
      !> Configured partition scheme
      class(ssf_partition_type), intent(in) :: self
      !> Sample positions (3, ng), bohr
      real(wp), intent(in) :: points(:, :)
      !> Nuclear positions (3, nat), bohr
      real(wp), intent(in) :: xyz(:, :)
      !> Atomic numbers (nat)
