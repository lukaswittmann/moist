      real(wp), intent(out) :: w(:)
      !> Normalized owner-partition weights (ng)
      real(wp), intent(out) :: partition_w(:)
      !> Invalid geometry, allocation or non-finite contraction
      type(error_type), intent(out), allocatable :: error
      !> Optional worker count; enclosing teams use one worker
      integer, intent(in), optional :: nthreads

      real(wp), allocatable :: pair_r(:, :), pair_a(:, :), dist(:, :), probs(:, :)
      real(wp) :: point(3), peak
      integer :: nat, ng, nt, slot, ip, owner, stat, i

      nat = size(numbers)
      ng = size(owners)
      if (ng == 0) return
      nt = 1
!$    if (.not. omp_in_parallel()) then
!$       nt = omp_get_max_threads()
!$       if (present(nthreads)) then
!$          if (nthreads > 0) nt = nthreads
!$       end if
!$       nt = min(nt, ng)
!$    end if
      allocate (pair_r(nat, nat), stat=stat)
      if (stat == 0) allocate (pair_a(nat, nat), stat=stat)
      if (stat == 0) allocate (dist(nat, nt), stat=stat)
      if (stat == 0) allocate (probs(nat, nt), stat=stat)
      if (stat /= 0) then
         call fatal_error(error, "ssf grid: cannot allocate weights scratch")
         return
      end if
      block
         real(wp) :: radius(size(numbers))
         real(wp) :: chi, u
         integer :: ia, ja

         radius = covalent_rad(numbers)
         pair_r = 0.0_wp
         pair_a = 0.0_wp
         do ia = 1, size(numbers)
            do ja = 1, ia - 1
               pair_r(ja, ia) = norm2(xyz(:, ia) - xyz(:, ja))
               chi = radius(ia)/radius(ja)
               u = (chi - 1.0_wp)/(chi + 1.0_wp)
               pair_a(ja, ia) = max(-0.5_wp, min(0.5_wp, u/(u*u - 1.0_wp)))
               pair_r(ia, ja) = pair_r(ja, ia)
               pair_a(ia, ja) = -pair_a(ja, ia)
            end do
         end do
      end block
      !$omp parallel num_threads(nt) default(none) &
      !$omp shared(points, xyz, owners, atomic_w, pair_a, dist, probs, nat, ng, pair_r, self, w, &
      !$omp    & partition_w) private(slot, ip, owner, point, i, peak)
