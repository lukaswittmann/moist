                  dist = 0.0_wp
                  do i = 1, size(dist)
                     probs(i) = pvoronoi_cell_log(i, point, xyz, dist, pair_a, width)
                  end do
                  if (probs(owner) == -huge(1.0_wp)) exit point_math
                  peak = maxval(probs)
                  probs = exp(probs - peak)
                  probs = probs/sum(probs)
                  owner_seed = seed*probs(owner)
                  do i = 1, size(dist)
                     log_seed = -owner_seed*probs(i)
                     if (i == owner) then
                        ! Sum other probabilities to retain derivatives of tiny partition tails
                        log_seed = owner_seed*(sum(probs(:i - 1)) + sum(probs(i + 1:)))
                     end if
                     if (log_seed == 0.0_wp) cycle
                     do j = 1, size(dist)
                        if (j == i) cycle
                        nu = (dot_product((point - xyz(:, i)) + (point - xyz(:, j)), &
                           & xyz(:, j) - xyz(:, i)) + pair_a(j, i))/width
                        block
                           real(wp) :: u, d, e, c0

                           s = 0.0_wp
                           ds = 0.0_wp
                           if (abs(nu) >= 1.0_wp) then
                              if (nu < 0.0_wp) s = 1.0_wp
                           else
                              u = abs(nu)
                              d = (1.0_wp - u)*(1.0_wp + u)
                              e = exp(-2.0_wp*u/d)
                              c0 = 1.0_wp + e
                              s = e*(1.0_wp/c0)
                              ds = e*(1.0_wp/c0**2)*(1.0_wp/d**2)*(-2.0_wp - 2.0_wp*u**2)
                              if (nu < 0.0_wp) then
                                 s = 1.0_wp - s
                              end if
                           end if
                        end block
                        if (s <= 0.0_wp .or. ds == 0.0_wp) cycle
                        factor = (log_seed/s)*ds
                        factor = 2.0_wp*factor/width
                        point_gradient = point_gradient + factor*(xyz(:, j) - xyz(:, i))
                        gradient(:, i) = gradient(:, i) - factor*(point - xyz(:, i))
                        gradient(:, j) = gradient(:, j) + factor*(point - xyz(:, j))
                     end do
                  end do
               end associate
            end block point_math
         end if
         workers(:, owner, slot) = workers(:, owner, slot) + point_response + adjoint_xyz(:, ip)
      end do
      !$omp end do
      !$omp end parallel
      local = 0.0_wp
      do slot = 1, nt
         local = local + workers(:, :, slot)
      end do
      if (.not. all(ieee_is_finite(local))) then
         call fatal_error(error, "pvoronoi grid: non-finite gaussian_gradient contraction")
         return
      end if
      gradient = gradient + local
   end subroutine pvoronoi_grid_gaussian_gradient

   !> Contract nuclear curvature with one prepared directional pass
   !>
   !> Unchecked shapes, finite inputs, valid owners and switch settings required
   !> Nuclear accumulators committed only after a finite contraction
   !>
   !> @param[in] self Configured partition scheme
   !> @param[in] points Sample positions (3, ng), bohr
   !> @param[in] xyz Nuclear positions (3, nat), bohr
   !> @param[in] numbers Atomic numbers (nat)
   !> @param[in] owners Point owners (ng), in [1, nat]
   !> @param[in] atomic_w Fixed atomic quadrature weights (ng), bohr**3
   !> @param[in] adjoint_w Integration-weight adjoints (ng)
   !> @param[in] direction Nuclear displacement direction (3, nat)
   !> @param[in,out] hessian_vector Nuclear Hessian-vector accumulator (3, nat)
   !> @param[out] error Invalid geometry, allocation or non-finite contraction
   !> @param[in] nthreads Optional worker count; enclosing teams use one worker
   subroutine pvoronoi_grid_hessian_vector(self, points, xyz, numbers, owners, atomic_w, adjoint_w, &
      & direction, hessian_vector, error, nthreads)
      !> Configured partition scheme
      class(pvoronoi_partition_type), intent(in) :: self
      !> Sample positions (3, ng), bohr
      real(wp), intent(in) :: points(:, :)
      !> Nuclear positions (3, nat), bohr
      real(wp), intent(in) :: xyz(:, :)
      !> Atomic numbers (nat)
      integer, intent(in) :: numbers(:)
      !> Point owners (ng), in [1, nat]
      integer, intent(in) :: owners(:)
      !> Fixed atomic quadrature weights (ng), bohr**3
      real(wp), intent(in) :: atomic_w(:)
      !> Integration-weight adjoints (ng)
      real(wp), intent(in) :: adjoint_w(:)
      !> Nuclear displacement direction (3, nat)
      real(wp), intent(in) :: direction(:, :)
      !> Nuclear Hessian-vector accumulator (3, nat)
      real(wp), intent(inout) :: hessian_vector(:, :)
      !> Invalid geometry, allocation or non-finite contraction
      type(error_type), intent(out), allocatable :: error
      !> Optional worker count; enclosing teams use one worker
      integer, intent(in), optional :: nthreads

      real(wp), allocatable :: pair_a(:, :), dist(:, :), probs(:, :), log_t(:, :), workers(:, :, :), &
         & local(:, :)
      real(wp) :: point(3), seed, point_response(3), half_width
      integer :: nat, ng, nt, slot, ip, owner, stat

      nat = size(numbers)
      ng = size(owners)
      if (ng == 0) return
      if (nat == 1 .or. all(atomic_w*adjoint_w == 0.0_wp)) return
      if (all(direction == 0.0_wp)) return
      half_width = self%width
      nt = 1
!$    if (.not. omp_in_parallel()) then
!$       nt = omp_get_max_threads()
!$       if (present(nthreads)) then
!$          if (nthreads > 0) nt = nthreads
!$       end if
!$       nt = min(nt, ng)
!$    end if
      allocate (pair_a(nat, nat), stat=stat)
      if (stat == 0) allocate (dist(nat, nt), stat=stat)
      if (stat == 0) allocate (probs(nat, nt), stat=stat)
      if (stat == 0) allocate (log_t(nat, nt), stat=stat)
      if (stat == 0) allocate (workers(3, nat, nt), stat=stat)
      if (stat == 0) allocate (local(3, nat), stat=stat)
      if (stat /= 0) then
         call fatal_error(error, "pvoronoi grid: cannot allocate hessian_vector scratch")
         return
      end if
      block
         real(wp) :: radius(size(numbers))
         integer :: ia, ja

         radius = covalent_rad(numbers)
         if (allocated(self%radii)) then
            if (size(self%radii) /= size(numbers)) then
               call fatal_error(error, "pvoronoi partition: radii needs one entry per atom")
               return
            end if
            radius = self%radii
         end if
         pair_a = 0.0_wp
         do ia = 1, size(numbers)
            do ja = 1, ia - 1
               pair_a(ja, ia) = (radius(ja) - radius(ia))*(radius(ja) + radius(ia))
               pair_a(ia, ja) = -pair_a(ja, ia)
            end do
         end do
      end block
      workers = 0.0_wp
      !$omp parallel num_threads(nt) default(none) &
      !$omp shared(points, xyz, owners, atomic_w, pair_a, dist, probs, nat, ng, half_width, adjoint_w, &
      !$omp    & workers, log_t, direction) private(slot, ip, owner, point, seed, point_response)
      slot = 1
!$    slot = omp_get_thread_num() + 1
      !$omp do schedule(static, 64)
      do ip = 1, ng
         owner = owners(ip)
         point = points(:, ip)
         seed = atomic_w(ip)*adjoint_w(ip)
         point_response = 0.0_wp
         if (seed /= 0.0_wp) then
            point_math: block
               real(wp) :: positions(3, 3), tangent(3, 3), g(3, 3), h(3, 3), contribution(3, 3)
               real(wp) :: nu, nu_t, s, ds, d2s, peak, q, qt, alpha, alpha_t, log_p_t, first, second, beta, beta_t
               integer :: i, j, k

               associate (dist => dist(:, slot), probs => probs(:, slot), hessian_vector => workers(:, :, &
                  & slot), point_hessian_vector => point_response, log_t => log_t(:, slot), &
                  & point_direction => direction(:, owner), width => half_width)
                  point_hessian_vector = 0.0_wp
                  dist = 0.0_wp
                  positions(:, 1) = point
                  tangent(:, 1) = point_direction
                  probs = 0.0_wp
                  log_t = 0.0_wp
                  do i = 1, size(dist)
                     positions(:, 2) = xyz(:, i)
                     tangent(:, 2) = direction(:, i)
                     do j = 1, size(dist)
                        if (j == i) cycle
                        positions(:, 3) = xyz(:, j)
                        tangent(:, 3) = direction(:, j)
                        ! Coordinate order 1: power
                        block
                           real(wp) :: c0, c1, c2, c3, c4, c5, c6, c7, c8, c9

                           nu = (dot_product((positions(:, 1) - positions(:, 2)) + (positions(:, 1) - positions(:, 3)), &
                              & positions(:, 3) - positions(:, 2)) + pair_a(j, i))/width
                           c0 = (1.0_wp/width)
                           c1 = 2.0_wp*positions(1, 2)
                           c2 = -2.0_wp*positions(1, 3)
                           c3 = 2.0_wp*positions(2, 2)
                           c4 = -2.0_wp*positions(2, 3)
                           c5 = 2.0_wp*positions(3, 2)
                           c6 = -2.0_wp*positions(3, 3)
                           c7 = 2.0_wp*positions(1, 1)
                           c8 = 2.0_wp*positions(2, 1)
                           c9 = 2.0_wp*positions(3, 1)
                           g(1, 1) = c0*(-c1 - c2)
                           g(2, 1) = c0*(-c3 - c4)
                           g(3, 1) = c0*(-c5 - c6)
                           g(1, 2) = c0*(c1 - c7)
                           g(2, 2) = c0*(c3 - c8)
                           g(3, 2) = c0*(c5 - c9)
                           g(1, 3) = c0*(c2 + c7)
                           g(2, 3) = c0*(c4 + c8)
                           g(3, 3) = c0*(c6 + c9)
                        end block
                        block
                           real(wp) :: u, d, e, c0

                           s = 0.0_wp
                           ds = 0.0_wp
                           if (abs(nu) >= 1.0_wp) then
                              if (nu < 0.0_wp) s = 1.0_wp
                           else
                              u = abs(nu)
                              d = (1.0_wp - u)*(1.0_wp + u)
                              e = exp(-2.0_wp*u/d)
                              c0 = 1.0_wp + e
                              s = e*(1.0_wp/c0)
                              ds = e*(1.0_wp/c0**2)*(1.0_wp/d**2)*(-2.0_wp - 2.0_wp*u**2)
                              if (nu < 0.0_wp) then
                                 s = 1.0_wp - s
                              end if
                           end if
                        end block
                        if (s <= 0.0_wp) then
                           probs(i) = -huge(1.0_wp)
                           log_t(i) = 0.0_wp
                           exit
                        end if
                        probs(i) = probs(i) + log(s)
                        log_t(i) = log_t(i) + (ds/s)*sum(g*tangent)
                     end do
                  end do
                  if (probs(owner) == -huge(1.0_wp)) exit point_math
                  peak = maxval(probs)
                  probs = exp(probs - peak)
                  probs = probs/sum(probs)
                  q = seed*probs(owner)
                  qt = q*sum(probs*(log_t(owner) - log_t))
                  do i = 1, size(dist)
                     log_p_t = sum(probs*(log_t(i) - log_t))
                     alpha = -q*probs(i)
                     alpha_t = -qt*probs(i) - q*probs(i)*log_p_t
                     if (i == owner) then
                        beta = 0.0_wp
                        beta_t = 0.0_wp
                        do k = 1, size(dist)
                           if (k == owner) cycle
                           beta = beta + probs(k)
                           beta_t = beta_t + probs(k)*sum(probs*(log_t(k) - log_t))
                        end do
                        alpha = q*beta
                        alpha_t = qt*beta + q*beta_t
                     end if
                     if (alpha == 0.0_wp .and. alpha_t == 0.0_wp) cycle
                     positions(:, 2) = xyz(:, i)
                     tangent(:, 2) = direction(:, i)
                     do j = 1, size(dist)
                        if (j == i) cycle
                        positions(:, 3) = xyz(:, j)
                        tangent(:, 3) = direction(:, j)
                        ! Coordinate order 2: power
                        block
                           real(wp) :: c0, c1, c2, c3, c4, c5, c6, c7, c8, c9, c10, c11, c12, c13, c14, c15, c16, c17, c18, &
                              & c19

                           nu = (dot_product((positions(:, 1) - positions(:, 2)) + (positions(:, 1) - positions(:, 3)), &
                              & positions(:, 3) - positions(:, 2)) + pair_a(j, i))/width
                           c0 = (1.0_wp/width)
                           c1 = 2.0_wp*positions(1, 2)
                           c2 = -2.0_wp*positions(1, 3)
                           c3 = 2.0_wp*positions(2, 2)
                           c4 = -2.0_wp*positions(2, 3)
                           c5 = 2.0_wp*positions(3, 2)
                           c6 = -2.0_wp*positions(3, 3)
                           c7 = 2.0_wp*positions(1, 1)
                           c8 = 2.0_wp*positions(2, 1)
                           c9 = 2.0_wp*positions(3, 1)
                           c10 = 2.0_wp*c0
                           c11 = c10*tangent(1, 2)
                           c12 = -c10*tangent(1, 3)
                           c13 = c10*tangent(2, 2)
                           c14 = -c10*tangent(2, 3)
                           c15 = c10*tangent(3, 2)
                           c16 = -c10*tangent(3, 3)
                           c17 = c10*tangent(1, 1)
                           c18 = c10*tangent(2, 1)
                           c19 = c10*tangent(3, 1)
                           g(1, 1) = c0*(-c1 - c2)
                           g(2, 1) = c0*(-c3 - c4)
                           g(3, 1) = c0*(-c5 - c6)
                           g(1, 2) = c0*(c1 - c7)
                           g(2, 2) = c0*(c3 - c8)
                           g(3, 2) = c0*(c5 - c9)
                           g(1, 3) = c0*(c2 + c7)
                           g(2, 3) = c0*(c4 + c8)
                           g(3, 3) = c0*(c6 + c9)
                           h(1, 1) = -c11 - c12
                           h(2, 1) = -c13 - c14
                           h(3, 1) = -c15 - c16
                           h(1, 2) = c11 - c17
                           h(2, 2) = c13 - c18
                           h(3, 2) = c15 - c19
                           h(1, 3) = c12 + c17
                           h(2, 3) = c14 + c18
                           h(3, 3) = c16 + c19
                        end block
                        block
                           real(wp) :: u, d, e, c0, c1, c2, c3, c4

                           s = 0.0_wp
                           ds = 0.0_wp
                           d2s = 0.0_wp
                           if (abs(nu) >= 1.0_wp) then
                              if (nu < 0.0_wp) s = 1.0_wp
                           else
                              u = abs(nu)
                              d = (1.0_wp - u)*(1.0_wp + u)
                              e = exp(-2.0_wp*u/d)
                              c0 = 1.0_wp + e
                              c1 = (1.0_wp/c0)
                              c2 = u**2
                              c3 = -2.0_wp - 2.0_wp*c2
                              c4 = e*(1.0_wp/c0**2)
                              s = c1*e
                              ds = c3*c4*(1.0_wp/d**2)
                              d2s = c4*(-4.0_wp*u*(1.0_wp/d**3)*(3.0_wp + c2) + c1*c3**2*(1.0_wp/d**4)*(1.0_wp - e))
                              if (nu < 0.0_wp) then
                                 s = 1.0_wp - s
                                 d2s = -d2s
                              end if
                           end if
                        end block
                        if (s <= 0.0_wp) cycle
                        first = ds/s
                        second = d2s/s - first*first
                        nu_t = sum(g*tangent)
                        contribution = (alpha_t*first + alpha*second*nu_t)*g + alpha*first*h
                        point_hessian_vector = point_hessian_vector + contribution(:, 1)
                        hessian_vector(:, i) = hessian_vector(:, i) + contribution(:, 2)
                        hessian_vector(:, j) = hessian_vector(:, j) + contribution(:, 3)
                     end do
                  end do
               end associate
            end block point_math
         end if
         workers(:, owner, slot) = workers(:, owner, slot) + point_response
      end do
      !$omp end do
      !$omp end parallel
      local = 0.0_wp
      do slot = 1, nt
         local = local + workers(:, :, slot)
      end do
      if (.not. all(ieee_is_finite(local))) then
         call fatal_error(error, "pvoronoi grid: non-finite hessian_vector contraction")
         return
      end if
      hessian_vector = hessian_vector + local
   end subroutine pvoronoi_grid_hessian_vector

