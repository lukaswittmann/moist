!> DPCM (point charges) phases: complex/energy; generated by pcmgen, do not edit
!>
!> - Procedures of pcmgen_point_dpcm: dpcm_point_complex_medium, dpcm_point_complex_solve
submodule(pcmgen_point_dpcm) pcmgen_point_dpcm_complex_energy
   implicit none(type, external)

contains

   module subroutine dpcm_point_complex_medium(state, eps, error)
      !> State of dpcm_point
      type(dpcm_point_complex_state), target, intent(inout) :: state
      !> Relative permittivity of the solvent (inf for a conductor)
      complex(wp), intent(in) :: eps
      !> Error handling
      type(error_type), allocatable, intent(out) :: error

      integer :: npt
      integer :: stat
      complex(wp) :: tmp1, tmp2

      if (state%matrix_free) then
         call dpcm_point_complex_mf_medium(state, eps, error)
         return
      end if
      stat = 0
      npt = state%npt
      if (state%ready < 1) then
         call fatal_error(error, "[dpcm_point_complex_medium] call dpcm_point_assemble first")
         return
      end if
      state%cx_ready = 0
      if (allocated(state%cx_v)) deallocate (state%cx_v)
      if (allocated(state%cx_vn)) deallocate (state%cx_vn)
      if (allocated(state%cx_s11)) deallocate (state%cx_s11)
      if (allocated(state%cx_s13)) deallocate (state%cx_s13)
      if (allocated(state%cx_s14)) deallocate (state%cx_s14)
      if (allocated(state%cx_s15)) deallocate (state%cx_s15)
      if (allocated(state%cx_s17)) deallocate (state%cx_s17)
      if (allocated(state%cx_s18)) deallocate (state%cx_s18)
      if (allocated(state%cx_s19)) deallocate (state%cx_s19)
      if (allocated(state%cx_s20)) deallocate (state%cx_s20)
      if (allocated(state%cx_s21)) deallocate (state%cx_s21)
      if (stat == 0) allocate (state%cx_v(npt), stat=stat)
      if (stat == 0) allocate (state%cx_vn(npt), stat=stat)
      if (stat == 0) allocate (state%cx_s11(npt), stat=stat)
      if (stat == 0) allocate (state%cx_s13(npt), stat=stat)
      if (stat == 0) allocate (state%cx_s14(npt), stat=stat)
      if (stat == 0) allocate (state%cx_s15(npt), stat=stat)
      if (stat == 0) allocate (state%cx_s17(npt), stat=stat)
      if (stat == 0) allocate (state%cx_s18(npt), stat=stat)
      if (stat == 0) allocate (state%cx_s19(npt), stat=stat)
      if (stat == 0) allocate (state%cx_s20(npt), stat=stat)
      if (stat == 0) allocate (state%cx_s21(npt), stat=stat)
      if (stat /= 0) then
         call fatal_error(error, "[dpcm_point_complex_medium] allocation failed")
         return
      end if
      state%cx_s11 = 0.0_wp
      state%cx_s13 = 0.0_wp
      state%cx_ready = 1
      state%cx_assembled = state%assembled
      ! Inputs that do not enter these outputs
      associate (unused1 => eps)
      end associate

      state%op3%npt = npt
      state%op3%npoint = npt
      state%op3%id = 3
      state%op3%points => state%r
      state%op3%a => state%a
      state%cx_s1 = eps + 1.0_wp
      tmp1 = 1.0_wp/state%cx_s1
      tmp2 = (-2.0_wp)*tmp1
      state%cx_s2 = 1.0_wp + tmp2
      state%cx_s3 = -state%cx_s2
      state%op3%c1 = state%cx_s3
      state%op3%c2 => state%s10
      call state%solver%setup_complex(state%op3, error)
      if (allocated(error)) return
      state%cx_s12 = 0.5_wp*state%cx_s2

      state%cx_ready = 2
   end subroutine dpcm_point_complex_medium

   module subroutine dpcm_point_complex_solve(state, v, vn, energy, q, grad_v, grad_vn, error)
      !> State of dpcm_point
      type(dpcm_point_complex_state), target, intent(inout) :: state
      !> Solute electrostatic potential at the surface points
      complex(wp), contiguous, intent(in) :: v(:)
      !> Outward normal derivative of the solute potential at the surface points
      complex(wp), contiguous, intent(in) :: vn(:)
      !> Solvation energy
      complex(wp), intent(out) :: energy
      !> Apparent surface charges
      complex(wp), contiguous, intent(out) :: q(:)
      !> Partial derivative of the energy with respect to v
      complex(wp), contiguous, intent(out) :: grad_v(:)
      !> Partial derivative of the energy with respect to vn
      complex(wp), contiguous, intent(out) :: grad_vn(:)
      !> Error handling
      type(error_type), allocatable, intent(out) :: error

      integer :: npt
      integer :: stat
      real(wp), allocatable :: tmp2(:), tmp3(:)
      complex(wp), allocatable :: tmp1(:), tmp5(:), tmp6(:), tmp7(:), tmp8(:), tmp9(:), tmp10(:)
      complex(wp) :: tmp4, tmp11

      if (state%matrix_free) then
         call dpcm_point_complex_mf_solve(state, v, vn, energy, q, grad_v, grad_vn, error)
         return
      end if
      stat = 0
      npt = state%npt
      if (state%cx_ready < 2 .or. state%cx_assembled /= state%assembled) then
         call fatal_error(error, "[dpcm_point_complex_solve] call dpcm_point_complex_medium first")
         return
      end if
      if (any(shape(v) /= [npt])) then
         call fatal_error(error, "[dpcm_point_complex_solve] v: wrong shape")
         return
      end if
      if (any(shape(vn) /= [npt])) then
         call fatal_error(error, "[dpcm_point_complex_solve] vn: wrong shape")
         return
      end if
      if (any(shape(q) /= [npt])) then
         call fatal_error(error, "[dpcm_point_complex_solve] q: wrong shape")
         return
      end if
      if (any(shape(grad_v) /= [npt])) then
         call fatal_error(error, "[dpcm_point_complex_solve] grad_v: wrong shape")
         return
      end if
      if (any(shape(grad_vn) /= [npt])) then
         call fatal_error(error, "[dpcm_point_complex_solve] grad_vn: wrong shape")
         return
      end if
      allocate (tmp1(npt), stat=stat)
      if (stat == 0) allocate (tmp2(npt), stat=stat)
      if (stat == 0) allocate (tmp3(npt), stat=stat)
      if (stat == 0) allocate (tmp5(npt), stat=stat)
      if (stat == 0) allocate (tmp6(npt), stat=stat)
      if (stat == 0) allocate (tmp7(npt), stat=stat)
      if (stat == 0) allocate (tmp8(npt), stat=stat)
      if (stat == 0) allocate (tmp9(npt), stat=stat)
      if (stat == 0) allocate (tmp10(npt), stat=stat)
      if (stat /= 0) then
         call fatal_error(error, "[dpcm_point_complex_solve] allocation failed")
         return
      end if
      state%cx_ready = 2

      state%op3%points => state%r
      state%op3%a => state%a
      state%op3%c2 => state%s10
      state%cx_v = v
      state%cx_vn = vn
      tmp1 = state%a*state%cx_vn
      call state%solver%solve_complex(state%op3, .false., tmp1, state%cx_s11, error)
      if (allocated(error)) return
      call state%solver%solve_complex(state%op3, .true., state%cx_v, state%cx_s13, error)
      if (allocated(error)) return
      state%cx_s14 = state%cx_s12*state%cx_s13
      call gemv(state%s10, real(state%cx_s11, wp), tmp2, trans="t")
      call gemv(state%s10, aimag(state%cx_s11), tmp3, trans="t")
      state%cx_s15 = cmplx(tmp2, tmp3, wp)
      q = state%cx_s2*state%cx_s11
      tmp4 = sum(state%cx_v*q)
      energy = 0.5_wp*tmp4
      grad_v = state%cx_s12*state%cx_s11
      grad_vn = state%cx_s14*state%a
      if (state%solver%inexact()) then
         ! First-order correction for the residuals of the solves
         tmp5 = 6.283185307179586_wp*state%cx_s11
         tmp6 = state%a*state%cx_s15
         tmp7 = state%cx_s3*tmp6
         tmp8 = tmp5 + tmp7
         tmp9 = -tmp8
         tmp10 = tmp1 + tmp9
         tmp11 = sum(state%cx_s14*tmp10)
         energy = energy + tmp11
      end if

      state%cx_ready = 3
   end subroutine dpcm_point_complex_solve

end submodule pcmgen_point_dpcm_complex_energy
