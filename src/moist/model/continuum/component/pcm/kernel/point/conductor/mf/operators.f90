                        tmp18, tmp20, tmp21, tmp22, tmp23, tmp24

            !$omp parallel &
            !$omp& private(i, j, tmp1_p) &
            !$omp& shared(self, tmp1, x) &
            !$omp& default(private)
            allocate (tmp1_p(self%npt))
            tmp1_p = 0.0_wp
