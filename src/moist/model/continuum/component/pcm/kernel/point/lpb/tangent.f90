   module subroutine lpb_point_response(state, dv, hvp_v, error)
      !> State of lpb_point
      type(lpb_point_state), intent(inout) :: state
      !> Direction for v
      real(wp), contiguous, intent(in) :: dv(:, :)
      !> Hessian times direction, v block
      real(wp), contiguous, intent(out) :: hvp_v(:, :)
      !> Error handling
      type(error_type), allocatable, intent(out) :: error

      integer :: npt, nblk, blk

      if (state%matrix_free) then
         call lpb_point_mf_response(state, dv, hvp_v, error)
         return
      end if
      if (state%ready < 3) then
         call fatal_error(error, "[lpb_point_response] call lpb_point_solve first")
         return
      end if
      npt = state%npt
      nblk = size(dv, 2)
      if (any(shape(dv) /= [npt, nblk])) then
         call fatal_error(error, "[lpb_point_response] dv: wrong shape")
