!> DPCM, original form (point charges) phases: complex/mf/energy; generated by pcmgen, do not edit
!>
!> - Procedures of pcmgen_point_dpcm_original: dpcm_original_point_complex_mf_medium,
!>   dpcm_original_point_complex_mf_solve
submodule(pcmgen_point_dpcm_original) pcmgen_point_dpcm_original_complex_mf_energy
   implicit none(type, external)

contains

   module subroutine dpcm_original_point_complex_mf_medium(state, eps, error)
      !> State of dpcm_original_point
      type(dpcm_original_point_complex_state), target, intent(inout) :: state
      !> Relative permittivity of the solvent (inf for a conductor)
      complex(wp), intent(in) :: eps
      !> Error handling
      type(error_type), allocatable, intent(out) :: error

      integer :: npt
      integer :: stat
      complex(wp) :: tmp1, tmp2

      stat = 0
      npt = state%npt
      if (state%ready < 1) then
         call fatal_error(error, &
                          "[dpcm_original_point_complex_mf_medium] call dpcm_original_point_assemble first")
         return
      end if
      state%cx_ready = 0
      if (allocated(state%cx_v)) deallocate (state%cx_v)
      if (allocated(state%cx_s12)) deallocate (state%cx_s12)
      if (allocated(state%cx_s14)) deallocate (state%cx_s14)
      if (allocated(state%cx_s16)) deallocate (state%cx_s16)
      if (allocated(state%cx_s17)) deallocate (state%cx_s17)
      if (allocated(state%cx_s18)) deallocate (state%cx_s18)
      if (allocated(state%cx_s19)) deallocate (state%cx_s19)
      if (allocated(state%cx_s21)) deallocate (state%cx_s21)
      if (allocated(state%cx_s22)) deallocate (state%cx_s22)
      if (allocated(state%cx_s23)) deallocate (state%cx_s23)
      if (stat == 0) allocate (state%cx_v(npt), stat=stat)
      if (stat == 0) allocate (state%cx_s12(npt), stat=stat)
      if (stat == 0) allocate (state%cx_s14(npt), stat=stat)
      if (stat == 0) allocate (state%cx_s16(npt), stat=stat)
      if (stat == 0) allocate (state%cx_s17(npt), stat=stat)
      if (stat == 0) allocate (state%cx_s18(npt), stat=stat)
      if (stat == 0) allocate (state%cx_s19(npt), stat=stat)
      if (stat == 0) allocate (state%cx_s21(npt), stat=stat)
      if (stat == 0) allocate (state%cx_s22(npt), stat=stat)
      if (stat == 0) allocate (state%cx_s23(npt), stat=stat)
      if (stat /= 0) then
         call fatal_error(error, "[dpcm_original_point_complex_mf_medium] allocation failed")
         return
      end if
      state%cx_s12 = 0.0_wp
      state%cx_s14 = 0.0_wp
      state%cx_ready = 1
      state%cx_assembled = state%assembled
      ! Inputs that do not enter these outputs
      associate (unused1 => eps)
      end associate

      state%op4%npt = npt
      state%op4%npoint = npt
      state%op4%id = 4
      state%op4%points => state%r
      state%op4%r => state%r
      state%op4%n => state%n
      state%op4%k1 => state%k1
      state%op4%k2 => state%k2
      state%op4%a => state%a
      state%op4%c1 => state%s3
      state%cx_s1 = eps + 1.0_wp
      tmp1 = 1.0_wp/state%cx_s1
      tmp2 = (-2.0_wp)*tmp1
      state%cx_s2 = 1.0_wp + tmp2
      state%cx_s4 = -state%cx_s2
      state%op4%c2 = state%cx_s4
      call state%solver%setup_complex(state%op4, error)
      if (allocated(error)) return
      state%cx_s13 = 0.5_wp*state%cx_s2

      state%cx_ready = 2
   end subroutine dpcm_original_point_complex_mf_medium

   module subroutine dpcm_original_point_complex_mf_solve(state, v, vn, energy, q, grad_v, &
                                                          grad_vn, error)
      !> State of dpcm_original_point
      type(dpcm_original_point_complex_state), target, intent(inout) :: state
      !> Solute electrostatic potential at the surface points
      complex(wp), contiguous, intent(in) :: v(:)
      !> Outward normal derivative of the solute potential at the surface points
      complex(wp), contiguous, intent(in) :: vn(:)
      !> Solvation energy
      complex(wp), intent(out) :: energy
      !> Apparent surface charges
      complex(wp), contiguous, intent(out) :: q(:)
      !> Partial derivative of the energy with respect to v
      complex(wp), contiguous, intent(out) :: grad_v(:)
      !> Partial derivative of the energy with respect to vn
      complex(wp), contiguous, intent(out) :: grad_vn(:)
      !> Error handling
      type(error_type), allocatable, intent(out) :: error

      integer :: npt
      integer :: stat
      real(wp), allocatable :: tmp5(:)
      real(wp) :: tmp6, tmp7, tmp8, tmp9, tmp10, tmp11
      complex(wp), allocatable :: tmp2(:), tmp3(:), tmp4(:), tmp12(:), tmp41(:), tmp42(:), &
                                  tmp43(:), tmp44(:)
      complex(wp) :: tmp1, tmp45
      integer :: i, j

      stat = 0
      npt = state%npt
      if (state%cx_ready < 2 .or. state%cx_assembled /= state%assembled) then
         call fatal_error(error, &
                          "[dpcm_original_point_complex_mf_solve] call dpcm_original_point_complex_medium first")
         return
      end if
      if (any(shape(v) /= [npt])) then
         call fatal_error(error, "[dpcm_original_point_complex_mf_solve] v: wrong shape")
         return
      end if
      if (any(shape(vn) /= [npt])) then
         call fatal_error(error, "[dpcm_original_point_complex_mf_solve] vn: wrong shape")
         return
      end if
      if (any(shape(q) /= [npt])) then
         call fatal_error(error, "[dpcm_original_point_complex_mf_solve] q: wrong shape")
         return
      end if
      if (any(shape(grad_v) /= [npt])) then
         call fatal_error(error, "[dpcm_original_point_complex_mf_solve] grad_v: wrong shape")
         return
      end if
      if (any(shape(grad_vn) /= [npt])) then
         call fatal_error(error, "[dpcm_original_point_complex_mf_solve] grad_vn: wrong shape")
         return
      end if
      allocate (tmp2(npt), stat=stat)
      if (stat == 0) allocate (tmp3(npt), stat=stat)
      if (stat == 0) allocate (tmp4(npt), stat=stat)
      if (stat == 0) allocate (tmp5(npt), stat=stat)
      if (stat == 0) allocate (tmp12(npt), stat=stat)
      if (stat == 0) allocate (tmp41(npt), stat=stat)
      if (stat == 0) allocate (tmp42(npt), stat=stat)
      if (stat == 0) allocate (tmp43(npt), stat=stat)
      if (stat == 0) allocate (tmp44(npt), stat=stat)
      if (stat /= 0) then
         call fatal_error(error, "[dpcm_original_point_complex_mf_solve] allocation failed")
         return
      end if
      state%cx_ready = 2

      state%op4%points => state%r
      state%op4%r => state%r
      state%op4%n => state%n
      state%op4%k1 => state%k1
      state%op4%k2 => state%k2
      state%op4%a => state%a
      state%op4%c1 => state%s3
      state%cx_v = v
      call state%solver%solve_complex(state%op4, .false., vn, state%cx_s12, error)
      if (allocated(error)) return
      call state%solver%solve_complex(state%op4, .true., state%cx_v, state%cx_s14, error)
      if (allocated(error)) return
      q = state%cx_s2*state%cx_s12
      tmp1 = sum(state%cx_v*q)
      energy = 0.5_wp*tmp1
      grad_v = state%cx_s13*state%cx_s12
      grad_vn = state%cx_s13*state%cx_s14
      if (state%solver%inexact()) then
         ! First-order correction for the residuals of the solves
         tmp2 = state%s3*state%cx_s12
         tmp3 = 6.283185307179586_wp*tmp2
         do i = 1, npt
            tmp6 = state%k1(i) + state%k2(i)
            tmp7 = 1.0_wp/state%a(i)
            tmp8 = 12.566370614359172_wp*tmp7
            tmp9 = sqrt(tmp8)
            tmp10 = tmp6*tmp9
            tmp11 = (-0.26735_wp)*tmp10
            tmp5(i) = tmp11
         end do
         tmp12 = tmp5*state%cx_s12
         tmp4 = tmp12
         block
            real(wp) :: tmp14, tmp15, tmp16, tmp17, tmp18, tmp19, tmp21, tmp24, tmp28, tmp22, &
                        tmp23, tmp25, tmp26, tmp27, tmp29, tmp30, tmp31, tmp32, tmp33, tmp34, &
                        tmp35, tmp36, tmp37, tmp38, tmp39
            complex(wp) :: tmp20, tmp13, tmp40

            !$omp parallel &
            !$omp& private(i, j) &
            !$omp& shared(npt, state, tmp4) &
            !$omp& default(private)
            !$omp do schedule(static)
            do j = 1, npt
               tmp14 = state%s5(j)
               tmp15 = state%s6(j)
               tmp16 = state%s7(j)
               tmp17 = state%s8(j)
               tmp18 = state%s9(j)
               tmp19 = state%s10(j)
               tmp20 = state%cx_s12(j)
               tmp21 = -tmp15
               tmp24 = -tmp16
               tmp28 = -tmp18
               tmp13 = 0.0_wp
               !$omp simd &
               !$omp& private(tmp22, tmp23, tmp25, tmp26, tmp27, tmp29, tmp30, tmp31) &
               !$omp& private(tmp32, tmp33, tmp34, tmp35, tmp36, tmp37, tmp38, tmp39) &
               !$omp& private(tmp40) &
               !$omp& reduction(+: tmp13)
               do i = 1, j - 1
                  tmp22 = state%s6(i) + tmp21
                  tmp23 = tmp14*tmp22
                  tmp25 = state%s7(i) + tmp24
                  tmp26 = tmp25*tmp17
                  tmp27 = tmp23 + tmp26
                  tmp29 = state%s9(i) + tmp28
                  tmp30 = tmp29*tmp19
                  tmp31 = tmp27 + tmp30
                  tmp32 = tmp22**(2)
                  tmp33 = tmp25**(2)
                  tmp34 = tmp32 + tmp33
                  tmp35 = tmp29**(2)
                  tmp36 = tmp34 + tmp35
                  tmp37 = 1.0_wp/sqrt(tmp36)
                  tmp38 = tmp37**(3)
                  tmp39 = tmp31*tmp38
                  tmp40 = tmp39*state%cx_s12(i)
                  tmp13 = tmp13 + tmp40
               end do
               !$omp simd &
               !$omp& private(tmp22, tmp23, tmp25, tmp26, tmp27, tmp29, tmp30, tmp31) &
               !$omp& private(tmp32, tmp33, tmp34, tmp35, tmp36, tmp37, tmp38, tmp39) &
               !$omp& private(tmp40) &
               !$omp& reduction(+: tmp13)
               do i = j + 1, npt
                  tmp22 = state%s6(i) + tmp21
                  tmp23 = tmp14*tmp22
                  tmp25 = state%s7(i) + tmp24
                  tmp26 = tmp25*tmp17
                  tmp27 = tmp23 + tmp26
                  tmp29 = state%s9(i) + tmp28
                  tmp30 = tmp29*tmp19
                  tmp31 = tmp27 + tmp30
                  tmp32 = tmp22**(2)
                  tmp33 = tmp25**(2)
                  tmp34 = tmp32 + tmp33
                  tmp35 = tmp29**(2)
                  tmp36 = tmp34 + tmp35
                  tmp37 = 1.0_wp/sqrt(tmp36)
                  tmp38 = tmp37**(3)
                  tmp39 = tmp31*tmp38
                  tmp40 = tmp39*state%cx_s12(i)
                  tmp13 = tmp13 + tmp40
               end do
               tmp4(j) = tmp4(j) + tmp13
            end do
            !$omp end do
            !$omp end parallel
         end block
         tmp41 = state%cx_s4*tmp4
         tmp42 = tmp3 + tmp41
         tmp43 = -tmp42
         tmp44 = vn + tmp43
         tmp45 = sum(grad_vn*tmp44)
         energy = energy + tmp45
      end if

      state%cx_ready = 3
   end subroutine dpcm_original_point_complex_mf_solve

end submodule pcmgen_point_dpcm_original_complex_mf_energy
