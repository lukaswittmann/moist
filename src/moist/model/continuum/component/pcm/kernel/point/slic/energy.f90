!> SLIC (point charges) phases: energy; generated by pcmgen, do not edit
!>
!> - Procedures of pcmgen_point_slic: slic_point_assemble, slic_point_medium, slic_point_solve
submodule(pcmgen_point_slic) pcmgen_point_slic_energy
   implicit none(type, external)

contains

   module subroutine slic_point_assemble(state, r, n, k1, k2, a, error, solver)
      !> State of slic_point
      type(slic_point_state), target, intent(inout) :: state
      !> Positions of the surface points
      real(wp), contiguous, intent(in) :: r(:, :)
      !> Outward unit normals at the surface points
      real(wp), contiguous, intent(in) :: n(:, :)
      !> First principal curvature (positive where convex)
      real(wp), contiguous, intent(in) :: k1(:)
      !> Second principal curvature (positive where convex)
      real(wp), contiguous, intent(in) :: k2(:)
      !> Grid point areas
      real(wp), contiguous, intent(in) :: a(:)
      !> Error handling
      type(error_type), allocatable, intent(out) :: error
      !> Linear solver
      class(pcm_solver), intent(in), optional :: solver

      integer :: npt
      integer :: stat
      real(wp) :: tmp35, tmp36, tmp37, tmp38, tmp39, tmp40
      integer :: i, j

      if (present(solver)) then
         if (solver%matrix_free(size(r, 2), 1)) then
            call slic_point_mf_assemble(state, r, n, k1, k2, a, error, solver)
            return
         end if
      end if
      stat = 0
      npt = size(r, 2)
      if (npt < 1) then
         call fatal_error(error, "[slic_point_assemble] empty discretization")
         return
      end if
      if (any(shape(r) /= [3, npt])) then
         call fatal_error(error, "[slic_point_assemble] r: wrong shape")
         return
      end if
      if (any(shape(n) /= [3, npt])) then
         call fatal_error(error, "[slic_point_assemble] n: wrong shape")
         return
      end if
      if (any(shape(k1) /= [npt])) then
         call fatal_error(error, "[slic_point_assemble] k1: wrong shape")
         return
      end if
      if (any(shape(k2) /= [npt])) then
         call fatal_error(error, "[slic_point_assemble] k2: wrong shape")
         return
      end if
      if (any(shape(a) /= [npt])) then
         call fatal_error(error, "[slic_point_assemble] a: wrong shape")
         return
      end if
      state%ready = 0
      if (allocated(state%solver)) deallocate (state%solver)
      if (allocated(state%a)) deallocate (state%a)
      if (allocated(state%s1)) deallocate (state%s1)
      if (allocated(state%r)) deallocate (state%r)
      if (allocated(state%s2)) deallocate (state%s2)
      if (allocated(state%s3)) deallocate (state%s3)
      if (allocated(state%s4)) deallocate (state%s4)
      if (allocated(state%s5)) deallocate (state%s5)
      if (allocated(state%s6)) deallocate (state%s6)
      if (allocated(state%k1)) deallocate (state%k1)
      if (allocated(state%k2)) deallocate (state%k2)
      if (allocated(state%s7)) deallocate (state%s7)
      if (allocated(state%s14)) deallocate (state%s14)
      if (allocated(state%s15)) deallocate (state%s15)
      if (allocated(state%s16)) deallocate (state%s16)
      if (allocated(state%s17)) deallocate (state%s17)
      if (allocated(state%s18)) deallocate (state%s18)
      if (allocated(state%s19)) deallocate (state%s19)
      if (allocated(state%s20)) deallocate (state%s20)
      if (allocated(state%s21)) deallocate (state%s21)
      if (allocated(state%s22)) deallocate (state%s22)
      if (allocated(state%s23)) deallocate (state%s23)
      if (allocated(state%s24)) deallocate (state%s24)
      if (allocated(state%s25)) deallocate (state%s25)
      if (allocated(state%s26)) deallocate (state%s26)
      if (allocated(state%s27)) deallocate (state%s27)
      if (allocated(state%s28)) deallocate (state%s28)
      if (allocated(state%n)) deallocate (state%n)
      state%npt = npt
      if (present(solver)) then
         allocate (state%solver, source=solver, stat=stat)
      else
         allocate (pcm_dense_solver :: state%solver, stat=stat)
      end if
      if (stat == 0) allocate (state%a(npt), stat=stat)
      if (stat == 0) allocate (state%s1(npt), stat=stat)
      if (stat == 0) allocate (state%r(3, npt), stat=stat)
      if (stat == 0) allocate (state%s2(npt), stat=stat)
      if (stat == 0) allocate (state%s3(npt), stat=stat)
      if (stat == 0) allocate (state%s4(npt), stat=stat)
      if (stat == 0) allocate (state%s5(npt), stat=stat)
      if (stat == 0) allocate (state%s6(npt), stat=stat)
      if (stat == 0) allocate (state%k1(npt), stat=stat)
      if (stat == 0) allocate (state%k2(npt), stat=stat)
      if (stat == 0) allocate (state%s7(npt, npt), stat=stat)
      if (stat == 0) allocate (state%s14(npt), stat=stat)
      if (stat == 0) allocate (state%s15(npt), stat=stat)
      if (stat == 0) allocate (state%s16(npt), stat=stat)
      if (stat == 0) allocate (state%s17(npt), stat=stat)
      if (stat == 0) allocate (state%s18(npt), stat=stat)
      if (stat == 0) allocate (state%s19(npt), stat=stat)
      if (stat == 0) allocate (state%s20(npt), stat=stat)
      if (stat == 0) allocate (state%s21(npt), stat=stat)
      if (stat == 0) allocate (state%s22(npt), stat=stat)
      if (stat == 0) allocate (state%s23(npt), stat=stat)
      if (stat == 0) allocate (state%s24(npt), stat=stat)
      if (stat == 0) allocate (state%s25(npt), stat=stat)
      if (stat == 0) allocate (state%s26(npt), stat=stat)
      if (stat == 0) allocate (state%s27(npt), stat=stat)
      if (stat == 0) allocate (state%s28(npt), stat=stat)
      if (stat /= 0) then
         call fatal_error(error, "[slic_point_assemble] allocation failed")
         return
      end if
      state%s14 = 0.0_wp
      state%s21 = 0.0_wp
      call state%solver%reset(slic_point_n_operators)
      state%matrix_free = .false.

      state%a = a
      state%r = r
      state%k1 = k1
      state%k2 = k2
      state%s1 = n(1, :)
      state%s2 = state%r(1, :)
      state%s3 = state%r(2, :)
      state%s4 = n(2, :)
      state%s5 = state%r(3, :)
      state%s6 = n(3, :)
      block
         real(wp) :: tmp1, tmp2, tmp3, tmp4, tmp5, tmp6, tmp7, tmp10, tmp14, tmp8, tmp9, tmp11, &
                     tmp12, tmp13, tmp15, tmp16, tmp17, tmp18, tmp19, tmp20, tmp21, tmp22, tmp23, &
                     tmp24, tmp25, tmp26, tmp27, tmp28, tmp29, tmp30, tmp31, tmp32, tmp33, tmp34

         !$omp parallel &
         !$omp& private(i, j) &
         !$omp& shared(npt, state) &
         !$omp& default(private)
         !$omp do schedule(dynamic, 16)
         do j = 2, npt
            tmp1 = state%s1(j)
            tmp2 = state%s2(j)
            tmp3 = state%s3(j)
            tmp4 = state%s4(j)
            tmp5 = state%s5(j)
            tmp6 = state%s6(j)
            tmp7 = -tmp2
            tmp10 = -tmp3
            tmp14 = -tmp5
            !$omp simd &
            !$omp& private(tmp8, tmp9, tmp11, tmp12, tmp13, tmp15, tmp16, tmp17) &
            !$omp& private(tmp18, tmp19, tmp20, tmp21, tmp22, tmp23, tmp24, tmp25) &
            !$omp& private(tmp26, tmp27, tmp28, tmp29, tmp30, tmp31, tmp32, tmp33) &
            !$omp& private(tmp34)
            do i = 1, j - 1
               tmp8 = state%s2(i) + tmp7
               tmp9 = tmp1*tmp8
               tmp11 = state%s3(i) + tmp10
               tmp12 = tmp11*tmp4
               tmp13 = tmp9 + tmp12
               tmp15 = state%s5(i) + tmp14
               tmp16 = tmp15*tmp6
               tmp17 = tmp13 + tmp16
               tmp18 = tmp8**(2)
               tmp19 = tmp11**(2)
               tmp20 = tmp18 + tmp19
               tmp21 = tmp15**(2)
               tmp22 = tmp20 + tmp21
               tmp23 = 1.0_wp/sqrt(tmp22)
               tmp24 = tmp23**(3)
               tmp25 = tmp17*tmp24
               state%s7(i, j) = tmp25
               tmp26 = -tmp8
               tmp27 = state%s1(i)*tmp26
               tmp28 = -tmp11
               tmp29 = tmp28*state%s4(i)
               tmp30 = tmp27 + tmp29
               tmp31 = -tmp15
               tmp32 = tmp31*state%s6(i)
               tmp33 = tmp30 + tmp32
               tmp34 = tmp33*tmp24
               state%s7(j, i) = tmp34
            end do
         end do
         !$omp end do
         !$omp end parallel
      end block
      do i = 1, npt
         tmp35 = state%k1(i) + state%k2(i)
         tmp36 = 1.0_wp/state%a(i)
         tmp37 = 12.566370614359172_wp*tmp36
         tmp38 = sqrt(tmp37)
         tmp39 = tmp35*tmp38
         tmp40 = (-0.26735_wp)*tmp39
         state%s7(i, i) = tmp40
      end do

      state%ready = 1
      state%assembled = state%assembled + 1
   end subroutine slic_point_assemble

   module subroutine slic_point_medium(state, eps, alpha, beta, gamma, mu, error)
      !> State of slic_point
      type(slic_point_state), target, intent(inout) :: state
      !> Relative permittivity of the solvent (inf for a conductor)
      real(wp), intent(in) :: eps
      !> SLIC amplitude of the solvation-layer perturbation h
      real(wp), intent(in) :: alpha
      !> SLIC steepness of h in the normal field (inverse field units)
      real(wp), intent(in) :: beta
      !> SLIC offset of the transition of h
      real(wp), intent(in) :: gamma
      !> SLIC shift of h
      real(wp), intent(in) :: mu
      !> Error handling
      type(error_type), allocatable, intent(out) :: error

      integer :: npt
      integer :: stat
      real(wp) :: tmp1, tmp2, tmp3, tmp4

      if (state%matrix_free) then
         call slic_point_mf_medium(state, eps, alpha, beta, gamma, mu, error)
         return
      end if
      stat = 0
      npt = state%npt
      if (state%ready < 1) then
         call fatal_error(error, "[slic_point_medium] call slic_point_assemble first")
         return
      end if
      state%s14 = 0.0_wp
      state%ready = 1
      ! Inputs that do not enter these outputs
      associate (unused1 => eps, unused2 => gamma)
      end associate

      state%beta = beta
      state%alpha = alpha
      state%mu = mu
      state%s8 = -gamma
      state%s9 = eps + 1.0_wp
      tmp1 = 1.0_wp/state%s9
      tmp2 = (-2.0_wp)*tmp1
      state%s10 = 1.0_wp + tmp2
      state%s11 = -state%s10
      state%s12 = state%s10*state%alpha
      state%s13 = state%s12*state%beta
      tmp3 = state%beta**(2)
      tmp4 = tmp3*state%s10
      state%s29 = tmp4*state%alpha

      state%ready = 2
   end subroutine slic_point_medium

   module subroutine slic_point_solve(state, v, vn, energy, q, grad_v, grad_vn, error)
      !> State of slic_point
      type(slic_point_state), target, intent(inout) :: state
      !> Solute electrostatic potential at the surface points
      real(wp), contiguous, intent(in) :: v(:)
      !> Outward normal derivative of the solute potential at the surface points
      real(wp), contiguous, target, intent(in) :: vn(:)
      !> Solvation energy
      real(wp), intent(out) :: energy
      !> Apparent surface charges
      real(wp), contiguous, intent(out) :: q(:)
      !> Partial derivative of the energy with respect to v
      real(wp), contiguous, intent(out) :: grad_v(:)
      !> Partial derivative of the energy with respect to vn
      real(wp), contiguous, intent(out) :: grad_vn(:)
      !> Error handling
      type(error_type), allocatable, intent(out) :: error

      integer :: npt
      integer :: stat
      type(slic_point_nl1) :: nl1
      real(wp), allocatable :: tmp1(:), tmp2(:), tmp3(:), tmp22(:), tmp33(:), tmp34(:), tmp35(:), &
                               tmp37(:), tmp48(:), tmp49(:)
      real(wp) :: tmp4, tmp5, tmp6, tmp7, tmp8, tmp9, tmp10, tmp11, tmp12, tmp13, tmp14, tmp15, &
                  tmp16, tmp17, tmp18, tmp19, tmp20, tmp21, tmp23, tmp24, tmp25, tmp26, tmp27, &
                  tmp28, tmp29, tmp30, tmp31, tmp32, tmp36, tmp38, tmp39, tmp40, tmp41, tmp42, &
                  tmp43, tmp44, tmp45, tmp46, tmp47, tmp50, tmp51
      integer :: i

      if (state%matrix_free) then
         call slic_point_mf_solve(state, v, vn, energy, q, grad_v, grad_vn, error)
         return
      end if
      stat = 0
      npt = state%npt
      if (state%ready < 2) then
         call fatal_error(error, "[slic_point_solve] call slic_point_medium first")
         return
      end if
      if (any(shape(v) /= [npt])) then
         call fatal_error(error, "[slic_point_solve] v: wrong shape")
         return
      end if
      if (any(shape(vn) /= [npt])) then
         call fatal_error(error, "[slic_point_solve] vn: wrong shape")
         return
      end if
      if (any(shape(q) /= [npt])) then
         call fatal_error(error, "[slic_point_solve] q: wrong shape")
         return
      end if
      if (any(shape(grad_v) /= [npt])) then
         call fatal_error(error, "[slic_point_solve] grad_v: wrong shape")
         return
      end if
      if (any(shape(grad_vn) /= [npt])) then
         call fatal_error(error, "[slic_point_solve] grad_vn: wrong shape")
         return
      end if
      allocate (tmp1(npt), stat=stat)
      if (stat == 0) allocate (tmp2(npt), stat=stat)
      if (stat == 0) allocate (tmp3(npt), stat=stat)
      if (stat == 0) allocate (tmp22(npt), stat=stat)
      if (stat == 0) allocate (tmp33(npt), stat=stat)
      if (stat == 0) allocate (tmp34(npt), stat=stat)
      if (stat == 0) allocate (tmp35(npt), stat=stat)
      if (stat == 0) allocate (tmp37(npt), stat=stat)
      if (stat == 0) allocate (tmp48(npt), stat=stat)
      if (stat == 0) allocate (tmp49(npt), stat=stat)
      if (stat /= 0) then
         call fatal_error(error, "[slic_point_solve] allocation failed")
         return
      end if
      state%ready = 2

      state%op1%npt = npt
      state%op1%npoint = npt
      state%op1%id = 1
      state%op1%points => state%r
      state%op1%a => state%a
      nl1%npt = npt
      nl1%solver => state%solver
      nl1%r => state%r
      nl1%a => state%a
      nl1%vn => vn
      nl1%alpha = state%alpha
      nl1%beta = state%beta
      nl1%mu = state%mu
      nl1%c1 => state%s7
      nl1%c2 = state%s8
      nl1%c3 = state%s10
      nl1%c4 = state%s11
      nl1%c5 = state%s13
      call nl1%solve(state%s14, error)
      if (allocated(error)) return
      state%s15 = state%a*state%s14
      call gemv(state%s7, state%s15, tmp1, trans="t")
      state%s16 = vn + tmp1
      tmp2 = 6.283185307179586_wp*state%s14
      tmp3 = state%s16 + tmp2
      state%s17 = -tmp3
      do i = 1, npt
         tmp4 = state%beta*state%s17(i)
         tmp5 = tmp4 + state%s8
         tmp6 = tanh(tmp5)
         tmp7 = tmp6**(2)
         tmp8 = -tmp7
         tmp9 = 1.0_wp + tmp8
         tmp10 = state%s13*tmp9
         tmp11 = tmp10*state%s14(i)
         tmp12 = (-12.566370614359172_wp)*tmp11
         state%s18(i) = tmp12
      end do
      state%op1%c1 => state%s18
      state%op1%c2 => state%s7
      do i = 1, npt
         tmp13 = state%beta*state%s17(i)
         tmp14 = tmp13 + state%s8
         tmp15 = tanh(tmp14)
         tmp16 = state%alpha*tmp15
         tmp17 = tmp16 + state%mu
         tmp18 = state%s10*tmp17
         tmp19 = (-2.0_wp)*tmp18
         tmp20 = 1.0_wp + tmp19
         tmp21 = 6.283185307179586_wp*tmp20
         state%s19(i) = tmp21
      end do
      state%op1%c3 => state%s19
      state%op1%c4 = state%s11
      call state%solver%setup(state%op1, error)
      if (allocated(error)) return
      state%s20 = 0.5_wp*v
      tmp22 = state%s20*state%a
      call state%solver%solve(state%op1, .true., tmp22, state%s21, error)
      if (allocated(error)) return
      do i = 1, npt
         tmp23 = state%s12*state%s14(i)
         tmp24 = state%beta*state%s17(i)
         tmp25 = tmp24 + state%s8
         tmp26 = tanh(tmp25)
         tmp27 = tmp26**(2)
         tmp28 = -tmp27
         tmp29 = 1.0_wp + tmp28
         tmp30 = tmp23*tmp29
         tmp31 = tmp30*state%beta
         tmp32 = (-12.566370614359172_wp)*tmp31
         state%s22(i) = tmp32
      end do
      tmp33 = state%s11*state%s21
      tmp34 = state%s21*state%s22
      tmp35 = -tmp34
      state%s23 = tmp33 + tmp35
      state%s24 = -state%s23
      tmp36 = dot(v, state%s15)
      energy = 0.5_wp*tmp36
      q = state%s15
      grad_v = 0.5_wp*state%s15
      grad_vn = state%s24
      if (state%solver%inexact()) then
         ! First-order correction for the residuals of the solves
         do i = 1, npt
            tmp38 = state%beta*state%s17(i)
            tmp39 = tmp38 + state%s8
            tmp40 = tanh(tmp39)
            tmp41 = state%alpha*tmp40
            tmp42 = tmp41 + state%mu
            tmp43 = state%s10*tmp42
            tmp44 = (-2.0_wp)*tmp43
            tmp45 = 1.0_wp + tmp44
            tmp46 = tmp45*state%s14(i)
            tmp47 = 6.283185307179586_wp*tmp46
            tmp37(i) = tmp47
         end do
         tmp48 = state%s11*state%s16
         tmp49 = tmp37 + tmp48
         tmp50 = dot(state%s21, tmp49)
         tmp51 = -tmp50
         energy = energy + tmp51
      end if

      state%ready = 3
   end subroutine slic_point_solve

end submodule pcmgen_point_slic_energy
