!> DPCM, original form (point charges) phases: mf/energy; generated by pcmgen, do not edit
!>
!> - Procedures of pcmgen_point_dpcm_original: dpcm_original_point_mf_assemble,
!>   dpcm_original_point_mf_medium, dpcm_original_point_mf_solve
submodule(pcmgen_point_dpcm_original) pcmgen_point_dpcm_original_mf_energy
   implicit none(type, external)

contains

   module subroutine dpcm_original_point_mf_assemble(state, r, n, k1, k2, a, error, solver)
      !> State of dpcm_original_point
      type(dpcm_original_point_state), target, intent(inout) :: state
      !> Positions of the surface points
      real(wp), contiguous, intent(in) :: r(:, :)
      !> Outward unit normals at the surface points
      real(wp), contiguous, intent(in) :: n(:, :)
      !> First principal curvature (positive where convex)
      real(wp), contiguous, intent(in) :: k1(:)
      !> Second principal curvature (positive where convex)
      real(wp), contiguous, intent(in) :: k2(:)
      !> Grid point areas
      real(wp), contiguous, intent(in) :: a(:)
      !> Error handling
      type(error_type), allocatable, intent(out) :: error
      !> Linear solver
      class(pcm_solver), intent(in), optional :: solver

      integer :: npt
      integer :: stat
      real(wp) :: tmp1
      integer :: i

      stat = 0
      npt = size(r, 2)
      if (npt < 1) then
         call fatal_error(error, "[dpcm_original_point_mf_assemble] empty discretization")
         return
      end if
      if (any(shape(r) /= [3, npt])) then
         call fatal_error(error, "[dpcm_original_point_mf_assemble] r: wrong shape")
         return
      end if
      if (any(shape(n) /= [3, npt])) then
         call fatal_error(error, "[dpcm_original_point_mf_assemble] n: wrong shape")
         return
      end if
      if (any(shape(k1) /= [npt])) then
         call fatal_error(error, "[dpcm_original_point_mf_assemble] k1: wrong shape")
         return
      end if
      if (any(shape(k2) /= [npt])) then
         call fatal_error(error, "[dpcm_original_point_mf_assemble] k2: wrong shape")
         return
      end if
      if (any(shape(a) /= [npt])) then
         call fatal_error(error, "[dpcm_original_point_mf_assemble] a: wrong shape")
         return
      end if
      state%ready = 0
      if (allocated(state%solver)) deallocate (state%solver)
      if (allocated(state%v)) deallocate (state%v)
      if (allocated(state%a)) deallocate (state%a)
      if (allocated(state%s3)) deallocate (state%s3)
      if (allocated(state%n)) deallocate (state%n)
      if (allocated(state%r)) deallocate (state%r)
      if (allocated(state%k1)) deallocate (state%k1)
      if (allocated(state%k2)) deallocate (state%k2)
      if (allocated(state%s12)) deallocate (state%s12)
      if (allocated(state%s14)) deallocate (state%s14)
      if (allocated(state%s5)) deallocate (state%s5)
      if (allocated(state%s6)) deallocate (state%s6)
      if (allocated(state%s7)) deallocate (state%s7)
      if (allocated(state%s8)) deallocate (state%s8)
      if (allocated(state%s9)) deallocate (state%s9)
      if (allocated(state%s10)) deallocate (state%s10)
      if (allocated(state%s16)) deallocate (state%s16)
      if (allocated(state%s17)) deallocate (state%s17)
      if (allocated(state%s18)) deallocate (state%s18)
      if (allocated(state%s19)) deallocate (state%s19)
      if (allocated(state%s21)) deallocate (state%s21)
      if (allocated(state%s22)) deallocate (state%s22)
      if (allocated(state%s23)) deallocate (state%s23)
      if (allocated(state%s11)) deallocate (state%s11)
      state%npt = npt
      if (present(solver)) then
         allocate (state%solver, source=solver, stat=stat)
      else
         allocate (pcm_dense_solver :: state%solver, stat=stat)
      end if
      if (stat == 0) allocate (state%v(npt), stat=stat)
      if (stat == 0) allocate (state%a(npt), stat=stat)
      if (stat == 0) allocate (state%s3(npt), stat=stat)
      if (stat == 0) allocate (state%n(3, npt), stat=stat)
      if (stat == 0) allocate (state%r(3, npt), stat=stat)
      if (stat == 0) allocate (state%k1(npt), stat=stat)
      if (stat == 0) allocate (state%k2(npt), stat=stat)
      if (stat == 0) allocate (state%s12(npt), stat=stat)
      if (stat == 0) allocate (state%s14(npt), stat=stat)
      if (stat == 0) allocate (state%s5(npt), stat=stat)
      if (stat == 0) allocate (state%s6(npt), stat=stat)
      if (stat == 0) allocate (state%s7(npt), stat=stat)
      if (stat == 0) allocate (state%s8(npt), stat=stat)
      if (stat == 0) allocate (state%s9(npt), stat=stat)
      if (stat == 0) allocate (state%s10(npt), stat=stat)
      if (stat == 0) allocate (state%s16(npt), stat=stat)
      if (stat == 0) allocate (state%s17(npt), stat=stat)
      if (stat == 0) allocate (state%s18(npt), stat=stat)
      if (stat == 0) allocate (state%s19(npt), stat=stat)
      if (stat == 0) allocate (state%s21(npt), stat=stat)
      if (stat == 0) allocate (state%s22(npt), stat=stat)
      if (stat == 0) allocate (state%s23(npt), stat=stat)
      if (stat /= 0) then
         call fatal_error(error, "[dpcm_original_point_mf_assemble] allocation failed")
         return
      end if
      state%s12 = 0.0_wp
      state%s14 = 0.0_wp
      call state%solver%reset(dpcm_original_point_n_operators)
      state%matrix_free = .true.

      state%a = a
      state%n = n
      state%r = r
      state%k1 = k1
      state%k2 = k2
      do i = 1, npt
         tmp1 = 1.0_wp/state%a(i)
         state%s3(i) = tmp1
      end do
      state%s5 = state%n(1, :)
      state%s6 = state%r(1, :)
      state%s7 = state%r(2, :)
      state%s8 = state%n(2, :)
      state%s9 = state%r(3, :)
      state%s10 = state%n(3, :)

      state%ready = 1
      state%assembled = state%assembled + 1
   end subroutine dpcm_original_point_mf_assemble

   module subroutine dpcm_original_point_mf_medium(state, eps, error)
      !> State of dpcm_original_point
      type(dpcm_original_point_state), target, intent(inout) :: state
      !> Relative permittivity of the solvent (inf for a conductor)
      real(wp), intent(in) :: eps
      !> Error handling
      type(error_type), allocatable, intent(out) :: error

      integer :: npt
      integer :: stat
      real(wp) :: tmp1, tmp2

      stat = 0
      npt = state%npt
      if (state%ready < 1) then
         call fatal_error(error, &
                          "[dpcm_original_point_mf_medium] call dpcm_original_point_assemble first")
         return
      end if
      state%ready = 1
      ! Inputs that do not enter these outputs
      associate (unused1 => eps)
      end associate

      state%op2%npt = npt
      state%op2%npoint = npt
      state%op2%id = 2
      state%op2%points => state%r
      state%op2%r => state%r
      state%op2%n => state%n
      state%op2%k1 => state%k1
      state%op2%k2 => state%k2
      state%op2%a => state%a
      state%op2%c1 => state%s3
      state%s1 = eps + 1.0_wp
      tmp1 = 1.0_wp/state%s1
      tmp2 = (-2.0_wp)*tmp1
      state%s2 = 1.0_wp + tmp2
      state%s4 = -state%s2
      state%op2%c2 = state%s4
      call state%solver%setup(state%op2, error)
      if (allocated(error)) return
      state%s13 = 0.5_wp*state%s2

      state%ready = 2
   end subroutine dpcm_original_point_mf_medium

   module subroutine dpcm_original_point_mf_solve(state, v, vn, energy, q, grad_v, grad_vn, error)
      !> State of dpcm_original_point
      type(dpcm_original_point_state), target, intent(inout) :: state
      !> Solute electrostatic potential at the surface points
      real(wp), contiguous, intent(in) :: v(:)
      !> Outward normal derivative of the solute potential at the surface points
      real(wp), contiguous, intent(in) :: vn(:)
      !> Solvation energy
      real(wp), intent(out) :: energy
      !> Apparent surface charges
      real(wp), contiguous, intent(out) :: q(:)
      !> Partial derivative of the energy with respect to v
      real(wp), contiguous, intent(out) :: grad_v(:)
      !> Partial derivative of the energy with respect to vn
      real(wp), contiguous, intent(out) :: grad_vn(:)
      !> Error handling
      type(error_type), allocatable, intent(out) :: error

      integer :: npt
      integer :: stat
      real(wp), allocatable :: tmp2(:), tmp3(:), tmp4(:), tmp5(:), tmp12(:), tmp41(:), tmp42(:), &
                               tmp43(:), tmp44(:)
      real(wp) :: tmp1, tmp6, tmp7, tmp8, tmp9, tmp10, tmp11, tmp45
      integer :: i, j

      stat = 0
      npt = state%npt
      if (state%ready < 2) then
         call fatal_error(error, &
                          "[dpcm_original_point_mf_solve] call dpcm_original_point_medium first")
         return
      end if
      if (any(shape(v) /= [npt])) then
         call fatal_error(error, "[dpcm_original_point_mf_solve] v: wrong shape")
         return
      end if
      if (any(shape(vn) /= [npt])) then
         call fatal_error(error, "[dpcm_original_point_mf_solve] vn: wrong shape")
         return
      end if
      if (any(shape(q) /= [npt])) then
         call fatal_error(error, "[dpcm_original_point_mf_solve] q: wrong shape")
         return
      end if
      if (any(shape(grad_v) /= [npt])) then
         call fatal_error(error, "[dpcm_original_point_mf_solve] grad_v: wrong shape")
         return
      end if
      if (any(shape(grad_vn) /= [npt])) then
         call fatal_error(error, "[dpcm_original_point_mf_solve] grad_vn: wrong shape")
         return
      end if
      allocate (tmp2(npt), stat=stat)
      if (stat == 0) allocate (tmp3(npt), stat=stat)
      if (stat == 0) allocate (tmp4(npt), stat=stat)
      if (stat == 0) allocate (tmp5(npt), stat=stat)
      if (stat == 0) allocate (tmp12(npt), stat=stat)
      if (stat == 0) allocate (tmp41(npt), stat=stat)
      if (stat == 0) allocate (tmp42(npt), stat=stat)
      if (stat == 0) allocate (tmp43(npt), stat=stat)
      if (stat == 0) allocate (tmp44(npt), stat=stat)
      if (stat /= 0) then
         call fatal_error(error, "[dpcm_original_point_mf_solve] allocation failed")
         return
      end if
      state%ready = 2

      state%op2%points => state%r
      state%op2%r => state%r
      state%op2%n => state%n
      state%op2%k1 => state%k1
      state%op2%k2 => state%k2
      state%op2%a => state%a
      state%op2%c1 => state%s3
      state%v = v
      call state%solver%solve(state%op2, .false., vn, state%s12, error)
      if (allocated(error)) return
      call state%solver%solve(state%op2, .true., state%v, state%s14, error)
      if (allocated(error)) return
      q = state%s2*state%s12
      tmp1 = dot(state%v, q)
      energy = 0.5_wp*tmp1
      grad_v = state%s13*state%s12
      grad_vn = state%s13*state%s14
      if (state%solver%inexact()) then
         ! First-order correction for the residuals of the solves
         tmp2 = state%s3*state%s12
         tmp3 = 6.283185307179586_wp*tmp2
         do i = 1, npt
            tmp6 = state%k1(i) + state%k2(i)
            tmp7 = 1.0_wp/state%a(i)
            tmp8 = 12.566370614359172_wp*tmp7
            tmp9 = sqrt(tmp8)
            tmp10 = tmp6*tmp9
            tmp11 = (-0.26735_wp)*tmp10
            tmp5(i) = tmp11
         end do
         tmp12 = tmp5*state%s12
         tmp4 = tmp12
         block
            real(wp) :: tmp14, tmp15, tmp16, tmp17, tmp18, tmp19, tmp20, tmp21, tmp24, tmp28, &
                        tmp13, tmp22, tmp23, tmp25, tmp26, tmp27, tmp29, tmp30, tmp31, tmp32, &
                        tmp33, tmp34, tmp35, tmp36, tmp37, tmp38, tmp39, tmp40

            !$omp parallel &
            !$omp& private(i, j) &
            !$omp& shared(npt, state, tmp4) &
            !$omp& default(private)
            !$omp do schedule(static)
            do j = 1, npt
               tmp14 = state%s5(j)
               tmp15 = state%s6(j)
               tmp16 = state%s7(j)
               tmp17 = state%s8(j)
               tmp18 = state%s9(j)
               tmp19 = state%s10(j)
               tmp20 = state%s12(j)
               tmp21 = -tmp15
               tmp24 = -tmp16
               tmp28 = -tmp18
               tmp13 = 0.0_wp
               !$omp simd &
               !$omp& private(tmp22, tmp23, tmp25, tmp26, tmp27, tmp29, tmp30, tmp31) &
               !$omp& private(tmp32, tmp33, tmp34, tmp35, tmp36, tmp37, tmp38, tmp39) &
               !$omp& private(tmp40) &
               !$omp& reduction(+: tmp13)
               do i = 1, j - 1
                  tmp22 = state%s6(i) + tmp21
                  tmp23 = tmp14*tmp22
                  tmp25 = state%s7(i) + tmp24
                  tmp26 = tmp25*tmp17
                  tmp27 = tmp23 + tmp26
                  tmp29 = state%s9(i) + tmp28
                  tmp30 = tmp29*tmp19
                  tmp31 = tmp27 + tmp30
                  tmp32 = tmp22**(2)
                  tmp33 = tmp25**(2)
                  tmp34 = tmp32 + tmp33
                  tmp35 = tmp29**(2)
                  tmp36 = tmp34 + tmp35
                  tmp37 = 1.0_wp/sqrt(tmp36)
                  tmp38 = tmp37**(3)
                  tmp39 = tmp31*tmp38
                  tmp40 = tmp39*state%s12(i)
                  tmp13 = tmp13 + tmp40
               end do
               !$omp simd &
               !$omp& private(tmp22, tmp23, tmp25, tmp26, tmp27, tmp29, tmp30, tmp31) &
               !$omp& private(tmp32, tmp33, tmp34, tmp35, tmp36, tmp37, tmp38, tmp39) &
               !$omp& private(tmp40) &
               !$omp& reduction(+: tmp13)
               do i = j + 1, npt
                  tmp22 = state%s6(i) + tmp21
                  tmp23 = tmp14*tmp22
                  tmp25 = state%s7(i) + tmp24
                  tmp26 = tmp25*tmp17
                  tmp27 = tmp23 + tmp26
                  tmp29 = state%s9(i) + tmp28
                  tmp30 = tmp29*tmp19
                  tmp31 = tmp27 + tmp30
                  tmp32 = tmp22**(2)
                  tmp33 = tmp25**(2)
                  tmp34 = tmp32 + tmp33
                  tmp35 = tmp29**(2)
                  tmp36 = tmp34 + tmp35
                  tmp37 = 1.0_wp/sqrt(tmp36)
                  tmp38 = tmp37**(3)
                  tmp39 = tmp31*tmp38
                  tmp40 = tmp39*state%s12(i)
                  tmp13 = tmp13 + tmp40
               end do
               tmp4(j) = tmp4(j) + tmp13
            end do
            !$omp end do
            !$omp end parallel
         end block
         tmp41 = state%s4*tmp4
         tmp42 = tmp3 + tmp41
         tmp43 = -tmp42
         tmp44 = vn + tmp43
         tmp45 = dot(grad_vn, tmp44)
         energy = energy + tmp45
      end if

      state%ready = 3
   end subroutine dpcm_original_point_mf_solve

end submodule pcmgen_point_dpcm_original_mf_energy
