   module subroutine dpcm_point_complex_param_weights(state, grad_eps, error)
      !> State of dpcm_point
      type(dpcm_point_complex_state), target, intent(inout) :: state
      !> Partial derivative of the energy with respect to eps
      complex(wp), intent(out) :: grad_eps
      !> Error handling
      type(error_type), allocatable, intent(out) :: error

      integer :: npt
      integer :: stat
      complex(wp), allocatable :: tmp2(:), tmp5(:), tmp6(:)
      complex(wp) :: tmp1, tmp3, tmp4, tmp7, tmp8, tmp9, tmp10

      if (state%matrix_free) then
         call dpcm_point_complex_mf_param_weights(state, grad_eps, error)
         return
