!> IEF-PCM (point charges) phases: energy; generated by pcmgen, do not edit
!>
!> - Procedures of pcmgen_point_iefpcm: iefpcm_point_assemble, iefpcm_point_medium,
!>   iefpcm_point_solve
submodule(pcmgen_point_iefpcm) pcmgen_point_iefpcm_energy
   implicit none(type, external)

contains

   module subroutine iefpcm_point_assemble(state, r, n, k1, k2, a, error, solver)
      !> State of iefpcm_point
      type(iefpcm_point_state), target, intent(inout) :: state
      !> Positions of the surface points
      real(wp), contiguous, intent(in) :: r(:, :)
      !> Outward unit normals at the surface points
      real(wp), contiguous, intent(in) :: n(:, :)
      !> First principal curvature (positive where convex)
      real(wp), contiguous, intent(in) :: k1(:)
      !> Second principal curvature (positive where convex)
      real(wp), contiguous, intent(in) :: k2(:)
      !> Grid point areas
      real(wp), contiguous, intent(in) :: a(:)
      !> Error handling
      type(error_type), allocatable, intent(out) :: error
      !> Linear solver
      class(pcm_solver), intent(in), optional :: solver

      integer :: npt
      integer :: stat
      real(wp) :: tmp16, tmp17, tmp18, tmp19, tmp54, tmp55, tmp56, tmp57, tmp58, tmp59
      integer :: i, j

      if (present(solver)) then
         if (solver%matrix_free(size(r, 2), 2)) then
            call iefpcm_point_mf_assemble(state, r, n, k1, k2, a, error, solver)
            return
         end if
      end if
      stat = 0
      npt = size(r, 2)
      if (npt < 1) then
         call fatal_error(error, "[iefpcm_point_assemble] empty discretization")
         return
      end if
      if (any(shape(r) /= [3, npt])) then
         call fatal_error(error, "[iefpcm_point_assemble] r: wrong shape")
         return
      end if
      if (any(shape(n) /= [3, npt])) then
         call fatal_error(error, "[iefpcm_point_assemble] n: wrong shape")
         return
      end if
      if (any(shape(k1) /= [npt])) then
         call fatal_error(error, "[iefpcm_point_assemble] k1: wrong shape")
         return
      end if
      if (any(shape(k2) /= [npt])) then
         call fatal_error(error, "[iefpcm_point_assemble] k2: wrong shape")
         return
      end if
      if (any(shape(a) /= [npt])) then
         call fatal_error(error, "[iefpcm_point_assemble] a: wrong shape")
         return
      end if
      state%ready = 0
      if (allocated(state%solver)) deallocate (state%solver)
      if (allocated(state%v)) deallocate (state%v)
      if (allocated(state%r)) deallocate (state%r)
      if (allocated(state%s4)) deallocate (state%s4)
      if (allocated(state%s5)) deallocate (state%s5)
      if (allocated(state%s6)) deallocate (state%s6)
      if (allocated(state%a)) deallocate (state%a)
      if (allocated(state%s7)) deallocate (state%s7)
      if (allocated(state%s9)) deallocate (state%s9)
      if (allocated(state%s10)) deallocate (state%s10)
      if (allocated(state%s11)) deallocate (state%s11)
      if (allocated(state%k1)) deallocate (state%k1)
      if (allocated(state%k2)) deallocate (state%k2)
      if (allocated(state%s12)) deallocate (state%s12)
      if (allocated(state%s13)) deallocate (state%s13)
      if (allocated(state%s14)) deallocate (state%s14)
      if (allocated(state%s16)) deallocate (state%s16)
      if (allocated(state%s18)) deallocate (state%s18)
      if (allocated(state%s19)) deallocate (state%s19)
      if (allocated(state%s20)) deallocate (state%s20)
      if (allocated(state%s21)) deallocate (state%s21)
      if (allocated(state%s23)) deallocate (state%s23)
      if (allocated(state%s25)) deallocate (state%s25)
      if (allocated(state%s26)) deallocate (state%s26)
      if (allocated(state%s27)) deallocate (state%s27)
      if (allocated(state%s28)) deallocate (state%s28)
      if (allocated(state%s29)) deallocate (state%s29)
      if (allocated(state%s30)) deallocate (state%s30)
      if (allocated(state%s31)) deallocate (state%s31)
      if (allocated(state%s32)) deallocate (state%s32)
      if (allocated(state%n)) deallocate (state%n)
      state%npt = npt
      if (present(solver)) then
         allocate (state%solver, source=solver, stat=stat)
      else
         allocate (pcm_dense_solver :: state%solver, stat=stat)
      end if
      if (stat == 0) allocate (state%v(npt), stat=stat)
      if (stat == 0) allocate (state%r(3, npt), stat=stat)
      if (stat == 0) allocate (state%s4(npt), stat=stat)
      if (stat == 0) allocate (state%s5(npt), stat=stat)
      if (stat == 0) allocate (state%s6(npt), stat=stat)
      if (stat == 0) allocate (state%a(npt), stat=stat)
      if (stat == 0) allocate (state%s7(npt, npt), stat=stat)
      if (stat == 0) allocate (state%s9(npt), stat=stat)
      if (stat == 0) allocate (state%s10(npt), stat=stat)
      if (stat == 0) allocate (state%s11(npt), stat=stat)
      if (stat == 0) allocate (state%k1(npt), stat=stat)
      if (stat == 0) allocate (state%k2(npt), stat=stat)
      if (stat == 0) allocate (state%s12(npt, npt), stat=stat)
      if (stat == 0) allocate (state%s13(npt), stat=stat)
      if (stat == 0) allocate (state%s14(npt), stat=stat)
      if (stat == 0) allocate (state%s16(npt), stat=stat)
      if (stat == 0) allocate (state%s18(npt), stat=stat)
      if (stat == 0) allocate (state%s19(npt), stat=stat)
      if (stat == 0) allocate (state%s20(npt), stat=stat)
      if (stat == 0) allocate (state%s21(npt), stat=stat)
      if (stat == 0) allocate (state%s23(npt), stat=stat)
      if (stat == 0) allocate (state%s25(npt), stat=stat)
      if (stat == 0) allocate (state%s26(npt), stat=stat)
      if (stat == 0) allocate (state%s27(npt), stat=stat)
      if (stat == 0) allocate (state%s28(npt), stat=stat)
      if (stat == 0) allocate (state%s29(npt), stat=stat)
      if (stat == 0) allocate (state%s30(npt), stat=stat)
      if (stat == 0) allocate (state%s31(npt), stat=stat)
      if (stat == 0) allocate (state%s32(npt), stat=stat)
      if (stat /= 0) then
         call fatal_error(error, "[iefpcm_point_assemble] allocation failed")
         return
      end if
      state%s14 = 0.0_wp
      state%s16 = 0.0_wp
      call state%solver%reset(iefpcm_point_n_operators)
      state%matrix_free = .false.

      state%r = r
      state%a = a
      state%k1 = k1
      state%k2 = k2
      state%s4 = state%r(1, :)
      state%s5 = state%r(2, :)
      state%s6 = state%r(3, :)
      block
         real(wp) :: tmp1, tmp2, tmp3, tmp4, tmp7, tmp11, tmp5, tmp6, tmp8, tmp9, tmp10, tmp12, &
                     tmp13, tmp14, tmp15

         !$omp parallel &
         !$omp& private(i, j) &
         !$omp& shared(npt, state) &
         !$omp& default(private)
         !$omp do schedule(dynamic, 16)
         do j = 2, npt
            tmp1 = state%s4(j)
            tmp2 = state%s5(j)
            tmp3 = state%s6(j)
            tmp4 = -tmp1
            tmp7 = -tmp2
            tmp11 = -tmp3
            !$omp simd &
            !$omp& private(tmp5, tmp6, tmp8, tmp9, tmp10, tmp12, tmp13, tmp14) &
            !$omp& private(tmp15)
            do i = 1, j - 1
               tmp5 = state%s4(i) + tmp4
               tmp6 = tmp5**(2)
               tmp8 = state%s5(i) + tmp7
               tmp9 = tmp8**(2)
               tmp10 = tmp6 + tmp9
               tmp12 = state%s6(i) + tmp11
               tmp13 = tmp12**(2)
               tmp14 = tmp10 + tmp13
               tmp15 = 1.0_wp/sqrt(tmp14)
               state%s7(i, j) = tmp15
               state%s7(j, i) = tmp15
            end do
         end do
         !$omp end do
         !$omp end parallel
      end block
      do i = 1, npt
         tmp16 = 1.0_wp/state%a(i)
         tmp17 = 12.566370614359172_wp*tmp16
         tmp18 = sqrt(tmp17)
         tmp19 = 1.0694_wp*tmp18
         state%s7(i, i) = tmp19
      end do
      state%s9 = n(1, :)
      state%s10 = n(2, :)
      state%s11 = n(3, :)
      block
         real(wp) :: tmp20, tmp21, tmp22, tmp23, tmp24, tmp25, tmp26, tmp29, tmp33, tmp27, tmp28, &
                     tmp30, tmp31, tmp32, tmp34, tmp35, tmp36, tmp37, tmp38, tmp39, tmp40, tmp41, &
                     tmp42, tmp43, tmp44, tmp45, tmp46, tmp47, tmp48, tmp49, tmp50, tmp51, tmp52, &
                     tmp53

         !$omp parallel &
         !$omp& private(i, j) &
         !$omp& shared(npt, state) &
         !$omp& default(private)
         !$omp do schedule(dynamic, 16)
         do j = 2, npt
            tmp20 = state%s9(j)
            tmp21 = state%s4(j)
            tmp22 = state%s5(j)
            tmp23 = state%s10(j)
            tmp24 = state%s6(j)
            tmp25 = state%s11(j)
            tmp26 = -tmp21
            tmp29 = -tmp22
            tmp33 = -tmp24
            !$omp simd &
            !$omp& private(tmp27, tmp28, tmp30, tmp31, tmp32, tmp34, tmp35, tmp36) &
            !$omp& private(tmp37, tmp38, tmp39, tmp40, tmp41, tmp42, tmp43, tmp44) &
            !$omp& private(tmp45, tmp46, tmp47, tmp48, tmp49, tmp50, tmp51, tmp52) &
            !$omp& private(tmp53)
            do i = 1, j - 1
               tmp27 = state%s4(i) + tmp26
               tmp28 = tmp20*tmp27
               tmp30 = state%s5(i) + tmp29
               tmp31 = tmp30*tmp23
               tmp32 = tmp28 + tmp31
               tmp34 = state%s6(i) + tmp33
               tmp35 = tmp34*tmp25
               tmp36 = tmp32 + tmp35
               tmp37 = tmp27**(2)
               tmp38 = tmp30**(2)
               tmp39 = tmp37 + tmp38
               tmp40 = tmp34**(2)
               tmp41 = tmp39 + tmp40
               tmp42 = 1.0_wp/sqrt(tmp41)
               tmp43 = tmp42**(3)
               tmp44 = tmp36*tmp43
               state%s12(i, j) = tmp44
               tmp45 = -tmp27
               tmp46 = state%s9(i)*tmp45
               tmp47 = -tmp30
               tmp48 = tmp47*state%s10(i)
               tmp49 = tmp46 + tmp48
               tmp50 = -tmp34
               tmp51 = tmp50*state%s11(i)
               tmp52 = tmp49 + tmp51
               tmp53 = tmp52*tmp43
               state%s12(j, i) = tmp53
            end do
         end do
         !$omp end do
         !$omp end parallel
      end block
      do i = 1, npt
         tmp54 = state%k1(i) + state%k2(i)
         tmp55 = 1.0_wp/state%a(i)
         tmp56 = 12.566370614359172_wp*tmp55
         tmp57 = sqrt(tmp56)
         tmp58 = tmp54*tmp57
         tmp59 = (-0.26735_wp)*tmp58
         state%s12(i, i) = tmp59
      end do

      state%ready = 1
      state%assembled = state%assembled + 1
   end subroutine iefpcm_point_assemble

   module subroutine iefpcm_point_medium(state, eps, error)
      !> State of iefpcm_point
      type(iefpcm_point_state), target, intent(inout) :: state
      !> Relative permittivity of the solvent (inf for a conductor)
      real(wp), intent(in) :: eps
      !> Error handling
      type(error_type), allocatable, intent(out) :: error

      integer :: npt
      integer :: stat
      real(wp) :: tmp1, tmp2

      if (state%matrix_free) then
         call iefpcm_point_mf_medium(state, eps, error)
         return
      end if
      stat = 0
      npt = state%npt
      if (state%ready < 1) then
         call fatal_error(error, "[iefpcm_point_medium] call iefpcm_point_assemble first")
         return
      end if
      state%ready = 1
      ! Inputs that do not enter these outputs
      associate (unused1 => eps)
      end associate

      state%op1%npt = npt
      state%op1%npoint = npt
      state%op1%id = 1
      state%op1%points => state%r
      state%op1%a => state%a
      state%op1%c1 => state%s7
      state%s1 = eps + 1.0_wp
      tmp1 = 1.0_wp/state%s1
      tmp2 = (-2.0_wp)*tmp1
      state%s2 = 1.0_wp + tmp2
      state%s8 = (-0.15915494309189535_wp)*state%s2
      state%op1%c2 = state%s8
      state%op1%c3 => state%s12
      call state%solver%setup(state%op1, error)
      if (allocated(error)) return
      state%s3 = -state%s2
      state%s15 = (-0.5_wp)*state%s2
      state%s17 = 0.07957747154594767_wp*state%s2
      state%s24 = 0.5_wp*state%s2

      state%ready = 2
   end subroutine iefpcm_point_medium

   module subroutine iefpcm_point_solve(state, v, energy, q, grad_v, error)
      !> State of iefpcm_point
      type(iefpcm_point_state), target, intent(inout) :: state
      !> Solute electrostatic potential at the surface points
      real(wp), contiguous, intent(in) :: v(:)
      !> Solvation energy
      real(wp), intent(out) :: energy
      !> Apparent surface charges
      real(wp), contiguous, intent(out) :: q(:)
      !> Partial derivative of the energy with respect to v
      real(wp), contiguous, intent(out) :: grad_v(:)
      !> Error handling
      type(error_type), allocatable, intent(out) :: error

      integer :: npt
      integer :: stat
      real(wp), allocatable :: tmp1(:), tmp2(:), tmp3(:), tmp5(:), tmp6(:), tmp7(:), tmp8(:), &
                               tmp9(:), tmp10(:), tmp11(:), tmp12(:), tmp13(:)
      real(wp) :: tmp4, tmp14

      if (state%matrix_free) then
         call iefpcm_point_mf_solve(state, v, energy, q, grad_v, error)
         return
      end if
      stat = 0
      npt = state%npt
      if (state%ready < 2) then
         call fatal_error(error, "[iefpcm_point_solve] call iefpcm_point_medium first")
         return
      end if
      if (any(shape(v) /= [npt])) then
         call fatal_error(error, "[iefpcm_point_solve] v: wrong shape")
         return
      end if
      if (any(shape(q) /= [npt])) then
         call fatal_error(error, "[iefpcm_point_solve] q: wrong shape")
         return
      end if
      if (any(shape(grad_v) /= [npt])) then
         call fatal_error(error, "[iefpcm_point_solve] grad_v: wrong shape")
         return
      end if
      allocate (tmp1(npt), stat=stat)
      if (stat == 0) allocate (tmp2(npt), stat=stat)
      if (stat == 0) allocate (tmp3(npt), stat=stat)
      if (stat == 0) allocate (tmp5(npt), stat=stat)
      if (stat == 0) allocate (tmp6(npt), stat=stat)
      if (stat == 0) allocate (tmp7(npt), stat=stat)
      if (stat == 0) allocate (tmp8(npt), stat=stat)
      if (stat == 0) allocate (tmp9(npt), stat=stat)
      if (stat == 0) allocate (tmp10(npt), stat=stat)
      if (stat == 0) allocate (tmp11(npt), stat=stat)
      if (stat == 0) allocate (tmp12(npt), stat=stat)
      if (stat == 0) allocate (tmp13(npt), stat=stat)
      if (stat /= 0) then
         call fatal_error(error, "[iefpcm_point_solve] allocation failed")
         return
      end if
      state%ready = 2

      state%op1%points => state%r
      state%op1%a => state%a
      state%op1%c1 => state%s7
      state%op1%c3 => state%s12
      state%v = v
      state%s13 = state%a*state%v
      call gemv(state%s12, state%s13, tmp1)
      tmp2 = (-0.15915494309189535_wp)*tmp1
      tmp3 = state%v + tmp2
      call state%solver%solve(state%op1, .false., tmp3, state%s14, error)
      if (allocated(error)) return
      call state%solver%solve(state%op1, .true., state%v, state%s16, error)
      if (allocated(error)) return
      state%s18 = state%s17*state%s16
      call gemv(state%s12, state%s18, state%s19, trans="t")
      call gemv(state%s7, state%s14, state%s20)
      state%s21 = state%a*state%s20
      state%s25 = state%s24*state%s16
      q = state%s3*state%s14
      tmp4 = dot(state%v, q)
      energy = 0.5_wp*tmp4
      tmp5 = state%s15*state%s14
      tmp6 = state%s15*state%s16
      tmp7 = tmp5 + tmp6
      tmp8 = state%s19*state%a
      grad_v = tmp7 + tmp8
      if (state%solver%inexact()) then
         ! First-order correction for the residuals of the solves
         call gemv(state%s12, state%s21, tmp9)
         tmp10 = state%s8*tmp9
         tmp11 = state%s20 + tmp10
         tmp12 = -tmp11
         tmp13 = tmp3 + tmp12
         tmp14 = dot(tmp6, tmp13)
         energy = energy + tmp14
      end if

      state%ready = 3
   end subroutine iefpcm_point_solve

end submodule pcmgen_point_iefpcm_energy
