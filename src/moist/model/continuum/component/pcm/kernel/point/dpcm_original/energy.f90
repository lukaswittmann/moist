!> DPCM, original form (point charges) phases: energy; generated by pcmgen, do not edit
!>
!> - Procedures of pcmgen_point_dpcm_original: dpcm_original_point_assemble,
!>   dpcm_original_point_medium, dpcm_original_point_solve
submodule(pcmgen_point_dpcm_original) pcmgen_point_dpcm_original_energy
   implicit none(type, external)

contains

   module subroutine dpcm_original_point_assemble(state, r, n, k1, k2, a, error, solver)
      !> State of dpcm_original_point
      type(dpcm_original_point_state), target, intent(inout) :: state
      !> Positions of the surface points
      real(wp), contiguous, intent(in) :: r(:, :)
      !> Outward unit normals at the surface points
      real(wp), contiguous, intent(in) :: n(:, :)
      !> First principal curvature (positive where convex)
      real(wp), contiguous, intent(in) :: k1(:)
      !> Second principal curvature (positive where convex)
      real(wp), contiguous, intent(in) :: k2(:)
      !> Grid point areas
      real(wp), contiguous, intent(in) :: a(:)
      !> Error handling
      type(error_type), allocatable, intent(out) :: error
      !> Linear solver
      class(pcm_solver), intent(in), optional :: solver

      integer :: npt
      integer :: stat
      real(wp) :: tmp1, tmp36, tmp37, tmp38, tmp39, tmp40, tmp41
      integer :: i, j

      if (present(solver)) then
         if (solver%matrix_free(size(r, 2), 1)) then
            call dpcm_original_point_mf_assemble(state, r, n, k1, k2, a, error, solver)
            return
         end if
      end if
      stat = 0
      npt = size(r, 2)
      if (npt < 1) then
         call fatal_error(error, "[dpcm_original_point_assemble] empty discretization")
         return
      end if
      if (any(shape(r) /= [3, npt])) then
         call fatal_error(error, "[dpcm_original_point_assemble] r: wrong shape")
         return
      end if
      if (any(shape(n) /= [3, npt])) then
         call fatal_error(error, "[dpcm_original_point_assemble] n: wrong shape")
         return
      end if
      if (any(shape(k1) /= [npt])) then
         call fatal_error(error, "[dpcm_original_point_assemble] k1: wrong shape")
         return
      end if
      if (any(shape(k2) /= [npt])) then
         call fatal_error(error, "[dpcm_original_point_assemble] k2: wrong shape")
         return
      end if
      if (any(shape(a) /= [npt])) then
         call fatal_error(error, "[dpcm_original_point_assemble] a: wrong shape")
         return
      end if
      state%ready = 0
      if (allocated(state%solver)) deallocate (state%solver)
      if (allocated(state%v)) deallocate (state%v)
      if (allocated(state%a)) deallocate (state%a)
      if (allocated(state%s3)) deallocate (state%s3)
      if (allocated(state%s5)) deallocate (state%s5)
      if (allocated(state%r)) deallocate (state%r)
      if (allocated(state%s6)) deallocate (state%s6)
      if (allocated(state%s7)) deallocate (state%s7)
      if (allocated(state%s8)) deallocate (state%s8)
      if (allocated(state%s9)) deallocate (state%s9)
      if (allocated(state%s10)) deallocate (state%s10)
      if (allocated(state%k1)) deallocate (state%k1)
      if (allocated(state%k2)) deallocate (state%k2)
      if (allocated(state%s11)) deallocate (state%s11)
      if (allocated(state%s12)) deallocate (state%s12)
      if (allocated(state%s14)) deallocate (state%s14)
      if (allocated(state%s16)) deallocate (state%s16)
      if (allocated(state%s17)) deallocate (state%s17)
      if (allocated(state%s18)) deallocate (state%s18)
      if (allocated(state%s19)) deallocate (state%s19)
      if (allocated(state%s21)) deallocate (state%s21)
      if (allocated(state%s22)) deallocate (state%s22)
      if (allocated(state%s23)) deallocate (state%s23)
      if (allocated(state%n)) deallocate (state%n)
      state%npt = npt
      if (present(solver)) then
         allocate (state%solver, source=solver, stat=stat)
      else
         allocate (pcm_dense_solver :: state%solver, stat=stat)
      end if
      if (stat == 0) allocate (state%v(npt), stat=stat)
      if (stat == 0) allocate (state%a(npt), stat=stat)
      if (stat == 0) allocate (state%s3(npt), stat=stat)
      if (stat == 0) allocate (state%s5(npt), stat=stat)
      if (stat == 0) allocate (state%r(3, npt), stat=stat)
      if (stat == 0) allocate (state%s6(npt), stat=stat)
      if (stat == 0) allocate (state%s7(npt), stat=stat)
      if (stat == 0) allocate (state%s8(npt), stat=stat)
      if (stat == 0) allocate (state%s9(npt), stat=stat)
      if (stat == 0) allocate (state%s10(npt), stat=stat)
      if (stat == 0) allocate (state%k1(npt), stat=stat)
      if (stat == 0) allocate (state%k2(npt), stat=stat)
      if (stat == 0) allocate (state%s11(npt, npt), stat=stat)
      if (stat == 0) allocate (state%s12(npt), stat=stat)
      if (stat == 0) allocate (state%s14(npt), stat=stat)
      if (stat == 0) allocate (state%s16(npt), stat=stat)
      if (stat == 0) allocate (state%s17(npt), stat=stat)
      if (stat == 0) allocate (state%s18(npt), stat=stat)
      if (stat == 0) allocate (state%s19(npt), stat=stat)
      if (stat == 0) allocate (state%s21(npt), stat=stat)
      if (stat == 0) allocate (state%s22(npt), stat=stat)
      if (stat == 0) allocate (state%s23(npt), stat=stat)
      if (stat /= 0) then
         call fatal_error(error, "[dpcm_original_point_assemble] allocation failed")
         return
      end if
      state%s12 = 0.0_wp
      state%s14 = 0.0_wp
      call state%solver%reset(dpcm_original_point_n_operators)
      state%matrix_free = .false.

      state%a = a
      state%r = r
      state%k1 = k1
      state%k2 = k2
      do i = 1, npt
         tmp1 = 1.0_wp/state%a(i)
         state%s3(i) = tmp1
      end do
      state%s5 = n(1, :)
      state%s6 = state%r(1, :)
      state%s7 = state%r(2, :)
      state%s8 = n(2, :)
      state%s9 = state%r(3, :)
      state%s10 = n(3, :)
      block
         real(wp) :: tmp2, tmp3, tmp4, tmp5, tmp6, tmp7, tmp8, tmp11, tmp15, tmp9, tmp10, tmp12, &
                     tmp13, tmp14, tmp16, tmp17, tmp18, tmp19, tmp20, tmp21, tmp22, tmp23, tmp24, &
                     tmp25, tmp26, tmp27, tmp28, tmp29, tmp30, tmp31, tmp32, tmp33, tmp34, tmp35

         !$omp parallel &
         !$omp& private(i, j) &
         !$omp& shared(npt, state) &
         !$omp& default(private)
         !$omp do schedule(dynamic, 16)
         do j = 2, npt
            tmp2 = state%s5(j)
            tmp3 = state%s6(j)
            tmp4 = state%s7(j)
            tmp5 = state%s8(j)
            tmp6 = state%s9(j)
            tmp7 = state%s10(j)
            tmp8 = -tmp3
            tmp11 = -tmp4
            tmp15 = -tmp6
            !$omp simd &
            !$omp& private(tmp9, tmp10, tmp12, tmp13, tmp14, tmp16, tmp17, tmp18) &
            !$omp& private(tmp19, tmp20, tmp21, tmp22, tmp23, tmp24, tmp25, tmp26) &
            !$omp& private(tmp27, tmp28, tmp29, tmp30, tmp31, tmp32, tmp33, tmp34) &
            !$omp& private(tmp35)
            do i = 1, j - 1
               tmp9 = state%s6(i) + tmp8
               tmp10 = tmp2*tmp9
               tmp12 = state%s7(i) + tmp11
               tmp13 = tmp12*tmp5
               tmp14 = tmp10 + tmp13
               tmp16 = state%s9(i) + tmp15
               tmp17 = tmp16*tmp7
               tmp18 = tmp14 + tmp17
               tmp19 = tmp9**(2)
               tmp20 = tmp12**(2)
               tmp21 = tmp19 + tmp20
               tmp22 = tmp16**(2)
               tmp23 = tmp21 + tmp22
               tmp24 = 1.0_wp/sqrt(tmp23)
               tmp25 = tmp24**(3)
               tmp26 = tmp18*tmp25
               state%s11(i, j) = tmp26
               tmp27 = -tmp9
               tmp28 = state%s5(i)*tmp27
               tmp29 = -tmp12
               tmp30 = tmp29*state%s8(i)
               tmp31 = tmp28 + tmp30
               tmp32 = -tmp16
               tmp33 = tmp32*state%s10(i)
               tmp34 = tmp31 + tmp33
               tmp35 = tmp34*tmp25
               state%s11(j, i) = tmp35
            end do
         end do
         !$omp end do
         !$omp end parallel
      end block
      do i = 1, npt
         tmp36 = state%k1(i) + state%k2(i)
         tmp37 = 1.0_wp/state%a(i)
         tmp38 = 12.566370614359172_wp*tmp37
         tmp39 = sqrt(tmp38)
         tmp40 = tmp36*tmp39
         tmp41 = (-0.26735_wp)*tmp40
         state%s11(i, i) = tmp41
      end do

      state%ready = 1
      state%assembled = state%assembled + 1
   end subroutine dpcm_original_point_assemble

   module subroutine dpcm_original_point_medium(state, eps, error)
      !> State of dpcm_original_point
      type(dpcm_original_point_state), target, intent(inout) :: state
      !> Relative permittivity of the solvent (inf for a conductor)
      real(wp), intent(in) :: eps
      !> Error handling
      type(error_type), allocatable, intent(out) :: error

      integer :: npt
      integer :: stat
      real(wp) :: tmp1, tmp2

      if (state%matrix_free) then
         call dpcm_original_point_mf_medium(state, eps, error)
         return
      end if
      stat = 0
      npt = state%npt
      if (state%ready < 1) then
         call fatal_error(error, &
                          "[dpcm_original_point_medium] call dpcm_original_point_assemble first")
         return
      end if
      state%ready = 1
      ! Inputs that do not enter these outputs
      associate (unused1 => eps)
      end associate

      state%op1%npt = npt
      state%op1%npoint = npt
      state%op1%id = 1
      state%op1%points => state%r
      state%op1%c1 => state%s3
      state%s1 = eps + 1.0_wp
      tmp1 = 1.0_wp/state%s1
      tmp2 = (-2.0_wp)*tmp1
      state%s2 = 1.0_wp + tmp2
      state%s4 = -state%s2
      state%op1%c2 = state%s4
      state%op1%c3 => state%s11
      call state%solver%setup(state%op1, error)
      if (allocated(error)) return
      state%s13 = 0.5_wp*state%s2

      state%ready = 2
   end subroutine dpcm_original_point_medium

   module subroutine dpcm_original_point_solve(state, v, vn, energy, q, grad_v, grad_vn, error)
      !> State of dpcm_original_point
      type(dpcm_original_point_state), target, intent(inout) :: state
      !> Solute electrostatic potential at the surface points
      real(wp), contiguous, intent(in) :: v(:)
      !> Outward normal derivative of the solute potential at the surface points
      real(wp), contiguous, intent(in) :: vn(:)
      !> Solvation energy
      real(wp), intent(out) :: energy
      !> Apparent surface charges
      real(wp), contiguous, intent(out) :: q(:)
      !> Partial derivative of the energy with respect to v
      real(wp), contiguous, intent(out) :: grad_v(:)
      !> Partial derivative of the energy with respect to vn
      real(wp), contiguous, intent(out) :: grad_vn(:)
      !> Error handling
      type(error_type), allocatable, intent(out) :: error

      integer :: npt
      integer :: stat
      real(wp), allocatable :: tmp2(:), tmp3(:), tmp4(:), tmp5(:), tmp6(:), tmp7(:), tmp8(:)
      real(wp) :: tmp1, tmp9

      if (state%matrix_free) then
         call dpcm_original_point_mf_solve(state, v, vn, energy, q, grad_v, grad_vn, error)
         return
      end if
      stat = 0
      npt = state%npt
      if (state%ready < 2) then
         call fatal_error(error, &
                          "[dpcm_original_point_solve] call dpcm_original_point_medium first")
         return
      end if
      if (any(shape(v) /= [npt])) then
         call fatal_error(error, "[dpcm_original_point_solve] v: wrong shape")
         return
      end if
      if (any(shape(vn) /= [npt])) then
         call fatal_error(error, "[dpcm_original_point_solve] vn: wrong shape")
         return
      end if
      if (any(shape(q) /= [npt])) then
         call fatal_error(error, "[dpcm_original_point_solve] q: wrong shape")
         return
      end if
      if (any(shape(grad_v) /= [npt])) then
         call fatal_error(error, "[dpcm_original_point_solve] grad_v: wrong shape")
         return
      end if
      if (any(shape(grad_vn) /= [npt])) then
         call fatal_error(error, "[dpcm_original_point_solve] grad_vn: wrong shape")
         return
      end if
      allocate (tmp2(npt), stat=stat)
      if (stat == 0) allocate (tmp3(npt), stat=stat)
      if (stat == 0) allocate (tmp4(npt), stat=stat)
      if (stat == 0) allocate (tmp5(npt), stat=stat)
      if (stat == 0) allocate (tmp6(npt), stat=stat)
      if (stat == 0) allocate (tmp7(npt), stat=stat)
      if (stat == 0) allocate (tmp8(npt), stat=stat)
      if (stat /= 0) then
         call fatal_error(error, "[dpcm_original_point_solve] allocation failed")
         return
      end if
      state%ready = 2

      state%op1%points => state%r
      state%op1%c1 => state%s3
      state%op1%c3 => state%s11
      state%v = v
      call state%solver%solve(state%op1, .false., vn, state%s12, error)
      if (allocated(error)) return
      call state%solver%solve(state%op1, .true., state%v, state%s14, error)
      if (allocated(error)) return
      q = state%s2*state%s12
      tmp1 = dot(state%v, q)
      energy = 0.5_wp*tmp1
      grad_v = state%s13*state%s12
      grad_vn = state%s13*state%s14
      if (state%solver%inexact()) then
         ! First-order correction for the residuals of the solves
         tmp2 = state%s3*state%s12
         tmp3 = 6.283185307179586_wp*tmp2
         call gemv(state%s11, state%s12, tmp4, trans="t")
         tmp5 = state%s4*tmp4
         tmp6 = tmp3 + tmp5
         tmp7 = -tmp6
         tmp8 = vn + tmp7
         tmp9 = dot(grad_vn, tmp8)
         energy = energy + tmp9
      end if

      state%ready = 3
   end subroutine dpcm_original_point_solve

end submodule pcmgen_point_dpcm_original_energy
