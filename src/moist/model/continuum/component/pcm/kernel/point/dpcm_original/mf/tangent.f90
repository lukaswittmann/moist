      end if
      if (any(shape(hvp_vn) /= [npt, nblk])) then
         call fatal_error(error, "[dpcm_original_point_mf_response] hvp_vn: wrong shape")
         return
      end if
      do blk = 1, nblk
         call dpcm_original_point_mf_response_one(state, dv(:, blk), dvn(:, blk), hvp_v(:, blk), &
                                                  hvp_vn(:, blk), error)
         if (allocated(error)) return
      end do
   end subroutine dpcm_original_point_mf_response

   !> One direction of dpcm_original_point_mf_response
   !>
   !> - Vectors have length npt, matrices are (npt, npt), point fields (3, npt)
   !> - Outputs are undefined if error is allocated
   !>
   !> @param[in,out] state  state of dpcm_original_point
   !> @param[in] dv  direction for v
   !> @param[in] dvn  direction for vn
   !> @param[out] hvp_v  hessian times direction, v block
   !> @param[out] hvp_vn  hessian times direction, vn block
   !> @param[out] error  error handling; allocated on failure
   subroutine dpcm_original_point_mf_response_one(state, dv, dvn, hvp_v, hvp_vn, error)
      !> State of dpcm_original_point
      type(dpcm_original_point_state), target, intent(inout) :: state
      !> Direction for v
      real(wp), contiguous, intent(in) :: dv(:)
      !> Direction for vn
      real(wp), contiguous, intent(in) :: dvn(:)
      !> Hessian times direction, v block
      real(wp), contiguous, intent(out) :: hvp_v(:)
      !> Hessian times direction, vn block
      real(wp), contiguous, intent(out) :: hvp_vn(:)
      !> Error handling
      type(error_type), allocatable, intent(out) :: error

      integer :: npt
      integer :: stat
      real(wp), allocatable :: tmp1(:), tmp2(:)

      stat = 0
      npt = state%npt
      if (any(shape(dv) /= [npt])) then
         call fatal_error(error, "[dpcm_original_point_mf_response_one] dv: wrong shape")
         return
      end if
      if (any(shape(dvn) /= [npt])) then
         call fatal_error(error, "[dpcm_original_point_mf_response_one] dvn: wrong shape")
         return
      end if
      if (any(shape(hvp_v) /= [npt])) then
         call fatal_error(error, "[dpcm_original_point_mf_response_one] hvp_v: wrong shape")
         return
      end if
      if (any(shape(hvp_vn) /= [npt])) then
         call fatal_error(error, "[dpcm_original_point_mf_response_one] hvp_vn: wrong shape")
         return
      end if
      allocate (tmp1(npt), stat=stat)
      if (stat == 0) allocate (tmp2(npt), stat=stat)
      if (stat /= 0) then
         call fatal_error(error, "[dpcm_original_point_mf_response_one] allocation failed")
         return
      end if

      state%op2%points => state%r
      state%op2%r => state%r
      state%op2%n => state%n
      state%op2%k1 => state%k1
      state%op2%k2 => state%k2
      state%op2%a => state%a
      state%op2%c1 => state%s3
      tmp1 = 0.0_wp
      call state%solver%solve(state%op2, .false., dvn, tmp1, error)
      if (allocated(error)) return
      hvp_v = state%s13*tmp1
      tmp2 = 0.0_wp
      call state%solver%solve(state%op2, .true., dv, tmp2, error)
      if (allocated(error)) return
      hvp_vn = state%s13*tmp2
   end subroutine dpcm_original_point_mf_response_one

end submodule pcmgen_point_dpcm_original_mf_tangent
