   module subroutine ssvpe_point_param_weights(state, grad_eps, error)
      !> State of ssvpe_point
      type(ssvpe_point_state), target, intent(inout) :: state
      !> Partial derivative of the energy with respect to eps
      real(wp), intent(out) :: grad_eps
      !> Error handling
      type(error_type), allocatable, intent(out) :: error

      integer :: npt
      integer :: stat
      real(wp), allocatable :: tmp1(:), tmp2(:), tmp3(:), tmp6(:)
      real(wp) :: tmp4, tmp5, tmp7, tmp8, tmp9, tmp10, tmp11

      if (state%matrix_free) then
         call ssvpe_point_mf_param_weights(state, grad_eps, error)
         return
      end if
      stat = 0
      npt = state%npt
      if (state%ready < 3) then
         call fatal_error(error, "[ssvpe_point_param_weights] call ssvpe_point_solve first")
         return
      end if
      allocate (tmp1(npt), stat=stat)
      if (stat == 0) allocate (tmp2(npt), stat=stat)
      if (stat == 0) allocate (tmp3(npt), stat=stat)
      if (stat == 0) allocate (tmp6(npt), stat=stat)
      if (stat /= 0) then
         call fatal_error(error, "[ssvpe_point_param_weights] allocation failed")
         return
      end if

      state%op1%points => state%r
      state%op1%a => state%a
      state%op1%c1 => state%s7
      state%op1%c3 => state%s12
      call gemv(state%s12, state%s21, tmp1)
      call gemv(state%s7, state%s23, tmp2, trans="t")
      tmp3 = tmp1 + tmp2
      tmp4 = dot(state%s29, tmp3)
      tmp5 = (-0.07957747154594767_wp)*tmp4
      tmp6 = 0.5_wp*state%v
      tmp7 = dot(tmp6, state%s14)
      tmp8 = -tmp7
      tmp9 = tmp5 + tmp8
      tmp10 = state%s1**(-2)
      tmp11 = tmp9*tmp10
      grad_eps = 2.0_wp*tmp11
   end subroutine ssvpe_point_param_weights

