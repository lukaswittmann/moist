!> SLIC (point charges) phases: mf/energy; generated by pcmgen, do not edit
!>
!> - Procedures of pcmgen_point_slic: slic_point_mf_assemble, slic_point_mf_medium,
!>   slic_point_mf_solve
submodule(pcmgen_point_slic) pcmgen_point_slic_mf_energy
   implicit none(type, external)

contains

   module subroutine slic_point_mf_assemble(state, r, n, k1, k2, a, error, solver)
      !> State of slic_point
      type(slic_point_state), target, intent(inout) :: state
      !> Positions of the surface points
      real(wp), contiguous, intent(in) :: r(:, :)
      !> Outward unit normals at the surface points
      real(wp), contiguous, intent(in) :: n(:, :)
      !> First principal curvature (positive where convex)
      real(wp), contiguous, intent(in) :: k1(:)
      !> Second principal curvature (positive where convex)
      real(wp), contiguous, intent(in) :: k2(:)
      !> Grid point areas
      real(wp), contiguous, intent(in) :: a(:)
      !> Error handling
      type(error_type), allocatable, intent(out) :: error
      !> Linear solver
      class(pcm_solver), intent(in), optional :: solver

      integer :: npt
      integer :: stat

      stat = 0
      npt = size(r, 2)
      if (npt < 1) then
         call fatal_error(error, "[slic_point_mf_assemble] empty discretization")
         return
      end if
      if (any(shape(r) /= [3, npt])) then
         call fatal_error(error, "[slic_point_mf_assemble] r: wrong shape")
         return
      end if
      if (any(shape(n) /= [3, npt])) then
         call fatal_error(error, "[slic_point_mf_assemble] n: wrong shape")
         return
      end if
      if (any(shape(k1) /= [npt])) then
         call fatal_error(error, "[slic_point_mf_assemble] k1: wrong shape")
         return
      end if
      if (any(shape(k2) /= [npt])) then
         call fatal_error(error, "[slic_point_mf_assemble] k2: wrong shape")
         return
      end if
      if (any(shape(a) /= [npt])) then
         call fatal_error(error, "[slic_point_mf_assemble] a: wrong shape")
         return
      end if
      state%ready = 0
      if (allocated(state%solver)) deallocate (state%solver)
      if (allocated(state%a)) deallocate (state%a)
      if (allocated(state%n)) deallocate (state%n)
      if (allocated(state%r)) deallocate (state%r)
      if (allocated(state%k1)) deallocate (state%k1)
      if (allocated(state%k2)) deallocate (state%k2)
      if (allocated(state%s14)) deallocate (state%s14)
      if (allocated(state%s15)) deallocate (state%s15)
      if (allocated(state%s1)) deallocate (state%s1)
      if (allocated(state%s2)) deallocate (state%s2)
      if (allocated(state%s3)) deallocate (state%s3)
      if (allocated(state%s4)) deallocate (state%s4)
      if (allocated(state%s5)) deallocate (state%s5)
      if (allocated(state%s6)) deallocate (state%s6)
      if (allocated(state%s16)) deallocate (state%s16)
      if (allocated(state%s17)) deallocate (state%s17)
      if (allocated(state%s18)) deallocate (state%s18)
      if (allocated(state%s19)) deallocate (state%s19)
      if (allocated(state%s20)) deallocate (state%s20)
      if (allocated(state%s21)) deallocate (state%s21)
      if (allocated(state%s22)) deallocate (state%s22)
      if (allocated(state%s23)) deallocate (state%s23)
      if (allocated(state%s24)) deallocate (state%s24)
      if (allocated(state%s25)) deallocate (state%s25)
      if (allocated(state%s26)) deallocate (state%s26)
      if (allocated(state%s27)) deallocate (state%s27)
      if (allocated(state%s28)) deallocate (state%s28)
      if (allocated(state%s7)) deallocate (state%s7)
      state%npt = npt
      if (present(solver)) then
         allocate (state%solver, source=solver, stat=stat)
      else
         allocate (pcm_dense_solver :: state%solver, stat=stat)
      end if
      if (stat == 0) allocate (state%a(npt), stat=stat)
      if (stat == 0) allocate (state%n(3, npt), stat=stat)
      if (stat == 0) allocate (state%r(3, npt), stat=stat)
      if (stat == 0) allocate (state%k1(npt), stat=stat)
      if (stat == 0) allocate (state%k2(npt), stat=stat)
      if (stat == 0) allocate (state%s14(npt), stat=stat)
      if (stat == 0) allocate (state%s15(npt), stat=stat)
      if (stat == 0) allocate (state%s1(npt), stat=stat)
      if (stat == 0) allocate (state%s2(npt), stat=stat)
      if (stat == 0) allocate (state%s3(npt), stat=stat)
      if (stat == 0) allocate (state%s4(npt), stat=stat)
      if (stat == 0) allocate (state%s5(npt), stat=stat)
      if (stat == 0) allocate (state%s6(npt), stat=stat)
      if (stat == 0) allocate (state%s16(npt), stat=stat)
      if (stat == 0) allocate (state%s17(npt), stat=stat)
      if (stat == 0) allocate (state%s18(npt), stat=stat)
      if (stat == 0) allocate (state%s19(npt), stat=stat)
      if (stat == 0) allocate (state%s20(npt), stat=stat)
      if (stat == 0) allocate (state%s21(npt), stat=stat)
      if (stat == 0) allocate (state%s22(npt), stat=stat)
      if (stat == 0) allocate (state%s23(npt), stat=stat)
      if (stat == 0) allocate (state%s24(npt), stat=stat)
      if (stat == 0) allocate (state%s25(npt), stat=stat)
      if (stat == 0) allocate (state%s26(npt), stat=stat)
      if (stat == 0) allocate (state%s27(npt), stat=stat)
      if (stat == 0) allocate (state%s28(npt), stat=stat)
      if (stat /= 0) then
         call fatal_error(error, "[slic_point_mf_assemble] allocation failed")
         return
      end if
      state%s14 = 0.0_wp
      state%s21 = 0.0_wp
      call state%solver%reset(slic_point_n_operators)
      state%matrix_free = .true.

      state%a = a
      state%n = n
      state%r = r
      state%k1 = k1
      state%k2 = k2
      state%s1 = state%n(1, :)
      state%s2 = state%r(1, :)
      state%s3 = state%r(2, :)
      state%s4 = state%n(2, :)
      state%s5 = state%r(3, :)
      state%s6 = state%n(3, :)

      state%ready = 1
      state%assembled = state%assembled + 1
   end subroutine slic_point_mf_assemble

   module subroutine slic_point_mf_medium(state, eps, alpha, beta, gamma, mu, error)
      !> State of slic_point
      type(slic_point_state), target, intent(inout) :: state
      !> Relative permittivity of the solvent (inf for a conductor)
      real(wp), intent(in) :: eps
      !> SLIC amplitude of the solvation-layer perturbation h
      real(wp), intent(in) :: alpha
      !> SLIC steepness of h in the normal field (inverse field units)
      real(wp), intent(in) :: beta
      !> SLIC offset of the transition of h
      real(wp), intent(in) :: gamma
      !> SLIC shift of h
      real(wp), intent(in) :: mu
      !> Error handling
      type(error_type), allocatable, intent(out) :: error

      integer :: npt
      integer :: stat
      real(wp) :: tmp1, tmp2, tmp3, tmp4

      stat = 0
      npt = state%npt
      if (state%ready < 1) then
         call fatal_error(error, "[slic_point_mf_medium] call slic_point_assemble first")
         return
      end if
      state%s14 = 0.0_wp
      state%ready = 1
      ! Inputs that do not enter these outputs
      associate (unused1 => eps, unused2 => gamma)
      end associate

      state%beta = beta
      state%alpha = alpha
      state%mu = mu
      state%s8 = -gamma
      state%s9 = eps + 1.0_wp
      tmp1 = 1.0_wp/state%s9
      tmp2 = (-2.0_wp)*tmp1
      state%s10 = 1.0_wp + tmp2
      state%s11 = -state%s10
      state%s12 = state%s10*state%alpha
      state%s13 = state%s12*state%beta
      tmp3 = state%beta**(2)
      tmp4 = tmp3*state%s10
      state%s29 = tmp4*state%alpha

      state%ready = 2
   end subroutine slic_point_mf_medium

   module subroutine slic_point_mf_solve(state, v, vn, energy, q, grad_v, grad_vn, error)
      !> State of slic_point
      type(slic_point_state), target, intent(inout) :: state
      !> Solute electrostatic potential at the surface points
      real(wp), contiguous, intent(in) :: v(:)
      !> Outward normal derivative of the solute potential at the surface points
      real(wp), contiguous, target, intent(in) :: vn(:)
      !> Solvation energy
      real(wp), intent(out) :: energy
      !> Apparent surface charges
      real(wp), contiguous, intent(out) :: q(:)
      !> Partial derivative of the energy with respect to v
      real(wp), contiguous, intent(out) :: grad_v(:)
      !> Partial derivative of the energy with respect to vn
      real(wp), contiguous, intent(out) :: grad_vn(:)
      !> Error handling
      type(error_type), allocatable, intent(out) :: error

      integer :: npt
      integer :: stat
      type(slic_point_nl2) :: nl2
      real(wp), allocatable :: tmp1(:), tmp2(:), tmp9(:), tmp38(:), tmp39(:), tmp58(:), tmp69(:), &
                               tmp70(:), tmp71(:), tmp73(:), tmp84(:), tmp85(:)
      real(wp) :: tmp3, tmp4, tmp5, tmp6, tmp7, tmp8, tmp40, tmp41, tmp42, tmp43, tmp44, tmp45, &
                  tmp46, tmp47, tmp48, tmp49, tmp50, tmp51, tmp52, tmp53, tmp54, tmp55, tmp56, &
                  tmp57, tmp59, tmp60, tmp61, tmp62, tmp63, tmp64, tmp65, tmp66, tmp67, tmp68, &
                  tmp72, tmp74, tmp75, tmp76, tmp77, tmp78, tmp79, tmp80, tmp81, tmp82, tmp83, &
                  tmp86, tmp87
      integer :: i, j

      stat = 0
      npt = state%npt
      if (state%ready < 2) then
         call fatal_error(error, "[slic_point_mf_solve] call slic_point_medium first")
         return
      end if
      if (any(shape(v) /= [npt])) then
         call fatal_error(error, "[slic_point_mf_solve] v: wrong shape")
         return
      end if
      if (any(shape(vn) /= [npt])) then
         call fatal_error(error, "[slic_point_mf_solve] vn: wrong shape")
         return
      end if
      if (any(shape(q) /= [npt])) then
         call fatal_error(error, "[slic_point_mf_solve] q: wrong shape")
         return
      end if
      if (any(shape(grad_v) /= [npt])) then
         call fatal_error(error, "[slic_point_mf_solve] grad_v: wrong shape")
         return
      end if
      if (any(shape(grad_vn) /= [npt])) then
         call fatal_error(error, "[slic_point_mf_solve] grad_vn: wrong shape")
         return
      end if
      allocate (tmp1(npt), stat=stat)
      if (stat == 0) allocate (tmp2(npt), stat=stat)
      if (stat == 0) allocate (tmp9(npt), stat=stat)
      if (stat == 0) allocate (tmp38(npt), stat=stat)
      if (stat == 0) allocate (tmp39(npt), stat=stat)
      if (stat == 0) allocate (tmp58(npt), stat=stat)
      if (stat == 0) allocate (tmp69(npt), stat=stat)
      if (stat == 0) allocate (tmp70(npt), stat=stat)
      if (stat == 0) allocate (tmp71(npt), stat=stat)
      if (stat == 0) allocate (tmp73(npt), stat=stat)
      if (stat == 0) allocate (tmp84(npt), stat=stat)
      if (stat == 0) allocate (tmp85(npt), stat=stat)
      if (stat /= 0) then
         call fatal_error(error, "[slic_point_mf_solve] allocation failed")
         return
      end if
      state%ready = 2

      state%op2%npt = npt
      state%op2%npoint = npt
      state%op2%id = 2
      state%op2%points => state%r
      state%op2%r => state%r
      state%op2%n => state%n
      state%op2%k1 => state%k1
      state%op2%k2 => state%k2
      state%op2%a => state%a
      nl2%npt = npt
      nl2%solver => state%solver
      nl2%r => state%r
      nl2%n => state%n
      nl2%k1 => state%k1
      nl2%k2 => state%k2
      nl2%a => state%a
      nl2%vn => vn
      nl2%alpha = state%alpha
      nl2%beta = state%beta
      nl2%mu = state%mu
      nl2%c1 = state%s8
      nl2%c2 = state%s10
      nl2%c3 = state%s11
      nl2%c4 = state%s13
      call nl2%solve(state%s14, error)
      if (allocated(error)) return
      state%s15 = state%a*state%s14
      do i = 1, npt
         tmp3 = state%k1(i) + state%k2(i)
         tmp4 = 1.0_wp/state%a(i)
         tmp5 = 12.566370614359172_wp*tmp4
         tmp6 = sqrt(tmp5)
         tmp7 = tmp3*tmp6
         tmp8 = (-0.26735_wp)*tmp7
         tmp2(i) = tmp8
      end do
      tmp9 = tmp2*state%s15
      tmp1 = tmp9
      block
         real(wp) :: tmp11, tmp12, tmp13, tmp14, tmp15, tmp16, tmp17, tmp18, tmp21, tmp25, tmp10, &
                     tmp19, tmp20, tmp22, tmp23, tmp24, tmp26, tmp27, tmp28, tmp29, tmp30, tmp31, &
                     tmp32, tmp33, tmp34, tmp35, tmp36, tmp37

         !$omp parallel &
         !$omp& private(i, j) &
         !$omp& shared(npt, state, tmp1) &
         !$omp& default(private)
         !$omp do schedule(static)
         do j = 1, npt
            tmp11 = state%s1(j)
            tmp12 = state%s2(j)
            tmp13 = state%s3(j)
            tmp14 = state%s4(j)
            tmp15 = state%s5(j)
            tmp16 = state%s6(j)
            tmp17 = state%s15(j)
            tmp18 = -tmp12
            tmp21 = -tmp13
            tmp25 = -tmp15
            tmp10 = 0.0_wp
            !$omp simd &
            !$omp& private(tmp19, tmp20, tmp22, tmp23, tmp24, tmp26, tmp27, tmp28) &
            !$omp& private(tmp29, tmp30, tmp31, tmp32, tmp33, tmp34, tmp35, tmp36) &
            !$omp& private(tmp37) &
            !$omp& reduction(+: tmp10)
            do i = 1, j - 1
               tmp19 = state%s2(i) + tmp18
               tmp20 = tmp11*tmp19
               tmp22 = state%s3(i) + tmp21
               tmp23 = tmp22*tmp14
               tmp24 = tmp20 + tmp23
               tmp26 = state%s5(i) + tmp25
               tmp27 = tmp26*tmp16
               tmp28 = tmp24 + tmp27
               tmp29 = tmp19**(2)
               tmp30 = tmp22**(2)
               tmp31 = tmp29 + tmp30
               tmp32 = tmp26**(2)
               tmp33 = tmp31 + tmp32
               tmp34 = 1.0_wp/sqrt(tmp33)
               tmp35 = tmp34**(3)
               tmp36 = tmp28*tmp35
               tmp37 = tmp36*state%s15(i)
               tmp10 = tmp10 + tmp37
            end do
            !$omp simd &
            !$omp& private(tmp19, tmp20, tmp22, tmp23, tmp24, tmp26, tmp27, tmp28) &
            !$omp& private(tmp29, tmp30, tmp31, tmp32, tmp33, tmp34, tmp35, tmp36) &
            !$omp& private(tmp37) &
            !$omp& reduction(+: tmp10)
            do i = j + 1, npt
               tmp19 = state%s2(i) + tmp18
               tmp20 = tmp11*tmp19
               tmp22 = state%s3(i) + tmp21
               tmp23 = tmp22*tmp14
               tmp24 = tmp20 + tmp23
               tmp26 = state%s5(i) + tmp25
               tmp27 = tmp26*tmp16
               tmp28 = tmp24 + tmp27
               tmp29 = tmp19**(2)
               tmp30 = tmp22**(2)
               tmp31 = tmp29 + tmp30
               tmp32 = tmp26**(2)
               tmp33 = tmp31 + tmp32
               tmp34 = 1.0_wp/sqrt(tmp33)
               tmp35 = tmp34**(3)
               tmp36 = tmp28*tmp35
               tmp37 = tmp36*state%s15(i)
               tmp10 = tmp10 + tmp37
            end do
            tmp1(j) = tmp1(j) + tmp10
         end do
         !$omp end do
         !$omp end parallel
      end block
      state%s16 = vn + tmp1
      tmp38 = 6.283185307179586_wp*state%s14
      tmp39 = state%s16 + tmp38
      state%s17 = -tmp39
      do i = 1, npt
         tmp40 = state%beta*state%s17(i)
         tmp41 = tmp40 + state%s8
         tmp42 = tanh(tmp41)
         tmp43 = tmp42**(2)
         tmp44 = -tmp43
         tmp45 = 1.0_wp + tmp44
         tmp46 = state%s13*tmp45
         tmp47 = tmp46*state%s14(i)
         tmp48 = (-12.566370614359172_wp)*tmp47
         state%s18(i) = tmp48
      end do
      state%op2%c1 => state%s18
      do i = 1, npt
         tmp49 = state%beta*state%s17(i)
         tmp50 = tmp49 + state%s8
         tmp51 = tanh(tmp50)
         tmp52 = state%alpha*tmp51
         tmp53 = tmp52 + state%mu
         tmp54 = state%s10*tmp53
         tmp55 = (-2.0_wp)*tmp54
         tmp56 = 1.0_wp + tmp55
         tmp57 = 6.283185307179586_wp*tmp56
         state%s19(i) = tmp57
      end do
      state%op2%c2 => state%s19
      state%op2%c3 = state%s11
      call state%solver%setup(state%op2, error)
      if (allocated(error)) return
      state%s20 = 0.5_wp*v
      tmp58 = state%s20*state%a
      call state%solver%solve(state%op2, .true., tmp58, state%s21, error)
      if (allocated(error)) return
      do i = 1, npt
         tmp59 = state%s12*state%s14(i)
         tmp60 = state%beta*state%s17(i)
         tmp61 = tmp60 + state%s8
         tmp62 = tanh(tmp61)
         tmp63 = tmp62**(2)
         tmp64 = -tmp63
         tmp65 = 1.0_wp + tmp64
         tmp66 = tmp59*tmp65
         tmp67 = tmp66*state%beta
         tmp68 = (-12.566370614359172_wp)*tmp67
         state%s22(i) = tmp68
      end do
      tmp69 = state%s11*state%s21
      tmp70 = state%s21*state%s22
      tmp71 = -tmp70
      state%s23 = tmp69 + tmp71
      state%s24 = -state%s23
      tmp72 = dot(v, state%s15)
      energy = 0.5_wp*tmp72
      q = state%s15
      grad_v = 0.5_wp*state%s15
      grad_vn = state%s24
      if (state%solver%inexact()) then
         ! First-order correction for the residuals of the solves
         do i = 1, npt
            tmp74 = state%beta*state%s17(i)
            tmp75 = tmp74 + state%s8
            tmp76 = tanh(tmp75)
            tmp77 = state%alpha*tmp76
            tmp78 = tmp77 + state%mu
            tmp79 = state%s10*tmp78
            tmp80 = (-2.0_wp)*tmp79
            tmp81 = 1.0_wp + tmp80
            tmp82 = tmp81*state%s14(i)
            tmp83 = 6.283185307179586_wp*tmp82
            tmp73(i) = tmp83
         end do
         tmp84 = state%s11*state%s16
         tmp85 = tmp73 + tmp84
         tmp86 = dot(state%s21, tmp85)
         tmp87 = -tmp86
         energy = energy + tmp87
      end if

      state%ready = 3
   end subroutine slic_point_mf_solve

end submodule pcmgen_point_slic_mf_energy
