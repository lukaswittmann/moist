submodule(pcmgen_point_conductor) pcmgen_point_conductor_complex_mf_gradient
   implicit none(type, external)

contains

   module subroutine conductor_point_complex_mf_weights(state, grad_r, grad_a, error)
      !> State of conductor_point
      type(conductor_point_complex_state), target, intent(inout) :: state
      !> Partial derivative of the energy with respect to r
      complex(wp), contiguous, intent(out) :: grad_r(:, :)
      !> Partial derivative of the energy with respect to a
      complex(wp), contiguous, intent(out) :: grad_a(:)
      !> Error handling
      type(error_type), allocatable, intent(out) :: error

      integer :: npt
      integer :: stat
      real(wp) :: tmp1, tmp2, tmp3, tmp4, tmp5, tmp6
      complex(wp), allocatable :: tmp7(:), tmp8(:), tmp9(:)
      complex(wp), allocatable :: tmp7_p(:), tmp8_p(:), tmp9_p(:)
      integer :: i, j

      stat = 0
      npt = state%npt
      if (state%cx_ready < 3 .or. state%cx_assembled /= state%assembled) then
         call fatal_error(error, &
                          "[conductor_point_complex_mf_weights] call conductor_point_complex_solve first")
         return
      end if
      if (any(shape(grad_r) /= [3, npt])) then
         call fatal_error(error, "[conductor_point_complex_mf_weights] grad_r: wrong shape")
         return
      end if
      if (any(shape(grad_a) /= [npt])) then
         call fatal_error(error, "[conductor_point_complex_mf_weights] grad_a: wrong shape")
         return
      end if
      allocate (tmp7(npt), stat=stat)
      if (stat == 0) allocate (tmp8(npt), stat=stat)
      if (stat == 0) allocate (tmp9(npt), stat=stat)
      if (stat /= 0) then
         call fatal_error(error, "[conductor_point_complex_mf_weights] allocation failed")
         return
      end if
      state%cx_ready = 3

      state%op2%points => state%r
      state%op2%r => state%r
      state%op2%a => state%a
      state%cx_s2 = state%r(1, :)
      state%cx_s3 = state%r(2, :)
      state%cx_s4 = state%r(3, :)
      state%cx_s7 = 0.5_wp*state%cx_feps
      state%cx_s8 = state%cx_s7*state%cx_s6
      state%cx_s9 = state%cx_s8*state%cx_s6
      do i = 1, npt
         tmp1 = 1.0_wp/state%a(i)
         tmp2 = 12.566370614359172_wp*tmp1
         tmp3 = 1.0_wp/sqrt(tmp2)
         tmp4 = state%a(i)**(-2)
         tmp5 = tmp3*tmp4
         tmp6 = (-6.719238367497849_wp)*tmp5
         state%cx_s10(i) = tmp6
      end do
      tmp7 = 0.0_wp
      tmp8 = 0.0_wp
      tmp9 = 0.0_wp
      block
         real(wp) :: tmp14, tmp15, tmp16, tmp18, tmp21, tmp25, tmp19, tmp20, tmp22, tmp23, tmp24, &
                     tmp26, tmp27, tmp28, tmp29, tmp30
         complex(wp) :: tmp13, tmp17, tmp10, tmp11, tmp12, tmp31, tmp32, tmp33, tmp34, tmp35, &
                        tmp36, tmp37, tmp38, tmp39, tmp40, tmp41, tmp42

         !$omp parallel &
         !$omp& private(i, j, tmp7_p, tmp8_p, tmp9_p) &
         !$omp& shared(npt, state, tmp7, tmp8, tmp9) &
         !$omp& default(private)
         allocate (tmp7_p(npt))
         allocate (tmp8_p(npt))
         allocate (tmp9_p(npt))
         tmp7_p = 0.0_wp
         tmp8_p = 0.0_wp
         tmp9_p = 0.0_wp
         !$omp do schedule(static)
         do j = 1, npt
            tmp13 = state%cx_s8(j)
            tmp14 = state%cx_s2(j)
            tmp15 = state%cx_s3(j)
            tmp16 = state%cx_s4(j)
            tmp17 = state%cx_s6(j)
            tmp18 = -tmp14
            tmp21 = -tmp15
            tmp25 = -tmp16
            tmp10 = 0.0_wp
            tmp11 = 0.0_wp
            tmp12 = 0.0_wp
            !$omp simd &
            !$omp& private(tmp19, tmp20, tmp22, tmp23, tmp24, tmp26, tmp27, tmp28) &
            !$omp& private(tmp29, tmp30, tmp31, tmp32, tmp33, tmp34, tmp35, tmp36) &
            !$omp& private(tmp37, tmp38, tmp39, tmp40, tmp41, tmp42) &
            !$omp& reduction(+: tmp10, tmp11, tmp12)
            do i = 1, j - 1
               tmp19 = state%cx_s2(i) + tmp18
               tmp20 = tmp19**(2)
               tmp22 = state%cx_s3(i) + tmp21
               tmp23 = tmp22**(2)
               tmp24 = tmp20 + tmp23
               tmp26 = state%cx_s4(i) + tmp25
               tmp27 = tmp26**(2)
               tmp28 = tmp24 + tmp27
               tmp29 = 1.0_wp/sqrt(tmp28)
               tmp30 = tmp29**(3)
               tmp31 = state%cx_s8(i)*tmp30
               tmp32 = tmp31*tmp19
               tmp33 = tmp32*tmp17
               tmp34 = -tmp33
               tmp7_p(i) = tmp7_p(i) + tmp34
               tmp10 = tmp10 + tmp33
               tmp35 = state%cx_s8(i)*tmp22
               tmp36 = tmp35*tmp30
               tmp37 = tmp36*tmp17
               tmp38 = -tmp37
               tmp8_p(i) = tmp8_p(i) + tmp38
               tmp11 = tmp11 + tmp37
               tmp39 = state%cx_s8(i)*tmp26
               tmp40 = tmp39*tmp30
               tmp41 = tmp40*tmp17
               tmp42 = -tmp41
               tmp9_p(i) = tmp9_p(i) + tmp42
               tmp12 = tmp12 + tmp41
            end do
            !$omp simd &
            !$omp& private(tmp19, tmp20, tmp22, tmp23, tmp24, tmp26, tmp27, tmp28) &
            !$omp& private(tmp29, tmp30, tmp31, tmp32, tmp33, tmp34, tmp35, tmp36) &
            !$omp& private(tmp37, tmp38, tmp39, tmp40, tmp41, tmp42) &
            !$omp& reduction(+: tmp10, tmp11, tmp12)
            do i = j + 1, npt
               tmp19 = state%cx_s2(i) + tmp18
               tmp20 = tmp19**(2)
               tmp22 = state%cx_s3(i) + tmp21
               tmp23 = tmp22**(2)
               tmp24 = tmp20 + tmp23
               tmp26 = state%cx_s4(i) + tmp25
               tmp27 = tmp26**(2)
               tmp28 = tmp24 + tmp27
               tmp29 = 1.0_wp/sqrt(tmp28)
               tmp30 = tmp29**(3)
               tmp31 = state%cx_s8(i)*tmp30
               tmp32 = tmp31*tmp19
               tmp33 = tmp32*tmp17
               tmp34 = -tmp33
               tmp7_p(i) = tmp7_p(i) + tmp34
               tmp10 = tmp10 + tmp33
               tmp35 = state%cx_s8(i)*tmp22
               tmp36 = tmp35*tmp30
               tmp37 = tmp36*tmp17
               tmp38 = -tmp37
               tmp8_p(i) = tmp8_p(i) + tmp38
               tmp11 = tmp11 + tmp37
               tmp39 = state%cx_s8(i)*tmp26
               tmp40 = tmp39*tmp30
               tmp41 = tmp40*tmp17
               tmp42 = -tmp41
               tmp9_p(i) = tmp9_p(i) + tmp42
               tmp12 = tmp12 + tmp41
            end do
            tmp7_p(j) = tmp7_p(j) + tmp10
            tmp8_p(j) = tmp8_p(j) + tmp11
            tmp9_p(j) = tmp9_p(j) + tmp12
         end do
         !$omp end do
         !$omp critical (pcmgen_sum)
         tmp7 = tmp7 + tmp7_p
         tmp8 = tmp8 + tmp8_p
         tmp9 = tmp9 + tmp9_p
         !$omp end critical (pcmgen_sum)
         deallocate (tmp7_p)
         deallocate (tmp8_p)
         deallocate (tmp9_p)
         !$omp end parallel
      end block
      grad_r(1, :) = tmp7
      grad_r(2, :) = tmp8
      grad_r(3, :) = tmp9
      grad_a = state%cx_s9*state%cx_s10

      state%cx_ready = 4
   end subroutine conductor_point_complex_mf_weights

   module subroutine conductor_point_complex_mf_param_weights(state, grad_feps, error)
      !> State of conductor_point
      type(conductor_point_complex_state), target, intent(inout) :: state
      !> Partial derivative of the energy with respect to feps
      complex(wp), intent(out) :: grad_feps
      !> Error handling
      type(error_type), allocatable, intent(out) :: error

      integer :: npt
      integer :: stat
      complex(wp), allocatable :: tmp1(:)
      complex(wp) :: tmp2

      stat = 0
      npt = state%npt
      if (state%cx_ready < 3 .or. state%cx_assembled /= state%assembled) then
         call fatal_error(error, &
                          "[conductor_point_complex_mf_param_weights] call conductor_point_complex_solve first")
         return
      end if
      allocate (tmp1(npt), stat=stat)
      if (stat /= 0) then
         call fatal_error(error, "[conductor_point_complex_mf_param_weights] allocation failed")
         return
      end if

      state%op2%points => state%r
      state%op2%r => state%r
      state%op2%a => state%a
      tmp1 = 0.5_wp*state%cx_v
      tmp2 = sum(tmp1*state%cx_s6)
      grad_feps = -tmp2
   end subroutine conductor_point_complex_mf_param_weights

end submodule pcmgen_point_conductor_complex_mf_gradient
