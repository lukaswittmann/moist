      call gemv(state%s7, real(state%cx_s19, wp), tmp23)
      call gemv(state%s7, aimag(state%cx_s19), tmp24)
      state%cx_s31 = cmplx(tmp23, tmp24, wp)
      state%cx_s32 = state%a*state%cx_s31
