      tmp15 = cmplx(tmp16, tmp17, wp)
      call state%solver%solve_complex(state%op1, .false., tmp15, state%cx_s23, error)
      if (allocated(error)) return
      state%cx_s25 = state%cx_s24*state%cx_s21
      state%cx_s26 = (-0.15915494309189535_wp)*state%cx_s23
      state%cx_s28 = state%cx_s27*state%cx_s21
      call gemv(state%cx_s11, real(state%cx_s28, wp), tmp18, trans="t")
      call gemv(state%cx_s11, aimag(state%cx_s28), tmp19, trans="t")
      state%cx_s29 = cmplx(tmp18, tmp19, wp)
      call gemv(state%s13, real(state%cx_s26, wp), tmp21, trans="t")
      call gemv(state%s13, aimag(state%cx_s26), tmp22, trans="t")
      tmp20 = cmplx(tmp21, tmp22, wp)
