      tmp30 = tmp29 + state%cx_s25
      tmp31 = state%cx_s30*state%a
      grad_v = tmp30 + tmp31
      if (state%solver%inexact()) then
         ! First-order correction for the residuals of the solves
         tmp32 = 0.5_wp*state%cx_s21
         call gemv(state%cx_s11, real(state%cx_s32, wp), tmp34)
         call gemv(state%cx_s11, aimag(state%cx_s32), tmp35)
         tmp33 = cmplx(tmp34, tmp35, wp)
