               tmp7 = tmp7 + tmp26
            end do
            tmp1(j) = tmp1(j) + tmp7
         end do
         !$omp end do
         !$omp end parallel
      end block
      y = tmp1
   end subroutine nonlocal_pcm_point_op4_apply_t

   !> Apply operator 4
   !>
   !> @param[in]  self  operator
   !> @param[in]  x     input vector
   !> @param[out] y     result vector
   subroutine nonlocal_pcm_point_op4_apply_n(self, x, y)
      !> Operator
      class(nonlocal_pcm_point_op4), intent(in) :: self
      !> Input vector
      real(wp), contiguous, intent(in) :: x(:)
      !> Result vector
      real(wp), contiguous, intent(out) :: y(:)

      real(wp), allocatable :: tmp1(:), tmp2(:), tmp6(:)
      real(wp) :: tmp3, tmp4, tmp5
      real(wp), allocatable :: tmp1_p(:)
      integer :: i, j

      allocate (tmp1(self%npt))
      allocate (tmp2(self%npt))
      allocate (tmp6(self%npt))
      do i = 1, self%npt
         tmp3 = 3.141592653589793_wp*self%a(i)
         tmp4 = sqrt(tmp3)
         tmp5 = 2.0_wp*tmp4
         tmp2(i) = tmp5
      end do
      tmp6 = tmp2*x
      tmp1 = tmp6
      block
         real(wp) :: tmp7, tmp8, tmp9, tmp10, tmp11, tmp12, tmp15, tmp19, tmp13, tmp14, tmp16, &
                     tmp17, tmp18, tmp20, tmp21, tmp22, tmp23, tmp24, tmp25

         !$omp parallel &
         !$omp& private(i, j, tmp1_p) &
         !$omp& shared(self, tmp1, x) &
         !$omp& default(private)
         allocate (tmp1_p(self%npt))
         tmp1_p = 0.0_wp
         !$omp do schedule(static)
         do j = 1, self%npt
            tmp7 = x(j)
            tmp8 = self%r(1, j)
            tmp9 = self%r(2, j)
            tmp10 = self%r(3, j)
            tmp11 = self%a(j)
            tmp12 = -tmp8
            tmp15 = -tmp9
            tmp19 = -tmp10
            !$omp simd &
            !$omp& private(tmp13, tmp14, tmp16, tmp17, tmp18, tmp20, tmp21, tmp22) &
            !$omp& private(tmp23, tmp24, tmp25)
            do i = 1, j - 1
               tmp13 = self%r(1, i) + tmp12
               tmp14 = tmp13**(2)
               tmp16 = self%r(2, i) + tmp15
               tmp17 = tmp16**(2)
               tmp18 = tmp14 + tmp17
               tmp20 = self%r(3, i) + tmp19
               tmp21 = tmp20**(2)
               tmp22 = tmp18 + tmp21
               tmp23 = 1.0_wp/sqrt(tmp22)
               tmp24 = tmp7*tmp23
               tmp25 = tmp24*tmp11
               tmp1_p(i) = tmp1_p(i) + tmp25
            end do
            !$omp simd &
            !$omp& private(tmp13, tmp14, tmp16, tmp17, tmp18, tmp20, tmp21, tmp22) &
            !$omp& private(tmp23, tmp24, tmp25)
            do i = j + 1, self%npt
               tmp13 = self%r(1, i) + tmp12
               tmp14 = tmp13**(2)
               tmp16 = self%r(2, i) + tmp15
               tmp17 = tmp16**(2)
               tmp18 = tmp14 + tmp17
               tmp20 = self%r(3, i) + tmp19
               tmp21 = tmp20**(2)
               tmp22 = tmp18 + tmp21
               tmp23 = 1.0_wp/sqrt(tmp22)
               tmp24 = tmp7*tmp23
               tmp25 = tmp24*tmp11
               tmp1_p(i) = tmp1_p(i) + tmp25
            end do
         end do
         !$omp end do
         !$omp critical (pcmgen_sum)
         tmp1 = tmp1 + tmp1_p
         !$omp end critical (pcmgen_sum)
         deallocate (tmp1_p)
         !$omp end parallel
      end block
      y = tmp1
   end subroutine nonlocal_pcm_point_op4_apply_n

   module subroutine nonlocal_pcm_point_op4_assemble_block(self, idx, a, error)
      !> Operator
      class(nonlocal_pcm_point_op4), intent(in) :: self
      !> Point indices
      integer, contiguous, intent(in) :: idx(:)
      !> Operator matrix of the points
      real(wp), contiguous, intent(out) :: a(:, :)
      !> Error handling
      type(error_type), allocatable, intent(out) :: error

      integer :: nb
      integer :: stat
      real(wp), allocatable :: tmp2(:)
      real(wp), allocatable :: tmp1(:, :)
      real(wp) :: tmp21, tmp22, tmp23
      integer :: i, j

      nb = size(idx)
      if (any(shape(a) /= [nb, nb])) then
         call fatal_error(error, "[nonlocal_pcm_point_op4_assemble_block] a: wrong shape")
         return
      end if
      allocate (tmp1(3, nb), stat=stat)
      if (stat == 0) allocate (tmp2(nb), stat=stat)
      if (stat /= 0) then
         call fatal_error(error, "[nonlocal_pcm_point_op4_assemble_block] allocation failed")
         return
      end if
      tmp1 = self%r(:, idx)
      tmp2 = self%a(idx)
      block
         real(wp) :: tmp3, tmp4, tmp5, tmp6, tmp7, tmp10, tmp14, tmp8, tmp9, tmp11, tmp12, tmp13, &
                     tmp15, tmp16, tmp17, tmp18, tmp19, tmp20

         !$omp parallel &
         !$omp& private(i, j) &
         !$omp& shared(a, nb, tmp1, tmp2) &
         !$omp& default(private)
         !$omp do schedule(dynamic, 16)
         do j = 2, nb
            tmp3 = tmp1(1, j)
            tmp4 = tmp1(2, j)
            tmp5 = tmp1(3, j)
            tmp6 = tmp2(j)
            tmp7 = -tmp3
            tmp10 = -tmp4
            tmp14 = -tmp5
            !$omp simd &
            !$omp& private(tmp8, tmp9, tmp11, tmp12, tmp13, tmp15, tmp16, tmp17) &
            !$omp& private(tmp18, tmp19, tmp20)
            do i = 1, j - 1
               tmp8 = tmp1(1, i) + tmp7
               tmp9 = tmp8**(2)
               tmp11 = tmp1(2, i) + tmp10
               tmp12 = tmp11**(2)
               tmp13 = tmp9 + tmp12
               tmp15 = tmp1(3, i) + tmp14
               tmp16 = tmp15**(2)
               tmp17 = tmp13 + tmp16
               tmp18 = 1.0_wp/sqrt(tmp17)
               tmp19 = tmp18*tmp6
               a(i, j) = tmp19
               tmp20 = tmp18*tmp2(i)
               a(j, i) = tmp20
            end do
         end do
         !$omp end do
         !$omp end parallel
      end block
      do i = 1, nb
         tmp21 = 3.141592653589793_wp*tmp2(i)
         tmp22 = sqrt(tmp21)
         tmp23 = 2.0_wp*tmp22
         a(i, i) = tmp23
      end do
   end subroutine nonlocal_pcm_point_op4_assemble_block

