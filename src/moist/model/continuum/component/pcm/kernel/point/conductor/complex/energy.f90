!> Conductor-like PCM (point charges) phases: complex/energy; generated by pcmgen, do not edit
!>
!> - Procedures of pcmgen_point_conductor: conductor_point_complex_medium,
!>   conductor_point_complex_solve
submodule(pcmgen_point_conductor) pcmgen_point_conductor_complex_energy
   implicit none(type, external)

contains

   module subroutine conductor_point_complex_medium(state, feps, error)
      !> State of conductor_point
      type(conductor_point_complex_state), target, intent(inout) :: state
      !> Dielectric factor of a conductor-like model, e.g. (eps - 1)/eps
      complex(wp), intent(in) :: feps
      !> Error handling
      type(error_type), allocatable, intent(out) :: error

      integer :: npt
      integer :: stat

      if (state%matrix_free) then
         call conductor_point_complex_mf_medium(state, feps, error)
         return
      end if
      stat = 0
      npt = state%npt
      if (state%ready < 1) then
         call fatal_error(error, &
                          "[conductor_point_complex_medium] call conductor_point_assemble first")
         return
      end if
      state%cx_ready = 0
      if (allocated(state%cx_v)) deallocate (state%cx_v)
      if (allocated(state%cx_s6)) deallocate (state%cx_s6)
      if (allocated(state%cx_s8)) deallocate (state%cx_s8)
      if (allocated(state%cx_s9)) deallocate (state%cx_s9)
      if (allocated(state%cx_s10)) deallocate (state%cx_s10)
      if (allocated(state%cx_s2)) deallocate (state%cx_s2)
      if (allocated(state%cx_s3)) deallocate (state%cx_s3)
      if (allocated(state%cx_s4)) deallocate (state%cx_s4)
      if (stat == 0) allocate (state%cx_v(npt), stat=stat)
      if (stat == 0) allocate (state%cx_s6(npt), stat=stat)
      if (stat == 0) allocate (state%cx_s8(npt), stat=stat)
      if (stat == 0) allocate (state%cx_s9(npt), stat=stat)
      if (stat == 0) allocate (state%cx_s10(npt), stat=stat)
      if (stat /= 0) then
         call fatal_error(error, "[conductor_point_complex_medium] allocation failed")
         return
      end if
      state%cx_s6 = 0.0_wp
      state%cx_ready = 1
      state%cx_assembled = state%assembled

      state%op1%points => state%r
      state%op1%c1 => state%s5
      state%cx_feps = feps
      state%cx_s1 = -state%cx_feps

      state%cx_ready = 2
   end subroutine conductor_point_complex_medium

   module subroutine conductor_point_complex_solve(state, v, energy, q, grad_v, error)
      !> State of conductor_point
      type(conductor_point_complex_state), target, intent(inout) :: state
      !> Solute electrostatic potential at the surface points
      complex(wp), contiguous, intent(in) :: v(:)
      !> Solvation energy
      complex(wp), intent(out) :: energy
      !> Apparent surface charges
      complex(wp), contiguous, intent(out) :: q(:)
      !> Partial derivative of the energy with respect to v
      complex(wp), contiguous, intent(out) :: grad_v(:)
      !> Error handling
      type(error_type), allocatable, intent(out) :: error

      integer :: npt
      integer :: stat
      real(wp), allocatable :: tmp5(:), tmp6(:)
      complex(wp), allocatable :: tmp3(:), tmp4(:), tmp7(:), tmp8(:)
      complex(wp) :: tmp1, tmp2, tmp9

      if (state%matrix_free) then
         call conductor_point_complex_mf_solve(state, v, energy, q, grad_v, error)
         return
      end if
      stat = 0
      npt = state%npt
      if (state%cx_ready < 2 .or. state%cx_assembled /= state%assembled) then
         call fatal_error(error, &
                          "[conductor_point_complex_solve] call conductor_point_complex_medium first")
         return
      end if
      if (any(shape(v) /= [npt])) then
         call fatal_error(error, "[conductor_point_complex_solve] v: wrong shape")
         return
      end if
      if (any(shape(q) /= [npt])) then
         call fatal_error(error, "[conductor_point_complex_solve] q: wrong shape")
         return
      end if
      if (any(shape(grad_v) /= [npt])) then
         call fatal_error(error, "[conductor_point_complex_solve] grad_v: wrong shape")
         return
      end if
      allocate (tmp3(npt), stat=stat)
      if (stat == 0) allocate (tmp4(npt), stat=stat)
      if (stat == 0) allocate (tmp5(npt), stat=stat)
      if (stat == 0) allocate (tmp6(npt), stat=stat)
      if (stat == 0) allocate (tmp7(npt), stat=stat)
      if (stat == 0) allocate (tmp8(npt), stat=stat)
      if (stat /= 0) then
         call fatal_error(error, "[conductor_point_complex_solve] allocation failed")
         return
      end if
      state%cx_ready = 2

      state%op1%points => state%r
      state%op1%c1 => state%s5
      state%cx_v = v
      call state%solver%solve_complex(state%op1, .false., state%cx_v, state%cx_s6, error)
      if (allocated(error)) return
      q = state%cx_s1*state%cx_s6
      tmp1 = sum(state%cx_v*q)
      energy = 0.5_wp*tmp1
      grad_v = q
      if (state%solver%inexact()) then
         ! First-order correction for the residuals of the solves
         tmp2 = (-0.5_wp)*state%cx_feps
         tmp3 = tmp2*state%cx_s6
         call gemv(state%s5, real(state%cx_s6, wp), tmp5)
         call gemv(state%s5, aimag(state%cx_s6), tmp6)
         tmp4 = cmplx(tmp5, tmp6, wp)
         tmp7 = -tmp4
         tmp8 = state%cx_v + tmp7
         tmp9 = sum(tmp3*tmp8)
         energy = energy + tmp9
      end if

      state%cx_ready = 3
   end subroutine conductor_point_complex_solve

end submodule pcmgen_point_conductor_complex_energy
