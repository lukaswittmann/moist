!> DPCM (point charges) phases: energy; generated by pcmgen, do not edit
!>
!> - Procedures of pcmgen_point_dpcm: dpcm_point_assemble, dpcm_point_medium, dpcm_point_solve
submodule(pcmgen_point_dpcm) pcmgen_point_dpcm_energy
   implicit none(type, external)

contains

   module subroutine dpcm_point_assemble(state, r, n, k1, k2, a, error, solver)
      !> State of dpcm_point
      type(dpcm_point_state), target, intent(inout) :: state
      !> Positions of the surface points
      real(wp), contiguous, intent(in) :: r(:, :)
      !> Outward unit normals at the surface points
      real(wp), contiguous, intent(in) :: n(:, :)
      !> First principal curvature (positive where convex)
      real(wp), contiguous, intent(in) :: k1(:)
      !> Second principal curvature (positive where convex)
      real(wp), contiguous, intent(in) :: k2(:)
      !> Grid point areas
      real(wp), contiguous, intent(in) :: a(:)
      !> Error handling
      type(error_type), allocatable, intent(out) :: error
      !> Linear solver
      class(pcm_solver), intent(in), optional :: solver

      integer :: npt
      integer :: stat
      real(wp) :: tmp35, tmp36, tmp37, tmp38, tmp39, tmp40
      integer :: i, j

      if (present(solver)) then
         if (solver%matrix_free(size(r, 2), 1)) then
            call dpcm_point_mf_assemble(state, r, n, k1, k2, a, error, solver)
            return
         end if
      end if
      stat = 0
      npt = size(r, 2)
      if (npt < 1) then
         call fatal_error(error, "[dpcm_point_assemble] empty discretization")
         return
      end if
      if (any(shape(r) /= [3, npt])) then
         call fatal_error(error, "[dpcm_point_assemble] r: wrong shape")
         return
      end if
      if (any(shape(n) /= [3, npt])) then
         call fatal_error(error, "[dpcm_point_assemble] n: wrong shape")
         return
      end if
      if (any(shape(k1) /= [npt])) then
         call fatal_error(error, "[dpcm_point_assemble] k1: wrong shape")
         return
      end if
      if (any(shape(k2) /= [npt])) then
         call fatal_error(error, "[dpcm_point_assemble] k2: wrong shape")
         return
      end if
      if (any(shape(a) /= [npt])) then
         call fatal_error(error, "[dpcm_point_assemble] a: wrong shape")
         return
      end if
      state%ready = 0
      if (allocated(state%solver)) deallocate (state%solver)
      if (allocated(state%v)) deallocate (state%v)
      if (allocated(state%a)) deallocate (state%a)
      if (allocated(state%s4)) deallocate (state%s4)
      if (allocated(state%r)) deallocate (state%r)
      if (allocated(state%s5)) deallocate (state%s5)
      if (allocated(state%s6)) deallocate (state%s6)
      if (allocated(state%s7)) deallocate (state%s7)
      if (allocated(state%s8)) deallocate (state%s8)
      if (allocated(state%s9)) deallocate (state%s9)
      if (allocated(state%k1)) deallocate (state%k1)
      if (allocated(state%k2)) deallocate (state%k2)
      if (allocated(state%s10)) deallocate (state%s10)
      if (allocated(state%vn)) deallocate (state%vn)
      if (allocated(state%s11)) deallocate (state%s11)
      if (allocated(state%s13)) deallocate (state%s13)
      if (allocated(state%s14)) deallocate (state%s14)
      if (allocated(state%s15)) deallocate (state%s15)
      if (allocated(state%s17)) deallocate (state%s17)
      if (allocated(state%s18)) deallocate (state%s18)
      if (allocated(state%s19)) deallocate (state%s19)
      if (allocated(state%s20)) deallocate (state%s20)
      if (allocated(state%s21)) deallocate (state%s21)
      if (allocated(state%n)) deallocate (state%n)
      state%npt = npt
      if (present(solver)) then
         allocate (state%solver, source=solver, stat=stat)
      else
         allocate (pcm_dense_solver :: state%solver, stat=stat)
      end if
      if (stat == 0) allocate (state%v(npt), stat=stat)
      if (stat == 0) allocate (state%a(npt), stat=stat)
      if (stat == 0) allocate (state%s4(npt), stat=stat)
      if (stat == 0) allocate (state%r(3, npt), stat=stat)
      if (stat == 0) allocate (state%s5(npt), stat=stat)
      if (stat == 0) allocate (state%s6(npt), stat=stat)
      if (stat == 0) allocate (state%s7(npt), stat=stat)
      if (stat == 0) allocate (state%s8(npt), stat=stat)
      if (stat == 0) allocate (state%s9(npt), stat=stat)
      if (stat == 0) allocate (state%k1(npt), stat=stat)
      if (stat == 0) allocate (state%k2(npt), stat=stat)
      if (stat == 0) allocate (state%s10(npt, npt), stat=stat)
      if (stat == 0) allocate (state%vn(npt), stat=stat)
      if (stat == 0) allocate (state%s11(npt), stat=stat)
      if (stat == 0) allocate (state%s13(npt), stat=stat)
      if (stat == 0) allocate (state%s14(npt), stat=stat)
      if (stat == 0) allocate (state%s15(npt), stat=stat)
      if (stat == 0) allocate (state%s17(npt), stat=stat)
      if (stat == 0) allocate (state%s18(npt), stat=stat)
      if (stat == 0) allocate (state%s19(npt), stat=stat)
      if (stat == 0) allocate (state%s20(npt), stat=stat)
      if (stat == 0) allocate (state%s21(npt), stat=stat)
      if (stat /= 0) then
         call fatal_error(error, "[dpcm_point_assemble] allocation failed")
         return
      end if
      state%s11 = 0.0_wp
      state%s13 = 0.0_wp
      call state%solver%reset(dpcm_point_n_operators)
      state%matrix_free = .false.

      state%a = a
      state%r = r
      state%k1 = k1
      state%k2 = k2
      state%s4 = n(1, :)
      state%s5 = state%r(1, :)
      state%s6 = state%r(2, :)
      state%s7 = n(2, :)
      state%s8 = state%r(3, :)
      state%s9 = n(3, :)
      block
         real(wp) :: tmp1, tmp2, tmp3, tmp4, tmp5, tmp6, tmp7, tmp10, tmp14, tmp8, tmp9, tmp11, &
                     tmp12, tmp13, tmp15, tmp16, tmp17, tmp18, tmp19, tmp20, tmp21, tmp22, tmp23, &
                     tmp24, tmp25, tmp26, tmp27, tmp28, tmp29, tmp30, tmp31, tmp32, tmp33, tmp34

         !$omp parallel &
         !$omp& private(i, j) &
         !$omp& shared(npt, state) &
         !$omp& default(private)
         !$omp do schedule(dynamic, 16)
         do j = 2, npt
            tmp1 = state%s4(j)
            tmp2 = state%s5(j)
            tmp3 = state%s6(j)
            tmp4 = state%s7(j)
            tmp5 = state%s8(j)
            tmp6 = state%s9(j)
            tmp7 = -tmp2
            tmp10 = -tmp3
            tmp14 = -tmp5
            !$omp simd &
            !$omp& private(tmp8, tmp9, tmp11, tmp12, tmp13, tmp15, tmp16, tmp17) &
            !$omp& private(tmp18, tmp19, tmp20, tmp21, tmp22, tmp23, tmp24, tmp25) &
            !$omp& private(tmp26, tmp27, tmp28, tmp29, tmp30, tmp31, tmp32, tmp33) &
            !$omp& private(tmp34)
            do i = 1, j - 1
               tmp8 = state%s5(i) + tmp7
               tmp9 = tmp1*tmp8
               tmp11 = state%s6(i) + tmp10
               tmp12 = tmp11*tmp4
               tmp13 = tmp9 + tmp12
               tmp15 = state%s8(i) + tmp14
               tmp16 = tmp15*tmp6
               tmp17 = tmp13 + tmp16
               tmp18 = tmp8**(2)
               tmp19 = tmp11**(2)
               tmp20 = tmp18 + tmp19
               tmp21 = tmp15**(2)
               tmp22 = tmp20 + tmp21
               tmp23 = 1.0_wp/sqrt(tmp22)
               tmp24 = tmp23**(3)
               tmp25 = tmp17*tmp24
               state%s10(i, j) = tmp25
               tmp26 = -tmp8
               tmp27 = state%s4(i)*tmp26
               tmp28 = -tmp11
               tmp29 = tmp28*state%s7(i)
               tmp30 = tmp27 + tmp29
               tmp31 = -tmp15
               tmp32 = tmp31*state%s9(i)
               tmp33 = tmp30 + tmp32
               tmp34 = tmp33*tmp24
               state%s10(j, i) = tmp34
            end do
         end do
         !$omp end do
         !$omp end parallel
      end block
      do i = 1, npt
         tmp35 = state%k1(i) + state%k2(i)
         tmp36 = 1.0_wp/state%a(i)
         tmp37 = 12.566370614359172_wp*tmp36
         tmp38 = sqrt(tmp37)
         tmp39 = tmp35*tmp38
         tmp40 = (-0.26735_wp)*tmp39
         state%s10(i, i) = tmp40
      end do

      state%ready = 1
      state%assembled = state%assembled + 1
   end subroutine dpcm_point_assemble

   module subroutine dpcm_point_medium(state, eps, error)
      !> State of dpcm_point
      type(dpcm_point_state), target, intent(inout) :: state
      !> Relative permittivity of the solvent (inf for a conductor)
      real(wp), intent(in) :: eps
      !> Error handling
      type(error_type), allocatable, intent(out) :: error

      integer :: npt
      integer :: stat
      real(wp) :: tmp1, tmp2

      if (state%matrix_free) then
         call dpcm_point_mf_medium(state, eps, error)
         return
      end if
      stat = 0
      npt = state%npt
      if (state%ready < 1) then
         call fatal_error(error, "[dpcm_point_medium] call dpcm_point_assemble first")
         return
      end if
      state%ready = 1
      ! Inputs that do not enter these outputs
      associate (unused1 => eps)
      end associate

      state%op1%npt = npt
      state%op1%npoint = npt
      state%op1%id = 1
      state%op1%points => state%r
      state%op1%a => state%a
      state%s1 = eps + 1.0_wp
      tmp1 = 1.0_wp/state%s1
      tmp2 = (-2.0_wp)*tmp1
      state%s2 = 1.0_wp + tmp2
      state%s3 = -state%s2
      state%op1%c1 = state%s3
      state%op1%c2 => state%s10
      call state%solver%setup(state%op1, error)
      if (allocated(error)) return
      state%s12 = 0.5_wp*state%s2

      state%ready = 2
   end subroutine dpcm_point_medium

   module subroutine dpcm_point_solve(state, v, vn, energy, q, grad_v, grad_vn, error)
      !> State of dpcm_point
      type(dpcm_point_state), target, intent(inout) :: state
      !> Solute electrostatic potential at the surface points
      real(wp), contiguous, intent(in) :: v(:)
      !> Outward normal derivative of the solute potential at the surface points
      real(wp), contiguous, intent(in) :: vn(:)
      !> Solvation energy
      real(wp), intent(out) :: energy
      !> Apparent surface charges
      real(wp), contiguous, intent(out) :: q(:)
      !> Partial derivative of the energy with respect to v
      real(wp), contiguous, intent(out) :: grad_v(:)
      !> Partial derivative of the energy with respect to vn
      real(wp), contiguous, intent(out) :: grad_vn(:)
      !> Error handling
      type(error_type), allocatable, intent(out) :: error

      integer :: npt
      integer :: stat
      real(wp), allocatable :: tmp1(:), tmp3(:), tmp4(:), tmp5(:), tmp6(:), tmp7(:), tmp8(:)
      real(wp) :: tmp2, tmp9

      if (state%matrix_free) then
         call dpcm_point_mf_solve(state, v, vn, energy, q, grad_v, grad_vn, error)
         return
      end if
      stat = 0
      npt = state%npt
      if (state%ready < 2) then
         call fatal_error(error, "[dpcm_point_solve] call dpcm_point_medium first")
         return
      end if
      if (any(shape(v) /= [npt])) then
         call fatal_error(error, "[dpcm_point_solve] v: wrong shape")
         return
      end if
      if (any(shape(vn) /= [npt])) then
         call fatal_error(error, "[dpcm_point_solve] vn: wrong shape")
         return
      end if
      if (any(shape(q) /= [npt])) then
         call fatal_error(error, "[dpcm_point_solve] q: wrong shape")
         return
      end if
      if (any(shape(grad_v) /= [npt])) then
         call fatal_error(error, "[dpcm_point_solve] grad_v: wrong shape")
         return
      end if
      if (any(shape(grad_vn) /= [npt])) then
         call fatal_error(error, "[dpcm_point_solve] grad_vn: wrong shape")
         return
      end if
      allocate (tmp1(npt), stat=stat)
      if (stat == 0) allocate (tmp3(npt), stat=stat)
      if (stat == 0) allocate (tmp4(npt), stat=stat)
      if (stat == 0) allocate (tmp5(npt), stat=stat)
      if (stat == 0) allocate (tmp6(npt), stat=stat)
      if (stat == 0) allocate (tmp7(npt), stat=stat)
      if (stat == 0) allocate (tmp8(npt), stat=stat)
      if (stat /= 0) then
         call fatal_error(error, "[dpcm_point_solve] allocation failed")
         return
      end if
      state%ready = 2

      state%op1%points => state%r
      state%op1%a => state%a
      state%op1%c2 => state%s10
      state%v = v
      state%vn = vn
      tmp1 = state%a*state%vn
      call state%solver%solve(state%op1, .false., tmp1, state%s11, error)
      if (allocated(error)) return
      call state%solver%solve(state%op1, .true., state%v, state%s13, error)
      if (allocated(error)) return
      state%s14 = state%s12*state%s13
      call gemv(state%s10, state%s11, state%s15, trans="t")
      q = state%s2*state%s11
      tmp2 = dot(state%v, q)
      energy = 0.5_wp*tmp2
      grad_v = state%s12*state%s11
      grad_vn = state%s14*state%a
      if (state%solver%inexact()) then
         ! First-order correction for the residuals of the solves
         tmp3 = 6.283185307179586_wp*state%s11
         tmp4 = state%a*state%s15
         tmp5 = state%s3*tmp4
         tmp6 = tmp3 + tmp5
         tmp7 = -tmp6
         tmp8 = tmp1 + tmp7
         tmp9 = dot(state%s14, tmp8)
         energy = energy + tmp9
      end if

      state%ready = 3
   end subroutine dpcm_point_solve

end submodule pcmgen_point_dpcm_energy
