   module subroutine dpcm_point_complex_mf_response(state, dv, dvn, hvp_v, hvp_vn, error)
      !> State of dpcm_point
      type(dpcm_point_complex_state), intent(inout) :: state
      !> Direction for v
      complex(wp), contiguous, intent(in) :: dv(:, :)
      !> Direction for vn
      complex(wp), contiguous, intent(in) :: dvn(:, :)
      !> Hessian times direction, v block
      complex(wp), contiguous, intent(out) :: hvp_v(:, :)
      !> Hessian times direction, vn block
      complex(wp), contiguous, intent(out) :: hvp_vn(:, :)
      !> Error handling
      type(error_type), allocatable, intent(out) :: error

      integer :: npt, nblk, blk

      if (state%cx_ready < 3 .or. state%cx_assembled /= state%assembled) then
         call fatal_error(error, &
                          "[dpcm_point_complex_mf_response] call dpcm_point_complex_solve first")
         return
      end if
      npt = state%npt
      nblk = size(dv, 2)
      if (any(shape(dv) /= [npt, nblk])) then
         call fatal_error(error, "[dpcm_point_complex_mf_response] dv: wrong shape")
         return
      end if
      if (any(shape(dvn) /= [npt, nblk])) then
         call fatal_error(error, "[dpcm_point_complex_mf_response] dvn: wrong shape")
         return
      end if
      if (any(shape(hvp_v) /= [npt, nblk])) then
         call fatal_error(error, "[dpcm_point_complex_mf_response] hvp_v: wrong shape")
         return
      end if
      if (any(shape(hvp_vn) /= [npt, nblk])) then
         call fatal_error(error, "[dpcm_point_complex_mf_response] hvp_vn: wrong shape")
         return
      end if
      do blk = 1, nblk
         call dpcm_point_complex_mf_response_one(state, dv(:, blk), dvn(:, blk), hvp_v(:, blk), &
                                                 hvp_vn(:, blk), error)
         if (allocated(error)) return
      end do
   end subroutine dpcm_point_complex_mf_response

   !> One direction of dpcm_point_complex_mf_response
   !>
   !> - Vectors have length npt, matrices are (npt, npt), point fields (3, npt)
   !> - Outputs are undefined if error is allocated
   !>
   !> @param[in,out] state  state of dpcm_point
   !> @param[in] dv  direction for v
   !> @param[in] dvn  direction for vn
   !> @param[out] hvp_v  hessian times direction, v block
   !> @param[out] hvp_vn  hessian times direction, vn block
   !> @param[out] error  error handling; allocated on failure
   subroutine dpcm_point_complex_mf_response_one(state, dv, dvn, hvp_v, hvp_vn, error)
      !> State of dpcm_point
      type(dpcm_point_complex_state), target, intent(inout) :: state
      !> Direction for v
      complex(wp), contiguous, intent(in) :: dv(:)
      !> Direction for vn
      complex(wp), contiguous, intent(in) :: dvn(:)
      !> Hessian times direction, v block
      complex(wp), contiguous, intent(out) :: hvp_v(:)
      !> Hessian times direction, vn block
      complex(wp), contiguous, intent(out) :: hvp_vn(:)
      !> Error handling
      type(error_type), allocatable, intent(out) :: error

      integer :: npt
      integer :: stat
      complex(wp), allocatable :: tmp1(:), tmp2(:), tmp3(:), tmp4(:)

      stat = 0
      npt = state%npt
      if (any(shape(dv) /= [npt])) then
         call fatal_error(error, "[dpcm_point_complex_mf_response_one] dv: wrong shape")
         return
      end if
      if (any(shape(dvn) /= [npt])) then
         call fatal_error(error, "[dpcm_point_complex_mf_response_one] dvn: wrong shape")
         return
      end if
      if (any(shape(hvp_v) /= [npt])) then
         call fatal_error(error, "[dpcm_point_complex_mf_response_one] hvp_v: wrong shape")
         return
      end if
      if (any(shape(hvp_vn) /= [npt])) then
         call fatal_error(error, "[dpcm_point_complex_mf_response_one] hvp_vn: wrong shape")
         return
      end if
      allocate (tmp1(npt), stat=stat)
      if (stat == 0) allocate (tmp2(npt), stat=stat)
      if (stat == 0) allocate (tmp3(npt), stat=stat)
      if (stat == 0) allocate (tmp4(npt), stat=stat)
      if (stat /= 0) then
         call fatal_error(error, "[dpcm_point_complex_mf_response_one] allocation failed")
         return
      end if

      state%op4%points => state%r
      state%op4%r => state%r
      state%op4%n => state%n
      state%op4%k1 => state%k1
      state%op4%k2 => state%k2
      state%op4%a => state%a
      tmp1 = state%a*dvn
      tmp2 = 0.0_wp
      call state%solver%solve_complex(state%op4, .false., tmp1, tmp2, error)
      if (allocated(error)) return
      hvp_v = state%cx_s12*tmp2
      tmp3 = 0.0_wp
      call state%solver%solve_complex(state%op4, .true., dv, tmp3, error)
      if (allocated(error)) return
      tmp4 = state%cx_s12*tmp3
      hvp_vn = tmp4*state%a
   end subroutine dpcm_point_complex_mf_response_one

