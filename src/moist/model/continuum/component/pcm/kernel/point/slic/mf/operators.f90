               tmp22 = tmp13*tmp21
               tmp24 = self%r(2, i) + tmp23
               tmp25 = tmp24*tmp16
               tmp26 = tmp22 + tmp25
               tmp28 = self%r(3, i) + tmp27
               tmp29 = tmp28*tmp18
               tmp30 = tmp26 + tmp29
               tmp31 = tmp21**(2)
               tmp32 = tmp24**(2)
               tmp33 = tmp31 + tmp32
               tmp34 = tmp28**(2)
