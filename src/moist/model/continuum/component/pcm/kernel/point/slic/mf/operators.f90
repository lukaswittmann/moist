   module subroutine slic_point_nl2_step(self, x, f, p, error)
      !> Problem
      class(slic_point_nl2), intent(in) :: self
      !> Unknowns
      real(wp), contiguous, intent(in) :: x(:)
      !> Residual at x
      real(wp), contiguous, intent(in) :: f(:)
      !> Newton step
      real(wp), contiguous, intent(out) :: p(:)
      !> Error handling
      type(error_type), allocatable, intent(out) :: error

      type(slic_point_op2) :: op2
      integer :: npt
      integer :: stat
      real(wp), allocatable :: tmp1(:), tmp2(:), tmp3(:), tmp4(:), tmp11(:), tmp40(:), tmp41(:), &
                               tmp42(:), tmp43(:)
      real(wp), allocatable, target :: tmp44(:), tmp54(:)
