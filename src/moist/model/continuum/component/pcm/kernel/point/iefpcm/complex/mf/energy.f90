contains

   module subroutine iefpcm_point_complex_mf_medium(state, eps, error)
      !> State of iefpcm_point
      type(iefpcm_point_complex_state), target, intent(inout) :: state
      !> Relative permittivity of the solvent (inf for a conductor)
      complex(wp), intent(in) :: eps
      !> Error handling
      type(error_type), allocatable, intent(out) :: error

      integer :: npt
      integer :: stat
      complex(wp) :: tmp1, tmp2

      stat = 0
      npt = state%npt
      if (state%ready < 1) then
         call fatal_error(error, &
                          "[iefpcm_point_complex_mf_medium] call iefpcm_point_assemble first")
         return
      end if
      state%cx_ready = 0
      if (allocated(state%cx_v)) deallocate (state%cx_v)
      if (allocated(state%cx_s13)) deallocate (state%cx_s13)
      if (allocated(state%cx_s14)) deallocate (state%cx_s14)
      if (allocated(state%cx_s16)) deallocate (state%cx_s16)
      if (allocated(state%cx_s18)) deallocate (state%cx_s18)
      if (allocated(state%cx_s19)) deallocate (state%cx_s19)
      if (allocated(state%cx_s20)) deallocate (state%cx_s20)
      if (allocated(state%cx_s21)) deallocate (state%cx_s21)
      if (allocated(state%cx_s23)) deallocate (state%cx_s23)
      if (allocated(state%cx_s25)) deallocate (state%cx_s25)
      if (allocated(state%cx_s26)) deallocate (state%cx_s26)
      if (allocated(state%cx_s27)) deallocate (state%cx_s27)
      if (allocated(state%cx_s28)) deallocate (state%cx_s28)
      if (allocated(state%cx_s29)) deallocate (state%cx_s29)
      if (allocated(state%cx_s30)) deallocate (state%cx_s30)
      if (allocated(state%cx_s31)) deallocate (state%cx_s31)
      if (allocated(state%cx_s32)) deallocate (state%cx_s32)
      if (stat == 0) allocate (state%cx_v(npt), stat=stat)
      if (stat == 0) allocate (state%cx_s13(npt), stat=stat)
      if (stat == 0) allocate (state%cx_s14(npt), stat=stat)
      if (stat == 0) allocate (state%cx_s16(npt), stat=stat)
      if (stat == 0) allocate (state%cx_s18(npt), stat=stat)
      if (stat == 0) allocate (state%cx_s19(npt), stat=stat)
      if (stat == 0) allocate (state%cx_s20(npt), stat=stat)
      if (stat == 0) allocate (state%cx_s21(npt), stat=stat)
      if (stat == 0) allocate (state%cx_s23(npt), stat=stat)
      if (stat == 0) allocate (state%cx_s25(npt), stat=stat)
      if (stat == 0) allocate (state%cx_s26(npt), stat=stat)
      if (stat == 0) allocate (state%cx_s27(npt), stat=stat)
      if (stat == 0) allocate (state%cx_s28(npt), stat=stat)
      if (stat == 0) allocate (state%cx_s29(npt), stat=stat)
      if (stat == 0) allocate (state%cx_s30(npt), stat=stat)
      if (stat == 0) allocate (state%cx_s31(npt), stat=stat)
      if (stat == 0) allocate (state%cx_s32(npt), stat=stat)
      if (stat /= 0) then
         call fatal_error(error, "[iefpcm_point_complex_mf_medium] allocation failed")
         return
      end if
      state%cx_s14 = 0.0_wp
      state%cx_s16 = 0.0_wp
      state%cx_ready = 1
      state%cx_assembled = state%assembled
      ! Inputs that do not enter these outputs
      associate (unused1 => eps)
      end associate

      state%op4%npt = npt
      state%op4%npoint = npt
      state%op4%id = 4
      state%op4%points => state%r
      state%op4%r => state%r
      state%op4%n => state%n
      state%op4%k1 => state%k1
      state%op4%k2 => state%k2
      state%op4%a => state%a
      state%cx_s1 = eps + 1.0_wp
      tmp1 = 1.0_wp/state%cx_s1
      tmp2 = (-2.0_wp)*tmp1
      state%cx_s2 = 1.0_wp + tmp2
      state%cx_s8 = (-0.15915494309189535_wp)*state%cx_s2
      state%op4%c1 = state%cx_s8
      call state%solver%setup_complex(state%op4, error)
      if (allocated(error)) return
      state%cx_s3 = -state%cx_s2
      state%cx_s15 = (-0.5_wp)*state%cx_s2
      state%cx_s17 = 0.07957747154594767_wp*state%cx_s2
      state%cx_s24 = 0.5_wp*state%cx_s2

      state%cx_ready = 2
   end subroutine iefpcm_point_complex_mf_medium

   module subroutine iefpcm_point_complex_mf_solve(state, v, energy, q, grad_v, error)
      !> State of iefpcm_point
      type(iefpcm_point_complex_state), target, intent(inout) :: state
      !> Solute electrostatic potential at the surface points
      complex(wp), contiguous, intent(in) :: v(:)
      !> Solvation energy
      complex(wp), intent(out) :: energy
      !> Apparent surface charges
      complex(wp), contiguous, intent(out) :: q(:)
      !> Partial derivative of the energy with respect to v
      complex(wp), contiguous, intent(out) :: grad_v(:)
      !> Error handling
      type(error_type), allocatable, intent(out) :: error

      integer :: npt
      integer :: stat
      real(wp), allocatable :: tmp2(:), tmp47(:)
      real(wp) :: tmp3, tmp4, tmp5, tmp6, tmp7, tmp8, tmp48, tmp49, tmp50, tmp51
      complex(wp), allocatable :: tmp1(:), tmp9(:), tmp10(:), tmp11(:), tmp12(:), tmp45(:), &
                                  tmp46(:), tmp52(:), tmp71(:), tmp72(:), tmp73(:), tmp74(:), &
                                  tmp75(:), tmp76(:), tmp104(:), tmp105(:), tmp106(:), tmp107(:)
      complex(wp) :: tmp70, tmp108
      complex(wp), allocatable :: tmp1_p(:), tmp46_p(:), tmp75_p(:)
      integer :: i, j

      stat = 0
      npt = state%npt
      if (state%cx_ready < 2 .or. state%cx_assembled /= state%assembled) then
         call fatal_error(error, &
                          "[iefpcm_point_complex_mf_solve] call iefpcm_point_complex_medium first")
         return
      end if
      if (any(shape(v) /= [npt])) then
         call fatal_error(error, "[iefpcm_point_complex_mf_solve] v: wrong shape")
         return
      end if
      if (any(shape(q) /= [npt])) then
         call fatal_error(error, "[iefpcm_point_complex_mf_solve] q: wrong shape")
         return
      end if
      if (any(shape(grad_v) /= [npt])) then
         call fatal_error(error, "[iefpcm_point_complex_mf_solve] grad_v: wrong shape")
         return
      end if
      allocate (tmp1(npt), stat=stat)
      if (stat == 0) allocate (tmp2(npt), stat=stat)
      if (stat == 0) allocate (tmp9(npt), stat=stat)
      if (stat == 0) allocate (tmp10(npt), stat=stat)
      if (stat == 0) allocate (tmp11(npt), stat=stat)
      if (stat == 0) allocate (tmp12(npt), stat=stat)
      if (stat == 0) allocate (tmp45(npt), stat=stat)
      if (stat == 0) allocate (tmp46(npt), stat=stat)
      if (stat == 0) allocate (tmp47(npt), stat=stat)
      if (stat == 0) allocate (tmp52(npt), stat=stat)
      if (stat == 0) allocate (tmp71(npt), stat=stat)
      if (stat == 0) allocate (tmp72(npt), stat=stat)
      if (stat == 0) allocate (tmp73(npt), stat=stat)
      if (stat == 0) allocate (tmp74(npt), stat=stat)
      if (stat == 0) allocate (tmp75(npt), stat=stat)
      if (stat == 0) allocate (tmp76(npt), stat=stat)
      if (stat == 0) allocate (tmp104(npt), stat=stat)
      if (stat == 0) allocate (tmp105(npt), stat=stat)
      if (stat == 0) allocate (tmp106(npt), stat=stat)
      if (stat == 0) allocate (tmp107(npt), stat=stat)
      if (stat /= 0) then
         call fatal_error(error, "[iefpcm_point_complex_mf_solve] allocation failed")
         return
      end if
      state%cx_ready = 2

      state%op4%points => state%r
      state%op4%r => state%r
      state%op4%n => state%n
      state%op4%k1 => state%k1
      state%op4%k2 => state%k2
      state%op4%a => state%a
      state%cx_v = v
      state%cx_s13 = state%a*state%cx_v
      call state%solver%solve_complex(state%op4, .true., state%cx_v, state%cx_s16, error)
      if (allocated(error)) return
      state%cx_s18 = state%cx_s17*state%cx_s16
      do i = 1, npt
         tmp3 = state%k1(i) + state%k2(i)
         tmp4 = 1.0_wp/state%a(i)
         tmp5 = 12.566370614359172_wp*tmp4
         tmp6 = sqrt(tmp5)
         tmp7 = tmp3*tmp6
         tmp8 = (-0.26735_wp)*tmp7
         tmp2(i) = tmp8
      end do
      tmp9 = tmp2*state%cx_s13
      tmp10 = (-0.15915494309189535_wp)*tmp9
      tmp1 = tmp10
      tmp12 = tmp2*state%cx_s18
      tmp11 = tmp12
      block
         real(wp) :: tmp15, tmp16, tmp17, tmp18, tmp19, tmp20, tmp22, tmp25, tmp29, tmp23, tmp24, &
                     tmp26, tmp27, tmp28, tmp30, tmp31, tmp32, tmp34, tmp35, tmp36, tmp37, tmp38, &
                     tmp39, tmp40, tmp43
         complex(wp) :: tmp14, tmp21, tmp13, tmp33, tmp41, tmp42, tmp44

         !$omp parallel &
         !$omp& private(i, j, tmp1_p) &
         !$omp& shared(npt, state, tmp1, tmp11) &
         !$omp& default(private)
         allocate (tmp1_p(npt))
         tmp1_p = 0.0_wp
         !$omp do schedule(static)
         do j = 1, npt
            tmp14 = state%cx_s13(j)
            tmp15 = state%s9(j)
            tmp16 = state%s4(j)
            tmp17 = state%s5(j)
            tmp18 = state%s10(j)
            tmp19 = state%s6(j)
            tmp20 = state%s11(j)
            tmp21 = state%cx_s18(j)
            tmp22 = -tmp16
            tmp25 = -tmp17
            tmp29 = -tmp19
            tmp13 = 0.0_wp
            !$omp simd &
            !$omp& private(tmp23, tmp24, tmp26, tmp27, tmp28, tmp30, tmp31, tmp32) &
            !$omp& private(tmp33, tmp34, tmp35, tmp36, tmp37, tmp38, tmp39, tmp40) &
            !$omp& private(tmp41, tmp42, tmp43, tmp44) &
            !$omp& reduction(+: tmp13)
            do i = 1, j - 1
               tmp23 = state%s4(i) + tmp22
               tmp24 = tmp15*tmp23
               tmp26 = state%s5(i) + tmp25
               tmp27 = tmp26*tmp18
               tmp28 = tmp24 + tmp27
               tmp30 = state%s6(i) + tmp29
               tmp31 = tmp30*tmp20
               tmp32 = tmp28 + tmp31
               tmp33 = tmp14*tmp32
               tmp34 = tmp23**(2)
               tmp35 = tmp26**(2)
               tmp36 = tmp34 + tmp35
               tmp37 = tmp30**(2)
               tmp38 = tmp36 + tmp37
               tmp39 = 1.0_wp/sqrt(tmp38)
               tmp40 = tmp39**(3)
               tmp41 = tmp33*tmp40
               tmp42 = (-0.15915494309189535_wp)*tmp41
               tmp1_p(i) = tmp1_p(i) + tmp42
               tmp43 = tmp32*tmp40
               tmp44 = tmp43*state%cx_s18(i)
               tmp13 = tmp13 + tmp44
            end do
            !$omp simd &
            !$omp& private(tmp23, tmp24, tmp26, tmp27, tmp28, tmp30, tmp31, tmp32) &
            !$omp& private(tmp33, tmp34, tmp35, tmp36, tmp37, tmp38, tmp39, tmp40) &
            !$omp& private(tmp41, tmp42, tmp43, tmp44) &
            !$omp& reduction(+: tmp13)
            do i = j + 1, npt
               tmp23 = state%s4(i) + tmp22
               tmp24 = tmp15*tmp23
               tmp26 = state%s5(i) + tmp25
               tmp27 = tmp26*tmp18
               tmp28 = tmp24 + tmp27
               tmp30 = state%s6(i) + tmp29
               tmp31 = tmp30*tmp20
               tmp32 = tmp28 + tmp31
               tmp33 = tmp14*tmp32
               tmp34 = tmp23**(2)
               tmp35 = tmp26**(2)
               tmp36 = tmp34 + tmp35
               tmp37 = tmp30**(2)
               tmp38 = tmp36 + tmp37
               tmp39 = 1.0_wp/sqrt(tmp38)
               tmp40 = tmp39**(3)
               tmp41 = tmp33*tmp40
               tmp42 = (-0.15915494309189535_wp)*tmp41
               tmp1_p(i) = tmp1_p(i) + tmp42
               tmp43 = tmp32*tmp40
               tmp44 = tmp43*state%cx_s18(i)
               tmp13 = tmp13 + tmp44
            end do
            tmp11(j) = tmp11(j) + tmp13
         end do
         !$omp end do
         !$omp critical (pcmgen_sum)
         tmp1 = tmp1 + tmp1_p
         !$omp end critical (pcmgen_sum)
         deallocate (tmp1_p)
         !$omp end parallel
      end block
      state%cx_s19 = tmp11
      tmp45 = state%cx_v + tmp1
      call state%solver%solve_complex(state%op4, .false., tmp45, state%cx_s14, error)
      if (allocated(error)) return
      do i = 1, npt
         tmp48 = 1.0_wp/state%a(i)
         tmp49 = 12.566370614359172_wp*tmp48
         tmp50 = sqrt(tmp49)
         tmp51 = 1.0694_wp*tmp50
         tmp47(i) = tmp51
      end do
      tmp52 = tmp47*state%cx_s14
      tmp46 = tmp52
      block
         real(wp) :: tmp54, tmp55, tmp56, tmp57, tmp60, tmp64, tmp58, tmp59, tmp61, tmp62, tmp63, &
                     tmp65, tmp66, tmp67, tmp68
         complex(wp) :: tmp53, tmp69

         !$omp parallel &
         !$omp& private(i, j, tmp46_p) &
         !$omp& shared(npt, state, tmp46) &
         !$omp& default(private)
         allocate (tmp46_p(npt))
         tmp46_p = 0.0_wp
         !$omp do schedule(static)
         do j = 1, npt
            tmp53 = state%cx_s14(j)
            tmp54 = state%s4(j)
            tmp55 = state%s5(j)
            tmp56 = state%s6(j)
            tmp57 = -tmp54
            tmp60 = -tmp55
            tmp64 = -tmp56
            !$omp simd &
            !$omp& private(tmp58, tmp59, tmp61, tmp62, tmp63, tmp65, tmp66, tmp67) &
            !$omp& private(tmp68, tmp69)
            do i = 1, j - 1
               tmp58 = state%s4(i) + tmp57
               tmp59 = tmp58**(2)
               tmp61 = state%s5(i) + tmp60
               tmp62 = tmp61**(2)
               tmp63 = tmp59 + tmp62
               tmp65 = state%s6(i) + tmp64
               tmp66 = tmp65**(2)
               tmp67 = tmp63 + tmp66
               tmp68 = 1.0_wp/sqrt(tmp67)
               tmp69 = tmp53*tmp68
               tmp46_p(i) = tmp46_p(i) + tmp69
            end do
            !$omp simd &
            !$omp& private(tmp58, tmp59, tmp61, tmp62, tmp63, tmp65, tmp66, tmp67) &
            !$omp& private(tmp68, tmp69)
            do i = j + 1, npt
               tmp58 = state%s4(i) + tmp57
               tmp59 = tmp58**(2)
               tmp61 = state%s5(i) + tmp60
               tmp62 = tmp61**(2)
               tmp63 = tmp59 + tmp62
               tmp65 = state%s6(i) + tmp64
               tmp66 = tmp65**(2)
               tmp67 = tmp63 + tmp66
               tmp68 = 1.0_wp/sqrt(tmp67)
               tmp69 = tmp53*tmp68
               tmp46_p(i) = tmp46_p(i) + tmp69
            end do
         end do
         !$omp end do
         !$omp critical (pcmgen_sum)
         tmp46 = tmp46 + tmp46_p
         !$omp end critical (pcmgen_sum)
         deallocate (tmp46_p)
         !$omp end parallel
      end block
      state%cx_s20 = tmp46
      state%cx_s21 = state%a*state%cx_s20
      state%cx_s25 = state%cx_s24*state%cx_s16
      q = state%cx_s3*state%cx_s14
      tmp70 = sum(state%cx_v*q)
      energy = 0.5_wp*tmp70
      tmp71 = state%cx_s15*state%cx_s14
      tmp72 = state%cx_s15*state%cx_s16
      tmp73 = tmp71 + tmp72
      tmp74 = state%cx_s19*state%a
      grad_v = tmp73 + tmp74
      if (state%solver%inexact()) then
         ! First-order correction for the residuals of the solves
         tmp76 = tmp2*state%cx_s21
         tmp75 = tmp76
         block
            real(wp) :: tmp78, tmp79, tmp80, tmp81, tmp82, tmp83, tmp84, tmp87, tmp91, tmp85, &
                        tmp86, tmp88, tmp89, tmp90, tmp92, tmp93, tmp94, tmp96, tmp97, tmp98, &
                        tmp99, tmp100, tmp101, tmp102
            complex(wp) :: tmp77, tmp95, tmp103

            !$omp parallel &
            !$omp& private(i, j, tmp75_p) &
            !$omp& shared(npt, state, tmp75) &
            !$omp& default(private)
            allocate (tmp75_p(npt))
            tmp75_p = 0.0_wp
            !$omp do schedule(static)
            do j = 1, npt
               tmp77 = state%cx_s21(j)
               tmp78 = state%s9(j)
               tmp79 = state%s4(j)
               tmp80 = state%s5(j)
               tmp81 = state%s10(j)
               tmp82 = state%s6(j)
               tmp83 = state%s11(j)
               tmp84 = -tmp79
               tmp87 = -tmp80
               tmp91 = -tmp82
               !$omp simd &
               !$omp& private(tmp85, tmp86, tmp88, tmp89, tmp90, tmp92, tmp93, tmp94) &
               !$omp& private(tmp95, tmp96, tmp97, tmp98, tmp99, tmp100, tmp101) &
               !$omp& private(tmp102, tmp103)
               do i = 1, j - 1
                  tmp85 = state%s4(i) + tmp84
                  tmp86 = tmp78*tmp85
                  tmp88 = state%s5(i) + tmp87
                  tmp89 = tmp88*tmp81
                  tmp90 = tmp86 + tmp89
                  tmp92 = state%s6(i) + tmp91
                  tmp93 = tmp92*tmp83
                  tmp94 = tmp90 + tmp93
                  tmp95 = tmp77*tmp94
                  tmp96 = tmp85**(2)
                  tmp97 = tmp88**(2)
                  tmp98 = tmp96 + tmp97
                  tmp99 = tmp92**(2)
                  tmp100 = tmp98 + tmp99
                  tmp101 = 1.0_wp/sqrt(tmp100)
                  tmp102 = tmp101**(3)
                  tmp103 = tmp95*tmp102
                  tmp75_p(i) = tmp75_p(i) + tmp103
               end do
               !$omp simd &
               !$omp& private(tmp85, tmp86, tmp88, tmp89, tmp90, tmp92, tmp93, tmp94) &
               !$omp& private(tmp95, tmp96, tmp97, tmp98, tmp99, tmp100, tmp101) &
               !$omp& private(tmp102, tmp103)
               do i = j + 1, npt
                  tmp85 = state%s4(i) + tmp84
                  tmp86 = tmp78*tmp85
                  tmp88 = state%s5(i) + tmp87
                  tmp89 = tmp88*tmp81
                  tmp90 = tmp86 + tmp89
                  tmp92 = state%s6(i) + tmp91
                  tmp93 = tmp92*tmp83
                  tmp94 = tmp90 + tmp93
                  tmp95 = tmp77*tmp94
                  tmp96 = tmp85**(2)
                  tmp97 = tmp88**(2)
                  tmp98 = tmp96 + tmp97
                  tmp99 = tmp92**(2)
                  tmp100 = tmp98 + tmp99
                  tmp101 = 1.0_wp/sqrt(tmp100)
                  tmp102 = tmp101**(3)
                  tmp103 = tmp95*tmp102
                  tmp75_p(i) = tmp75_p(i) + tmp103
               end do
            end do
            !$omp end do
            !$omp critical (pcmgen_sum)
            tmp75 = tmp75 + tmp75_p
            !$omp end critical (pcmgen_sum)
            deallocate (tmp75_p)
            !$omp end parallel
         end block
         tmp104 = state%cx_s8*tmp75
         tmp105 = state%cx_s20 + tmp104
         tmp106 = -tmp105
         tmp107 = tmp45 + tmp106
         tmp108 = sum(tmp72*tmp107)
         energy = energy + tmp108
      end if

      state%cx_ready = 3
   end subroutine iefpcm_point_complex_mf_solve

end submodule pcmgen_point_iefpcm_complex_mf_energy
