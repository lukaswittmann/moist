      !> Error handling
      type(error_type), allocatable, intent(out) :: error

      integer :: npt
      integer :: stat
      type(slic_point_nl1) :: nl1
      real(wp), allocatable :: tmp1(:), tmp2(:), tmp3(:), tmp22(:), tmp33(:), tmp34(:), tmp35(:), &
