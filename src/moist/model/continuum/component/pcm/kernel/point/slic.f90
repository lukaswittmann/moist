         !$omp& private(i) &
         !$omp& shared(npt, state) &
         !$omp& default(private)
         do j = 1, npt
            do i = 1, j - 1
               tmp1 = -state%s2(j)
               tmp2 = state%s2(i) + tmp1
               tmp3 = state%s1(j)*tmp2
               tmp4 = -state%s3(j)
               tmp5 = state%s3(i) + tmp4
               tmp6 = tmp5*state%s4(j)
               tmp7 = tmp3 + tmp6
