   !> SLIC (point charges): gradient tangents along blocks of directions
   !>
   !> - Directions of the cavity and QM inputs; for the inputs of the last solve
   !> - Needs slic_point_weights on the same state first; keeps the state as it is
   !> - Arrays carry a last dimension nblk: one direction per column block
   !> - Vectors are (npt, nblk), point fields (3, npt, nblk)
   !> - Outputs are undefined if error is allocated
   !>
   !> @param[in,out] state  state of slic_point
   !> @param[in] dr  direction for r
   !> @param[in] dn  direction for n
   !> @param[in] dk1  direction for k1
   !> @param[in] dk2  direction for k2
   !> @param[in] da  direction for a
   !> @param[in] dv  direction for v
   !> @param[in] dvn  direction for vn
   !> @param[out] hvp_r  hessian times direction, r block
   !> @param[out] hvp_n  hessian times direction, n block
   !> @param[out] hvp_k1  hessian times direction, k1 block
   !> @param[out] hvp_k2  hessian times direction, k2 block
   !> @param[out] hvp_a  hessian times direction, a block
   !> @param[out] hvp_v  hessian times direction, v block
   !> @param[out] hvp_vn  hessian times direction, vn block
   !> @param[out] error  error handling; allocated on failure
   subroutine slic_point_tangent(state, dr, dn, dk1, dk2, da, dv, dvn, hvp_r, hvp_n, hvp_k1, &
                                 hvp_k2, hvp_a, hvp_v, hvp_vn, error)
      !> State of slic_point
      type(slic_point_state), intent(inout) :: state
      !> Direction for r
      real(wp), contiguous, intent(in) :: dr(:, :, :)
      !> Direction for n
      real(wp), contiguous, intent(in) :: dn(:, :, :)
      !> Direction for k1
      real(wp), contiguous, intent(in) :: dk1(:, :)
      !> Direction for k2
      real(wp), contiguous, intent(in) :: dk2(:, :)
      !> Direction for a
      real(wp), contiguous, intent(in) :: da(:, :)
      !> Direction for v
      real(wp), contiguous, intent(in) :: dv(:, :)
      !> Direction for vn
      real(wp), contiguous, intent(in) :: dvn(:, :)
      !> Hessian times direction, r block
      real(wp), contiguous, intent(out) :: hvp_r(:, :, :)
      !> Hessian times direction, n block
      real(wp), contiguous, intent(out) :: hvp_n(:, :, :)
      !> Hessian times direction, k1 block
      real(wp), contiguous, intent(out) :: hvp_k1(:, :)
      !> Hessian times direction, k2 block
      real(wp), contiguous, intent(out) :: hvp_k2(:, :)
      !> Hessian times direction, a block
      real(wp), contiguous, intent(out) :: hvp_a(:, :)
      !> Hessian times direction, v block
      real(wp), contiguous, intent(out) :: hvp_v(:, :)
      !> Hessian times direction, vn block
      real(wp), contiguous, intent(out) :: hvp_vn(:, :)
      !> Error handling
      type(error_type), allocatable, intent(out) :: error

      integer :: npt, nblk, blk

      if (state%matrix_free) then
         call slic_point_mf_tangent(state, dr, dn, dk1, dk2, da, dv, dvn, hvp_r, hvp_n, hvp_k1, &
                                    hvp_k2, hvp_a, hvp_v, hvp_vn, error)
         return
      end if
      if (state%ready < 4) then
         call fatal_error(error, "[slic_point_tangent] call slic_point_weights first")
         return
      end if
      npt = state%npt
      nblk = size(dr, 3)
      if (any(shape(dr) /= [3, npt, nblk])) then
         call fatal_error(error, "[slic_point_tangent] dr: wrong shape")
         return
      end if
      if (any(shape(dn) /= [3, npt, nblk])) then
         call fatal_error(error, "[slic_point_tangent] dn: wrong shape")
