               tmp30 = tmp20**(2)
               tmp31 = tmp23**(2)
               tmp32 = tmp30 + tmp31
               tmp33 = tmp27**(2)
               tmp34 = tmp32 + tmp33
               tmp35 = 1.0_wp/sqrt(tmp34)
               tmp36 = tmp35**(3)
               tmp37 = tmp29*tmp36
               tmp38 = tmp37*tmp1(i)
               tmp11 = tmp11 + tmp38
            end do
            tmp2(j) = tmp2(j) + tmp11
         end do
         !$omp end do
         !$omp end parallel
      end block
      tmp39 = self%vn + tmp2
      tmp40 = 6.283185307179586_wp*x
      tmp41 = tmp39 + tmp40
      tmp42 = -tmp41
      do i = 1, self%npt
         tmp44 = self%beta*tmp42(i)
         tmp45 = tmp44 + self%c1
         tmp46 = tanh(tmp45)
         tmp47 = self%alpha*tmp46
         tmp48 = tmp47 + self%mu
         tmp49 = self%c2*tmp48
         tmp50 = (-2.0_wp)*tmp49
         tmp51 = 1.0_wp + tmp50
         tmp52 = tmp51*x(i)
         tmp53 = 6.283185307179586_wp*tmp52
         tmp43(i) = tmp53
      end do
      tmp54 = self%c3*tmp39
      f = tmp43 + tmp54
   end subroutine slic_point_nl2_residual

   !> Newton step of nonlinear system 2: p = -J(x)^-1 f
   !>
   !> - Sets up the Jacobian operator at x with the linear solver
   !>
   !> @param[in]     self   problem
   !> @param[in]     x      unknowns
   !> @param[in]     f      residual at x
   !> @param[out]    p      step
   !> @param[out]    error  allocated if an allocation or the linear solve failed
   subroutine slic_point_nl2_step(self, x, f, p, error)
      !> Problem
      class(slic_point_nl2), intent(in) :: self
      !> Unknowns
      real(wp), contiguous, intent(in) :: x(:)
      !> Residual at x
      real(wp), contiguous, intent(in) :: f(:)
      !> Newton step
      real(wp), contiguous, intent(out) :: p(:)
      !> Error handling
      type(error_type), allocatable, intent(out) :: error

      type(slic_point_op2) :: op2
      integer :: npt
      integer :: stat
      real(wp), allocatable :: tmp1(:), tmp2(:), tmp3(:), tmp4(:), tmp11(:), tmp40(:), tmp41(:), &
                               tmp42(:), tmp43(:)
      real(wp), allocatable, target :: tmp44(:), tmp54(:)
      real(wp) :: tmp5, tmp6, tmp7, tmp8, tmp9, tmp10, tmp45, tmp46, tmp47, tmp48, tmp49, tmp50, &
                  tmp51, tmp52, tmp53, tmp55, tmp56, tmp57, tmp58, tmp59, tmp60, tmp61, tmp62, &
                  tmp63
      integer :: i, j

      npt = self%npt
      allocate (tmp1(npt), stat=stat)
      if (stat == 0) allocate (tmp2(npt), stat=stat)
      if (stat == 0) allocate (tmp3(npt), stat=stat)
      if (stat == 0) allocate (tmp4(npt), stat=stat)
      if (stat == 0) allocate (tmp11(npt), stat=stat)
      if (stat == 0) allocate (tmp40(npt), stat=stat)
      if (stat == 0) allocate (tmp41(npt), stat=stat)
      if (stat == 0) allocate (tmp42(npt), stat=stat)
      if (stat == 0) allocate (tmp43(npt), stat=stat)
      if (stat == 0) allocate (tmp44(npt), stat=stat)
      if (stat == 0) allocate (tmp54(npt), stat=stat)
      if (stat /= 0) then
         call fatal_error(error, "[slic_point_nl2_step] allocation failed")
         return
      end if
      tmp1 = x
      op2%npt = npt
      op2%npoint = npt
      op2%id = 2
      op2%points => self%r
      op2%r => self%r
      op2%n => self%n
      op2%k1 => self%k1
      op2%k2 => self%k2
      op2%a => self%a
      tmp2 = self%a*tmp1
      do i = 1, self%npt
         tmp5 = self%k1(i) + self%k2(i)
         tmp6 = 1.0_wp/self%a(i)
         tmp7 = 12.566370614359172_wp*tmp6
         tmp8 = sqrt(tmp7)
         tmp9 = tmp5*tmp8
         tmp10 = (-0.26735_wp)*tmp9
         tmp4(i) = tmp10
      end do
      tmp11 = tmp4*tmp2
      tmp3 = tmp11
      block
         real(wp) :: tmp13, tmp14, tmp15, tmp16, tmp17, tmp18, tmp19, tmp20, tmp23, tmp27, tmp12, &
                     tmp21, tmp22, tmp24, tmp25, tmp26, tmp28, tmp29, tmp30, tmp31, tmp32, tmp33, &
                     tmp34, tmp35, tmp36, tmp37, tmp38, tmp39

         !$omp parallel &
         !$omp& private(i, j) &
         !$omp& shared(self, tmp2, tmp3) &
         !$omp& default(private)
         !$omp do schedule(static)
         do j = 1, self%npt
            tmp13 = self%n(1, j)
            tmp14 = self%r(1, j)
            tmp15 = self%r(2, j)
            tmp16 = self%n(2, j)
            tmp17 = self%r(3, j)
            tmp18 = self%n(3, j)
            tmp19 = tmp2(j)
            tmp20 = -tmp14
            tmp23 = -tmp15
            tmp27 = -tmp17
            tmp12 = 0.0_wp
            !$omp simd &
            !$omp& private(tmp21, tmp22, tmp24, tmp25, tmp26, tmp28, tmp29, tmp30) &
            !$omp& private(tmp31, tmp32, tmp33, tmp34, tmp35, tmp36, tmp37, tmp38) &
            !$omp& private(tmp39) &
            !$omp& reduction(+: tmp12)
            do i = 1, j - 1
               tmp21 = self%r(1, i) + tmp20
               tmp22 = tmp13*tmp21
               tmp24 = self%r(2, i) + tmp23
               tmp25 = tmp24*tmp16
               tmp26 = tmp22 + tmp25
               tmp28 = self%r(3, i) + tmp27
               tmp29 = tmp28*tmp18
               tmp30 = tmp26 + tmp29
               tmp31 = tmp21**(2)
               tmp32 = tmp24**(2)
               tmp33 = tmp31 + tmp32
               tmp34 = tmp28**(2)
               tmp35 = tmp33 + tmp34
               tmp36 = 1.0_wp/sqrt(tmp35)
               tmp37 = tmp36**(3)
               tmp38 = tmp30*tmp37
               tmp39 = tmp38*tmp2(i)
               tmp12 = tmp12 + tmp39
            end do
            !$omp simd &
            !$omp& private(tmp21, tmp22, tmp24, tmp25, tmp26, tmp28, tmp29, tmp30) &
            !$omp& private(tmp31, tmp32, tmp33, tmp34, tmp35, tmp36, tmp37, tmp38) &
            !$omp& private(tmp39) &
            !$omp& reduction(+: tmp12)
            do i = j + 1, self%npt
               tmp21 = self%r(1, i) + tmp20
               tmp22 = tmp13*tmp21
               tmp24 = self%r(2, i) + tmp23
               tmp25 = tmp24*tmp16
               tmp26 = tmp22 + tmp25
               tmp28 = self%r(3, i) + tmp27
               tmp29 = tmp28*tmp18
               tmp30 = tmp26 + tmp29
               tmp31 = tmp21**(2)
               tmp32 = tmp24**(2)
               tmp33 = tmp31 + tmp32
               tmp34 = tmp28**(2)
               tmp35 = tmp33 + tmp34
               tmp36 = 1.0_wp/sqrt(tmp35)
               tmp37 = tmp36**(3)
               tmp38 = tmp30*tmp37
               tmp39 = tmp38*tmp2(i)
               tmp12 = tmp12 + tmp39
            end do
            tmp3(j) = tmp3(j) + tmp12
         end do
         !$omp end do
         !$omp end parallel
      end block
      tmp40 = self%vn + tmp3
      tmp41 = 6.283185307179586_wp*tmp1
      tmp42 = tmp40 + tmp41
      tmp43 = -tmp42
      do i = 1, self%npt
         tmp45 = self%beta*tmp43(i)
         tmp46 = tmp45 + self%c1
         tmp47 = tanh(tmp46)
         tmp48 = tmp47**(2)
         tmp49 = -tmp48
         tmp50 = 1.0_wp + tmp49
         tmp51 = self%c4*tmp50
         tmp52 = tmp51*tmp1(i)
         tmp53 = (-12.566370614359172_wp)*tmp52
         tmp44(i) = tmp53
      end do
      op2%c1 => tmp44
      do i = 1, self%npt
         tmp55 = self%beta*tmp43(i)
         tmp56 = tmp55 + self%c1
         tmp57 = tanh(tmp56)
         tmp58 = self%alpha*tmp57
         tmp59 = tmp58 + self%mu
         tmp60 = self%c2*tmp59
         tmp61 = (-2.0_wp)*tmp60
         tmp62 = 1.0_wp + tmp61
         tmp63 = 6.283185307179586_wp*tmp62
         tmp54(i) = tmp63
      end do
      op2%c2 => tmp54
      op2%c3 = self%c3
      call self%solver%setup(op2, error)
      if (allocated(error)) return
      p = 0.0_wp
      call self%solver%solve(op2, .false., f, p, error)
      if (allocated(error)) return
      p = -p
   end subroutine slic_point_nl2_step

