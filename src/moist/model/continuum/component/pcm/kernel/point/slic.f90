      if (stat == 0) allocate (state%s15(npt), stat=stat)
      if (stat == 0) allocate (state%s16(npt), stat=stat)
      if (stat == 0) allocate (state%s17(npt), stat=stat)
      if (stat == 0) allocate (state%s18(npt), stat=stat)
      if (stat == 0) allocate (state%s19(npt), stat=stat)
      if (stat == 0) allocate (state%s20(npt), stat=stat)
      if (stat == 0) allocate (state%s21(npt), stat=stat)
      if (stat == 0) allocate (state%s22(npt), stat=stat)
      if (stat == 0) allocate (state%s23(npt), stat=stat)
      if (stat == 0) allocate (state%s24(npt), stat=stat)
      if (stat == 0) allocate (state%s25(npt), stat=stat)
      if (stat == 0) allocate (state%s26(npt), stat=stat)
      if (stat == 0) allocate (state%s27(npt), stat=stat)
      if (stat == 0) allocate (state%s28(npt), stat=stat)
      if (stat /= 0) then
         call fatal_error(error, "[slic_point_assemble] allocation failed")
         return
      end if
      state%s14 = 0.0_wp
      state%s21 = 0.0_wp
      call state%solver%reset(slic_point_n_operators)
      state%matrix_free = .false.

      state%a = a
      state%r = r
      state%k1 = k1
      state%k2 = k2
      state%s1 = n(1, :)
      state%s2 = state%r(1, :)
      state%s3 = state%r(2, :)
      state%s4 = n(2, :)
      state%s5 = state%r(3, :)
      state%s6 = n(3, :)
      block
