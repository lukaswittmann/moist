               tmp18 = tmp17**(3)
               tmp19 = tmp11*tmp18
               state%s7(i, j) = tmp19
               tmp20 = -tmp2
               tmp21 = state%s1(i)*tmp20
               tmp22 = -tmp5
               tmp23 = tmp22*state%s4(i)
               tmp24 = tmp21 + tmp23
               tmp25 = -tmp9
               tmp26 = tmp25*state%s6(i)
               tmp27 = tmp24 + tmp26
               tmp28 = tmp27*tmp18
               state%s7(j, i) = tmp28
            end do
         end do
         !$omp end parallel do
      end block
      do i = 1, npt
         tmp29 = state%k1(i) + state%k2(i)
         tmp30 = 1.0_wp/state%a(i)
         tmp31 = 12.566370614359172_wp*tmp30
         tmp32 = sqrt(tmp31)
         tmp33 = tmp29*tmp32
         tmp34 = (-0.26735_wp)*tmp33
         state%s7(i, i) = tmp34
      end do

      state%ready = 1
      state%assembled = state%assembled + 1
   end subroutine slic_point_assemble

   !> SLIC (point charges): combine and factor the operators for the solvent
   !>
   !> - Repeat with new solvent inputs as often as needed; the cavity operators are reused
   !> - Needs slic_point_assemble on the same state first
   !> - Vectors have length npt, matrices are (npt, npt), point fields (3, npt)
   !> - Outputs are undefined if error is allocated
