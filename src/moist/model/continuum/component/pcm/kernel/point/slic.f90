      integer :: i

      if (state%matrix_free) then
         call slic_point_mf_solve(state, v, vn, energy, q, grad_v, grad_vn, error)
         return
      end if
      stat = 0
      npt = state%npt
      if (state%ready < 2) then
         call fatal_error(error, "[slic_point_solve] call slic_point_medium first")
         return
      end if
      if (any(shape(v) /= [npt])) then
         call fatal_error(error, "[slic_point_solve] v: wrong shape")
         return
      end if
      if (any(shape(vn) /= [npt])) then
         call fatal_error(error, "[slic_point_solve] vn: wrong shape")
         return
      end if
      if (any(shape(q) /= [npt])) then
         call fatal_error(error, "[slic_point_solve] q: wrong shape")
         return
      end if
      if (any(shape(grad_v) /= [npt])) then
         call fatal_error(error, "[slic_point_solve] grad_v: wrong shape")
         return
      end if
      if (any(shape(grad_vn) /= [npt])) then
         call fatal_error(error, "[slic_point_solve] grad_vn: wrong shape")
         return
      end if
      allocate (tmp1(npt), stat=stat)
      if (stat == 0) allocate (tmp2(npt), stat=stat)
      if (stat == 0) allocate (tmp3(npt), stat=stat)
      if (stat == 0) allocate (tmp22(npt), stat=stat)
      if (stat == 0) allocate (tmp33(npt), stat=stat)
      if (stat == 0) allocate (tmp34(npt), stat=stat)
      if (stat == 0) allocate (tmp35(npt), stat=stat)
      if (stat == 0) allocate (tmp37(npt), stat=stat)
      if (stat == 0) allocate (tmp48(npt), stat=stat)
      if (stat == 0) allocate (tmp49(npt), stat=stat)
      if (stat /= 0) then
         call fatal_error(error, "[slic_point_solve] allocation failed")
         return
      end if
      state%ready = 2

      state%op1%npt = npt
      state%op1%npoint = npt
      state%op1%id = 1
      state%op1%points => state%r
      state%op1%a => state%a
      nl1%npt = npt
      nl1%solver => state%solver
      nl1%r => state%r
      nl1%a => state%a
      nl1%vn => vn
      nl1%alpha = state%alpha
      nl1%beta = state%beta
      nl1%mu = state%mu
      nl1%c1 => state%s7
      nl1%c2 = state%s8
      nl1%c3 = state%s10
      nl1%c4 = state%s11
      nl1%c5 = state%s13
      call nl1%solve(state%s14, error)
      if (allocated(error)) return
      state%s15 = state%a*state%s14
      call gemv(state%s7, state%s15, tmp1, trans="t")
      state%s16 = vn + tmp1
      tmp2 = 6.283185307179586_wp*state%s14
      tmp3 = state%s16 + tmp2
      state%s17 = -tmp3
      do i = 1, npt
         tmp4 = state%beta*state%s17(i)
         tmp5 = tmp4 + state%s8
         tmp6 = tanh(tmp5)
         tmp7 = tmp6**(2)
         tmp8 = -tmp7
         tmp9 = 1.0_wp + tmp8
         tmp10 = state%s13*tmp9
         tmp11 = tmp10*state%s14(i)
         tmp12 = (-12.566370614359172_wp)*tmp11
         state%s18(i) = tmp12
      end do
      state%op1%c1 => state%s18
      state%op1%c2 => state%s7
      do i = 1, npt
         tmp13 = state%beta*state%s17(i)
         tmp14 = tmp13 + state%s8
         tmp15 = tanh(tmp14)
         tmp16 = state%alpha*tmp15
         tmp17 = tmp16 + state%mu
         tmp18 = state%s10*tmp17
         tmp19 = (-2.0_wp)*tmp18
         tmp20 = 1.0_wp + tmp19
         tmp21 = 6.283185307179586_wp*tmp20
         state%s19(i) = tmp21
      end do
      state%op1%c3 => state%s19
      state%op1%c4 = state%s11
      call state%solver%setup(state%op1, error)
      if (allocated(error)) return
      state%s20 = 0.5_wp*v
      tmp22 = state%s20*state%a
      call state%solver%solve(state%op1, .true., tmp22, state%s21, error)
      if (allocated(error)) return
      do i = 1, npt
         tmp23 = state%s12*state%s14(i)
         tmp24 = state%beta*state%s17(i)
         tmp25 = tmp24 + state%s8
         tmp26 = tanh(tmp25)
         tmp27 = tmp26**(2)
         tmp28 = -tmp27
         tmp29 = 1.0_wp + tmp28
         tmp30 = tmp23*tmp29
         tmp31 = tmp30*state%beta
         tmp32 = (-12.566370614359172_wp)*tmp31
         state%s22(i) = tmp32
      end do
      tmp33 = state%s11*state%s21
      tmp34 = state%s21*state%s22
      tmp35 = -tmp34
      state%s23 = tmp33 + tmp35
      state%s24 = -state%s23
      tmp36 = dot(v, state%s15)
      energy = 0.5_wp*tmp36
      q = state%s15
      grad_v = 0.5_wp*state%s15
      grad_vn = state%s24
      if (state%solver%inexact()) then
         ! First-order correction for the residuals of the solves
         do i = 1, npt
            tmp38 = state%beta*state%s17(i)
            tmp39 = tmp38 + state%s8
            tmp40 = tanh(tmp39)
            tmp41 = state%alpha*tmp40
            tmp42 = tmp41 + state%mu
            tmp43 = state%s10*tmp42
            tmp44 = (-2.0_wp)*tmp43
            tmp45 = 1.0_wp + tmp44
            tmp46 = tmp45*state%s14(i)
            tmp47 = 6.283185307179586_wp*tmp46
            tmp37(i) = tmp47
         end do
         tmp48 = state%s11*state%s16
         tmp49 = tmp37 + tmp48
         tmp50 = dot(state%s21, tmp49)
         tmp51 = -tmp50
         energy = energy + tmp51
      end if

      state%ready = 3
   end subroutine slic_point_solve

