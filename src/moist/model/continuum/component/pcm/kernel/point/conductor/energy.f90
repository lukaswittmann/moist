!> Conductor-like PCM (point charges) phases: energy; generated by pcmgen, do not edit
!>
!> - Procedures of pcmgen_point_conductor: conductor_point_assemble, conductor_point_medium,
!>   conductor_point_solve
submodule(pcmgen_point_conductor) pcmgen_point_conductor_energy
   implicit none(type, external)

contains

   module subroutine conductor_point_assemble(state, r, a, error, solver)
      !> State of conductor_point
      type(conductor_point_state), target, intent(inout) :: state
      !> Positions of the surface points
      real(wp), contiguous, intent(in) :: r(:, :)
      !> Grid point areas
      real(wp), contiguous, intent(in) :: a(:)
      !> Error handling
      type(error_type), allocatable, intent(out) :: error
      !> Linear solver
      class(pcm_solver), intent(in), optional :: solver

      integer :: npt
      integer :: stat
      real(wp) :: tmp16, tmp17, tmp18, tmp19
      integer :: i, j

      if (present(solver)) then
         if (solver%matrix_free(size(r, 2), 1)) then
            call conductor_point_mf_assemble(state, r, a, error, solver)
            return
         end if
      end if
      stat = 0
      npt = size(r, 2)
      if (npt < 1) then
         call fatal_error(error, "[conductor_point_assemble] empty discretization")
         return
      end if
      if (any(shape(r) /= [3, npt])) then
         call fatal_error(error, "[conductor_point_assemble] r: wrong shape")
         return
      end if
      if (any(shape(a) /= [npt])) then
         call fatal_error(error, "[conductor_point_assemble] a: wrong shape")
         return
      end if
      state%ready = 0
      if (allocated(state%solver)) deallocate (state%solver)
      if (allocated(state%v)) deallocate (state%v)
      if (allocated(state%r)) deallocate (state%r)
      if (allocated(state%s2)) deallocate (state%s2)
      if (allocated(state%s3)) deallocate (state%s3)
      if (allocated(state%s4)) deallocate (state%s4)
      if (allocated(state%a)) deallocate (state%a)
      if (allocated(state%s5)) deallocate (state%s5)
      if (allocated(state%s6)) deallocate (state%s6)
      if (allocated(state%s8)) deallocate (state%s8)
      if (allocated(state%s9)) deallocate (state%s9)
      if (allocated(state%s10)) deallocate (state%s10)
      state%npt = npt
      if (present(solver)) then
         allocate (state%solver, source=solver, stat=stat)
      else
         allocate (pcm_dense_solver :: state%solver, stat=stat)
      end if
      if (stat == 0) allocate (state%v(npt), stat=stat)
      if (stat == 0) allocate (state%r(3, npt), stat=stat)
      if (stat == 0) allocate (state%s2(npt), stat=stat)
      if (stat == 0) allocate (state%s3(npt), stat=stat)
      if (stat == 0) allocate (state%s4(npt), stat=stat)
      if (stat == 0) allocate (state%a(npt), stat=stat)
      if (stat == 0) allocate (state%s5(npt, npt), stat=stat)
      if (stat == 0) allocate (state%s6(npt), stat=stat)
      if (stat == 0) allocate (state%s8(npt), stat=stat)
      if (stat == 0) allocate (state%s9(npt), stat=stat)
      if (stat == 0) allocate (state%s10(npt), stat=stat)
      if (stat /= 0) then
         call fatal_error(error, "[conductor_point_assemble] allocation failed")
         return
      end if
      state%s6 = 0.0_wp
      call state%solver%reset(conductor_point_n_operators)
      state%matrix_free = .false.

      state%r = r
      state%a = a
      state%op1%npt = npt
      state%op1%npoint = npt
      state%op1%id = 1
      state%op1%points => state%r
      state%op1%symmetric = .true.
      block
         real(wp) :: tmp1, tmp2, tmp3, tmp4, tmp7, tmp11, tmp5, tmp6, tmp8, tmp9, tmp10, tmp12, &
                     tmp13, tmp14, tmp15

         !$omp parallel &
         !$omp& private(i, j) &
         !$omp& shared(npt, state) &
         !$omp& default(private)
         !$omp do schedule(dynamic, 16)
         do j = 2, npt
            tmp1 = state%r(1, j)
            tmp2 = state%r(2, j)
            tmp3 = state%r(3, j)
            tmp4 = -tmp1
            tmp7 = -tmp2
            tmp11 = -tmp3
            !$omp simd &
            !$omp& private(tmp5, tmp6, tmp8, tmp9, tmp10, tmp12, tmp13, tmp14) &
            !$omp& private(tmp15)
            do i = 1, j - 1
               tmp5 = state%r(1, i) + tmp4
               tmp6 = tmp5**(2)
               tmp8 = state%r(2, i) + tmp7
               tmp9 = tmp8**(2)
               tmp10 = tmp6 + tmp9
               tmp12 = state%r(3, i) + tmp11
               tmp13 = tmp12**(2)
               tmp14 = tmp10 + tmp13
               tmp15 = 1.0_wp/sqrt(tmp14)
               state%s5(i, j) = tmp15
               state%s5(j, i) = tmp15
            end do
         end do
         !$omp end do
         !$omp end parallel
      end block
      do i = 1, npt
         tmp16 = 1.0_wp/state%a(i)
         tmp17 = 12.566370614359172_wp*tmp16
         tmp18 = sqrt(tmp17)
         tmp19 = 1.0694_wp*tmp18
         state%s5(i, i) = tmp19
      end do
      state%op1%c1 => state%s5
      call state%solver%setup(state%op1, error)
      if (allocated(error)) return
      state%s2 = state%r(1, :)
      state%s3 = state%r(2, :)
      state%s4 = state%r(3, :)

      state%ready = 1
      state%assembled = state%assembled + 1
   end subroutine conductor_point_assemble

   module subroutine conductor_point_medium(state, feps, error)
      !> State of conductor_point
      type(conductor_point_state), target, intent(inout) :: state
      !> Dielectric factor of a conductor-like model, e.g. (eps - 1)/eps
      real(wp), intent(in) :: feps
      !> Error handling
      type(error_type), allocatable, intent(out) :: error

      integer :: npt
      integer :: stat

      if (state%matrix_free) then
         call conductor_point_mf_medium(state, feps, error)
         return
      end if
      stat = 0
      npt = state%npt
      if (state%ready < 1) then
         call fatal_error(error, "[conductor_point_medium] call conductor_point_assemble first")
         return
      end if
      state%ready = 1

      state%op1%points => state%r
      state%op1%c1 => state%s5
      state%feps = feps
      state%s1 = -state%feps

      state%ready = 2
   end subroutine conductor_point_medium

   module subroutine conductor_point_solve(state, v, energy, q, grad_v, error)
      !> State of conductor_point
      type(conductor_point_state), target, intent(inout) :: state
      !> Solute electrostatic potential at the surface points
      real(wp), contiguous, intent(in) :: v(:)
      !> Solvation energy
      real(wp), intent(out) :: energy
      !> Apparent surface charges
      real(wp), contiguous, intent(out) :: q(:)
      !> Partial derivative of the energy with respect to v
      real(wp), contiguous, intent(out) :: grad_v(:)
      !> Error handling
      type(error_type), allocatable, intent(out) :: error

      integer :: npt
      integer :: stat
      real(wp), allocatable :: tmp3(:), tmp4(:), tmp5(:), tmp6(:)
      real(wp) :: tmp1, tmp2, tmp7

      if (state%matrix_free) then
         call conductor_point_mf_solve(state, v, energy, q, grad_v, error)
         return
      end if
      stat = 0
      npt = state%npt
      if (state%ready < 2) then
         call fatal_error(error, "[conductor_point_solve] call conductor_point_medium first")
         return
      end if
      if (any(shape(v) /= [npt])) then
         call fatal_error(error, "[conductor_point_solve] v: wrong shape")
         return
      end if
      if (any(shape(q) /= [npt])) then
         call fatal_error(error, "[conductor_point_solve] q: wrong shape")
         return
      end if
      if (any(shape(grad_v) /= [npt])) then
         call fatal_error(error, "[conductor_point_solve] grad_v: wrong shape")
         return
      end if
      allocate (tmp3(npt), stat=stat)
      if (stat == 0) allocate (tmp4(npt), stat=stat)
      if (stat == 0) allocate (tmp5(npt), stat=stat)
      if (stat == 0) allocate (tmp6(npt), stat=stat)
      if (stat /= 0) then
         call fatal_error(error, "[conductor_point_solve] allocation failed")
         return
      end if
      state%ready = 2

      state%op1%points => state%r
      state%op1%c1 => state%s5
      state%v = v
      call state%solver%solve(state%op1, .false., state%v, state%s6, error)
      if (allocated(error)) return
      q = state%s1*state%s6
      tmp1 = dot(state%v, q)
      energy = 0.5_wp*tmp1
      grad_v = q
      if (state%solver%inexact()) then
         ! First-order correction for the residuals of the solves
         tmp2 = (-0.5_wp)*state%feps
         tmp3 = tmp2*state%s6
         call gemv(state%s5, state%s6, tmp4)
         tmp5 = -tmp4
         tmp6 = state%v + tmp5
         tmp7 = dot(tmp3, tmp6)
         energy = energy + tmp7
      end if

      state%ready = 3
   end subroutine conductor_point_solve

end submodule pcmgen_point_conductor_energy
