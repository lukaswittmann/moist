      type(dpcm_original_point_state), target, intent(inout) :: state
      !> Partial derivative of the energy with respect to r
      real(wp), contiguous, intent(out) :: grad_r(:, :)
      !> Partial derivative of the energy with respect to n
      real(wp), contiguous, intent(out) :: grad_n(:, :)
      !> Partial derivative of the energy with respect to k1
      real(wp), contiguous, intent(out) :: grad_k1(:)
      !> Partial derivative of the energy with respect to k2
      real(wp), contiguous, intent(out) :: grad_k2(:)
      !> Partial derivative of the energy with respect to a
      real(wp), contiguous, intent(out) :: grad_a(:)
      !> Error handling
      type(error_type), allocatable, intent(out) :: error

      integer :: npt
      integer :: stat
      real(wp), allocatable :: tmp16(:), tmp17(:), tmp18(:), tmp19(:), tmp20(:), tmp21(:), &
                               tmp88(:), tmp89(:)
      real(wp) :: tmp1, tmp2, tmp3, tmp4, tmp5, tmp6, tmp7, tmp8, tmp9, tmp10, tmp11, tmp12, &
                  tmp13, tmp14, tmp15
      real(wp), allocatable :: tmp16_p(:), tmp17_p(:), tmp18_p(:)
      integer :: i, j

      if (state%matrix_free) then
         call dpcm_original_point_mf_weights(state, grad_r, grad_n, grad_k1, grad_k2, grad_a, error)
         return
      end if
      stat = 0
      npt = state%npt
      if (state%ready < 3) then
         call fatal_error(error, &
                          "[dpcm_original_point_weights] call dpcm_original_point_solve first")
         return
      end if
      if (any(shape(grad_r) /= [3, npt])) then
         call fatal_error(error, "[dpcm_original_point_weights] grad_r: wrong shape")
         return
      end if
      if (any(shape(grad_n) /= [3, npt])) then
         call fatal_error(error, "[dpcm_original_point_weights] grad_n: wrong shape")
         return
      end if
      if (any(shape(grad_k1) /= [npt])) then
         call fatal_error(error, "[dpcm_original_point_weights] grad_k1: wrong shape")
         return
      end if
      if (any(shape(grad_k2) /= [npt])) then
         call fatal_error(error, "[dpcm_original_point_weights] grad_k2: wrong shape")
         return
      end if
      if (any(shape(grad_a) /= [npt])) then
         call fatal_error(error, "[dpcm_original_point_weights] grad_a: wrong shape")
         return
      end if
      allocate (tmp16(npt), stat=stat)
      if (stat == 0) allocate (tmp17(npt), stat=stat)
      if (stat == 0) allocate (tmp18(npt), stat=stat)
      if (stat == 0) allocate (tmp19(npt), stat=stat)
      if (stat == 0) allocate (tmp20(npt), stat=stat)
      if (stat == 0) allocate (tmp21(npt), stat=stat)
      if (stat == 0) allocate (tmp88(npt), stat=stat)
      if (stat == 0) allocate (tmp89(npt), stat=stat)
      if (stat /= 0) then
         call fatal_error(error, "[dpcm_original_point_weights] allocation failed")
         return
      end if
      state%ready = 3

      state%op1%points => state%r
      state%op1%c1 => state%s3
      state%op1%c3 => state%s11
      tmp1 = state%s2**(2)
      state%s15 = 0.5_wp*tmp1
      state%s16 = state%s15*state%s14
      state%s17 = state%s12*state%s16
      do i = 1, npt
         tmp2 = 1.0_wp/state%a(i)
         tmp3 = 12.566370614359172_wp*tmp2
         tmp4 = sqrt(tmp3)
         tmp5 = (-0.26735_wp)*tmp4
         state%s18(i) = tmp5
      end do
      do i = 1, npt
         tmp6 = 1.0_wp/state%a(i)
         tmp7 = 12.566370614359172_wp*tmp6
         tmp8 = 1.0_wp/sqrt(tmp7)
         tmp9 = state%k1(i) + state%k2(i)
         tmp10 = tmp8*tmp9
         tmp11 = state%a(i)**(-2)
         tmp12 = tmp10*tmp11
         tmp13 = 1.6798095918744622_wp*tmp12
         state%s19(i) = tmp13
      end do
      state%s20 = (-3.141592653589793_wp)*state%s2
      state%s21 = state%s20*state%s14
      state%s22 = state%s21*state%s12
      do i = 1, npt
         tmp14 = state%a(i)**(-2)
         tmp15 = -tmp14
         state%s23(i) = tmp15
      end do
      tmp16 = 0.0_wp
      tmp17 = 0.0_wp
      tmp18 = 0.0_wp
      tmp19 = 0.0_wp
      tmp20 = 0.0_wp
      tmp21 = 0.0_wp
      block
         real(wp) :: tmp28, tmp29, tmp30, tmp31, tmp32, tmp33, tmp34, tmp35, tmp36, tmp39, tmp43, &
                     tmp22, tmp23, tmp24, tmp25, tmp26, tmp27, tmp37, tmp38, tmp40, tmp41, tmp42, &
                     tmp44, tmp45, tmp46, tmp47, tmp48, tmp49, tmp50, tmp51, tmp52, tmp53, tmp54, &
                     tmp55, tmp56, tmp57, tmp58, tmp59, tmp60, tmp61, tmp62, tmp63, tmp64, tmp65, &
                     tmp66, tmp67, tmp68, tmp69, tmp70, tmp71, tmp72, tmp73, tmp74, tmp75, tmp76, &
                     tmp77, tmp78, tmp79, tmp80, tmp81, tmp82, tmp83, tmp84, tmp85, tmp86, tmp87

