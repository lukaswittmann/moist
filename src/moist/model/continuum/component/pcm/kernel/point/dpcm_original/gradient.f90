         !$omp& private(i, j, tmp16_p, tmp17_p, tmp18_p) &
         !$omp& shared(npt, state, tmp16, tmp17, tmp18, tmp19, tmp20, tmp21) &
         !$omp& default(private)
         allocate (tmp16_p(npt))
         allocate (tmp17_p(npt))
         allocate (tmp18_p(npt))
         tmp16_p = 0.0_wp
         tmp17_p = 0.0_wp
         tmp18_p = 0.0_wp
         !$omp do schedule(static)
         do j = 1, npt
            tmp28 = state%s5(j)
            tmp29 = state%s6(j)
            tmp30 = state%s7(j)
            tmp31 = state%s8(j)
            tmp32 = state%s9(j)
            tmp33 = state%s10(j)
            tmp34 = state%s16(j)
            tmp35 = state%s12(j)
            tmp36 = -tmp29
            tmp39 = -tmp30
            tmp43 = -tmp32
            tmp22 = 0.0_wp
            tmp23 = 0.0_wp
            tmp24 = 0.0_wp
            tmp25 = 0.0_wp
            tmp26 = 0.0_wp
            tmp27 = 0.0_wp
            !$omp simd &
            !$omp& private(tmp37, tmp38, tmp40, tmp41, tmp42, tmp44, tmp45, tmp46) &
            !$omp& private(tmp47, tmp48, tmp49, tmp50, tmp51, tmp52, tmp53, tmp54) &
            !$omp& private(tmp55, tmp56, tmp57, tmp58, tmp59, tmp60, tmp61, tmp62) &
            !$omp& private(tmp63, tmp64, tmp65, tmp66, tmp67, tmp68, tmp69, tmp70) &
            !$omp& private(tmp71, tmp72, tmp73, tmp74, tmp75, tmp76, tmp77, tmp78) &
            !$omp& private(tmp79, tmp80, tmp81, tmp82, tmp83, tmp84, tmp85, tmp86) &
            !$omp& private(tmp87) &
            !$omp& reduction(+: tmp22, tmp23, tmp24, tmp25, tmp26, tmp27)
            do i = 1, j - 1
               tmp37 = state%s6(i) + tmp36
               tmp38 = tmp28*tmp37
               tmp40 = state%s7(i) + tmp39
               tmp41 = tmp40*tmp31
               tmp42 = tmp38 + tmp41
               tmp44 = state%s9(i) + tmp43
               tmp45 = tmp44*tmp33
               tmp46 = tmp42 + tmp45
               tmp47 = tmp46*tmp37
               tmp48 = tmp37**(2)
               tmp49 = tmp40**(2)
               tmp50 = tmp48 + tmp49
               tmp51 = tmp44**(2)
               tmp52 = tmp50 + tmp51
               tmp53 = 1.0_wp/sqrt(tmp52)
               tmp54 = tmp53**(5)
               tmp55 = tmp47*tmp54
               tmp56 = (-3.0_wp)*tmp55
               tmp57 = tmp53**(3)
               tmp58 = tmp28*tmp57
               tmp59 = tmp56 + tmp58
               tmp60 = tmp59*tmp34
               tmp61 = tmp60*state%s12(i)
               tmp16_p(i) = tmp16_p(i) + tmp61
               tmp62 = -tmp61
               tmp22 = tmp22 + tmp62
               tmp63 = tmp40*tmp46
               tmp64 = tmp63*tmp54
               tmp65 = (-3.0_wp)*tmp64
               tmp66 = tmp31*tmp57
               tmp67 = tmp65 + tmp66
               tmp68 = tmp67*tmp34
               tmp69 = tmp68*state%s12(i)
               tmp17_p(i) = tmp17_p(i) + tmp69
               tmp70 = -tmp69
               tmp23 = tmp23 + tmp70
               tmp71 = tmp44*tmp46
               tmp72 = tmp71*tmp54
               tmp73 = (-3.0_wp)*tmp72
               tmp74 = tmp33*tmp57
               tmp75 = tmp73 + tmp74
               tmp76 = tmp34*tmp75
               tmp77 = tmp76*state%s12(i)
               tmp18_p(i) = tmp18_p(i) + tmp77
               tmp78 = -tmp77
               tmp24 = tmp24 + tmp78
               tmp79 = tmp34*tmp57
               tmp80 = tmp79*tmp37
               tmp81 = tmp80*state%s12(i)
               tmp25 = tmp25 + tmp81
               tmp82 = tmp40*tmp34
               tmp83 = tmp82*tmp57
               tmp84 = tmp83*state%s12(i)
               tmp26 = tmp26 + tmp84
               tmp85 = tmp44*tmp34
               tmp86 = tmp85*tmp57
               tmp87 = tmp86*state%s12(i)
               tmp27 = tmp27 + tmp87
            end do
            !$omp simd &
            !$omp& private(tmp37, tmp38, tmp40, tmp41, tmp42, tmp44, tmp45, tmp46) &
            !$omp& private(tmp47, tmp48, tmp49, tmp50, tmp51, tmp52, tmp53, tmp54) &
            !$omp& private(tmp55, tmp56, tmp57, tmp58, tmp59, tmp60, tmp61, tmp62) &
            !$omp& private(tmp63, tmp64, tmp65, tmp66, tmp67, tmp68, tmp69, tmp70) &
            !$omp& private(tmp71, tmp72, tmp73, tmp74, tmp75, tmp76, tmp77, tmp78) &
            !$omp& private(tmp79, tmp80, tmp81, tmp82, tmp83, tmp84, tmp85, tmp86) &
            !$omp& private(tmp87) &
            !$omp& reduction(+: tmp22, tmp23, tmp24, tmp25, tmp26, tmp27)
            do i = j + 1, npt
               tmp37 = state%s6(i) + tmp36
               tmp38 = tmp28*tmp37
               tmp40 = state%s7(i) + tmp39
               tmp41 = tmp40*tmp31
               tmp42 = tmp38 + tmp41
               tmp44 = state%s9(i) + tmp43
               tmp45 = tmp44*tmp33
               tmp46 = tmp42 + tmp45
               tmp47 = tmp46*tmp37
               tmp48 = tmp37**(2)
               tmp49 = tmp40**(2)
               tmp50 = tmp48 + tmp49
               tmp51 = tmp44**(2)
               tmp52 = tmp50 + tmp51
               tmp53 = 1.0_wp/sqrt(tmp52)
               tmp54 = tmp53**(5)
               tmp55 = tmp47*tmp54
               tmp56 = (-3.0_wp)*tmp55
               tmp57 = tmp53**(3)
               tmp58 = tmp28*tmp57
               tmp59 = tmp56 + tmp58
               tmp60 = tmp59*tmp34
               tmp61 = tmp60*state%s12(i)
               tmp16_p(i) = tmp16_p(i) + tmp61
               tmp62 = -tmp61
               tmp22 = tmp22 + tmp62
               tmp63 = tmp40*tmp46
               tmp64 = tmp63*tmp54
               tmp65 = (-3.0_wp)*tmp64
               tmp66 = tmp31*tmp57
               tmp67 = tmp65 + tmp66
               tmp68 = tmp67*tmp34
               tmp69 = tmp68*state%s12(i)
               tmp17_p(i) = tmp17_p(i) + tmp69
               tmp70 = -tmp69
               tmp23 = tmp23 + tmp70
               tmp71 = tmp44*tmp46
               tmp72 = tmp71*tmp54
               tmp73 = (-3.0_wp)*tmp72
               tmp74 = tmp33*tmp57
               tmp75 = tmp73 + tmp74
               tmp76 = tmp34*tmp75
               tmp77 = tmp76*state%s12(i)
               tmp18_p(i) = tmp18_p(i) + tmp77
               tmp78 = -tmp77
               tmp24 = tmp24 + tmp78
               tmp79 = tmp34*tmp57
               tmp80 = tmp79*tmp37
               tmp81 = tmp80*state%s12(i)
               tmp25 = tmp25 + tmp81
               tmp82 = tmp40*tmp34
               tmp83 = tmp82*tmp57
               tmp84 = tmp83*state%s12(i)
               tmp26 = tmp26 + tmp84
               tmp85 = tmp44*tmp34
               tmp86 = tmp85*tmp57
               tmp87 = tmp86*state%s12(i)
               tmp27 = tmp27 + tmp87
            end do
            tmp16_p(j) = tmp16_p(j) + tmp22
            tmp17_p(j) = tmp17_p(j) + tmp23
            tmp18_p(j) = tmp18_p(j) + tmp24
            tmp19(j) = tmp19(j) + tmp25
            tmp20(j) = tmp20(j) + tmp26
            tmp21(j) = tmp21(j) + tmp27
         end do
         !$omp end do
         !$omp critical (pcmgen_sum)
         tmp16 = tmp16 + tmp16_p
         tmp17 = tmp17 + tmp17_p
         tmp18 = tmp18 + tmp18_p
         !$omp end critical (pcmgen_sum)
         deallocate (tmp16_p)
         deallocate (tmp17_p)
         deallocate (tmp18_p)
         !$omp end parallel
      end block
      grad_r(1, :) = tmp16
      grad_r(2, :) = tmp17
      grad_r(3, :) = tmp18
      grad_n(1, :) = tmp19
      grad_n(2, :) = tmp20
      grad_n(3, :) = tmp21
      grad_k1 = state%s17*state%s18
      grad_k2 = grad_k1
      tmp88 = state%s17*state%s19
      tmp89 = state%s22*state%s23
      grad_a = tmp88 + tmp89

      state%ready = 4
   end subroutine dpcm_original_point_weights

   module subroutine dpcm_original_point_param_weights(state, grad_eps, error)
      !> State of dpcm_original_point
      type(dpcm_original_point_state), target, intent(inout) :: state
      !> Partial derivative of the energy with respect to eps
      real(wp), intent(out) :: grad_eps
      !> Error handling
      type(error_type), allocatable, intent(out) :: error

      integer :: npt
      integer :: stat
      real(wp), allocatable :: tmp1(:), tmp4(:), tmp5(:)
      real(wp) :: tmp2, tmp3, tmp6, tmp7, tmp8, tmp9, tmp10

      if (state%matrix_free) then
         call dpcm_original_point_mf_param_weights(state, grad_eps, error)
         return
      end if
      stat = 0
      npt = state%npt
      if (state%ready < 3) then
         call fatal_error(error, &
                          "[dpcm_original_point_param_weights] call dpcm_original_point_solve first")
         return
      end if
      allocate (tmp1(npt), stat=stat)
      if (stat == 0) allocate (tmp4(npt), stat=stat)
      if (stat == 0) allocate (tmp5(npt), stat=stat)
      if (stat /= 0) then
         call fatal_error(error, "[dpcm_original_point_param_weights] allocation failed")
         return
      end if

      state%op1%points => state%r
      state%op1%c1 => state%s3
      state%op1%c3 => state%s11
      tmp1 = 0.5_wp*state%v
      tmp2 = dot(tmp1, state%s12)
      tmp3 = (-0.5_wp)*state%s2
      tmp4 = tmp3*state%s14
      call gemv(state%s11, state%s12, tmp5, trans="t")
      tmp6 = dot(tmp4, tmp5)
      tmp7 = -tmp6
      tmp8 = tmp2 + tmp7
      tmp9 = state%s1**(-2)
      tmp10 = tmp8*tmp9
      grad_eps = 2.0_wp*tmp10
   end subroutine dpcm_original_point_param_weights

end submodule pcmgen_point_dpcm_original_gradient
