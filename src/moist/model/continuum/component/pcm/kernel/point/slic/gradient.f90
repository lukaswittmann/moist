   module subroutine slic_point_weights(state, grad_r, grad_n, grad_k1, grad_k2, grad_a, error)
      !> State of slic_point
      type(slic_point_state), target, intent(inout) :: state
      !> Partial derivative of the energy with respect to r
      real(wp), contiguous, intent(out) :: grad_r(:, :)
      !> Partial derivative of the energy with respect to n
      real(wp), contiguous, intent(out) :: grad_n(:, :)
      !> Partial derivative of the energy with respect to k1
      real(wp), contiguous, intent(out) :: grad_k1(:)
      !> Partial derivative of the energy with respect to k2
      real(wp), contiguous, intent(out) :: grad_k2(:)
      !> Partial derivative of the energy with respect to a
      real(wp), contiguous, intent(out) :: grad_a(:)
      !> Error handling
      type(error_type), allocatable, intent(out) :: error

      integer :: npt
      integer :: stat
      real(wp), allocatable :: tmp13(:), tmp14(:), tmp15(:), tmp16(:), tmp17(:), tmp18(:), &
                               tmp85(:), tmp86(:), tmp87(:), tmp88(:), tmp89(:)
      real(wp) :: tmp1, tmp2, tmp3, tmp4, tmp5, tmp6, tmp7, tmp8, tmp9, tmp10, tmp11, tmp12
      real(wp), allocatable :: tmp13_p(:), tmp14_p(:), tmp15_p(:)
      integer :: i, j

      if (state%matrix_free) then
         call slic_point_mf_weights(state, grad_r, grad_n, grad_k1, grad_k2, grad_a, error)
         return
      end if
      stat = 0
      npt = state%npt
      if (state%ready < 3) then
         call fatal_error(error, "[slic_point_weights] call slic_point_solve first")
         return
      end if
      if (any(shape(grad_r) /= [3, npt])) then
         call fatal_error(error, "[slic_point_weights] grad_r: wrong shape")
         return
      end if
      if (any(shape(grad_n) /= [3, npt])) then
         call fatal_error(error, "[slic_point_weights] grad_n: wrong shape")
         return
      end if
      if (any(shape(grad_k1) /= [npt])) then
         call fatal_error(error, "[slic_point_weights] grad_k1: wrong shape")
         return
      end if
      if (any(shape(grad_k2) /= [npt])) then
         call fatal_error(error, "[slic_point_weights] grad_k2: wrong shape")
         return
      end if
      if (any(shape(grad_a) /= [npt])) then
         call fatal_error(error, "[slic_point_weights] grad_a: wrong shape")
         return
      end if
      allocate (tmp13(npt), stat=stat)
      if (stat == 0) allocate (tmp14(npt), stat=stat)
      if (stat == 0) allocate (tmp15(npt), stat=stat)
      if (stat == 0) allocate (tmp16(npt), stat=stat)
      if (stat == 0) allocate (tmp17(npt), stat=stat)
      if (stat == 0) allocate (tmp18(npt), stat=stat)
      if (stat == 0) allocate (tmp85(npt), stat=stat)
      if (stat == 0) allocate (tmp86(npt), stat=stat)
      if (stat == 0) allocate (tmp87(npt), stat=stat)
      if (stat == 0) allocate (tmp88(npt), stat=stat)
      if (stat == 0) allocate (tmp89(npt), stat=stat)
      if (stat /= 0) then
         call fatal_error(error, "[slic_point_weights] allocation failed")
         return
      end if
      state%ready = 3

      state%op1%points => state%r
      state%op1%a => state%a
      state%op1%c1 => state%s18
      state%op1%c2 => state%s7
      state%op1%c3 => state%s19
      state%s25 = state%s15*state%s24
      do i = 1, npt
         tmp1 = 1.0_wp/state%a(i)
         tmp2 = 12.566370614359172_wp*tmp1
         tmp3 = sqrt(tmp2)
         tmp4 = (-0.26735_wp)*tmp3
         state%s26(i) = tmp4
      end do
      call gemv(state%s7, state%s23, state%s27)
      do i = 1, npt
         tmp5 = 1.0_wp/state%a(i)
         tmp6 = 12.566370614359172_wp*tmp5
         tmp7 = 1.0_wp/sqrt(tmp6)
         tmp8 = state%k1(i) + state%k2(i)
         tmp9 = tmp7*tmp8
         tmp10 = state%a(i)**(-2)
         tmp11 = tmp9*tmp10
         tmp12 = 1.6798095918744622_wp*tmp11
         state%s28(i) = tmp12
      end do
      tmp13 = 0.0_wp
      tmp14 = 0.0_wp
      tmp15 = 0.0_wp
      tmp16 = 0.0_wp
      tmp17 = 0.0_wp
      tmp18 = 0.0_wp
      block
         real(wp) :: tmp25, tmp26, tmp27, tmp28, tmp29, tmp30, tmp31, tmp32, tmp33, tmp36, tmp40, &
                     tmp19, tmp20, tmp21, tmp22, tmp23, tmp24, tmp34, tmp35, tmp37, tmp38, tmp39, &
                     tmp41, tmp42, tmp43, tmp44, tmp45, tmp46, tmp47, tmp48, tmp49, tmp50, tmp51, &
                     tmp52, tmp53, tmp54, tmp55, tmp56, tmp57, tmp58, tmp59, tmp60, tmp61, tmp62, &
                     tmp63, tmp64, tmp65, tmp66, tmp67, tmp68, tmp69, tmp70, tmp71, tmp72, tmp73, &
                     tmp74, tmp75, tmp76, tmp77, tmp78, tmp79, tmp80, tmp81, tmp82, tmp83, tmp84

         !$omp parallel &
         !$omp& private(i, j, tmp13_p, tmp14_p, tmp15_p) &
         !$omp& shared(npt, state, tmp13, tmp14, tmp15, tmp16, tmp17, tmp18) &
         !$omp& default(private)
         allocate (tmp13_p(npt))
         allocate (tmp14_p(npt))
         allocate (tmp15_p(npt))
         tmp13_p = 0.0_wp
         tmp14_p = 0.0_wp
         tmp15_p = 0.0_wp
         !$omp do schedule(static)
         do j = 1, npt
            tmp25 = state%s1(j)
            tmp26 = state%s2(j)
            tmp27 = state%s3(j)
            tmp28 = state%s4(j)
            tmp29 = state%s5(j)
            tmp30 = state%s6(j)
            tmp31 = state%s24(j)
            tmp32 = state%s15(j)
            tmp33 = -tmp26
            tmp36 = -tmp27
            tmp40 = -tmp29
            tmp19 = 0.0_wp
            tmp20 = 0.0_wp
            tmp21 = 0.0_wp
            tmp22 = 0.0_wp
            tmp23 = 0.0_wp
            tmp24 = 0.0_wp
            !$omp simd &
            !$omp& private(tmp34, tmp35, tmp37, tmp38, tmp39, tmp41, tmp42, tmp43) &
            !$omp& private(tmp44, tmp45, tmp46, tmp47, tmp48, tmp49, tmp50, tmp51) &
            !$omp& private(tmp52, tmp53, tmp54, tmp55, tmp56, tmp57, tmp58, tmp59) &
            !$omp& private(tmp60, tmp61, tmp62, tmp63, tmp64, tmp65, tmp66, tmp67) &
            !$omp& private(tmp68, tmp69, tmp70, tmp71, tmp72, tmp73, tmp74, tmp75) &
            !$omp& private(tmp76, tmp77, tmp78, tmp79, tmp80, tmp81, tmp82, tmp83) &
            !$omp& private(tmp84) &
            !$omp& reduction(+: tmp19, tmp20, tmp21, tmp22, tmp23, tmp24)
            do i = 1, j - 1
               tmp34 = state%s2(i) + tmp33
               tmp35 = tmp25*tmp34
               tmp37 = state%s3(i) + tmp36
               tmp38 = tmp37*tmp28
               tmp39 = tmp35 + tmp38
               tmp41 = state%s5(i) + tmp40
               tmp42 = tmp41*tmp30
               tmp43 = tmp39 + tmp42
               tmp44 = tmp43*tmp34
               tmp45 = tmp34**(2)
               tmp46 = tmp37**(2)
               tmp47 = tmp45 + tmp46
               tmp48 = tmp41**(2)
               tmp49 = tmp47 + tmp48
               tmp50 = 1.0_wp/sqrt(tmp49)
               tmp51 = tmp50**(5)
               tmp52 = tmp44*tmp51
               tmp53 = (-3.0_wp)*tmp52
               tmp54 = tmp50**(3)
               tmp55 = tmp25*tmp54
               tmp56 = tmp53 + tmp55
               tmp57 = tmp56*tmp31
               tmp58 = tmp57*state%s15(i)
               tmp13_p(i) = tmp13_p(i) + tmp58
               tmp59 = -tmp58
               tmp19 = tmp19 + tmp59
               tmp60 = tmp37*tmp43
               tmp61 = tmp60*tmp51
               tmp62 = (-3.0_wp)*tmp61
               tmp63 = tmp28*tmp54
               tmp64 = tmp62 + tmp63
               tmp65 = tmp64*tmp31
               tmp66 = tmp65*state%s15(i)
               tmp14_p(i) = tmp14_p(i) + tmp66
               tmp67 = -tmp66
               tmp20 = tmp20 + tmp67
               tmp68 = tmp41*tmp43
               tmp69 = tmp68*tmp51
               tmp70 = (-3.0_wp)*tmp69
               tmp71 = tmp30*tmp54
               tmp72 = tmp70 + tmp71
               tmp73 = tmp72*tmp31
               tmp74 = tmp73*state%s15(i)
               tmp15_p(i) = tmp15_p(i) + tmp74
               tmp75 = -tmp74
               tmp21 = tmp21 + tmp75
               tmp76 = tmp54*tmp31
               tmp77 = tmp76*tmp34
               tmp78 = tmp77*state%s15(i)
               tmp22 = tmp22 + tmp78
               tmp79 = tmp37*tmp54
               tmp80 = tmp79*tmp31
               tmp81 = tmp80*state%s15(i)
               tmp23 = tmp23 + tmp81
               tmp82 = tmp41*tmp54
               tmp83 = tmp82*tmp31
               tmp84 = tmp83*state%s15(i)
               tmp24 = tmp24 + tmp84
            end do
            !$omp simd &
            !$omp& private(tmp34, tmp35, tmp37, tmp38, tmp39, tmp41, tmp42, tmp43) &
            !$omp& private(tmp44, tmp45, tmp46, tmp47, tmp48, tmp49, tmp50, tmp51) &
            !$omp& private(tmp52, tmp53, tmp54, tmp55, tmp56, tmp57, tmp58, tmp59) &
            !$omp& private(tmp60, tmp61, tmp62, tmp63, tmp64, tmp65, tmp66, tmp67) &
            !$omp& private(tmp68, tmp69, tmp70, tmp71, tmp72, tmp73, tmp74, tmp75) &
            !$omp& private(tmp76, tmp77, tmp78, tmp79, tmp80, tmp81, tmp82, tmp83) &
            !$omp& private(tmp84) &
            !$omp& reduction(+: tmp19, tmp20, tmp21, tmp22, tmp23, tmp24)
            do i = j + 1, npt
               tmp34 = state%s2(i) + tmp33
               tmp35 = tmp25*tmp34
               tmp37 = state%s3(i) + tmp36
               tmp38 = tmp37*tmp28
               tmp39 = tmp35 + tmp38
               tmp41 = state%s5(i) + tmp40
               tmp42 = tmp41*tmp30
               tmp43 = tmp39 + tmp42
               tmp44 = tmp43*tmp34
               tmp45 = tmp34**(2)
               tmp46 = tmp37**(2)
               tmp47 = tmp45 + tmp46
               tmp48 = tmp41**(2)
               tmp49 = tmp47 + tmp48
               tmp50 = 1.0_wp/sqrt(tmp49)
               tmp51 = tmp50**(5)
               tmp52 = tmp44*tmp51
               tmp53 = (-3.0_wp)*tmp52
               tmp54 = tmp50**(3)
               tmp55 = tmp25*tmp54
               tmp56 = tmp53 + tmp55
               tmp57 = tmp56*tmp31
               tmp58 = tmp57*state%s15(i)
               tmp13_p(i) = tmp13_p(i) + tmp58
               tmp59 = -tmp58
               tmp19 = tmp19 + tmp59
               tmp60 = tmp37*tmp43
               tmp61 = tmp60*tmp51
               tmp62 = (-3.0_wp)*tmp61
               tmp63 = tmp28*tmp54
               tmp64 = tmp62 + tmp63
               tmp65 = tmp64*tmp31
               tmp66 = tmp65*state%s15(i)
               tmp14_p(i) = tmp14_p(i) + tmp66
               tmp67 = -tmp66
               tmp20 = tmp20 + tmp67
               tmp68 = tmp41*tmp43
               tmp69 = tmp68*tmp51
               tmp70 = (-3.0_wp)*tmp69
               tmp71 = tmp30*tmp54
               tmp72 = tmp70 + tmp71
               tmp73 = tmp72*tmp31
               tmp74 = tmp73*state%s15(i)
               tmp15_p(i) = tmp15_p(i) + tmp74
               tmp75 = -tmp74
               tmp21 = tmp21 + tmp75
               tmp76 = tmp54*tmp31
               tmp77 = tmp76*tmp34
               tmp78 = tmp77*state%s15(i)
               tmp22 = tmp22 + tmp78
               tmp79 = tmp37*tmp54
               tmp80 = tmp79*tmp31
               tmp81 = tmp80*state%s15(i)
               tmp23 = tmp23 + tmp81
               tmp82 = tmp41*tmp54
               tmp83 = tmp82*tmp31
               tmp84 = tmp83*state%s15(i)
               tmp24 = tmp24 + tmp84
            end do
            tmp13_p(j) = tmp13_p(j) + tmp19
            tmp14_p(j) = tmp14_p(j) + tmp20
            tmp15_p(j) = tmp15_p(j) + tmp21
            tmp16(j) = tmp16(j) + tmp22
            tmp17(j) = tmp17(j) + tmp23
            tmp18(j) = tmp18(j) + tmp24
         end do
         !$omp end do
         !$omp critical (pcmgen_sum)
         tmp13 = tmp13 + tmp13_p
         tmp14 = tmp14 + tmp14_p
         tmp15 = tmp15 + tmp15_p
         !$omp end critical (pcmgen_sum)
         deallocate (tmp13_p)
         deallocate (tmp14_p)
         deallocate (tmp15_p)
         !$omp end parallel
      end block
      grad_r(1, :) = tmp13
      grad_r(2, :) = tmp14
      grad_r(3, :) = tmp15
      grad_n(1, :) = tmp16
      grad_n(2, :) = tmp17
      grad_n(3, :) = tmp18
      grad_k1 = state%s25*state%s26
      grad_k2 = grad_k1
      tmp85 = state%s20*state%s14
      tmp86 = state%s27*state%s14
      tmp87 = -tmp86
      tmp88 = tmp85 + tmp87
      tmp89 = state%s25*state%s28
      grad_a = tmp88 + tmp89

      state%ready = 4
   end subroutine slic_point_weights

   module subroutine slic_point_param_weights(state, grad_eps, grad_alpha, grad_beta, grad_gamma, &
                                              grad_mu, error)
      !> State of slic_point
      type(slic_point_state), target, intent(inout) :: state
      !> Partial derivative of the energy with respect to eps
      real(wp), intent(out) :: grad_eps
      !> Partial derivative of the energy with respect to alpha
      real(wp), intent(out) :: grad_alpha
      !> Partial derivative of the energy with respect to beta
      real(wp), intent(out) :: grad_beta
      !> Partial derivative of the energy with respect to gamma
      real(wp), intent(out) :: grad_gamma
      !> Partial derivative of the energy with respect to mu
      real(wp), intent(out) :: grad_mu
      !> Error handling
      type(error_type), allocatable, intent(out) :: error

      integer :: npt
      integer :: stat
      real(wp), allocatable :: tmp1(:), tmp15(:), tmp23(:), tmp35(:), tmp45(:)
      real(wp) :: tmp2, tmp3, tmp4, tmp5, tmp6, tmp7, tmp8, tmp9, tmp10, tmp11, tmp12, tmp13, &
                  tmp14, tmp16, tmp17, tmp18, tmp19, tmp20, tmp21, tmp22, tmp24, tmp25, tmp26, &
                  tmp27, tmp28, tmp29, tmp30, tmp31, tmp32, tmp33, tmp34, tmp36, tmp37, tmp38, &
                  tmp39, tmp40, tmp41, tmp42, tmp43, tmp44, tmp46, tmp47, tmp48
      integer :: i

      if (state%matrix_free) then
         call slic_point_mf_param_weights(state, grad_eps, grad_alpha, grad_beta, grad_gamma, &
                                          grad_mu, error)
         return
      end if
      stat = 0
      npt = state%npt
      if (state%ready < 3) then
         call fatal_error(error, "[slic_point_param_weights] call slic_point_solve first")
         return
      end if
      allocate (tmp1(npt), stat=stat)
      if (stat == 0) allocate (tmp15(npt), stat=stat)
      if (stat == 0) allocate (tmp23(npt), stat=stat)
      if (stat == 0) allocate (tmp35(npt), stat=stat)
      if (stat == 0) allocate (tmp45(npt), stat=stat)
      if (stat /= 0) then
         call fatal_error(error, "[slic_point_param_weights] allocation failed")
         return
      end if

      state%op1%points => state%r
      state%op1%a => state%a
      state%op1%c1 => state%s18
      state%op1%c2 => state%s7
      state%op1%c3 => state%s19
      do i = 1, npt
         tmp2 = state%beta*state%s17(i)
         tmp3 = tmp2 + state%s8
         tmp4 = tanh(tmp3)
         tmp5 = state%alpha*tmp4
         tmp6 = tmp5 + state%mu
         tmp7 = tmp6*state%s14(i)
         tmp8 = (-12.566370614359172_wp)*tmp7
         tmp1(i) = tmp8
      end do
      tmp9 = dot(state%s21, tmp1)
      tmp10 = -tmp9
      tmp11 = dot(state%s21, state%s16)
      tmp12 = tmp10 + tmp11
      tmp13 = state%s9**(-2)
      tmp14 = tmp12*tmp13
      grad_eps = 2.0_wp*tmp14
      do i = 1, npt
         tmp16 = state%s10*state%s14(i)
         tmp17 = state%beta*state%s17(i)
         tmp18 = tmp17 + state%s8
         tmp19 = tanh(tmp18)
         tmp20 = tmp16*tmp19
         tmp21 = (-12.566370614359172_wp)*tmp20
         tmp15(i) = tmp21
      end do
      tmp22 = dot(state%s21, tmp15)
      grad_alpha = -tmp22
      do i = 1, npt
         tmp24 = state%s12*state%s14(i)
         tmp25 = state%beta*state%s17(i)
         tmp26 = tmp25 + state%s8
         tmp27 = tanh(tmp26)
         tmp28 = tmp27**(2)
         tmp29 = -tmp28
         tmp30 = 1.0_wp + tmp29
         tmp31 = tmp24*tmp30
         tmp32 = tmp31*state%s17(i)
         tmp33 = (-12.566370614359172_wp)*tmp32
         tmp23(i) = tmp33
      end do
      tmp34 = dot(state%s21, tmp23)
      grad_beta = -tmp34
      do i = 1, npt
         tmp36 = state%s12*state%s14(i)
         tmp37 = state%beta*state%s17(i)
         tmp38 = tmp37 + state%s8
         tmp39 = tanh(tmp38)
         tmp40 = tmp39**(2)
         tmp41 = -tmp40
         tmp42 = 1.0_wp + tmp41
         tmp43 = tmp36*tmp42
         tmp44 = (-12.566370614359172_wp)*tmp43
         tmp35(i) = tmp44
      end do
      grad_gamma = dot(state%s21, tmp35)
      do i = 1, npt
         tmp46 = state%s10*state%s14(i)
         tmp47 = (-12.566370614359172_wp)*tmp46
         tmp45(i) = tmp47
      end do
      tmp48 = dot(state%s21, tmp45)
      grad_mu = -tmp48
   end subroutine slic_point_param_weights

end submodule pcmgen_point_slic_gradient
