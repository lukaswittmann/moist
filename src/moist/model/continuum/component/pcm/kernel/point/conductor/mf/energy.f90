!> Conductor-like PCM (point charges) phases: mf/energy; generated by pcmgen, do not edit
!>
!> - Procedures of pcmgen_point_conductor: conductor_point_mf_assemble, conductor_point_mf_medium,
!>   conductor_point_mf_solve
submodule(pcmgen_point_conductor) pcmgen_point_conductor_mf_energy
   implicit none(type, external)

contains

   module subroutine conductor_point_mf_assemble(state, r, a, error, solver)
      !> State of conductor_point
      type(conductor_point_state), target, intent(inout) :: state
      !> Positions of the surface points
      real(wp), contiguous, intent(in) :: r(:, :)
      !> Grid point areas
      real(wp), contiguous, intent(in) :: a(:)
      !> Error handling
      type(error_type), allocatable, intent(out) :: error
      !> Linear solver
      class(pcm_solver), intent(in), optional :: solver

      integer :: npt
      integer :: stat

      stat = 0
      npt = size(r, 2)
      if (npt < 1) then
         call fatal_error(error, "[conductor_point_mf_assemble] empty discretization")
         return
      end if
      if (any(shape(r) /= [3, npt])) then
         call fatal_error(error, "[conductor_point_mf_assemble] r: wrong shape")
         return
      end if
      if (any(shape(a) /= [npt])) then
         call fatal_error(error, "[conductor_point_mf_assemble] a: wrong shape")
         return
      end if
      state%ready = 0
      if (allocated(state%solver)) deallocate (state%solver)
      if (allocated(state%v)) deallocate (state%v)
      if (allocated(state%r)) deallocate (state%r)
      if (allocated(state%a)) deallocate (state%a)
      if (allocated(state%s6)) deallocate (state%s6)
      if (allocated(state%s2)) deallocate (state%s2)
      if (allocated(state%s3)) deallocate (state%s3)
      if (allocated(state%s4)) deallocate (state%s4)
      if (allocated(state%s8)) deallocate (state%s8)
      if (allocated(state%s9)) deallocate (state%s9)
      if (allocated(state%s10)) deallocate (state%s10)
      if (allocated(state%s5)) deallocate (state%s5)
      state%npt = npt
      if (present(solver)) then
         allocate (state%solver, source=solver, stat=stat)
      else
         allocate (pcm_dense_solver :: state%solver, stat=stat)
      end if
      if (stat == 0) allocate (state%v(npt), stat=stat)
      if (stat == 0) allocate (state%r(3, npt), stat=stat)
      if (stat == 0) allocate (state%a(npt), stat=stat)
      if (stat == 0) allocate (state%s6(npt), stat=stat)
      if (stat == 0) allocate (state%s2(npt), stat=stat)
      if (stat == 0) allocate (state%s3(npt), stat=stat)
      if (stat == 0) allocate (state%s4(npt), stat=stat)
      if (stat == 0) allocate (state%s8(npt), stat=stat)
      if (stat == 0) allocate (state%s9(npt), stat=stat)
      if (stat == 0) allocate (state%s10(npt), stat=stat)
      if (stat /= 0) then
         call fatal_error(error, "[conductor_point_mf_assemble] allocation failed")
         return
      end if
      state%s6 = 0.0_wp
      call state%solver%reset(conductor_point_n_operators)
      state%matrix_free = .true.

      state%r = r
      state%a = a
      state%op2%npt = npt
      state%op2%npoint = npt
      state%op2%id = 2
      state%op2%points => state%r
      state%op2%symmetric = .true.
      state%op2%r => state%r
      state%op2%a => state%a
      call state%solver%setup(state%op2, error)
      if (allocated(error)) return

      state%ready = 1
      state%assembled = state%assembled + 1
   end subroutine conductor_point_mf_assemble

   module subroutine conductor_point_mf_medium(state, feps, error)
      !> State of conductor_point
      type(conductor_point_state), target, intent(inout) :: state
      !> Dielectric factor of a conductor-like model, e.g. (eps - 1)/eps
      real(wp), intent(in) :: feps
      !> Error handling
      type(error_type), allocatable, intent(out) :: error

      integer :: npt
      integer :: stat

      stat = 0
      npt = state%npt
      if (state%ready < 1) then
         call fatal_error(error, "[conductor_point_mf_medium] call conductor_point_assemble first")
         return
      end if
      state%ready = 1

      state%op2%points => state%r
      state%op2%r => state%r
      state%op2%a => state%a
      state%feps = feps
      state%s1 = -state%feps

      state%ready = 2
   end subroutine conductor_point_mf_medium

   module subroutine conductor_point_mf_solve(state, v, energy, q, grad_v, error)
      !> State of conductor_point
      type(conductor_point_state), target, intent(inout) :: state
      !> Solute electrostatic potential at the surface points
      real(wp), contiguous, intent(in) :: v(:)
      !> Solvation energy
      real(wp), intent(out) :: energy
      !> Apparent surface charges
      real(wp), contiguous, intent(out) :: q(:)
      !> Partial derivative of the energy with respect to v
      real(wp), contiguous, intent(out) :: grad_v(:)
      !> Error handling
      type(error_type), allocatable, intent(out) :: error

      integer :: npt
      integer :: stat
      real(wp), allocatable :: tmp3(:), tmp4(:), tmp5(:), tmp10(:), tmp28(:), tmp29(:)
      real(wp) :: tmp1, tmp2, tmp6, tmp7, tmp8, tmp9, tmp30
      real(wp), allocatable :: tmp4_p(:)
      integer :: i, j

      stat = 0
      npt = state%npt
      if (state%ready < 2) then
         call fatal_error(error, "[conductor_point_mf_solve] call conductor_point_medium first")
         return
      end if
      if (any(shape(v) /= [npt])) then
         call fatal_error(error, "[conductor_point_mf_solve] v: wrong shape")
         return
      end if
      if (any(shape(q) /= [npt])) then
         call fatal_error(error, "[conductor_point_mf_solve] q: wrong shape")
         return
      end if
      if (any(shape(grad_v) /= [npt])) then
         call fatal_error(error, "[conductor_point_mf_solve] grad_v: wrong shape")
         return
      end if
      allocate (tmp3(npt), stat=stat)
      if (stat == 0) allocate (tmp4(npt), stat=stat)
      if (stat == 0) allocate (tmp5(npt), stat=stat)
      if (stat == 0) allocate (tmp10(npt), stat=stat)
      if (stat == 0) allocate (tmp28(npt), stat=stat)
      if (stat == 0) allocate (tmp29(npt), stat=stat)
      if (stat /= 0) then
         call fatal_error(error, "[conductor_point_mf_solve] allocation failed")
         return
      end if
      state%ready = 2

      state%op2%points => state%r
      state%op2%r => state%r
      state%op2%a => state%a
      state%v = v
      call state%solver%solve(state%op2, .false., state%v, state%s6, error)
      if (allocated(error)) return
      q = state%s1*state%s6
      tmp1 = dot(state%v, q)
      energy = 0.5_wp*tmp1
      grad_v = q
      if (state%solver%inexact()) then
         ! First-order correction for the residuals of the solves
         tmp2 = (-0.5_wp)*state%feps
         tmp3 = tmp2*state%s6
         do i = 1, npt
            tmp6 = 1.0_wp/state%a(i)
            tmp7 = 12.566370614359172_wp*tmp6
            tmp8 = sqrt(tmp7)
            tmp9 = 1.0694_wp*tmp8
            tmp5(i) = tmp9
         end do
         tmp10 = tmp5*state%s6
         tmp4 = tmp10
         block
            real(wp) :: tmp11, tmp12, tmp13, tmp14, tmp15, tmp18, tmp22, tmp16, tmp17, tmp19, &
                        tmp20, tmp21, tmp23, tmp24, tmp25, tmp26, tmp27

            !$omp parallel &
            !$omp& private(i, j, tmp4_p) &
            !$omp& shared(npt, state, tmp4) &
            !$omp& default(private)
            allocate (tmp4_p(npt))
            tmp4_p = 0.0_wp
            !$omp do schedule(static)
            do j = 1, npt
               tmp11 = state%r(1, j)
               tmp12 = state%r(2, j)
               tmp13 = state%r(3, j)
               tmp14 = state%s6(j)
               tmp15 = -tmp11
               tmp18 = -tmp12
               tmp22 = -tmp13
               !$omp simd &
               !$omp& private(tmp16, tmp17, tmp19, tmp20, tmp21, tmp23, tmp24, tmp25) &
               !$omp& private(tmp26, tmp27)
               do i = 1, j - 1
                  tmp16 = state%r(1, i) + tmp15
                  tmp17 = tmp16**(2)
                  tmp19 = state%r(2, i) + tmp18
                  tmp20 = tmp19**(2)
                  tmp21 = tmp17 + tmp20
                  tmp23 = state%r(3, i) + tmp22
                  tmp24 = tmp23**(2)
                  tmp25 = tmp21 + tmp24
                  tmp26 = 1.0_wp/sqrt(tmp25)
                  tmp27 = tmp26*tmp14
                  tmp4_p(i) = tmp4_p(i) + tmp27
               end do
               !$omp simd &
               !$omp& private(tmp16, tmp17, tmp19, tmp20, tmp21, tmp23, tmp24, tmp25) &
               !$omp& private(tmp26, tmp27)
               do i = j + 1, npt
                  tmp16 = state%r(1, i) + tmp15
                  tmp17 = tmp16**(2)
                  tmp19 = state%r(2, i) + tmp18
                  tmp20 = tmp19**(2)
                  tmp21 = tmp17 + tmp20
                  tmp23 = state%r(3, i) + tmp22
                  tmp24 = tmp23**(2)
                  tmp25 = tmp21 + tmp24
                  tmp26 = 1.0_wp/sqrt(tmp25)
                  tmp27 = tmp26*tmp14
                  tmp4_p(i) = tmp4_p(i) + tmp27
               end do
            end do
            !$omp end do
            !$omp critical (pcmgen_sum)
            tmp4 = tmp4 + tmp4_p
            !$omp end critical (pcmgen_sum)
            deallocate (tmp4_p)
            !$omp end parallel
         end block
         tmp28 = -tmp4
         tmp29 = state%v + tmp28
         tmp30 = dot(tmp3, tmp29)
         energy = energy + tmp30
      end if

      state%ready = 3
   end subroutine conductor_point_mf_solve

end submodule pcmgen_point_conductor_mf_energy
