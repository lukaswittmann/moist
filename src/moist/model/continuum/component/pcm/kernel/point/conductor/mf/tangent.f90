   !> One direction of conductor_point_mf_response
   !>
   !> - Vectors have length npt, matrices are (npt, npt), point fields (3, npt)
   !> - Outputs are undefined if error is allocated
   !>
   !> @param[in,out] state  state of conductor_point
   !> @param[in] dv  direction for v
   !> @param[out] hvp_v  hessian times direction, v block
   !> @param[out] error  error handling; allocated on failure
   subroutine conductor_point_mf_response_one(state, dv, hvp_v, error)
      !> State of conductor_point
      type(conductor_point_state), target, intent(inout) :: state
      !> Direction for v
      real(wp), contiguous, intent(in) :: dv(:)
      !> Hessian times direction, v block
      real(wp), contiguous, intent(out) :: hvp_v(:)
      !> Error handling
      type(error_type), allocatable, intent(out) :: error

      integer :: npt
      integer :: stat
      real(wp), allocatable :: tmp1(:)

      stat = 0
      npt = state%npt
      if (any(shape(dv) /= [npt])) then
         call fatal_error(error, "[conductor_point_mf_response_one] dv: wrong shape")
         return
      end if
      if (any(shape(hvp_v) /= [npt])) then
         call fatal_error(error, "[conductor_point_mf_response_one] hvp_v: wrong shape")
         return
      end if
      allocate (tmp1(npt), stat=stat)
      if (stat /= 0) then
         call fatal_error(error, "[conductor_point_mf_response_one] allocation failed")
         return
      end if

      state%op2%points => state%r
      state%op2%r => state%r
      state%op2%a => state%a
      tmp1 = 0.0_wp
      call state%solver%solve(state%op2, .false., dv, tmp1, error)
      if (allocated(error)) return
      hvp_v = state%s1*tmp1
   end subroutine conductor_point_mf_response_one

end submodule pcmgen_point_conductor_mf_tangent
