contains

   module subroutine iefpcm_point_mf_assemble(state, r, n, k1, k2, a, error, solver)
      !> State of iefpcm_point
      type(iefpcm_point_state), target, intent(inout) :: state
      !> Positions of the surface points
      real(wp), contiguous, intent(in) :: r(:, :)
      !> Outward unit normals at the surface points
      real(wp), contiguous, intent(in) :: n(:, :)
      !> First principal curvature (positive where convex)
      real(wp), contiguous, intent(in) :: k1(:)
      !> Second principal curvature (positive where convex)
      real(wp), contiguous, intent(in) :: k2(:)
      !> Grid point areas
      real(wp), contiguous, intent(in) :: a(:)
      !> Error handling
      type(error_type), allocatable, intent(out) :: error
      !> Linear solver
      class(pcm_solver), intent(in), optional :: solver

      integer :: npt
      integer :: stat

      stat = 0
      npt = size(r, 2)
      if (npt < 1) then
         call fatal_error(error, "[iefpcm_point_mf_assemble] empty discretization")
         return
      end if
      if (any(shape(r) /= [3, npt])) then
         call fatal_error(error, "[iefpcm_point_mf_assemble] r: wrong shape")
         return
      end if
      if (any(shape(n) /= [3, npt])) then
         call fatal_error(error, "[iefpcm_point_mf_assemble] n: wrong shape")
         return
      end if
      if (any(shape(k1) /= [npt])) then
         call fatal_error(error, "[iefpcm_point_mf_assemble] k1: wrong shape")
         return
      end if
      if (any(shape(k2) /= [npt])) then
         call fatal_error(error, "[iefpcm_point_mf_assemble] k2: wrong shape")
         return
      end if
      if (any(shape(a) /= [npt])) then
         call fatal_error(error, "[iefpcm_point_mf_assemble] a: wrong shape")
         return
      end if
      state%ready = 0
      if (allocated(state%solver)) deallocate (state%solver)
      if (allocated(state%v)) deallocate (state%v)
      if (allocated(state%r)) deallocate (state%r)
      if (allocated(state%a)) deallocate (state%a)
      if (allocated(state%n)) deallocate (state%n)
      if (allocated(state%k1)) deallocate (state%k1)
      if (allocated(state%k2)) deallocate (state%k2)
      if (allocated(state%s9)) deallocate (state%s9)
      if (allocated(state%s4)) deallocate (state%s4)
      if (allocated(state%s5)) deallocate (state%s5)
      if (allocated(state%s10)) deallocate (state%s10)
      if (allocated(state%s6)) deallocate (state%s6)
      if (allocated(state%s11)) deallocate (state%s11)
      if (allocated(state%s13)) deallocate (state%s13)
      if (allocated(state%s14)) deallocate (state%s14)
      if (allocated(state%s16)) deallocate (state%s16)
      if (allocated(state%s18)) deallocate (state%s18)
      if (allocated(state%s19)) deallocate (state%s19)
      if (allocated(state%s20)) deallocate (state%s20)
      if (allocated(state%s21)) deallocate (state%s21)
      if (allocated(state%s23)) deallocate (state%s23)
      if (allocated(state%s25)) deallocate (state%s25)
      if (allocated(state%s26)) deallocate (state%s26)
      if (allocated(state%s27)) deallocate (state%s27)
      if (allocated(state%s28)) deallocate (state%s28)
      if (allocated(state%s29)) deallocate (state%s29)
      if (allocated(state%s30)) deallocate (state%s30)
      if (allocated(state%s31)) deallocate (state%s31)
      if (allocated(state%s32)) deallocate (state%s32)
      if (allocated(state%s7)) deallocate (state%s7)
      if (allocated(state%s12)) deallocate (state%s12)
      state%npt = npt
      if (present(solver)) then
         allocate (state%solver, source=solver, stat=stat)
      else
         allocate (pcm_dense_solver :: state%solver, stat=stat)
      end if
      if (stat == 0) allocate (state%v(npt), stat=stat)
      if (stat == 0) allocate (state%r(3, npt), stat=stat)
      if (stat == 0) allocate (state%a(npt), stat=stat)
      if (stat == 0) allocate (state%n(3, npt), stat=stat)
      if (stat == 0) allocate (state%k1(npt), stat=stat)
      if (stat == 0) allocate (state%k2(npt), stat=stat)
      if (stat == 0) allocate (state%s9(npt), stat=stat)
      if (stat == 0) allocate (state%s4(npt), stat=stat)
      if (stat == 0) allocate (state%s5(npt), stat=stat)
      if (stat == 0) allocate (state%s10(npt), stat=stat)
      if (stat == 0) allocate (state%s6(npt), stat=stat)
      if (stat == 0) allocate (state%s11(npt), stat=stat)
      if (stat == 0) allocate (state%s13(npt), stat=stat)
      if (stat == 0) allocate (state%s14(npt), stat=stat)
      if (stat == 0) allocate (state%s16(npt), stat=stat)
      if (stat == 0) allocate (state%s18(npt), stat=stat)
      if (stat == 0) allocate (state%s19(npt), stat=stat)
      if (stat == 0) allocate (state%s20(npt), stat=stat)
      if (stat == 0) allocate (state%s21(npt), stat=stat)
      if (stat == 0) allocate (state%s23(npt), stat=stat)
      if (stat == 0) allocate (state%s25(npt), stat=stat)
      if (stat == 0) allocate (state%s26(npt), stat=stat)
      if (stat == 0) allocate (state%s27(npt), stat=stat)
      if (stat == 0) allocate (state%s28(npt), stat=stat)
      if (stat == 0) allocate (state%s29(npt), stat=stat)
      if (stat == 0) allocate (state%s30(npt), stat=stat)
      if (stat == 0) allocate (state%s31(npt), stat=stat)
      if (stat == 0) allocate (state%s32(npt), stat=stat)
      if (stat /= 0) then
         call fatal_error(error, "[iefpcm_point_mf_assemble] allocation failed")
         return
      end if
      state%s14 = 0.0_wp
      state%s16 = 0.0_wp
      call state%solver%reset(iefpcm_point_n_operators)
      state%matrix_free = .true.

      state%r = r
      state%a = a
      state%n = n
      state%k1 = k1
      state%k2 = k2
      state%s9 = state%n(1, :)
      state%s4 = state%r(1, :)
      state%s5 = state%r(2, :)
      state%s10 = state%n(2, :)
      state%s6 = state%r(3, :)
      state%s11 = state%n(3, :)

      state%ready = 1
      state%assembled = state%assembled + 1
   end subroutine iefpcm_point_mf_assemble

   module subroutine iefpcm_point_mf_medium(state, eps, error)
      !> State of iefpcm_point
      type(iefpcm_point_state), target, intent(inout) :: state
      !> Relative permittivity of the solvent (inf for a conductor)
      real(wp), intent(in) :: eps
      !> Error handling
      type(error_type), allocatable, intent(out) :: error

      integer :: npt
      integer :: stat
      real(wp) :: tmp1, tmp2

      stat = 0
      npt = state%npt
      if (state%ready < 1) then
         call fatal_error(error, "[iefpcm_point_mf_medium] call iefpcm_point_assemble first")
         return
      end if
      state%ready = 1
      ! Inputs that do not enter these outputs
      associate (unused1 => eps)
      end associate

      state%op2%npt = npt
      state%op2%npoint = npt
      state%op2%id = 2
      state%op2%points => state%r
      state%op2%r => state%r
      state%op2%n => state%n
      state%op2%k1 => state%k1
      state%op2%k2 => state%k2
      state%op2%a => state%a
      state%s1 = eps + 1.0_wp
      tmp1 = 1.0_wp/state%s1
      tmp2 = (-2.0_wp)*tmp1
      state%s2 = 1.0_wp + tmp2
      state%s8 = (-0.15915494309189535_wp)*state%s2
      state%op2%c1 = state%s8
      call state%solver%setup(state%op2, error)
      if (allocated(error)) return
      state%s3 = -state%s2
      state%s15 = (-0.5_wp)*state%s2
      state%s17 = 0.07957747154594767_wp*state%s2
      state%s24 = 0.5_wp*state%s2

      state%ready = 2
   end subroutine iefpcm_point_mf_medium

   module subroutine iefpcm_point_mf_solve(state, v, energy, q, grad_v, error)
      !> State of iefpcm_point
      type(iefpcm_point_state), target, intent(inout) :: state
      !> Solute electrostatic potential at the surface points
      real(wp), contiguous, intent(in) :: v(:)
      !> Solvation energy
      real(wp), intent(out) :: energy
      !> Apparent surface charges
      real(wp), contiguous, intent(out) :: q(:)
      !> Partial derivative of the energy with respect to v
      real(wp), contiguous, intent(out) :: grad_v(:)
      !> Error handling
      type(error_type), allocatable, intent(out) :: error

      integer :: npt
      integer :: stat
      real(wp), allocatable :: tmp1(:), tmp2(:), tmp9(:), tmp10(:), tmp11(:), tmp12(:), tmp45(:), &
                               tmp46(:), tmp47(:), tmp52(:), tmp71(:), tmp72(:), tmp73(:), &
                               tmp74(:), tmp75(:), tmp76(:), tmp104(:), tmp105(:), tmp106(:), &
                               tmp107(:)
      real(wp) :: tmp3, tmp4, tmp5, tmp6, tmp7, tmp8, tmp48, tmp49, tmp50, tmp51, tmp70, tmp108
      real(wp), allocatable :: tmp1_p(:), tmp46_p(:), tmp75_p(:)
      integer :: i, j

      stat = 0
      npt = state%npt
      if (state%ready < 2) then
         call fatal_error(error, "[iefpcm_point_mf_solve] call iefpcm_point_medium first")
         return
      end if
      if (any(shape(v) /= [npt])) then
         call fatal_error(error, "[iefpcm_point_mf_solve] v: wrong shape")
         return
      end if
      if (any(shape(q) /= [npt])) then
         call fatal_error(error, "[iefpcm_point_mf_solve] q: wrong shape")
         return
      end if
      if (any(shape(grad_v) /= [npt])) then
         call fatal_error(error, "[iefpcm_point_mf_solve] grad_v: wrong shape")
         return
      end if
      allocate (tmp1(npt), stat=stat)
      if (stat == 0) allocate (tmp2(npt), stat=stat)
      if (stat == 0) allocate (tmp9(npt), stat=stat)
      if (stat == 0) allocate (tmp10(npt), stat=stat)
      if (stat == 0) allocate (tmp11(npt), stat=stat)
      if (stat == 0) allocate (tmp12(npt), stat=stat)
      if (stat == 0) allocate (tmp45(npt), stat=stat)
      if (stat == 0) allocate (tmp46(npt), stat=stat)
      if (stat == 0) allocate (tmp47(npt), stat=stat)
      if (stat == 0) allocate (tmp52(npt), stat=stat)
      if (stat == 0) allocate (tmp71(npt), stat=stat)
      if (stat == 0) allocate (tmp72(npt), stat=stat)
      if (stat == 0) allocate (tmp73(npt), stat=stat)
      if (stat == 0) allocate (tmp74(npt), stat=stat)
      if (stat == 0) allocate (tmp75(npt), stat=stat)
      if (stat == 0) allocate (tmp76(npt), stat=stat)
      if (stat == 0) allocate (tmp104(npt), stat=stat)
      if (stat == 0) allocate (tmp105(npt), stat=stat)
      if (stat == 0) allocate (tmp106(npt), stat=stat)
      if (stat == 0) allocate (tmp107(npt), stat=stat)
      if (stat /= 0) then
         call fatal_error(error, "[iefpcm_point_mf_solve] allocation failed")
         return
      end if
      state%ready = 2

      state%op2%points => state%r
      state%op2%r => state%r
      state%op2%n => state%n
      state%op2%k1 => state%k1
      state%op2%k2 => state%k2
      state%op2%a => state%a
      state%v = v
      state%s13 = state%a*state%v
      call state%solver%solve(state%op2, .true., state%v, state%s16, error)
      if (allocated(error)) return
      state%s18 = state%s17*state%s16
      do i = 1, npt
         tmp3 = state%k1(i) + state%k2(i)
         tmp4 = 1.0_wp/state%a(i)
         tmp5 = 12.566370614359172_wp*tmp4
         tmp6 = sqrt(tmp5)
         tmp7 = tmp3*tmp6
         tmp8 = (-0.26735_wp)*tmp7
         tmp2(i) = tmp8
      end do
      tmp9 = tmp2*state%s13
      tmp10 = (-0.15915494309189535_wp)*tmp9
      tmp1 = tmp10
      tmp12 = tmp2*state%s18
      tmp11 = tmp12
      block
         real(wp) :: tmp14, tmp15, tmp16, tmp17, tmp18, tmp19, tmp20, tmp21, tmp22, tmp25, tmp29, &
                     tmp13, tmp23, tmp24, tmp26, tmp27, tmp28, tmp30, tmp31, tmp32, tmp33, tmp34, &
                     tmp35, tmp36, tmp37, tmp38, tmp39, tmp40, tmp41, tmp42, tmp43, tmp44

         !$omp parallel &
         !$omp& private(i, j, tmp1_p) &
         !$omp& shared(npt, state, tmp1, tmp11) &
         !$omp& default(private)
         allocate (tmp1_p(npt))
         tmp1_p = 0.0_wp
         !$omp do schedule(static)
         do j = 1, npt
            tmp14 = state%s13(j)
            tmp15 = state%s9(j)
            tmp16 = state%s4(j)
            tmp17 = state%s5(j)
            tmp18 = state%s10(j)
            tmp19 = state%s6(j)
            tmp20 = state%s11(j)
            tmp21 = state%s18(j)
            tmp22 = -tmp16
            tmp25 = -tmp17
            tmp29 = -tmp19
            tmp13 = 0.0_wp
            !$omp simd &
            !$omp& private(tmp23, tmp24, tmp26, tmp27, tmp28, tmp30, tmp31, tmp32) &
            !$omp& private(tmp33, tmp34, tmp35, tmp36, tmp37, tmp38, tmp39, tmp40) &
            !$omp& private(tmp41, tmp42, tmp43, tmp44) &
            !$omp& reduction(+: tmp13)
            do i = 1, j - 1
               tmp23 = state%s4(i) + tmp22
               tmp24 = tmp15*tmp23
               tmp26 = state%s5(i) + tmp25
               tmp27 = tmp26*tmp18
               tmp28 = tmp24 + tmp27
               tmp30 = state%s6(i) + tmp29
               tmp31 = tmp30*tmp20
               tmp32 = tmp28 + tmp31
               tmp33 = tmp14*tmp32
               tmp34 = tmp23**(2)
               tmp35 = tmp26**(2)
               tmp36 = tmp34 + tmp35
               tmp37 = tmp30**(2)
               tmp38 = tmp36 + tmp37
               tmp39 = 1.0_wp/sqrt(tmp38)
               tmp40 = tmp39**(3)
               tmp41 = tmp33*tmp40
               tmp42 = (-0.15915494309189535_wp)*tmp41
               tmp1_p(i) = tmp1_p(i) + tmp42
               tmp43 = tmp32*tmp40
               tmp44 = tmp43*state%s18(i)
               tmp13 = tmp13 + tmp44
            end do
            !$omp simd &
            !$omp& private(tmp23, tmp24, tmp26, tmp27, tmp28, tmp30, tmp31, tmp32) &
            !$omp& private(tmp33, tmp34, tmp35, tmp36, tmp37, tmp38, tmp39, tmp40) &
            !$omp& private(tmp41, tmp42, tmp43, tmp44) &
            !$omp& reduction(+: tmp13)
            do i = j + 1, npt
               tmp23 = state%s4(i) + tmp22
               tmp24 = tmp15*tmp23
               tmp26 = state%s5(i) + tmp25
               tmp27 = tmp26*tmp18
               tmp28 = tmp24 + tmp27
               tmp30 = state%s6(i) + tmp29
               tmp31 = tmp30*tmp20
               tmp32 = tmp28 + tmp31
               tmp33 = tmp14*tmp32
               tmp34 = tmp23**(2)
               tmp35 = tmp26**(2)
               tmp36 = tmp34 + tmp35
               tmp37 = tmp30**(2)
               tmp38 = tmp36 + tmp37
               tmp39 = 1.0_wp/sqrt(tmp38)
               tmp40 = tmp39**(3)
               tmp41 = tmp33*tmp40
               tmp42 = (-0.15915494309189535_wp)*tmp41
               tmp1_p(i) = tmp1_p(i) + tmp42
               tmp43 = tmp32*tmp40
               tmp44 = tmp43*state%s18(i)
               tmp13 = tmp13 + tmp44
            end do
            tmp11(j) = tmp11(j) + tmp13
         end do
         !$omp end do
         !$omp critical (pcmgen_sum)
         tmp1 = tmp1 + tmp1_p
         !$omp end critical (pcmgen_sum)
         deallocate (tmp1_p)
         !$omp end parallel
      end block
      state%s19 = tmp11
      tmp45 = state%v + tmp1
      call state%solver%solve(state%op2, .false., tmp45, state%s14, error)
      if (allocated(error)) return
      do i = 1, npt
         tmp48 = 1.0_wp/state%a(i)
         tmp49 = 12.566370614359172_wp*tmp48
         tmp50 = sqrt(tmp49)
         tmp51 = 1.0694_wp*tmp50
         tmp47(i) = tmp51
      end do
      tmp52 = tmp47*state%s14
      tmp46 = tmp52
      block
         real(wp) :: tmp53, tmp54, tmp55, tmp56, tmp57, tmp60, tmp64, tmp58, tmp59, tmp61, tmp62, &
                     tmp63, tmp65, tmp66, tmp67, tmp68, tmp69

         !$omp parallel &
         !$omp& private(i, j, tmp46_p) &
         !$omp& shared(npt, state, tmp46) &
         !$omp& default(private)
         allocate (tmp46_p(npt))
         tmp46_p = 0.0_wp
         !$omp do schedule(static)
         do j = 1, npt
            tmp53 = state%s14(j)
            tmp54 = state%s4(j)
            tmp55 = state%s5(j)
            tmp56 = state%s6(j)
            tmp57 = -tmp54
            tmp60 = -tmp55
            tmp64 = -tmp56
            !$omp simd &
            !$omp& private(tmp58, tmp59, tmp61, tmp62, tmp63, tmp65, tmp66, tmp67) &
            !$omp& private(tmp68, tmp69)
            do i = 1, j - 1
               tmp58 = state%s4(i) + tmp57
               tmp59 = tmp58**(2)
               tmp61 = state%s5(i) + tmp60
               tmp62 = tmp61**(2)
               tmp63 = tmp59 + tmp62
               tmp65 = state%s6(i) + tmp64
               tmp66 = tmp65**(2)
               tmp67 = tmp63 + tmp66
               tmp68 = 1.0_wp/sqrt(tmp67)
               tmp69 = tmp53*tmp68
               tmp46_p(i) = tmp46_p(i) + tmp69
            end do
            !$omp simd &
            !$omp& private(tmp58, tmp59, tmp61, tmp62, tmp63, tmp65, tmp66, tmp67) &
            !$omp& private(tmp68, tmp69)
            do i = j + 1, npt
               tmp58 = state%s4(i) + tmp57
               tmp59 = tmp58**(2)
               tmp61 = state%s5(i) + tmp60
               tmp62 = tmp61**(2)
               tmp63 = tmp59 + tmp62
               tmp65 = state%s6(i) + tmp64
               tmp66 = tmp65**(2)
               tmp67 = tmp63 + tmp66
               tmp68 = 1.0_wp/sqrt(tmp67)
               tmp69 = tmp53*tmp68
               tmp46_p(i) = tmp46_p(i) + tmp69
            end do
         end do
         !$omp end do
         !$omp critical (pcmgen_sum)
         tmp46 = tmp46 + tmp46_p
         !$omp end critical (pcmgen_sum)
         deallocate (tmp46_p)
         !$omp end parallel
      end block
      state%s20 = tmp46
      state%s21 = state%a*state%s20
      state%s25 = state%s24*state%s16
      q = state%s3*state%s14
      tmp70 = dot(state%v, q)
      energy = 0.5_wp*tmp70
      tmp71 = state%s15*state%s14
      tmp72 = state%s15*state%s16
      tmp73 = tmp71 + tmp72
      tmp74 = state%s19*state%a
      grad_v = tmp73 + tmp74
      if (state%solver%inexact()) then
         ! First-order correction for the residuals of the solves
         tmp76 = tmp2*state%s21
         tmp75 = tmp76
         block
            real(wp) :: tmp77, tmp78, tmp79, tmp80, tmp81, tmp82, tmp83, tmp84, tmp87, tmp91, &
                        tmp85, tmp86, tmp88, tmp89, tmp90, tmp92, tmp93, tmp94, tmp95, tmp96, &
                        tmp97, tmp98, tmp99, tmp100, tmp101, tmp102, tmp103

            !$omp parallel &
            !$omp& private(i, j, tmp75_p) &
            !$omp& shared(npt, state, tmp75) &
            !$omp& default(private)
            allocate (tmp75_p(npt))
            tmp75_p = 0.0_wp
            !$omp do schedule(static)
            do j = 1, npt
               tmp77 = state%s21(j)
               tmp78 = state%s9(j)
               tmp79 = state%s4(j)
               tmp80 = state%s5(j)
               tmp81 = state%s10(j)
               tmp82 = state%s6(j)
               tmp83 = state%s11(j)
               tmp84 = -tmp79
               tmp87 = -tmp80
               tmp91 = -tmp82
               !$omp simd &
               !$omp& private(tmp85, tmp86, tmp88, tmp89, tmp90, tmp92, tmp93, tmp94) &
               !$omp& private(tmp95, tmp96, tmp97, tmp98, tmp99, tmp100, tmp101) &
               !$omp& private(tmp102, tmp103)
               do i = 1, j - 1
                  tmp85 = state%s4(i) + tmp84
                  tmp86 = tmp78*tmp85
                  tmp88 = state%s5(i) + tmp87
                  tmp89 = tmp88*tmp81
                  tmp90 = tmp86 + tmp89
                  tmp92 = state%s6(i) + tmp91
                  tmp93 = tmp92*tmp83
                  tmp94 = tmp90 + tmp93
                  tmp95 = tmp77*tmp94
                  tmp96 = tmp85**(2)
                  tmp97 = tmp88**(2)
                  tmp98 = tmp96 + tmp97
                  tmp99 = tmp92**(2)
                  tmp100 = tmp98 + tmp99
                  tmp101 = 1.0_wp/sqrt(tmp100)
                  tmp102 = tmp101**(3)
                  tmp103 = tmp95*tmp102
                  tmp75_p(i) = tmp75_p(i) + tmp103
               end do
               !$omp simd &
               !$omp& private(tmp85, tmp86, tmp88, tmp89, tmp90, tmp92, tmp93, tmp94) &
               !$omp& private(tmp95, tmp96, tmp97, tmp98, tmp99, tmp100, tmp101) &
               !$omp& private(tmp102, tmp103)
               do i = j + 1, npt
                  tmp85 = state%s4(i) + tmp84
                  tmp86 = tmp78*tmp85
                  tmp88 = state%s5(i) + tmp87
                  tmp89 = tmp88*tmp81
                  tmp90 = tmp86 + tmp89
                  tmp92 = state%s6(i) + tmp91
                  tmp93 = tmp92*tmp83
                  tmp94 = tmp90 + tmp93
                  tmp95 = tmp77*tmp94
                  tmp96 = tmp85**(2)
                  tmp97 = tmp88**(2)
                  tmp98 = tmp96 + tmp97
                  tmp99 = tmp92**(2)
                  tmp100 = tmp98 + tmp99
                  tmp101 = 1.0_wp/sqrt(tmp100)
                  tmp102 = tmp101**(3)
                  tmp103 = tmp95*tmp102
                  tmp75_p(i) = tmp75_p(i) + tmp103
               end do
            end do
            !$omp end do
            !$omp critical (pcmgen_sum)
            tmp75 = tmp75 + tmp75_p
            !$omp end critical (pcmgen_sum)
            deallocate (tmp75_p)
            !$omp end parallel
         end block
         tmp104 = state%s8*tmp75
         tmp105 = state%s20 + tmp104
         tmp106 = -tmp105
         tmp107 = tmp45 + tmp106
         tmp108 = dot(tmp72, tmp107)
         energy = energy + tmp108
      end if

      state%ready = 3
   end subroutine iefpcm_point_mf_solve

