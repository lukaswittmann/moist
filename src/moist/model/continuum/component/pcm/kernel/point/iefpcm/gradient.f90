               tmp34 = tmp34 + tmp110
            end do
            !$omp simd &
            !$omp& private(tmp48, tmp49, tmp51, tmp52, tmp53, tmp55, tmp56, tmp57) &
            !$omp& private(tmp58, tmp59, tmp60, tmp61, tmp62, tmp63, tmp64, tmp65) &
            !$omp& private(tmp66, tmp67, tmp68, tmp69, tmp70, tmp71, tmp72, tmp73) &
            !$omp& private(tmp74, tmp75, tmp76, tmp77, tmp78, tmp79, tmp80, tmp81) &
            !$omp& private(tmp82, tmp83, tmp84, tmp85, tmp86, tmp87, tmp88, tmp89) &
            !$omp& private(tmp90, tmp91, tmp92, tmp93, tmp94, tmp95, tmp96, tmp97) &
            !$omp& private(tmp98, tmp99, tmp100, tmp101, tmp102, tmp103, tmp104) &
            !$omp& private(tmp105, tmp106, tmp107, tmp108, tmp109, tmp110) &
            !$omp& reduction(+: tmp29, tmp30, tmp31, tmp32, tmp33, tmp34)
            do i = j + 1, npt
               tmp48 = state%s4(i) + tmp47
               tmp49 = tmp35*tmp48
               tmp51 = state%s5(i) + tmp50
               tmp52 = tmp51*tmp38
               tmp53 = tmp49 + tmp52
               tmp55 = state%s6(i) + tmp54
               tmp56 = tmp55*tmp40
               tmp57 = tmp53 + tmp56
               tmp58 = tmp57*tmp48
