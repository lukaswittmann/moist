            !$omp& private(tmp58, tmp59, tmp60, tmp61, tmp62, tmp63, tmp64, tmp65) &
            !$omp& private(tmp66, tmp67, tmp68, tmp69, tmp70, tmp71, tmp72, tmp73) &
            !$omp& private(tmp74, tmp75, tmp76, tmp77, tmp78, tmp79, tmp80, tmp81) &
            !$omp& private(tmp82, tmp83, tmp84, tmp85, tmp86, tmp87, tmp88, tmp89) &
            !$omp& private(tmp90, tmp91, tmp92, tmp93, tmp94, tmp95, tmp96, tmp97) &
            !$omp& private(tmp98, tmp99, tmp100, tmp101, tmp102, tmp103, tmp104) &
            !$omp& private(tmp105, tmp106, tmp107, tmp108, tmp109, tmp110) &
            !$omp& reduction(+: tmp29, tmp30, tmp31, tmp32, tmp33, tmp34)
            do i = 1, j - 1
               tmp48 = state%s4(i) + tmp47
               tmp49 = tmp35*tmp48
               tmp51 = state%s5(i) + tmp50
               tmp52 = tmp51*tmp38
               tmp53 = tmp49 + tmp52
               tmp55 = state%s6(i) + tmp54
               tmp56 = tmp55*tmp40
               tmp57 = tmp53 + tmp56
               tmp58 = tmp57*tmp48
               tmp59 = tmp48**(2)
               tmp60 = tmp51**(2)
               tmp61 = tmp59 + tmp60
               tmp62 = tmp55**(2)
               tmp63 = tmp61 + tmp62
               tmp64 = 1.0_wp/sqrt(tmp63)
               tmp65 = tmp64**(5)
               tmp66 = tmp58*tmp65
               tmp67 = (-3.0_wp)*tmp66
               tmp68 = tmp64**(3)
               tmp69 = tmp35*tmp68
               tmp70 = tmp67 + tmp69
               tmp71 = tmp41*state%s18(i)
               tmp72 = tmp43*state%s23(i)
               tmp73 = tmp71 + tmp72
               tmp74 = tmp70*tmp73
               tmp75 = tmp45*state%s27(i)
               tmp76 = tmp75*tmp68
               tmp77 = tmp76*tmp48
               tmp78 = -tmp77
               tmp79 = tmp74 + tmp78
               tmp23_p(i) = tmp23_p(i) + tmp79
               tmp80 = -tmp79
               tmp29 = tmp29 + tmp80
               tmp81 = tmp51*tmp57
               tmp82 = tmp81*tmp65
               tmp83 = (-3.0_wp)*tmp82
               tmp84 = tmp38*tmp68
               tmp85 = tmp83 + tmp84
               tmp86 = tmp85*tmp73
