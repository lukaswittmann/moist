   module subroutine iefpcm_point_param_weights(state, grad_eps, error)
      !> State of iefpcm_point
      type(iefpcm_point_state), target, intent(inout) :: state
      !> Partial derivative of the energy with respect to eps
      real(wp), intent(out) :: grad_eps
      !> Error handling
      type(error_type), allocatable, intent(out) :: error

      integer :: npt
      integer :: stat
      real(wp), allocatable :: tmp1(:), tmp4(:)
      real(wp) :: tmp2, tmp3, tmp5, tmp6, tmp7, tmp8, tmp9

      if (state%matrix_free) then
         call iefpcm_point_mf_param_weights(state, grad_eps, error)
         return
      end if
      stat = 0
      npt = state%npt
      if (state%ready < 3) then
         call fatal_error(error, "[iefpcm_point_param_weights] call iefpcm_point_solve first")
         return
      end if
      allocate (tmp1(npt), stat=stat)
      if (stat == 0) allocate (tmp4(npt), stat=stat)
      if (stat /= 0) then
         call fatal_error(error, "[iefpcm_point_param_weights] allocation failed")
         return
      end if

      state%op1%points => state%r
      state%op1%a => state%a
      state%op1%c1 => state%s7
      state%op1%c3 => state%s12
      call gemv(state%s12, state%s21, tmp1)
      tmp2 = dot(state%s25, tmp1)
      tmp3 = (-0.15915494309189535_wp)*tmp2
      tmp4 = 0.5_wp*state%v
      tmp5 = dot(tmp4, state%s14)
      tmp6 = -tmp5
      tmp7 = tmp3 + tmp6
      tmp8 = state%s1**(-2)
      tmp9 = tmp7*tmp8
      grad_eps = 2.0_wp*tmp9
   end subroutine iefpcm_point_param_weights

