      tmp2 = state%a*state%s26
      state%s27 = state%s25 + tmp2
      tmp3 = state%s18*state%s13
      tmp4 = state%s23*state%s21
      state%s28 = tmp3 + tmp4
      do i = 1, npt
         tmp5 = 1.0_wp/state%a(i)
         tmp6 = 12.566370614359172_wp*tmp5
         tmp7 = sqrt(tmp6)
         tmp8 = (-0.26735_wp)*tmp7
         state%s29(i) = tmp8
      end do
      do i = 1, npt
         tmp9 = 1.0_wp/state%a(i)
         tmp10 = 12.566370614359172_wp*tmp9
         tmp11 = 1.0_wp/sqrt(tmp10)
         tmp12 = state%k1(i) + state%k2(i)
         tmp13 = tmp11*tmp12
         tmp14 = state%a(i)**(-2)
         tmp15 = tmp13*tmp14
         tmp16 = 1.6798095918744622_wp*tmp15
         state%s30(i) = tmp16
      end do
      state%s31 = state%s27*state%s14
      do i = 1, npt
         tmp17 = 1.0_wp/state%a(i)
         tmp18 = 12.566370614359172_wp*tmp17
         tmp19 = 1.0_wp/sqrt(tmp18)
         tmp20 = state%a(i)**(-2)
