      complex(wp), contiguous, intent(in) :: dv(:, :)
      !> Hessian times direction, v block
      complex(wp), contiguous, intent(out) :: hvp_v(:, :)
      !> Error handling
      type(error_type), allocatable, intent(out) :: error

      integer :: npt, nblk, blk

      if (state%matrix_free) then
         call ssvpe_point_complex_mf_response(state, dv, hvp_v, error)
         return
      end if
      if (state%cx_ready < 3 .or. state%cx_assembled /= state%assembled) then
         call fatal_error(error, &
                          "[ssvpe_point_complex_response] call ssvpe_point_complex_solve first")
         return
      end if
      npt = state%npt
      nblk = size(dv, 2)
      if (any(shape(dv) /= [npt, nblk])) then
         call fatal_error(error, "[ssvpe_point_complex_response] dv: wrong shape")
         return
      end if
      if (any(shape(hvp_v) /= [npt, nblk])) then
         call fatal_error(error, "[ssvpe_point_complex_response] hvp_v: wrong shape")
         return
      end if
      do blk = 1, nblk
         call ssvpe_point_complex_response_one(state, dv(:, blk), hvp_v(:, blk), error)
         if (allocated(error)) return
      end do
   end subroutine ssvpe_point_complex_response

   !> One direction of ssvpe_point_complex_response
   !>
   !> - Vectors have length npt, matrices are (npt, npt), point fields (3, npt)
   !> - Outputs are undefined if error is allocated
   !>
   !> @param[in,out] state  state of ssvpe_point
   !> @param[in] dv  direction for v
   !> @param[out] hvp_v  hessian times direction, v block
   !> @param[out] error  error handling; allocated on failure
   subroutine ssvpe_point_complex_response_one(state, dv, hvp_v, error)
      !> State of ssvpe_point
      type(ssvpe_point_complex_state), target, intent(inout) :: state
      !> Direction for v
      complex(wp), contiguous, intent(in) :: dv(:)
      !> Hessian times direction, v block
      complex(wp), contiguous, intent(out) :: hvp_v(:)
      !> Error handling
      type(error_type), allocatable, intent(out) :: error

      integer :: npt
      integer :: stat
      real(wp), allocatable :: tmp3(:), tmp4(:), tmp14(:), tmp15(:)
      complex(wp), allocatable :: tmp1(:), tmp2(:), tmp5(:), tmp6(:), tmp7(:), tmp8(:), tmp9(:), &
                                  tmp10(:), tmp11(:), tmp12(:), tmp13(:), tmp16(:)

      stat = 0
      npt = state%npt
      if (any(shape(dv) /= [npt])) then
         call fatal_error(error, "[ssvpe_point_complex_response_one] dv: wrong shape")
         return
      end if
      if (any(shape(hvp_v) /= [npt])) then
         call fatal_error(error, "[ssvpe_point_complex_response_one] hvp_v: wrong shape")
         return
      end if
      allocate (tmp1(npt), stat=stat)
      if (stat == 0) allocate (tmp2(npt), stat=stat)
      if (stat == 0) allocate (tmp3(npt), stat=stat)
      if (stat == 0) allocate (tmp4(npt), stat=stat)
      if (stat == 0) allocate (tmp5(npt), stat=stat)
      if (stat == 0) allocate (tmp6(npt), stat=stat)
      if (stat == 0) allocate (tmp7(npt), stat=stat)
      if (stat == 0) allocate (tmp8(npt), stat=stat)
      if (stat == 0) allocate (tmp9(npt), stat=stat)
      if (stat == 0) allocate (tmp10(npt), stat=stat)
      if (stat == 0) allocate (tmp11(npt), stat=stat)
      if (stat == 0) allocate (tmp12(npt), stat=stat)
      if (stat == 0) allocate (tmp13(npt), stat=stat)
      if (stat == 0) allocate (tmp14(npt), stat=stat)
      if (stat == 0) allocate (tmp15(npt), stat=stat)
      if (stat == 0) allocate (tmp16(npt), stat=stat)
      if (stat /= 0) then
         call fatal_error(error, "[ssvpe_point_complex_response_one] allocation failed")
         return
      end if

      state%op3%points => state%r
      state%op3%a => state%a
      state%op3%c1 => state%s7
      state%op3%c3 => state%s12
      tmp1 = state%a*dv
      call gemv(state%s12, real(tmp1, wp), tmp3)
      call gemv(state%s12, aimag(tmp1), tmp4)
      tmp2 = cmplx(tmp3, tmp4, wp)
      tmp5 = (-0.15915494309189535_wp)*tmp2
      tmp6 = dv + tmp5
      tmp7 = 0.0_wp
      call state%solver%solve_complex(state%op3, .false., tmp6, tmp7, error)
      if (allocated(error)) return
      tmp8 = state%cx_s15*tmp7
      tmp9 = 0.0_wp
      call state%solver%solve_complex(state%op3, .false., dv, tmp9, error)
      if (allocated(error)) return
      tmp10 = state%cx_s15*tmp9
      tmp11 = tmp8 + tmp10
      tmp12 = state%cx_s17*tmp9
      call gemv(state%s12, real(tmp12, wp), tmp14, trans="t")
      call gemv(state%s12, aimag(tmp12), tmp15, trans="t")
      tmp13 = cmplx(tmp14, tmp15, wp)
      tmp16 = tmp13*state%a
      hvp_v = tmp11 + tmp16
   end subroutine ssvpe_point_complex_response_one

