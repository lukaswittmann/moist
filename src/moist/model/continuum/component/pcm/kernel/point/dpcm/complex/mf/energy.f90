!> DPCM (point charges) phases: complex/mf/energy; generated by pcmgen, do not edit
!>
!> - Procedures of pcmgen_point_dpcm: dpcm_point_complex_mf_medium, dpcm_point_complex_mf_solve
submodule(pcmgen_point_dpcm) pcmgen_point_dpcm_complex_mf_energy
   implicit none(type, external)

contains

   module subroutine dpcm_point_complex_mf_medium(state, eps, error)
      !> State of dpcm_point
      type(dpcm_point_complex_state), target, intent(inout) :: state
      !> Relative permittivity of the solvent (inf for a conductor)
      complex(wp), intent(in) :: eps
      !> Error handling
      type(error_type), allocatable, intent(out) :: error

      integer :: npt
      integer :: stat
      complex(wp) :: tmp1, tmp2

      stat = 0
      npt = state%npt
      if (state%ready < 1) then
         call fatal_error(error, "[dpcm_point_complex_mf_medium] call dpcm_point_assemble first")
         return
      end if
      state%cx_ready = 0
      if (allocated(state%cx_v)) deallocate (state%cx_v)
      if (allocated(state%cx_vn)) deallocate (state%cx_vn)
      if (allocated(state%cx_s11)) deallocate (state%cx_s11)
      if (allocated(state%cx_s13)) deallocate (state%cx_s13)
      if (allocated(state%cx_s14)) deallocate (state%cx_s14)
      if (allocated(state%cx_s15)) deallocate (state%cx_s15)
      if (allocated(state%cx_s17)) deallocate (state%cx_s17)
      if (allocated(state%cx_s18)) deallocate (state%cx_s18)
      if (allocated(state%cx_s19)) deallocate (state%cx_s19)
      if (allocated(state%cx_s20)) deallocate (state%cx_s20)
      if (allocated(state%cx_s21)) deallocate (state%cx_s21)
      if (stat == 0) allocate (state%cx_v(npt), stat=stat)
      if (stat == 0) allocate (state%cx_vn(npt), stat=stat)
      if (stat == 0) allocate (state%cx_s11(npt), stat=stat)
      if (stat == 0) allocate (state%cx_s13(npt), stat=stat)
      if (stat == 0) allocate (state%cx_s14(npt), stat=stat)
      if (stat == 0) allocate (state%cx_s15(npt), stat=stat)
      if (stat == 0) allocate (state%cx_s17(npt), stat=stat)
      if (stat == 0) allocate (state%cx_s18(npt), stat=stat)
      if (stat == 0) allocate (state%cx_s19(npt), stat=stat)
      if (stat == 0) allocate (state%cx_s20(npt), stat=stat)
      if (stat == 0) allocate (state%cx_s21(npt), stat=stat)
      if (stat /= 0) then
         call fatal_error(error, "[dpcm_point_complex_mf_medium] allocation failed")
         return
      end if
      state%cx_s11 = 0.0_wp
      state%cx_s13 = 0.0_wp
      state%cx_ready = 1
      state%cx_assembled = state%assembled
      ! Inputs that do not enter these outputs
      associate (unused1 => eps)
      end associate

      state%op4%npt = npt
      state%op4%npoint = npt
      state%op4%id = 4
      state%op4%points => state%r
      state%op4%r => state%r
      state%op4%n => state%n
      state%op4%k1 => state%k1
      state%op4%k2 => state%k2
      state%op4%a => state%a
      state%cx_s1 = eps + 1.0_wp
      tmp1 = 1.0_wp/state%cx_s1
      tmp2 = (-2.0_wp)*tmp1
      state%cx_s2 = 1.0_wp + tmp2
      state%cx_s3 = -state%cx_s2
      state%op4%c1 = state%cx_s3
      call state%solver%setup_complex(state%op4, error)
      if (allocated(error)) return
      state%cx_s12 = 0.5_wp*state%cx_s2

      state%cx_ready = 2
   end subroutine dpcm_point_complex_mf_medium

   module subroutine dpcm_point_complex_mf_solve(state, v, vn, energy, q, grad_v, grad_vn, error)
      !> State of dpcm_point
      type(dpcm_point_complex_state), target, intent(inout) :: state
      !> Solute electrostatic potential at the surface points
      complex(wp), contiguous, intent(in) :: v(:)
      !> Outward normal derivative of the solute potential at the surface points
      complex(wp), contiguous, intent(in) :: vn(:)
      !> Solvation energy
      complex(wp), intent(out) :: energy
      !> Apparent surface charges
      complex(wp), contiguous, intent(out) :: q(:)
      !> Partial derivative of the energy with respect to v
      complex(wp), contiguous, intent(out) :: grad_v(:)
      !> Partial derivative of the energy with respect to vn
      complex(wp), contiguous, intent(out) :: grad_vn(:)
      !> Error handling
      type(error_type), allocatable, intent(out) :: error

      integer :: npt
      integer :: stat
      real(wp), allocatable :: tmp3(:)
      real(wp) :: tmp4, tmp5, tmp6, tmp7, tmp8, tmp9
      complex(wp), allocatable :: tmp1(:), tmp2(:), tmp10(:), tmp40(:), tmp41(:), tmp42(:), &
                                  tmp43(:), tmp44(:), tmp45(:)
      complex(wp) :: tmp39, tmp46
      integer :: i, j

      stat = 0
      npt = state%npt
      if (state%cx_ready < 2 .or. state%cx_assembled /= state%assembled) then
         call fatal_error(error, &
                          "[dpcm_point_complex_mf_solve] call dpcm_point_complex_medium first")
         return
      end if
      if (any(shape(v) /= [npt])) then
         call fatal_error(error, "[dpcm_point_complex_mf_solve] v: wrong shape")
         return
      end if
      if (any(shape(vn) /= [npt])) then
         call fatal_error(error, "[dpcm_point_complex_mf_solve] vn: wrong shape")
         return
      end if
      if (any(shape(q) /= [npt])) then
         call fatal_error(error, "[dpcm_point_complex_mf_solve] q: wrong shape")
         return
      end if
      if (any(shape(grad_v) /= [npt])) then
         call fatal_error(error, "[dpcm_point_complex_mf_solve] grad_v: wrong shape")
         return
      end if
      if (any(shape(grad_vn) /= [npt])) then
         call fatal_error(error, "[dpcm_point_complex_mf_solve] grad_vn: wrong shape")
         return
      end if
      allocate (tmp1(npt), stat=stat)
      if (stat == 0) allocate (tmp2(npt), stat=stat)
      if (stat == 0) allocate (tmp3(npt), stat=stat)
      if (stat == 0) allocate (tmp10(npt), stat=stat)
      if (stat == 0) allocate (tmp40(npt), stat=stat)
      if (stat == 0) allocate (tmp41(npt), stat=stat)
      if (stat == 0) allocate (tmp42(npt), stat=stat)
      if (stat == 0) allocate (tmp43(npt), stat=stat)
      if (stat == 0) allocate (tmp44(npt), stat=stat)
      if (stat == 0) allocate (tmp45(npt), stat=stat)
      if (stat /= 0) then
         call fatal_error(error, "[dpcm_point_complex_mf_solve] allocation failed")
         return
      end if
      state%cx_ready = 2

      state%op4%points => state%r
      state%op4%r => state%r
      state%op4%n => state%n
      state%op4%k1 => state%k1
      state%op4%k2 => state%k2
      state%op4%a => state%a
      state%cx_v = v
      state%cx_vn = vn
      tmp1 = state%a*state%cx_vn
      call state%solver%solve_complex(state%op4, .false., tmp1, state%cx_s11, error)
      if (allocated(error)) return
      call state%solver%solve_complex(state%op4, .true., state%cx_v, state%cx_s13, error)
      if (allocated(error)) return
      state%cx_s14 = state%cx_s12*state%cx_s13
      do i = 1, npt
         tmp4 = state%k1(i) + state%k2(i)
         tmp5 = 1.0_wp/state%a(i)
         tmp6 = 12.566370614359172_wp*tmp5
         tmp7 = sqrt(tmp6)
         tmp8 = tmp4*tmp7
         tmp9 = (-0.26735_wp)*tmp8
         tmp3(i) = tmp9
      end do
      tmp10 = tmp3*state%cx_s11
      tmp2 = tmp10
      block
         real(wp) :: tmp12, tmp13, tmp14, tmp15, tmp16, tmp17, tmp19, tmp22, tmp26, tmp20, tmp21, &
                     tmp23, tmp24, tmp25, tmp27, tmp28, tmp29, tmp30, tmp31, tmp32, tmp33, tmp34, &
                     tmp35, tmp36, tmp37
         complex(wp) :: tmp18, tmp11, tmp38

         !$omp parallel &
         !$omp& private(i, j) &
         !$omp& shared(npt, state, tmp2) &
         !$omp& default(private)
         !$omp do schedule(static)
         do j = 1, npt
            tmp12 = state%s4(j)
            tmp13 = state%s5(j)
            tmp14 = state%s6(j)
            tmp15 = state%s7(j)
            tmp16 = state%s8(j)
            tmp17 = state%s9(j)
            tmp18 = state%cx_s11(j)
            tmp19 = -tmp13
            tmp22 = -tmp14
            tmp26 = -tmp16
            tmp11 = 0.0_wp
            !$omp simd &
            !$omp& private(tmp20, tmp21, tmp23, tmp24, tmp25, tmp27, tmp28, tmp29) &
            !$omp& private(tmp30, tmp31, tmp32, tmp33, tmp34, tmp35, tmp36, tmp37) &
            !$omp& private(tmp38) &
            !$omp& reduction(+: tmp11)
            do i = 1, j - 1
               tmp20 = state%s5(i) + tmp19
               tmp21 = tmp12*tmp20
               tmp23 = state%s6(i) + tmp22
               tmp24 = tmp23*tmp15
               tmp25 = tmp21 + tmp24
               tmp27 = state%s8(i) + tmp26
               tmp28 = tmp27*tmp17
               tmp29 = tmp25 + tmp28
               tmp30 = tmp20**(2)
               tmp31 = tmp23**(2)
               tmp32 = tmp30 + tmp31
               tmp33 = tmp27**(2)
               tmp34 = tmp32 + tmp33
               tmp35 = 1.0_wp/sqrt(tmp34)
               tmp36 = tmp35**(3)
               tmp37 = tmp29*tmp36
               tmp38 = tmp37*state%cx_s11(i)
               tmp11 = tmp11 + tmp38
            end do
            !$omp simd &
            !$omp& private(tmp20, tmp21, tmp23, tmp24, tmp25, tmp27, tmp28, tmp29) &
            !$omp& private(tmp30, tmp31, tmp32, tmp33, tmp34, tmp35, tmp36, tmp37) &
            !$omp& private(tmp38) &
            !$omp& reduction(+: tmp11)
            do i = j + 1, npt
               tmp20 = state%s5(i) + tmp19
               tmp21 = tmp12*tmp20
               tmp23 = state%s6(i) + tmp22
               tmp24 = tmp23*tmp15
               tmp25 = tmp21 + tmp24
               tmp27 = state%s8(i) + tmp26
               tmp28 = tmp27*tmp17
               tmp29 = tmp25 + tmp28
               tmp30 = tmp20**(2)
               tmp31 = tmp23**(2)
               tmp32 = tmp30 + tmp31
               tmp33 = tmp27**(2)
               tmp34 = tmp32 + tmp33
               tmp35 = 1.0_wp/sqrt(tmp34)
               tmp36 = tmp35**(3)
               tmp37 = tmp29*tmp36
               tmp38 = tmp37*state%cx_s11(i)
               tmp11 = tmp11 + tmp38
            end do
            tmp2(j) = tmp2(j) + tmp11
         end do
         !$omp end do
         !$omp end parallel
      end block
      state%cx_s15 = tmp2
      q = state%cx_s2*state%cx_s11
      tmp39 = sum(state%cx_v*q)
      energy = 0.5_wp*tmp39
      grad_v = state%cx_s12*state%cx_s11
      grad_vn = state%cx_s14*state%a
      if (state%solver%inexact()) then
         ! First-order correction for the residuals of the solves
         tmp40 = 6.283185307179586_wp*state%cx_s11
         tmp41 = state%a*state%cx_s15
         tmp42 = state%cx_s3*tmp41
         tmp43 = tmp40 + tmp42
         tmp44 = -tmp43
         tmp45 = tmp1 + tmp44
         tmp46 = sum(state%cx_s14*tmp45)
         energy = energy + tmp46
      end if

      state%cx_ready = 3
   end subroutine dpcm_point_complex_mf_solve

end submodule pcmgen_point_dpcm_complex_mf_energy
