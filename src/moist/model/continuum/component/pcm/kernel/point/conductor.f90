      !> Hessian times direction, v block
      real(wp), contiguous, intent(out) :: hvp_v(:)
      !> Error handling
      type(error_type), allocatable, intent(out) :: error

      integer :: npt
      integer :: stat
      real(wp), allocatable :: tmp1(:)

      stat = 0
      npt = state%npt
      if (any(shape(dv) /= [npt])) then
         call fatal_error(error, "[conductor_point_response_one] dv: wrong shape")
         return
      end if
      if (any(shape(hvp_v) /= [npt])) then
         call fatal_error(error, "[conductor_point_response_one] hvp_v: wrong shape")
         return
      end if
      allocate (tmp1(npt), stat=stat)
      if (stat /= 0) then
         call fatal_error(error, "[conductor_point_response_one] allocation failed")
         return
      end if

      state%op1%points => state%r
      state%op1%c1 => state%s5
      tmp1 = 0.0_wp
      call state%solver%solve(state%op1, .false., dv, tmp1, error)
      if (allocated(error)) return
      hvp_v = state%s1*tmp1
   end subroutine conductor_point_response_one

   !> Conductor-like PCM (point charges): combine and factor the operators for the solvent
   !>
   !> - Repeat with new solvent inputs as often as needed; the cavity operators are reused
   !> - Needs conductor_point_assemble on the same state first
   !> - Complex variant: holomorphic arithmetic, transposes and never conjugates
   !> - Vectors have length npt, matrices are (npt, npt), point fields (3, npt)
   !> - Outputs are undefined if error is allocated
   !>
   !> @param[in,out] state  state of conductor_point
   !> @param[in] feps  dielectric factor of a conductor-like model, e.g. (eps - 1)/eps
   !> @param[out] error  error handling; allocated on failure
   subroutine conductor_point_complex_medium(state, feps, error)
      !> State of conductor_point
      type(conductor_point_complex_state), target, intent(inout) :: state
      !> Dielectric factor of a conductor-like model, e.g. (eps - 1)/eps
      complex(wp), intent(in) :: feps
      !> Error handling
      type(error_type), allocatable, intent(out) :: error

      integer :: npt
      integer :: stat

      if (state%matrix_free) then
         call conductor_point_complex_mf_medium(state, feps, error)
         return
      end if
      stat = 0
      npt = state%npt
      if (state%ready < 1) then
         call fatal_error(error, &
                          "[conductor_point_complex_medium] call conductor_point_assemble first")
         return
      end if
      state%cx_ready = 0
      if (allocated(state%cx_v)) deallocate (state%cx_v)
      if (allocated(state%cx_s6)) deallocate (state%cx_s6)
      if (allocated(state%cx_s8)) deallocate (state%cx_s8)
      if (allocated(state%cx_s9)) deallocate (state%cx_s9)
      if (allocated(state%cx_s10)) deallocate (state%cx_s10)
      if (allocated(state%cx_s2)) deallocate (state%cx_s2)
      if (allocated(state%cx_s3)) deallocate (state%cx_s3)
      if (allocated(state%cx_s4)) deallocate (state%cx_s4)
      if (stat == 0) allocate (state%cx_v(npt), stat=stat)
      if (stat == 0) allocate (state%cx_s6(npt), stat=stat)
      if (stat == 0) allocate (state%cx_s8(npt), stat=stat)
      if (stat == 0) allocate (state%cx_s9(npt), stat=stat)
      if (stat == 0) allocate (state%cx_s10(npt), stat=stat)
      if (stat /= 0) then
         call fatal_error(error, "[conductor_point_complex_medium] allocation failed")
         return
      end if
      state%cx_s6 = 0.0_wp
      state%cx_ready = 1
      state%cx_assembled = state%assembled

      state%op1%points => state%r
      state%op1%c1 => state%s5
      state%cx_feps = feps
      state%cx_s1 = -state%cx_feps

      state%cx_ready = 2
   end subroutine conductor_point_complex_medium

   !> Conductor-like PCM (point charges): energy, solution and gradient for v
   !>
   !> - Repeat with new inputs as often as needed; the operators are reused
   !> - Needs conductor_point_complex_medium on the same state first
   !> - Complex variant: holomorphic arithmetic, transposes and never conjugates
   !> - Vectors have length npt, matrices are (npt, npt), point fields (3, npt)
   !> - Outputs are undefined if error is allocated
   !>
   !> @param[in,out] state  state of conductor_point
   !> @param[in] v  solute electrostatic potential at the surface points
   !> @param[out] energy  solvation energy
   !> @param[out] q  apparent surface charges
   !> @param[out] grad_v  partial derivative of the energy with respect to v
   !> @param[out] error  error handling; allocated on failure
   subroutine conductor_point_complex_solve(state, v, energy, q, grad_v, error)
      !> State of conductor_point
      type(conductor_point_complex_state), target, intent(inout) :: state
      !> Solute electrostatic potential at the surface points
      complex(wp), contiguous, intent(in) :: v(:)
      !> Solvation energy
      complex(wp), intent(out) :: energy
      !> Apparent surface charges
      complex(wp), contiguous, intent(out) :: q(:)
      !> Partial derivative of the energy with respect to v
      complex(wp), contiguous, intent(out) :: grad_v(:)
      !> Error handling
      type(error_type), allocatable, intent(out) :: error

      integer :: npt
      integer :: stat
      real(wp), allocatable :: tmp5(:), tmp6(:)
      complex(wp), allocatable :: tmp3(:), tmp4(:), tmp7(:), tmp8(:)
      complex(wp) :: tmp1, tmp2, tmp9

      if (state%matrix_free) then
         call conductor_point_complex_mf_solve(state, v, energy, q, grad_v, error)
         return
      end if
      stat = 0
      npt = state%npt
      if (state%cx_ready < 2 .or. state%cx_assembled /= state%assembled) then
         call fatal_error(error, &
                          "[conductor_point_complex_solve] call conductor_point_complex_medium first")
         return
      end if
      if (any(shape(v) /= [npt])) then
         call fatal_error(error, "[conductor_point_complex_solve] v: wrong shape")
         return
      end if
      if (any(shape(q) /= [npt])) then
         call fatal_error(error, "[conductor_point_complex_solve] q: wrong shape")
         return
      end if
      if (any(shape(grad_v) /= [npt])) then
         call fatal_error(error, "[conductor_point_complex_solve] grad_v: wrong shape")
         return
      end if
      allocate (tmp3(npt), stat=stat)
      if (stat == 0) allocate (tmp4(npt), stat=stat)
      if (stat == 0) allocate (tmp5(npt), stat=stat)
      if (stat == 0) allocate (tmp6(npt), stat=stat)
      if (stat == 0) allocate (tmp7(npt), stat=stat)
      if (stat == 0) allocate (tmp8(npt), stat=stat)
      if (stat /= 0) then
         call fatal_error(error, "[conductor_point_complex_solve] allocation failed")
         return
      end if
      state%cx_ready = 2

      state%op1%points => state%r
      state%op1%c1 => state%s5
      state%cx_v = v
      call state%solver%solve_complex(state%op1, .false., state%cx_v, state%cx_s6, error)
      if (allocated(error)) return
      q = state%cx_s1*state%cx_s6
      tmp1 = sum(state%cx_v*q)
      energy = 0.5_wp*tmp1
      grad_v = q
      if (state%solver%inexact()) then
         ! First-order correction for the residuals of the solves
         tmp2 = (-0.5_wp)*state%cx_feps
         tmp3 = tmp2*state%cx_s6
         call gemv(state%s5, real(state%cx_s6, wp), tmp5)
         call gemv(state%s5, aimag(state%cx_s6), tmp6)
         tmp4 = cmplx(tmp5, tmp6, wp)
         tmp7 = -tmp4
         tmp8 = state%cx_v + tmp7
         tmp9 = sum(tmp3*tmp8)
         energy = energy + tmp9
      end if

      state%cx_ready = 3
   end subroutine conductor_point_complex_solve

   !> Conductor-like PCM (point charges): energy gradient with respect to the other inputs
   !>
   !> - For the inputs of the last solve
   !> - Needs conductor_point_complex_solve on the same state first
   !> - Complex variant: holomorphic arithmetic, transposes and never conjugates
   !> - Vectors have length npt, matrices are (npt, npt), point fields (3, npt)
   !> - Outputs are undefined if error is allocated
   !>
   !> @param[in,out] state  state of conductor_point
   !> @param[out] grad_r  partial derivative of the energy with respect to r
   !> @param[out] grad_a  partial derivative of the energy with respect to a
   !> @param[out] grad_feps  partial derivative of the energy with respect to feps
   !> @param[out] error  error handling; allocated on failure
   subroutine conductor_point_complex_weights(state, grad_r, grad_a, grad_feps, error)
      !> State of conductor_point
      type(conductor_point_complex_state), target, intent(inout) :: state
      !> Partial derivative of the energy with respect to r
      complex(wp), contiguous, intent(out) :: grad_r(:, :)
      !> Partial derivative of the energy with respect to a
      complex(wp), contiguous, intent(out) :: grad_a(:)
      !> Partial derivative of the energy with respect to feps
      complex(wp), intent(out) :: grad_feps
      !> Error handling
      type(error_type), allocatable, intent(out) :: error

      integer :: npt
      integer :: stat
      real(wp) :: tmp1, tmp2, tmp3, tmp4, tmp5, tmp6
      complex(wp), allocatable :: tmp7(:), tmp8(:), tmp9(:), tmp43(:)
      complex(wp) :: tmp44
      integer :: i, j

      if (state%matrix_free) then
         call conductor_point_complex_mf_weights(state, grad_r, grad_a, grad_feps, error)
         return
      end if
      stat = 0
      npt = state%npt
      if (state%cx_ready < 3 .or. state%cx_assembled /= state%assembled) then
         call fatal_error(error, &
                          "[conductor_point_complex_weights] call conductor_point_complex_solve first")
         return
      end if
      if (any(shape(grad_r) /= [3, npt])) then
         call fatal_error(error, "[conductor_point_complex_weights] grad_r: wrong shape")
         return
      end if
      if (any(shape(grad_a) /= [npt])) then
         call fatal_error(error, "[conductor_point_complex_weights] grad_a: wrong shape")
         return
      end if
      allocate (tmp7(npt), stat=stat)
      if (stat == 0) allocate (tmp8(npt), stat=stat)
      if (stat == 0) allocate (tmp9(npt), stat=stat)
      if (stat == 0) allocate (tmp43(npt), stat=stat)
      if (stat /= 0) then
         call fatal_error(error, "[conductor_point_complex_weights] allocation failed")
         return
      end if
      state%cx_ready = 3

      state%op1%points => state%r
      state%op1%c1 => state%s5
      state%cx_s7 = 0.5_wp*state%cx_feps
      state%cx_s8 = state%cx_s7*state%cx_s6
      state%cx_s9 = state%cx_s8*state%cx_s6
      do i = 1, npt
         tmp1 = 1.0_wp/state%a(i)
         tmp2 = 12.566370614359172_wp*tmp1
         tmp3 = 1.0_wp/sqrt(tmp2)
         tmp4 = state%a(i)**(-2)
         tmp5 = tmp3*tmp4
         tmp6 = (-6.719238367497849_wp)*tmp5
         state%cx_s10(i) = tmp6
      end do
      tmp7 = 0.0_wp
      tmp8 = 0.0_wp
      tmp9 = 0.0_wp
      !$omp parallel default(none) &
      !$omp& private(i, j) &
      !$omp& shared(npt, state) &
      !$omp& reduction(+: tmp7, tmp8, tmp9)
      block
         real(wp) :: tmp14, tmp15, tmp16, tmp18, tmp21, tmp25
         complex(wp) :: tmp13, tmp17, tmp10, tmp11, tmp12

         !$omp do schedule(static)
         do j = 1, npt
            tmp13 = state%cx_s8(j)
            tmp14 = state%s2(j)
            tmp15 = state%s3(j)
            tmp16 = state%s4(j)
            tmp17 = state%cx_s6(j)
            tmp18 = -tmp14
            tmp21 = -tmp15
            tmp25 = -tmp16
            tmp10 = 0.0_wp
            tmp11 = 0.0_wp
            tmp12 = 0.0_wp
            !$omp simd &
            !$omp& reduction(+: tmp10, tmp11, tmp12)
            do i = 1, j - 1
               block
                  real(wp) :: tmp19, tmp20, tmp22, tmp23, tmp24, tmp26, tmp27, tmp28, tmp29, tmp30
                  complex(wp) :: tmp31, tmp32, tmp33, tmp34, tmp35, tmp36, tmp37, tmp38, tmp39, &
                                 tmp40, tmp41, tmp42

                  tmp19 = state%s2(i) + tmp18
                  tmp20 = tmp19**(2)
                  tmp22 = state%s3(i) + tmp21
                  tmp23 = tmp22**(2)
                  tmp24 = tmp20 + tmp23
                  tmp26 = state%s4(i) + tmp25
                  tmp27 = tmp26**(2)
                  tmp28 = tmp24 + tmp27
                  tmp29 = 1.0_wp/sqrt(tmp28)
                  tmp30 = tmp29**(3)
                  tmp31 = state%cx_s8(i)*tmp30
                  tmp32 = tmp31*tmp19
                  tmp33 = tmp32*tmp17
                  tmp34 = -tmp33
                  tmp7(i) = tmp7(i) + tmp34
                  tmp10 = tmp10 + tmp33
                  tmp35 = state%cx_s8(i)*tmp22
                  tmp36 = tmp35*tmp30
                  tmp37 = tmp36*tmp17
                  tmp38 = -tmp37
                  tmp8(i) = tmp8(i) + tmp38
                  tmp11 = tmp11 + tmp37
                  tmp39 = state%cx_s8(i)*tmp26
                  tmp40 = tmp39*tmp30
                  tmp41 = tmp40*tmp17
                  tmp42 = -tmp41
                  tmp9(i) = tmp9(i) + tmp42
                  tmp12 = tmp12 + tmp41
               end block
            end do
            !$omp simd &
            !$omp& reduction(+: tmp10, tmp11, tmp12)
            do i = j + 1, npt
               block
                  real(wp) :: tmp19, tmp20, tmp22, tmp23, tmp24, tmp26, tmp27, tmp28, tmp29, tmp30
                  complex(wp) :: tmp31, tmp32, tmp33, tmp34, tmp35, tmp36, tmp37, tmp38, tmp39, &
                                 tmp40, tmp41, tmp42

                  tmp19 = state%s2(i) + tmp18
                  tmp20 = tmp19**(2)
                  tmp22 = state%s3(i) + tmp21
                  tmp23 = tmp22**(2)
                  tmp24 = tmp20 + tmp23
                  tmp26 = state%s4(i) + tmp25
                  tmp27 = tmp26**(2)
                  tmp28 = tmp24 + tmp27
                  tmp29 = 1.0_wp/sqrt(tmp28)
                  tmp30 = tmp29**(3)
                  tmp31 = state%cx_s8(i)*tmp30
                  tmp32 = tmp31*tmp19
                  tmp33 = tmp32*tmp17
                  tmp34 = -tmp33
                  tmp7(i) = tmp7(i) + tmp34
                  tmp10 = tmp10 + tmp33
                  tmp35 = state%cx_s8(i)*tmp22
                  tmp36 = tmp35*tmp30
                  tmp37 = tmp36*tmp17
                  tmp38 = -tmp37
                  tmp8(i) = tmp8(i) + tmp38
                  tmp11 = tmp11 + tmp37
                  tmp39 = state%cx_s8(i)*tmp26
                  tmp40 = tmp39*tmp30
                  tmp41 = tmp40*tmp17
                  tmp42 = -tmp41
                  tmp9(i) = tmp9(i) + tmp42
                  tmp12 = tmp12 + tmp41
               end block
            end do
            tmp7(j) = tmp7(j) + tmp10
            tmp8(j) = tmp8(j) + tmp11
            tmp9(j) = tmp9(j) + tmp12
         end do
         !$omp end do
      end block
      !$omp end parallel
      grad_r(1, :) = tmp7
      grad_r(2, :) = tmp8
      grad_r(3, :) = tmp9
      grad_a = state%cx_s9*state%cx_s10
      tmp43 = 0.5_wp*state%cx_v
      tmp44 = sum(tmp43*state%cx_s6)
      grad_feps = -tmp44

      state%cx_ready = 4
   end subroutine conductor_point_complex_weights

