            tmp8(j) = tmp8(j) + tmp11
            tmp9(j) = tmp9(j) + tmp12
         end do
         !$omp end do
      end block
      !$omp end parallel
      grad_r(1, :) = tmp7
      grad_r(2, :) = tmp8
      grad_r(3, :) = tmp9
      grad_a = state%s9*state%s10
      tmp43 = 0.5_wp*state%v
      tmp44 = dot(tmp43, state%s6)
      grad_feps = -tmp44

      state%ready = 4
   end subroutine conductor_point_mf_weights

