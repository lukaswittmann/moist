   !> @param[out] hvp_v  hessian times direction, v block
   !> @param[out] error  error handling; allocated on failure
   subroutine conductor_point_complex_mf_response(state, dv, hvp_v, error)
      !> State of conductor_point
      type(conductor_point_complex_state), intent(inout) :: state
      !> Direction for v
      complex(wp), contiguous, intent(in) :: dv(:, :)
      !> Hessian times direction, v block
      complex(wp), contiguous, intent(out) :: hvp_v(:, :)
      !> Error handling
      type(error_type), allocatable, intent(out) :: error

      integer :: npt, nblk, blk

      if (state%cx_ready < 3 .or. state%cx_assembled /= state%assembled) then
         call fatal_error(error, &
                          "[conductor_point_complex_mf_response] call conductor_point_complex_solve first")
         return
      end if
      npt = state%npt
      nblk = size(dv, 2)
      if (any(shape(dv) /= [npt, nblk])) then
         call fatal_error(error, "[conductor_point_complex_mf_response] dv: wrong shape")
         return
      end if
      if (any(shape(hvp_v) /= [npt, nblk])) then
         call fatal_error(error, "[conductor_point_complex_mf_response] hvp_v: wrong shape")
         return
      end if
      do blk = 1, nblk
         call conductor_point_complex_mf_response_one(state, dv(:, blk), hvp_v(:, blk), error)
