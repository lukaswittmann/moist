                  tmp33 = tmp32*tmp17
                  tmp34 = -tmp33
                  tmp7(i) = tmp7(i) + tmp34
                  tmp10 = tmp10 + tmp33
                  tmp35 = state%s8(i)*tmp22
                  tmp36 = tmp35*tmp30
                  tmp37 = tmp36*tmp17
                  tmp38 = -tmp37
                  tmp8(i) = tmp8(i) + tmp38
                  tmp11 = tmp11 + tmp37
                  tmp39 = state%s8(i)*tmp26
                  tmp40 = tmp39*tmp30
                  tmp41 = tmp40*tmp17
                  tmp42 = -tmp41
                  tmp9(i) = tmp9(i) + tmp42
                  tmp12 = tmp12 + tmp41
               end block
            end do
            !$omp simd &
            !$omp& reduction(+: tmp10, tmp11, tmp12)
            do i = j + 1, npt
               block
                  real(wp) :: tmp19, tmp20, tmp22, tmp23, tmp24, tmp26, tmp27, tmp28, tmp29, &
                              tmp30, tmp31, tmp32, tmp33, tmp34, tmp35, tmp36, tmp37, tmp38, &
                              tmp39, tmp40, tmp41, tmp42

                  tmp19 = state%s2(i) + tmp18
                  tmp20 = tmp19**(2)
                  tmp22 = state%s3(i) + tmp21
                  tmp23 = tmp22**(2)
                  tmp24 = tmp20 + tmp23
                  tmp26 = state%s4(i) + tmp25
