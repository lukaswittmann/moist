      end if
      if (any(shape(v) /= [npt])) then
         call fatal_error(error, "[conductor_point_mf_solve] v: wrong shape")
         return
      end if
      if (any(shape(q) /= [npt])) then
         call fatal_error(error, "[conductor_point_mf_solve] q: wrong shape")
         return
      end if
      if (any(shape(grad_v) /= [npt])) then
         call fatal_error(error, "[conductor_point_mf_solve] grad_v: wrong shape")
         return
      end if
      allocate (tmp3(npt), stat=stat)
      if (stat == 0) allocate (tmp4(npt), stat=stat)
      if (stat == 0) allocate (tmp5(npt), stat=stat)
      if (stat == 0) allocate (tmp10(npt), stat=stat)
      if (stat == 0) allocate (tmp28(npt), stat=stat)
      if (stat == 0) allocate (tmp29(npt), stat=stat)
      if (stat /= 0) then
         call fatal_error(error, "[conductor_point_mf_solve] allocation failed")
         return
      end if
      state%ready = 2

      state%op2%points => state%r
      state%op2%r => state%r
      state%op2%a => state%a
      state%v = v
      call state%solver%solve(state%op2, .false., state%v, state%s6, error)
      if (allocated(error)) return
      q = state%s1*state%s6
      tmp1 = dot(state%v, q)
      energy = 0.5_wp*tmp1
      grad_v = q
      if (state%solver%inexact()) then
         ! First-order correction for the residuals of the solves
         tmp2 = (-0.5_wp)*state%feps
         tmp3 = tmp2*state%s6
         do i = 1, npt
            tmp6 = 1.0_wp/state%a(i)
            tmp7 = 12.566370614359172_wp*tmp6
            tmp8 = sqrt(tmp7)
            tmp9 = 1.0694_wp*tmp8
            tmp5(i) = tmp9
         end do
         tmp10 = tmp5*state%s6
         tmp4 = tmp10
         !$omp parallel default(none) &
         !$omp& private(i, j) &
         !$omp& shared(npt, state) &
         !$omp& reduction(+: tmp4)
         block
            real(wp) :: tmp11, tmp12, tmp13, tmp14, tmp15, tmp18, tmp22

            !$omp do schedule(static)
            do j = 1, npt
               tmp11 = state%r(1, j)
               tmp12 = state%r(2, j)
               tmp13 = state%r(3, j)
               tmp14 = state%s6(j)
               tmp15 = -tmp11
               tmp18 = -tmp12
               tmp22 = -tmp13
               !$omp simd
               do i = 1, j - 1
                  block
                     real(wp) :: tmp16, tmp17, tmp19, tmp20, tmp21, tmp23, tmp24, tmp25, tmp26, &
                                 tmp27

                     tmp16 = state%r(1, i) + tmp15
                     tmp17 = tmp16**(2)
                     tmp19 = state%r(2, i) + tmp18
                     tmp20 = tmp19**(2)
                     tmp21 = tmp17 + tmp20
                     tmp23 = state%r(3, i) + tmp22
                     tmp24 = tmp23**(2)
                     tmp25 = tmp21 + tmp24
                     tmp26 = 1.0_wp/sqrt(tmp25)
                     tmp27 = tmp26*tmp14
                     tmp4(i) = tmp4(i) + tmp27
                  end block
               end do
               !$omp simd
               do i = j + 1, npt
                  block
                     real(wp) :: tmp16, tmp17, tmp19, tmp20, tmp21, tmp23, tmp24, tmp25, tmp26, &
                                 tmp27

                     tmp16 = state%r(1, i) + tmp15
                     tmp17 = tmp16**(2)
                     tmp19 = state%r(2, i) + tmp18
                     tmp20 = tmp19**(2)
                     tmp21 = tmp17 + tmp20
                     tmp23 = state%r(3, i) + tmp22
                     tmp24 = tmp23**(2)
                     tmp25 = tmp21 + tmp24
                     tmp26 = 1.0_wp/sqrt(tmp25)
                     tmp27 = tmp26*tmp14
                     tmp4(i) = tmp4(i) + tmp27
                  end block
               end do
            end do
            !$omp end do
         end block
         !$omp end parallel
         tmp28 = -tmp4
         tmp29 = state%v + tmp28
         tmp30 = dot(tmp3, tmp29)
         energy = energy + tmp30
      end if

      state%ready = 3
   end subroutine conductor_point_mf_solve

   !> Conductor-like PCM (point charges): energy gradient with respect to the other inputs
