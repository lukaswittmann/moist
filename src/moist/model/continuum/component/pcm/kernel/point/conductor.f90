   !> Conductor-like PCM (point charges): energy, solution and gradient for v
   !>
   !> - Repeat with new inputs as often as needed; the operators are reused
   !> - Needs conductor_point_complex_medium on the same state first
   !> - Complex variant: holomorphic arithmetic, transposes and never conjugates
   !> - Vectors have length npt, matrices are (npt, npt), point fields (3, npt)
   !> - Outputs are undefined if error is allocated
   !>
   !> @param[in,out] state  state of conductor_point
   !> @param[in] v  solute electrostatic potential at the surface points
   !> @param[out] energy  solvation energy
   !> @param[out] q  apparent surface charges
   !> @param[out] grad_v  partial derivative of the energy with respect to v
   !> @param[out] error  error handling; allocated on failure
   subroutine conductor_point_complex_mf_solve(state, v, energy, q, grad_v, error)
      !> State of conductor_point
      type(conductor_point_complex_state), target, intent(inout) :: state
      !> Solute electrostatic potential at the surface points
      complex(wp), contiguous, intent(in) :: v(:)
      !> Solvation energy
      complex(wp), intent(out) :: energy
      !> Apparent surface charges
      complex(wp), contiguous, intent(out) :: q(:)
      !> Partial derivative of the energy with respect to v
      complex(wp), contiguous, intent(out) :: grad_v(:)
      !> Error handling
      type(error_type), allocatable, intent(out) :: error

      integer :: npt
      integer :: stat
      real(wp), allocatable :: tmp5(:)
      real(wp) :: tmp6, tmp7, tmp8, tmp9
      complex(wp), allocatable :: tmp3(:), tmp4(:), tmp10(:), tmp28(:), tmp29(:)
      complex(wp) :: tmp1, tmp2, tmp30
      integer :: i, j

      stat = 0
      npt = state%npt
      if (state%cx_ready < 2 .or. state%cx_assembled /= state%assembled) then
         call fatal_error(error, &
                          "[conductor_point_complex_mf_solve] call conductor_point_complex_medium first")
         return
      end if
      if (any(shape(v) /= [npt])) then
         call fatal_error(error, "[conductor_point_complex_mf_solve] v: wrong shape")
         return
      end if
      if (any(shape(q) /= [npt])) then
         call fatal_error(error, "[conductor_point_complex_mf_solve] q: wrong shape")
         return
      end if
      if (any(shape(grad_v) /= [npt])) then
         call fatal_error(error, "[conductor_point_complex_mf_solve] grad_v: wrong shape")
         return
      end if
      allocate (tmp3(npt), stat=stat)
      if (stat == 0) allocate (tmp4(npt), stat=stat)
      if (stat == 0) allocate (tmp5(npt), stat=stat)
      if (stat == 0) allocate (tmp10(npt), stat=stat)
      if (stat == 0) allocate (tmp28(npt), stat=stat)
      if (stat == 0) allocate (tmp29(npt), stat=stat)
      if (stat /= 0) then
         call fatal_error(error, "[conductor_point_complex_mf_solve] allocation failed")
         return
      end if
      state%cx_ready = 2

      state%op2%points => state%r
      state%op2%r => state%r
      state%op2%a => state%a
      state%cx_v = v
      call state%solver%solve_complex(state%op2, .false., state%cx_v, state%cx_s6, error)
      if (allocated(error)) return
      q = state%cx_s1*state%cx_s6
      tmp1 = sum(state%cx_v*q)
      energy = 0.5_wp*tmp1
      grad_v = q
      if (state%solver%inexact()) then
         ! First-order correction for the residuals of the solves
         tmp2 = (-0.5_wp)*state%cx_feps
         tmp3 = tmp2*state%cx_s6
         do i = 1, npt
            tmp6 = 1.0_wp/state%a(i)
            tmp7 = 12.566370614359172_wp*tmp6
            tmp8 = sqrt(tmp7)
            tmp9 = 1.0694_wp*tmp8
            tmp5(i) = tmp9
