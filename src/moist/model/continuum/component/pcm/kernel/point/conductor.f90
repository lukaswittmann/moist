         !$omp parallel default(none) &
         !$omp& private(i, j) &
         !$omp& shared(npt, state) &
         !$omp& reduction(+: tmp4)
         block
            real(wp) :: tmp11, tmp12, tmp13, tmp15, tmp18, tmp22
            complex(wp) :: tmp14

            !$omp do schedule(static)
            do j = 1, npt
               tmp11 = state%r(1, j)
               tmp12 = state%r(2, j)
               tmp13 = state%r(3, j)
               tmp14 = state%cx_s6(j)
               tmp15 = -tmp11
               tmp18 = -tmp12
               tmp22 = -tmp13
               !$omp simd
               do i = 1, j - 1
                  block
                     real(wp) :: tmp16, tmp17, tmp19, tmp20, tmp21, tmp23, tmp24, tmp25, tmp26
                     complex(wp) :: tmp27

                     tmp16 = state%r(1, i) + tmp15
                     tmp17 = tmp16**(2)
                     tmp19 = state%r(2, i) + tmp18
                     tmp20 = tmp19**(2)
                     tmp21 = tmp17 + tmp20
                     tmp23 = state%r(3, i) + tmp22
                     tmp24 = tmp23**(2)
                     tmp25 = tmp21 + tmp24
                     tmp26 = 1.0_wp/sqrt(tmp25)
                     tmp27 = tmp26*tmp14
                     tmp4(i) = tmp4(i) + tmp27
                  end block
               end do
               !$omp simd
               do i = j + 1, npt
                  block
                     real(wp) :: tmp16, tmp17, tmp19, tmp20, tmp21, tmp23, tmp24, tmp25, tmp26
                     complex(wp) :: tmp27

                     tmp16 = state%r(1, i) + tmp15
                     tmp17 = tmp16**(2)
                     tmp19 = state%r(2, i) + tmp18
                     tmp20 = tmp19**(2)
                     tmp21 = tmp17 + tmp20
                     tmp23 = state%r(3, i) + tmp22
                     tmp24 = tmp23**(2)
                     tmp25 = tmp21 + tmp24
                     tmp26 = 1.0_wp/sqrt(tmp25)
                     tmp27 = tmp26*tmp14
                     tmp4(i) = tmp4(i) + tmp27
                  end block
               end do
            end do
            !$omp end do
         end block
         !$omp end parallel
         tmp28 = -tmp4
         tmp29 = state%cx_v + tmp28
         tmp30 = sum(tmp3*tmp29)
