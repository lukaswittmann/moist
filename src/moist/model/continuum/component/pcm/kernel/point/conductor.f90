   !> @param[out] error  error handling; allocated on failure
   subroutine conductor_point_solve(state, v, energy, q, grad_v, error)
      !> State of conductor_point
      type(conductor_point_state), target, intent(inout) :: state
      !> Solute electrostatic potential at the surface points
      real(wp), contiguous, intent(in) :: v(:)
      !> Solvation energy
      real(wp), intent(out) :: energy
      !> Apparent surface charges
      real(wp), contiguous, intent(out) :: q(:)
      !> Partial derivative of the energy with respect to v
      real(wp), contiguous, intent(out) :: grad_v(:)
      !> Error handling
      type(error_type), allocatable, intent(out) :: error

      integer :: npt
      integer :: stat
      real(wp), allocatable :: tmp3(:), tmp4(:), tmp5(:), tmp6(:)
      real(wp) :: tmp1, tmp2, tmp7

      if (state%matrix_free) then
         call conductor_point_mf_solve(state, v, energy, q, grad_v, error)
         return
      end if
      stat = 0
      npt = state%npt
      if (state%ready < 2) then
         call fatal_error(error, "[conductor_point_solve] call conductor_point_medium first")
         return
      end if
      if (any(shape(v) /= [npt])) then
         call fatal_error(error, "[conductor_point_solve] v: wrong shape")
         return
      end if
      if (any(shape(q) /= [npt])) then
         call fatal_error(error, "[conductor_point_solve] q: wrong shape")
         return
      end if
      if (any(shape(grad_v) /= [npt])) then
         call fatal_error(error, "[conductor_point_solve] grad_v: wrong shape")
         return
      end if
      allocate (tmp3(npt), stat=stat)
      if (stat == 0) allocate (tmp4(npt), stat=stat)
      if (stat == 0) allocate (tmp5(npt), stat=stat)
      if (stat == 0) allocate (tmp6(npt), stat=stat)
      if (stat /= 0) then
         call fatal_error(error, "[conductor_point_solve] allocation failed")
         return
      end if
      state%ready = 2

      state%op1%points => state%r
      state%op1%c1 => state%s5
      state%v = v
      call state%solver%solve(state%op1, .false., state%v, state%s6, error)
      if (allocated(error)) return
      q = state%s1*state%s6
      tmp1 = dot(state%v, q)
      energy = 0.5_wp*tmp1
      grad_v = q
      if (state%solver%inexact()) then
         ! First-order correction for the residuals of the solves
         tmp2 = (-0.5_wp)*state%feps
         tmp3 = tmp2*state%s6
         call gemv(state%s5, state%s6, tmp4)
         tmp5 = -tmp4
         tmp6 = state%v + tmp5
         tmp7 = dot(tmp3, tmp6)
         energy = energy + tmp7
      end if

      state%ready = 3
   end subroutine conductor_point_solve

