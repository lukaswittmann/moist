      stat = 0
      npt = state%npt
      if (state%cx_ready < 3 .or. state%cx_assembled /= state%assembled) then
         call fatal_error(error, &
                          "[iefpcm_point_complex_param_weights] call iefpcm_point_complex_solve first")
         return
