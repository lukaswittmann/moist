                          "[nonlocal_pcm_point_mf_medium] call nonlocal_pcm_point_assemble first")
         return
      end if
      state%ready = 1
      ! Inputs that do not enter these outputs
      associate (unused1 => lam)
      end associate

      state%op4%points => state%r
      state%op4%r => state%r
      state%op4%a => state%a
      state%eps_solute = eps_solute
      state%eps_inf = eps_inf
      state%eps = eps
      state%op3%npt = 3*npt
      state%op3%npoint = npt
      state%op3%id = 3
      state%op3%points => state%r
