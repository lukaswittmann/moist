         state%s12(i, i) = tmp94
      end do
      state%op2%c5 => state%s12
      state%op2%c6 => state%s13
      call state%solver%setup(state%op2, error)
      if (allocated(error)) return
      state%s14 = -state%s3
      state%s20 = 0.5_wp*state%s2
      state%s24 = (-0.5_wp)*state%s3
      state%s27 = 0.07957747154594767_wp*state%s3
      state%s35 = (-0.07957747154594767_wp)*state%s2
      state%s39 = (-0.5_wp)*state%s2

      state%ready = 2
   end subroutine lpb_point_medium

   module subroutine lpb_point_solve(state, v, energy, q, grad_v, error)
      !> State of lpb_point
      type(lpb_point_state), target, intent(inout) :: state
      !> Solute electrostatic potential at the surface points
      real(wp), contiguous, intent(in) :: v(:)
      !> Solvation energy
      real(wp), intent(out) :: energy
      !> Apparent surface charges
      real(wp), contiguous, intent(out) :: q(:)
      !> Partial derivative of the energy with respect to v
      real(wp), contiguous, intent(out) :: grad_v(:)
      !> Error handling
      type(error_type), allocatable, intent(out) :: error

      integer :: npt
      integer :: stat
      real(wp), allocatable :: tmp1(:), tmp2(:), tmp3(:), tmp4(:), tmp5(:), tmp6(:), tmp7(:), &
                               tmp8(:), tmp9(:), tmp10(:), tmp12(:), tmp13(:), tmp14(:), tmp15(:), &
                               tmp16(:), tmp17(:), tmp18(:), tmp19(:), tmp20(:), tmp21(:), &
                               tmp22(:), tmp23(:), tmp24(:), tmp25(:), tmp26(:), tmp27(:), &
                               tmp29(:), tmp30(:), tmp31(:)
      real(wp) :: tmp11, tmp28, tmp32, tmp33

      if (state%matrix_free) then
         call lpb_point_mf_solve(state, v, energy, q, grad_v, error)
         return
      end if
      stat = 0
      npt = state%npt
      if (state%ready < 2) then
         call fatal_error(error, "[lpb_point_solve] call lpb_point_medium first")
         return
      end if
      if (any(shape(v) /= [npt])) then
         call fatal_error(error, "[lpb_point_solve] v: wrong shape")
         return
      end if
      if (any(shape(q) /= [npt])) then
         call fatal_error(error, "[lpb_point_solve] q: wrong shape")
         return
      end if
      if (any(shape(grad_v) /= [npt])) then
         call fatal_error(error, "[lpb_point_solve] grad_v: wrong shape")
         return
      end if
      allocate (tmp1(npt), stat=stat)
      if (stat == 0) allocate (tmp2(npt), stat=stat)
      if (stat == 0) allocate (tmp3(npt), stat=stat)
      if (stat == 0) allocate (tmp4(npt), stat=stat)
      if (stat == 0) allocate (tmp5(npt), stat=stat)
      if (stat == 0) allocate (tmp6(npt), stat=stat)
      if (stat == 0) allocate (tmp7(npt), stat=stat)
      if (stat == 0) allocate (tmp8(npt), stat=stat)
      if (stat == 0) allocate (tmp9(npt), stat=stat)
      if (stat == 0) allocate (tmp10(npt), stat=stat)
      if (stat == 0) allocate (tmp12(npt), stat=stat)
      if (stat == 0) allocate (tmp13(npt), stat=stat)
      if (stat == 0) allocate (tmp14(npt), stat=stat)
      if (stat == 0) allocate (tmp15(npt), stat=stat)
      if (stat == 0) allocate (tmp16(npt), stat=stat)
      if (stat == 0) allocate (tmp17(npt), stat=stat)
      if (stat == 0) allocate (tmp18(npt), stat=stat)
      if (stat == 0) allocate (tmp19(npt), stat=stat)
      if (stat == 0) allocate (tmp20(npt), stat=stat)
      if (stat == 0) allocate (tmp21(npt), stat=stat)
      if (stat == 0) allocate (tmp22(npt), stat=stat)
      if (stat == 0) allocate (tmp23(npt), stat=stat)
      if (stat == 0) allocate (tmp24(npt), stat=stat)
      if (stat == 0) allocate (tmp25(npt), stat=stat)
      if (stat == 0) allocate (tmp26(npt), stat=stat)
      if (stat == 0) allocate (tmp27(npt), stat=stat)
      if (stat == 0) allocate (tmp29(npt), stat=stat)
      if (stat == 0) allocate (tmp30(npt), stat=stat)
      if (stat == 0) allocate (tmp31(npt), stat=stat)
      if (stat /= 0) then
         call fatal_error(error, "[lpb_point_solve] allocation failed")
         return
      end if
      state%ready = 2

      state%op1%points => state%r
      state%op1%c1 => state%s7
      state%op2%points => state%r
      state%op2%a => state%a
      state%op2%c2 => state%s7
      state%op2%c3 => state%s11
      state%op2%c5 => state%s12
      state%op2%c6 => state%s13
      state%v = v
      state%s15 = state%a*state%v
      call gemv(state%s11, state%s15, tmp1)
      tmp2 = (-0.15915494309189535_wp)*tmp1
      state%s16 = state%v + tmp2
      call gemv(state%s13, state%s15, tmp3)
      tmp4 = (-0.15915494309189535_wp)*tmp3
      tmp5 = state%v + tmp4
      call state%solver%solve(state%op1, .false., tmp5, state%s17, error)
      if (allocated(error)) return
      call gemv(state%s12, state%s17, state%s18)
      tmp6 = state%s14*state%s16
      tmp7 = state%s2*state%s18
      tmp8 = tmp6 + tmp7
      call state%solver%solve(state%op2, .false., tmp8, state%s19, error)
      if (allocated(error)) return
      call state%solver%solve(state%op2, .true., state%v, state%s21, error)
      if (allocated(error)) return
      state%s22 = state%s20*state%s21
      call gemv(state%s12, state%s22, tmp9, trans="t")
      call state%solver%solve(state%op1, .false., tmp9, state%s23, error)
      if (allocated(error)) return
      state%s25 = state%s24*state%s21
      state%s26 = (-0.15915494309189535_wp)*state%s23
      state%s28 = state%s27*state%s21
      call gemv(state%s11, state%s28, state%s29, trans="t")
      call gemv(state%s13, state%s26, tmp10, trans="t")
      state%s30 = tmp10 + state%s29
      call gemv(state%s7, state%s19, state%s31)
      state%s32 = state%a*state%s31
      call gemv(state%s13, state%s19, state%s33, trans="t")
      state%s34 = state%a*state%s33
      state%s36 = state%s35*state%s21
      state%s40 = state%s39*state%s21
      state%s41 = state%s15 + state%s32
      tmp11 = dot(state%v, state%s19)
      energy = 0.5_wp*tmp11
      q = state%s19
      tmp12 = 0.5_wp*state%s19
      tmp13 = tmp12 + state%s23
      tmp14 = tmp13 + state%s25
      tmp15 = state%s30*state%a
      grad_v = tmp14 + tmp15
      if (state%solver%inexact()) then
         ! First-order correction for the residuals of the solves
         tmp16 = 0.5_wp*state%s21
         call gemv(state%s11, state%s32, tmp17)
         tmp18 = (-0.15915494309189535_wp)*tmp17
         tmp19 = state%s31 + tmp18
         tmp20 = state%s3*tmp19
         tmp21 = 0.15915494309189535_wp*state%s34
         tmp22 = state%s19 + tmp21
         call gemv(state%s12, tmp22, tmp23)
         tmp24 = state%s2*tmp23
         tmp25 = tmp20 + tmp24
         tmp26 = -tmp25
         tmp27 = tmp8 + tmp26
         tmp28 = dot(tmp16, tmp27)
         call gemv(state%s7, state%s17, tmp29)
         tmp30 = -tmp29
         tmp31 = tmp5 + tmp30
         tmp32 = dot(state%s23, tmp31)
         tmp33 = tmp28 + tmp32
         energy = energy + tmp33
      end if

      state%ready = 3
   end subroutine lpb_point_solve

end submodule pcmgen_point_lpb_energy
