!> DPCM (point charges) phases: mf/energy; generated by pcmgen, do not edit
!>
!> - Procedures of pcmgen_point_dpcm: dpcm_point_mf_assemble, dpcm_point_mf_medium,
!>   dpcm_point_mf_solve
submodule(pcmgen_point_dpcm) pcmgen_point_dpcm_mf_energy
   implicit none(type, external)

contains

   module subroutine dpcm_point_mf_assemble(state, r, n, k1, k2, a, error, solver)
      !> State of dpcm_point
      type(dpcm_point_state), target, intent(inout) :: state
      !> Positions of the surface points
      real(wp), contiguous, intent(in) :: r(:, :)
      !> Outward unit normals at the surface points
      real(wp), contiguous, intent(in) :: n(:, :)
      !> First principal curvature (positive where convex)
      real(wp), contiguous, intent(in) :: k1(:)
      !> Second principal curvature (positive where convex)
      real(wp), contiguous, intent(in) :: k2(:)
      !> Grid point areas
      real(wp), contiguous, intent(in) :: a(:)
      !> Error handling
      type(error_type), allocatable, intent(out) :: error
      !> Linear solver
      class(pcm_solver), intent(in), optional :: solver

      integer :: npt
      integer :: stat

      stat = 0
      npt = size(r, 2)
      if (npt < 1) then
         call fatal_error(error, "[dpcm_point_mf_assemble] empty discretization")
         return
      end if
      if (any(shape(r) /= [3, npt])) then
         call fatal_error(error, "[dpcm_point_mf_assemble] r: wrong shape")
         return
      end if
      if (any(shape(n) /= [3, npt])) then
         call fatal_error(error, "[dpcm_point_mf_assemble] n: wrong shape")
         return
      end if
      if (any(shape(k1) /= [npt])) then
         call fatal_error(error, "[dpcm_point_mf_assemble] k1: wrong shape")
         return
      end if
      if (any(shape(k2) /= [npt])) then
         call fatal_error(error, "[dpcm_point_mf_assemble] k2: wrong shape")
         return
      end if
      if (any(shape(a) /= [npt])) then
         call fatal_error(error, "[dpcm_point_mf_assemble] a: wrong shape")
         return
      end if
      state%ready = 0
      if (allocated(state%solver)) deallocate (state%solver)
      if (allocated(state%v)) deallocate (state%v)
      if (allocated(state%a)) deallocate (state%a)
      if (allocated(state%n)) deallocate (state%n)
      if (allocated(state%r)) deallocate (state%r)
      if (allocated(state%k1)) deallocate (state%k1)
      if (allocated(state%k2)) deallocate (state%k2)
      if (allocated(state%vn)) deallocate (state%vn)
      if (allocated(state%s11)) deallocate (state%s11)
      if (allocated(state%s13)) deallocate (state%s13)
      if (allocated(state%s14)) deallocate (state%s14)
      if (allocated(state%s4)) deallocate (state%s4)
      if (allocated(state%s5)) deallocate (state%s5)
      if (allocated(state%s6)) deallocate (state%s6)
      if (allocated(state%s7)) deallocate (state%s7)
      if (allocated(state%s8)) deallocate (state%s8)
      if (allocated(state%s9)) deallocate (state%s9)
      if (allocated(state%s15)) deallocate (state%s15)
      if (allocated(state%s17)) deallocate (state%s17)
      if (allocated(state%s18)) deallocate (state%s18)
      if (allocated(state%s19)) deallocate (state%s19)
      if (allocated(state%s20)) deallocate (state%s20)
      if (allocated(state%s21)) deallocate (state%s21)
      if (allocated(state%s10)) deallocate (state%s10)
      state%npt = npt
      if (present(solver)) then
         allocate (state%solver, source=solver, stat=stat)
      else
         allocate (pcm_dense_solver :: state%solver, stat=stat)
      end if
      if (stat == 0) allocate (state%v(npt), stat=stat)
      if (stat == 0) allocate (state%a(npt), stat=stat)
      if (stat == 0) allocate (state%n(3, npt), stat=stat)
      if (stat == 0) allocate (state%r(3, npt), stat=stat)
      if (stat == 0) allocate (state%k1(npt), stat=stat)
      if (stat == 0) allocate (state%k2(npt), stat=stat)
      if (stat == 0) allocate (state%vn(npt), stat=stat)
      if (stat == 0) allocate (state%s11(npt), stat=stat)
      if (stat == 0) allocate (state%s13(npt), stat=stat)
      if (stat == 0) allocate (state%s14(npt), stat=stat)
      if (stat == 0) allocate (state%s4(npt), stat=stat)
      if (stat == 0) allocate (state%s5(npt), stat=stat)
      if (stat == 0) allocate (state%s6(npt), stat=stat)
      if (stat == 0) allocate (state%s7(npt), stat=stat)
      if (stat == 0) allocate (state%s8(npt), stat=stat)
      if (stat == 0) allocate (state%s9(npt), stat=stat)
      if (stat == 0) allocate (state%s15(npt), stat=stat)
      if (stat == 0) allocate (state%s17(npt), stat=stat)
      if (stat == 0) allocate (state%s18(npt), stat=stat)
      if (stat == 0) allocate (state%s19(npt), stat=stat)
      if (stat == 0) allocate (state%s20(npt), stat=stat)
      if (stat == 0) allocate (state%s21(npt), stat=stat)
      if (stat /= 0) then
         call fatal_error(error, "[dpcm_point_mf_assemble] allocation failed")
         return
      end if
      state%s11 = 0.0_wp
      state%s13 = 0.0_wp
      call state%solver%reset(dpcm_point_n_operators)
      state%matrix_free = .true.

      state%a = a
      state%n = n
      state%r = r
      state%k1 = k1
      state%k2 = k2
      state%s4 = state%n(1, :)
      state%s5 = state%r(1, :)
      state%s6 = state%r(2, :)
      state%s7 = state%n(2, :)
      state%s8 = state%r(3, :)
      state%s9 = state%n(3, :)

      state%ready = 1
      state%assembled = state%assembled + 1
   end subroutine dpcm_point_mf_assemble

   module subroutine dpcm_point_mf_medium(state, eps, error)
      !> State of dpcm_point
      type(dpcm_point_state), target, intent(inout) :: state
      !> Relative permittivity of the solvent (inf for a conductor)
      real(wp), intent(in) :: eps
      !> Error handling
      type(error_type), allocatable, intent(out) :: error

      integer :: npt
      integer :: stat
      real(wp) :: tmp1, tmp2

      stat = 0
      npt = state%npt
      if (state%ready < 1) then
         call fatal_error(error, "[dpcm_point_mf_medium] call dpcm_point_assemble first")
         return
      end if
      state%ready = 1
      ! Inputs that do not enter these outputs
      associate (unused1 => eps)
      end associate

      state%op2%npt = npt
      state%op2%npoint = npt
      state%op2%id = 2
      state%op2%points => state%r
      state%op2%r => state%r
      state%op2%n => state%n
      state%op2%k1 => state%k1
      state%op2%k2 => state%k2
      state%op2%a => state%a
      state%s1 = eps + 1.0_wp
      tmp1 = 1.0_wp/state%s1
      tmp2 = (-2.0_wp)*tmp1
      state%s2 = 1.0_wp + tmp2
      state%s3 = -state%s2
      state%op2%c1 = state%s3
      call state%solver%setup(state%op2, error)
      if (allocated(error)) return
      state%s12 = 0.5_wp*state%s2

      state%ready = 2
   end subroutine dpcm_point_mf_medium

   module subroutine dpcm_point_mf_solve(state, v, vn, energy, q, grad_v, grad_vn, error)
      !> State of dpcm_point
      type(dpcm_point_state), target, intent(inout) :: state
      !> Solute electrostatic potential at the surface points
      real(wp), contiguous, intent(in) :: v(:)
      !> Outward normal derivative of the solute potential at the surface points
      real(wp), contiguous, intent(in) :: vn(:)
      !> Solvation energy
      real(wp), intent(out) :: energy
      !> Apparent surface charges
      real(wp), contiguous, intent(out) :: q(:)
      !> Partial derivative of the energy with respect to v
      real(wp), contiguous, intent(out) :: grad_v(:)
      !> Partial derivative of the energy with respect to vn
      real(wp), contiguous, intent(out) :: grad_vn(:)
      !> Error handling
      type(error_type), allocatable, intent(out) :: error

      integer :: npt
      integer :: stat
      real(wp), allocatable :: tmp1(:), tmp2(:), tmp3(:), tmp10(:), tmp40(:), tmp41(:), tmp42(:), &
                               tmp43(:), tmp44(:), tmp45(:)
      real(wp) :: tmp4, tmp5, tmp6, tmp7, tmp8, tmp9, tmp39, tmp46
      integer :: i, j

      stat = 0
      npt = state%npt
      if (state%ready < 2) then
         call fatal_error(error, "[dpcm_point_mf_solve] call dpcm_point_medium first")
         return
      end if
      if (any(shape(v) /= [npt])) then
         call fatal_error(error, "[dpcm_point_mf_solve] v: wrong shape")
         return
      end if
      if (any(shape(vn) /= [npt])) then
         call fatal_error(error, "[dpcm_point_mf_solve] vn: wrong shape")
         return
      end if
      if (any(shape(q) /= [npt])) then
         call fatal_error(error, "[dpcm_point_mf_solve] q: wrong shape")
         return
      end if
      if (any(shape(grad_v) /= [npt])) then
         call fatal_error(error, "[dpcm_point_mf_solve] grad_v: wrong shape")
         return
      end if
      if (any(shape(grad_vn) /= [npt])) then
         call fatal_error(error, "[dpcm_point_mf_solve] grad_vn: wrong shape")
         return
      end if
      allocate (tmp1(npt), stat=stat)
      if (stat == 0) allocate (tmp2(npt), stat=stat)
      if (stat == 0) allocate (tmp3(npt), stat=stat)
      if (stat == 0) allocate (tmp10(npt), stat=stat)
      if (stat == 0) allocate (tmp40(npt), stat=stat)
      if (stat == 0) allocate (tmp41(npt), stat=stat)
      if (stat == 0) allocate (tmp42(npt), stat=stat)
      if (stat == 0) allocate (tmp43(npt), stat=stat)
      if (stat == 0) allocate (tmp44(npt), stat=stat)
      if (stat == 0) allocate (tmp45(npt), stat=stat)
      if (stat /= 0) then
         call fatal_error(error, "[dpcm_point_mf_solve] allocation failed")
         return
      end if
      state%ready = 2

      state%op2%points => state%r
      state%op2%r => state%r
      state%op2%n => state%n
      state%op2%k1 => state%k1
      state%op2%k2 => state%k2
      state%op2%a => state%a
      state%v = v
      state%vn = vn
      tmp1 = state%a*state%vn
      call state%solver%solve(state%op2, .false., tmp1, state%s11, error)
      if (allocated(error)) return
      call state%solver%solve(state%op2, .true., state%v, state%s13, error)
      if (allocated(error)) return
      state%s14 = state%s12*state%s13
      do i = 1, npt
         tmp4 = state%k1(i) + state%k2(i)
         tmp5 = 1.0_wp/state%a(i)
         tmp6 = 12.566370614359172_wp*tmp5
         tmp7 = sqrt(tmp6)
         tmp8 = tmp4*tmp7
         tmp9 = (-0.26735_wp)*tmp8
         tmp3(i) = tmp9
      end do
      tmp10 = tmp3*state%s11
      tmp2 = tmp10
      block
         real(wp) :: tmp12, tmp13, tmp14, tmp15, tmp16, tmp17, tmp18, tmp19, tmp22, tmp26, tmp11, &
                     tmp20, tmp21, tmp23, tmp24, tmp25, tmp27, tmp28, tmp29, tmp30, tmp31, tmp32, &
                     tmp33, tmp34, tmp35, tmp36, tmp37, tmp38

         !$omp parallel &
         !$omp& private(i, j) &
         !$omp& shared(npt, state, tmp2) &
         !$omp& default(private)
         !$omp do schedule(static)
         do j = 1, npt
            tmp12 = state%s4(j)
            tmp13 = state%s5(j)
            tmp14 = state%s6(j)
            tmp15 = state%s7(j)
            tmp16 = state%s8(j)
            tmp17 = state%s9(j)
            tmp18 = state%s11(j)
            tmp19 = -tmp13
            tmp22 = -tmp14
            tmp26 = -tmp16
            tmp11 = 0.0_wp
            !$omp simd &
            !$omp& private(tmp20, tmp21, tmp23, tmp24, tmp25, tmp27, tmp28, tmp29) &
            !$omp& private(tmp30, tmp31, tmp32, tmp33, tmp34, tmp35, tmp36, tmp37) &
            !$omp& private(tmp38) &
            !$omp& reduction(+: tmp11)
            do i = 1, j - 1
               tmp20 = state%s5(i) + tmp19
               tmp21 = tmp12*tmp20
               tmp23 = state%s6(i) + tmp22
               tmp24 = tmp23*tmp15
               tmp25 = tmp21 + tmp24
               tmp27 = state%s8(i) + tmp26
               tmp28 = tmp27*tmp17
               tmp29 = tmp25 + tmp28
               tmp30 = tmp20**(2)
               tmp31 = tmp23**(2)
               tmp32 = tmp30 + tmp31
               tmp33 = tmp27**(2)
               tmp34 = tmp32 + tmp33
               tmp35 = 1.0_wp/sqrt(tmp34)
               tmp36 = tmp35**(3)
               tmp37 = tmp29*tmp36
               tmp38 = tmp37*state%s11(i)
               tmp11 = tmp11 + tmp38
            end do
            !$omp simd &
            !$omp& private(tmp20, tmp21, tmp23, tmp24, tmp25, tmp27, tmp28, tmp29) &
            !$omp& private(tmp30, tmp31, tmp32, tmp33, tmp34, tmp35, tmp36, tmp37) &
            !$omp& private(tmp38) &
            !$omp& reduction(+: tmp11)
            do i = j + 1, npt
               tmp20 = state%s5(i) + tmp19
               tmp21 = tmp12*tmp20
               tmp23 = state%s6(i) + tmp22
               tmp24 = tmp23*tmp15
               tmp25 = tmp21 + tmp24
               tmp27 = state%s8(i) + tmp26
               tmp28 = tmp27*tmp17
               tmp29 = tmp25 + tmp28
               tmp30 = tmp20**(2)
               tmp31 = tmp23**(2)
               tmp32 = tmp30 + tmp31
               tmp33 = tmp27**(2)
               tmp34 = tmp32 + tmp33
               tmp35 = 1.0_wp/sqrt(tmp34)
               tmp36 = tmp35**(3)
               tmp37 = tmp29*tmp36
               tmp38 = tmp37*state%s11(i)
               tmp11 = tmp11 + tmp38
            end do
            tmp2(j) = tmp2(j) + tmp11
         end do
         !$omp end do
         !$omp end parallel
      end block
      state%s15 = tmp2
      q = state%s2*state%s11
      tmp39 = dot(state%v, q)
      energy = 0.5_wp*tmp39
      grad_v = state%s12*state%s11
      grad_vn = state%s14*state%a
      if (state%solver%inexact()) then
         ! First-order correction for the residuals of the solves
         tmp40 = 6.283185307179586_wp*state%s11
         tmp41 = state%a*state%s15
         tmp42 = state%s3*tmp41
         tmp43 = tmp40 + tmp42
         tmp44 = -tmp43
         tmp45 = tmp1 + tmp44
         tmp46 = dot(state%s14, tmp45)
         energy = energy + tmp46
      end if

      state%ready = 3
   end subroutine dpcm_point_mf_solve

end submodule pcmgen_point_dpcm_mf_energy
