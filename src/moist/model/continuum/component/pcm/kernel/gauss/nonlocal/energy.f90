            end do
         end do
         !$omp end do
         deallocate (tmp1722)
         !$omp end parallel
      end block
      do i = 1, npt
         tmp1857 = 1.0_wp/state%F(i)
         tmp1858 = state%xi(i)*tmp1857
         tmp1859 = tmp1858*state%a(i)
         tmp1860 = 0.7978845608028654_wp*tmp1859
         state%s10(i, i) = tmp1860
      end do
      state%op1%c6 => state%s10
      state%s21 = state%s16*state%eps_inf
      state%op1%c7 = state%s21
      call state%solver%setup(state%op1, error)
      if (allocated(error)) return
      state%op2%npt = npt
      state%op2%npoint = npt
      state%op2%id = 2
      state%op2%points => state%r
      state%op2%c1 => state%s10
      call state%solver%setup(state%op2, error)
      if (allocated(error)) return
      state%s1 = 1.0_wp/state%eps_solute
      state%s22 = -state%s21
      state%s23 = 1.0_wp + state%s22
      state%s25 = -state%s18
      state%s27 = -state%s20
      state%s28 = 1.0_wp + state%s27
      state%s35 = 0.5_wp*state%s1
      state%s36 = (-6.283185307179586_wp)*state%s28
      state%s57 = state%lam**(-2)

      state%ready = 2
   end subroutine nonlocal_pcm_medium

   module subroutine nonlocal_pcm_solve(state, v, vn, energy, u, q, w_ext, grad_v, grad_vn, error)
      !> State of nonlocal_pcm
      type(nonlocal_pcm_state), target, intent(inout) :: state
      !> Solute electrostatic potential at the surface points
      real(wp), contiguous, intent(in) :: v(:)
      !> Outward normal derivative of the solute potential at the surface points
      real(wp), contiguous, intent(in) :: vn(:)
      !> Solvation energy
      real(wp), intent(out) :: energy
      !> Interior trace of eps_solute times the reaction potential
      real(wp), contiguous, intent(out) :: u(:)
      !> Interior normal trace of eps_solute times the reaction potential
      real(wp), contiguous, intent(out) :: q(:)
      !> Exterior auxiliary trace
      real(wp), contiguous, intent(out) :: w_ext(:)
      !> Partial derivative of the energy with respect to v
      real(wp), contiguous, intent(out) :: grad_v(:)
      !> Partial derivative of the energy with respect to vn
      real(wp), contiguous, intent(out) :: grad_vn(:)
      !> Error handling
      type(error_type), allocatable, intent(out) :: error

      integer :: npt
      integer :: stat
      real(wp), allocatable :: tmp1(:), tmp2(:), tmp3(:), tmp4(:), tmp5(:), tmp6(:), tmp7(:), &
                               tmp10(:), tmp11(:), tmp14(:), tmp15(:), tmp16(:), tmp17(:), &
                               tmp18(:), tmp19(:), tmp20(:), tmp21(:), tmp22(:), tmp23(:), &
                               tmp25(:), tmp26(:), tmp27(:), tmp28(:), tmp29(:), tmp30(:), &
                               tmp31(:), tmp32(:), tmp33(:), tmp34(:), tmp35(:), tmp36(:), &
                               tmp37(:), tmp38(:), tmp39(:), tmp40(:), tmp41(:), tmp42(:), &
                               tmp43(:), tmp46(:), tmp47(:), tmp48(:), tmp49(:), tmp52(:), &
                               tmp53(:), tmp54(:), tmp55(:), tmp56(:), tmp57(:), tmp58(:), &
                               tmp59(:)
      real(wp), allocatable :: tmp8(:), tmp9(:), tmp12(:)
      real(wp) :: tmp13, tmp24, tmp44, tmp45, tmp50, tmp51, tmp60, tmp61

      if (state%matrix_free) then
         call nonlocal_pcm_mf_solve(state, v, vn, energy, u, q, w_ext, grad_v, grad_vn, error)
         return
      end if
      stat = 0
      npt = state%npt
      if (state%ready < 2) then
         call fatal_error(error, "[nonlocal_pcm_solve] call nonlocal_pcm_medium first")
         return
      end if
      if (any(shape(v) /= [npt])) then
         call fatal_error(error, "[nonlocal_pcm_solve] v: wrong shape")
         return
      end if
      if (any(shape(vn) /= [npt])) then
         call fatal_error(error, "[nonlocal_pcm_solve] vn: wrong shape")
         return
      end if
      if (any(shape(u) /= [npt])) then
         call fatal_error(error, "[nonlocal_pcm_solve] u: wrong shape")
         return
      end if
      if (any(shape(q) /= [npt])) then
         call fatal_error(error, "[nonlocal_pcm_solve] q: wrong shape")
         return
      end if
      if (any(shape(w_ext) /= [npt])) then
         call fatal_error(error, "[nonlocal_pcm_solve] w_ext: wrong shape")
         return
      end if
      if (any(shape(grad_v) /= [npt])) then
         call fatal_error(error, "[nonlocal_pcm_solve] grad_v: wrong shape")
         return
      end if
      if (any(shape(grad_vn) /= [npt])) then
         call fatal_error(error, "[nonlocal_pcm_solve] grad_vn: wrong shape")
         return
      end if
      allocate (tmp1(npt), stat=stat)
      if (stat == 0) allocate (tmp2(npt), stat=stat)
      if (stat == 0) allocate (tmp3(npt), stat=stat)
      if (stat == 0) allocate (tmp4(npt), stat=stat)
      if (stat == 0) allocate (tmp5(npt), stat=stat)
      if (stat == 0) allocate (tmp6(npt), stat=stat)
      if (stat == 0) allocate (tmp7(npt), stat=stat)
      if (stat == 0) allocate (tmp10(npt), stat=stat)
      if (stat == 0) allocate (tmp11(npt), stat=stat)
      if (stat == 0) allocate (tmp14(npt), stat=stat)
      if (stat == 0) allocate (tmp15(npt), stat=stat)
      if (stat == 0) allocate (tmp16(npt), stat=stat)
      if (stat == 0) allocate (tmp17(npt), stat=stat)
      if (stat == 0) allocate (tmp18(npt), stat=stat)
      if (stat == 0) allocate (tmp19(npt), stat=stat)
      if (stat == 0) allocate (tmp20(npt), stat=stat)
      if (stat == 0) allocate (tmp21(npt), stat=stat)
      if (stat == 0) allocate (tmp22(npt), stat=stat)
      if (stat == 0) allocate (tmp23(npt), stat=stat)
      if (stat == 0) allocate (tmp25(npt), stat=stat)
      if (stat == 0) allocate (tmp26(npt), stat=stat)
      if (stat == 0) allocate (tmp27(npt), stat=stat)
      if (stat == 0) allocate (tmp28(npt), stat=stat)
      if (stat == 0) allocate (tmp29(npt), stat=stat)
      if (stat == 0) allocate (tmp30(npt), stat=stat)
      if (stat == 0) allocate (tmp31(npt), stat=stat)
      if (stat == 0) allocate (tmp32(npt), stat=stat)
      if (stat == 0) allocate (tmp33(npt), stat=stat)
      if (stat == 0) allocate (tmp34(npt), stat=stat)
      if (stat == 0) allocate (tmp35(npt), stat=stat)
      if (stat == 0) allocate (tmp36(npt), stat=stat)
      if (stat == 0) allocate (tmp37(npt), stat=stat)
      if (stat == 0) allocate (tmp38(npt), stat=stat)
      if (stat == 0) allocate (tmp39(npt), stat=stat)
      if (stat == 0) allocate (tmp40(npt), stat=stat)
      if (stat == 0) allocate (tmp41(npt), stat=stat)
      if (stat == 0) allocate (tmp42(npt), stat=stat)
      if (stat == 0) allocate (tmp43(npt), stat=stat)
      if (stat == 0) allocate (tmp46(npt), stat=stat)
      if (stat == 0) allocate (tmp47(npt), stat=stat)
      if (stat == 0) allocate (tmp48(npt), stat=stat)
      if (stat == 0) allocate (tmp49(npt), stat=stat)
      if (stat == 0) allocate (tmp52(npt), stat=stat)
      if (stat == 0) allocate (tmp53(npt), stat=stat)
      if (stat == 0) allocate (tmp54(npt), stat=stat)
      if (stat == 0) allocate (tmp55(npt), stat=stat)
      if (stat == 0) allocate (tmp56(npt), stat=stat)
      if (stat == 0) allocate (tmp57(npt), stat=stat)
      if (stat == 0) allocate (tmp58(npt), stat=stat)
      if (stat == 0) allocate (tmp59(npt), stat=stat)
      if (stat == 0) allocate (tmp8(3*npt), stat=stat)
      if (stat == 0) allocate (tmp9(3*npt), stat=stat)
      if (stat == 0) allocate (tmp12(3*npt), stat=stat)
      if (stat /= 0) then
         call fatal_error(error, "[nonlocal_pcm_solve] allocation failed")
         return
      end if
      state%ready = 2

      state%op1%points => state%r
      state%op1%c1 => state%s14
      state%op1%c2 => state%s15
      state%op1%c4 => state%s19
      state%op1%c6 => state%s10
      state%op2%points => state%r
      state%op2%c1 => state%s10
      state%v = v
      state%vn = vn
      call gemv(state%s14, state%v, state%s24)
      call gemv(state%s19, state%vn, state%s26)
      call gemv(state%s15, state%v, tmp1)
      tmp2 = (-6.283185307179586_wp)*state%v
      state%s29 = tmp1 + tmp2
      tmp3 = state%s23*state%s24
      tmp4 = state%s25*state%s26
      tmp5 = tmp3 + tmp4
      tmp6 = state%s28*state%s29
      tmp7 = tmp5 + tmp6
      tmp8(1:npt) = tmp7
      tmp8(npt + 1:2*npt) = 0.0_wp
      tmp8(2*npt + 1:3*npt) = tmp6
      tmp9 = 0.0_wp
      call state%solver%solve(state%op1, .false., tmp8, tmp9, error)
      if (allocated(error)) return
      state%s30 = tmp9(1:npt)
      call state%solver%solve(state%op2, .false., state%s30, state%s31, error)
      if (allocated(error)) return
      tmp10 = state%a*state%s31
      state%s32 = dot(tmp10, state%v)
      state%s33 = tmp9(npt + 1:2*npt)
      state%s34 = tmp9(2*npt + 1:3*npt)
      state%s37 = state%s35*state%v
      tmp11 = state%s37*state%a
      call state%solver%solve(state%op2, .true., tmp11, state%s38, error)
      if (allocated(error)) return
      tmp12(1:npt) = state%s38
      tmp12(npt + 1:2*npt) = 0.0_wp
      tmp12(2*npt + 1:3*npt) = 0.0_wp
      call state%solver%solve(state%op1, .true., tmp12, state%s39, error)
      if (allocated(error)) return
      state%s40 = state%s39(2*npt + 1:3*npt)
      state%s41 = state%s39(1:npt)
      state%s42 = state%s40 + state%s41
      state%s43 = state%s28*state%s42
      state%s44 = state%s23*state%s41
      state%s45 = state%s25*state%s41
      state%s47 = state%vn + state%s33
      state%s49 = -state%s40
      state%s50 = -state%s41
      state%s51 = state%s22*state%s41
      state%s53 = state%s49 + state%s50
      tmp13 = state%s1*state%s32
      energy = 0.5_wp*tmp13
      u = state%s30
      q = state%s33
      tmp14 = state%s28*state%v
      w_ext = state%s34 + tmp14
      tmp15 = state%s35*tmp10
      tmp16 = state%s36*state%s42
      tmp17 = tmp15 + tmp16
      call gemv(state%s15, state%s43, tmp18, trans="t")
      tmp19 = tmp17 + tmp18
      call gemv(state%s14, state%s44, tmp20, trans="t")
      grad_v = tmp19 + tmp20
      call gemv(state%s19, state%s45, grad_vn, trans="t")
      if (state%solver%inexact()) then
         ! First-order correction for the residuals of the solves
         call gemv(state%s10, state%s31, tmp21)
         tmp22 = -tmp21
         tmp23 = state%s30 + tmp22
         tmp24 = dot(state%s38, tmp23)
         tmp25 = 6.283185307179586_wp*state%s30
         call gemv(state%s14, state%s30, tmp26)
         tmp27 = -tmp26
         tmp28 = tmp25 + tmp27
         call gemv(state%s15, state%s30, tmp29)
         tmp30 = -tmp29
         tmp31 = tmp28 + tmp30
         tmp32 = -tmp31
         tmp33 = tmp7 + tmp32
         call gemv(state%s19, state%s33, tmp34)
         tmp35 = state%s18*tmp34
         call gemv(state%s10, state%s33, tmp36)
         tmp37 = state%s20*tmp36
         tmp38 = tmp35 + tmp37
         tmp39 = -tmp38
         tmp40 = tmp33 + tmp39
         call gemv(state%s14, state%s34, tmp41)
         tmp42 = state%s22*tmp41
         tmp43 = tmp40 + tmp42
         tmp44 = dot(state%s41, tmp43)
         tmp45 = tmp24 + tmp44
         tmp46 = state%s39(npt + 1:2*npt)
         tmp47 = tmp25 + tmp29
         tmp48 = -tmp47
         tmp49 = tmp48 + tmp36
         tmp50 = dot(tmp46, tmp49)
         tmp51 = tmp45 + tmp50
         tmp52 = state%s27*tmp36
         tmp53 = tmp6 + tmp52
         tmp54 = 6.283185307179586_wp*state%s34
         call gemv(state%s15, state%s34, tmp55)
         tmp56 = -tmp55
         tmp57 = tmp54 + tmp56
         tmp58 = -tmp57
         tmp59 = tmp53 + tmp58
         tmp60 = dot(state%s40, tmp59)
         tmp61 = tmp51 + tmp60
         energy = energy + tmp61
      end if

      state%ready = 3
   end subroutine nonlocal_pcm_solve

