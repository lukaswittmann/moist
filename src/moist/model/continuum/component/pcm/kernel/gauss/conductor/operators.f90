!> - Procedures of pcmgen_gauss_conductor: conductor_op1_apply, conductor_op1_assemble,
!>   conductor_op1_assemble_block
submodule(pcmgen_gauss_conductor) pcmgen_gauss_conductor_operators
   implicit none(type, external)

contains

   module subroutine conductor_op1_apply(self, trans, x, y)
      !> Operator
      class(conductor_op1), intent(in) :: self
      !> Apply the transpose
      logical, intent(in) :: trans
      !> Input vector
      real(wp), contiguous, intent(in) :: x(:)
      !> Result vector
      real(wp), contiguous, intent(out) :: y(:)

      ! The transpose is the operator itself
      associate (unused1 => trans)
      end associate
      call gemv(self%c1, x, y)
   end subroutine conductor_op1_apply

   module subroutine conductor_op1_assemble(self, a, error)
      !> Operator
      class(conductor_op1), intent(in) :: self
      !> Dense operator matrix
      real(wp), contiguous, intent(out) :: a(:, :)
      !> Error handling
      type(error_type), allocatable, intent(out) :: error

      if (allocated(error)) return   ! nothing to allocate; error stays unset
      a = self%c1
   end subroutine conductor_op1_assemble

   module subroutine conductor_op1_assemble_block(self, idx, a, error)
      !> Operator
      class(conductor_op1), intent(in) :: self
      !> Point indices
      integer, contiguous, intent(in) :: idx(:)
      !> Operator matrix of the points
      real(wp), contiguous, intent(out) :: a(:, :)
      !> Error handling
      type(error_type), allocatable, intent(out) :: error

      integer :: nb
      integer :: stat
      real(wp), allocatable :: tmp1(:, :)

      nb = size(idx)
      if (any(shape(a) /= [nb, nb])) then
         call fatal_error(error, "[conductor_op1_assemble_block] a: wrong shape")
         return
      end if
      allocate (tmp1(nb, nb), stat=stat)
      if (stat /= 0) then
         call fatal_error(error, "[conductor_op1_assemble_block] allocation failed")
         return
      end if
      tmp1 = self%c1(idx, idx)
      a = tmp1
   end subroutine conductor_op1_assemble_block

end submodule pcmgen_gauss_conductor_operators
