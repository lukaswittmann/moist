!> IEF-PCM (gaussian charges) phases: complex/energy; generated by pcmgen, do not edit
!>
!> - Procedures of pcmgen_gauss_iefpcm: iefpcm_complex_medium, iefpcm_complex_solve
submodule(pcmgen_gauss_iefpcm) pcmgen_gauss_iefpcm_complex_energy
   implicit none(type, external)

contains

   module subroutine iefpcm_complex_medium(state, eps, error)
      !> State of iefpcm
      type(iefpcm_complex_state), target, intent(inout) :: state
      !> Relative permittivity of the solvent (inf for a conductor)
      complex(wp), intent(in) :: eps
      !> Error handling
      type(error_type), allocatable, intent(out) :: error

      integer :: npt
      integer :: stat
      complex(wp) :: tmp1, tmp2

      if (state%matrix_free) then
         call iefpcm_complex_mf_medium(state, eps, error)
         return
      end if
      stat = 0
      npt = state%npt
      if (state%ready < 1) then
         call fatal_error(error, "[iefpcm_complex_medium] call iefpcm_assemble first")
         return
      end if
      state%cx_ready = 0
      if (allocated(state%cx_v)) deallocate (state%cx_v)
      if (allocated(state%cx_s13)) deallocate (state%cx_s13)
      if (allocated(state%cx_s14)) deallocate (state%cx_s14)
      if (allocated(state%cx_s16)) deallocate (state%cx_s16)
      if (allocated(state%cx_s18)) deallocate (state%cx_s18)
      if (allocated(state%cx_s19)) deallocate (state%cx_s19)
      if (allocated(state%cx_s20)) deallocate (state%cx_s20)
      if (allocated(state%cx_s21)) deallocate (state%cx_s21)
      if (allocated(state%cx_s23)) deallocate (state%cx_s23)
      if (allocated(state%cx_s25)) deallocate (state%cx_s25)
      if (allocated(state%cx_s26)) deallocate (state%cx_s26)
      if (allocated(state%cx_s27)) deallocate (state%cx_s27)
      if (allocated(state%cx_s28)) deallocate (state%cx_s28)
      if (allocated(state%cx_s29)) deallocate (state%cx_s29)
      if (allocated(state%cx_s30)) deallocate (state%cx_s30)
      if (allocated(state%cx_s31)) deallocate (state%cx_s31)
      if (allocated(state%cx_s32)) deallocate (state%cx_s32)
      if (allocated(state%cx_s33)) deallocate (state%cx_s33)
      if (stat == 0) allocate (state%cx_v(npt), stat=stat)
      if (stat == 0) allocate (state%cx_s13(npt), stat=stat)
      if (stat == 0) allocate (state%cx_s14(npt), stat=stat)
      if (stat == 0) allocate (state%cx_s16(npt), stat=stat)
      if (stat == 0) allocate (state%cx_s18(npt), stat=stat)
      if (stat == 0) allocate (state%cx_s19(npt), stat=stat)
      if (stat == 0) allocate (state%cx_s20(npt), stat=stat)
      if (stat == 0) allocate (state%cx_s21(npt), stat=stat)
      if (stat == 0) allocate (state%cx_s23(npt), stat=stat)
      if (stat == 0) allocate (state%cx_s25(npt), stat=stat)
      if (stat == 0) allocate (state%cx_s26(npt), stat=stat)
      if (stat == 0) allocate (state%cx_s27(npt), stat=stat)
      if (stat == 0) allocate (state%cx_s28(npt), stat=stat)
      if (stat == 0) allocate (state%cx_s29(npt), stat=stat)
      if (stat == 0) allocate (state%cx_s30(npt), stat=stat)
      if (stat == 0) allocate (state%cx_s31(npt), stat=stat)
      if (stat == 0) allocate (state%cx_s32(npt), stat=stat)
      if (stat == 0) allocate (state%cx_s33(npt), stat=stat)
      if (stat /= 0) then
         call fatal_error(error, "[iefpcm_complex_medium] allocation failed")
         return
      end if
      state%cx_s14 = 0.0_wp
      state%cx_s16 = 0.0_wp
      state%cx_ready = 1
      state%cx_assembled = state%assembled
      ! Inputs that do not enter these outputs
      associate (unused1 => eps)
      end associate

      state%op3%npt = npt
      state%op3%npoint = npt
      state%op3%id = 3
      state%op3%points => state%r
      state%op3%a => state%a
      state%op3%c1 => state%s7
      state%cx_s1 = eps + 1.0_wp
      tmp1 = 1.0_wp/state%cx_s1
      tmp2 = (-2.0_wp)*tmp1
      state%cx_s2 = 1.0_wp + tmp2
      state%cx_s8 = (-0.15915494309189535_wp)*state%cx_s2
      state%op3%c2 = state%cx_s8
      state%op3%c3 => state%s12
      call state%solver%setup_complex(state%op3, error)
      if (allocated(error)) return
      state%cx_s3 = -state%cx_s2
      state%cx_s15 = (-0.5_wp)*state%cx_s2
      state%cx_s17 = 0.07957747154594767_wp*state%cx_s2
      state%cx_s24 = 0.5_wp*state%cx_s2

      state%cx_ready = 2
   end subroutine iefpcm_complex_medium

   module subroutine iefpcm_complex_solve(state, v, energy, q, grad_v, error)
      !> State of iefpcm
      type(iefpcm_complex_state), target, intent(inout) :: state
      !> Solute electrostatic potential at the surface points
      complex(wp), contiguous, intent(in) :: v(:)
      !> Solvation energy
      complex(wp), intent(out) :: energy
      !> Apparent surface charges
      complex(wp), contiguous, intent(out) :: q(:)
      !> Partial derivative of the energy with respect to v
      complex(wp), contiguous, intent(out) :: grad_v(:)
      !> Error handling
      type(error_type), allocatable, intent(out) :: error

      integer :: npt
      integer :: stat
      real(wp), allocatable :: tmp2(:), tmp3(:), tmp6(:), tmp7(:), tmp8(:), tmp9(:), tmp16(:), &
                               tmp17(:)
      complex(wp), allocatable :: tmp1(:), tmp4(:), tmp5(:), tmp11(:), tmp12(:), tmp13(:), &
                                  tmp14(:), tmp15(:), tmp18(:), tmp19(:), tmp20(:), tmp21(:)
      complex(wp) :: tmp10, tmp22

      if (state%matrix_free) then
         call iefpcm_complex_mf_solve(state, v, energy, q, grad_v, error)
         return
      end if
      stat = 0
      npt = state%npt
      if (state%cx_ready < 2 .or. state%cx_assembled /= state%assembled) then
         call fatal_error(error, "[iefpcm_complex_solve] call iefpcm_complex_medium first")
         return
      end if
      if (any(shape(v) /= [npt])) then
         call fatal_error(error, "[iefpcm_complex_solve] v: wrong shape")
         return
      end if
      if (any(shape(q) /= [npt])) then
         call fatal_error(error, "[iefpcm_complex_solve] q: wrong shape")
         return
      end if
      if (any(shape(grad_v) /= [npt])) then
         call fatal_error(error, "[iefpcm_complex_solve] grad_v: wrong shape")
         return
      end if
      allocate (tmp1(npt), stat=stat)
      if (stat == 0) allocate (tmp2(npt), stat=stat)
      if (stat == 0) allocate (tmp3(npt), stat=stat)
      if (stat == 0) allocate (tmp4(npt), stat=stat)
      if (stat == 0) allocate (tmp5(npt), stat=stat)
      if (stat == 0) allocate (tmp6(npt), stat=stat)
      if (stat == 0) allocate (tmp7(npt), stat=stat)
      if (stat == 0) allocate (tmp8(npt), stat=stat)
      if (stat == 0) allocate (tmp9(npt), stat=stat)
      if (stat == 0) allocate (tmp11(npt), stat=stat)
      if (stat == 0) allocate (tmp12(npt), stat=stat)
      if (stat == 0) allocate (tmp13(npt), stat=stat)
      if (stat == 0) allocate (tmp14(npt), stat=stat)
      if (stat == 0) allocate (tmp15(npt), stat=stat)
      if (stat == 0) allocate (tmp16(npt), stat=stat)
      if (stat == 0) allocate (tmp17(npt), stat=stat)
      if (stat == 0) allocate (tmp18(npt), stat=stat)
      if (stat == 0) allocate (tmp19(npt), stat=stat)
      if (stat == 0) allocate (tmp20(npt), stat=stat)
      if (stat == 0) allocate (tmp21(npt), stat=stat)
      if (stat /= 0) then
         call fatal_error(error, "[iefpcm_complex_solve] allocation failed")
         return
      end if
      state%cx_ready = 2

      state%op3%points => state%r
      state%op3%a => state%a
      state%op3%c1 => state%s7
      state%op3%c3 => state%s12
      state%cx_v = v
      state%cx_s13 = state%a*state%cx_v
      call gemv(state%s12, real(state%cx_s13, wp), tmp2)
      call gemv(state%s12, aimag(state%cx_s13), tmp3)
      tmp1 = cmplx(tmp2, tmp3, wp)
      tmp4 = (-0.15915494309189535_wp)*tmp1
      tmp5 = state%cx_v + tmp4
      call state%solver%solve_complex(state%op3, .false., tmp5, state%cx_s14, error)
      if (allocated(error)) return
      call state%solver%solve_complex(state%op3, .true., state%cx_v, state%cx_s16, error)
      if (allocated(error)) return
      state%cx_s18 = state%cx_s17*state%cx_s16
      call gemv(state%s12, real(state%cx_s18, wp), tmp6, trans="t")
      call gemv(state%s12, aimag(state%cx_s18), tmp7, trans="t")
      state%cx_s19 = cmplx(tmp6, tmp7, wp)
      call gemv(state%s7, real(state%cx_s14, wp), tmp8)
      call gemv(state%s7, aimag(state%cx_s14), tmp9)
      state%cx_s20 = cmplx(tmp8, tmp9, wp)
      state%cx_s21 = state%a*state%cx_s20
      state%cx_s25 = state%cx_s24*state%cx_s16
      q = state%cx_s3*state%cx_s14
      tmp10 = sum(state%cx_v*q)
      energy = 0.5_wp*tmp10
      tmp11 = state%cx_s15*state%cx_s14
      tmp12 = state%cx_s15*state%cx_s16
      tmp13 = tmp11 + tmp12
      tmp14 = state%cx_s19*state%a
      grad_v = tmp13 + tmp14
      if (state%solver%inexact()) then
         ! First-order correction for the residuals of the solves
         call gemv(state%s12, real(state%cx_s21, wp), tmp16)
         call gemv(state%s12, aimag(state%cx_s21), tmp17)
         tmp15 = cmplx(tmp16, tmp17, wp)
         tmp18 = state%cx_s8*tmp15
         tmp19 = state%cx_s20 + tmp18
         tmp20 = -tmp19
         tmp21 = tmp5 + tmp20
         tmp22 = sum(tmp12*tmp21)
         energy = energy + tmp22
      end if

      state%cx_ready = 3
   end subroutine iefpcm_complex_solve

end submodule pcmgen_gauss_iefpcm_complex_energy
