!> Linearized Poisson-Boltzmann (gaussian charges) phases: operators; generated by pcmgen, do not
!> edit
!>
!> - Procedures of pcmgen_gauss_lpb: lpb_op1_apply, lpb_op1_assemble, lpb_op1_assemble_block,
!>   lpb_op2_apply, lpb_op2_apply_t, lpb_op2_apply_n, lpb_op2_assemble, lpb_op2_assemble_block
submodule(pcmgen_gauss_lpb) pcmgen_gauss_lpb_operators
   implicit none(type, external)

contains

   module subroutine lpb_op1_apply(self, trans, x, y)
      !> Operator
      class(lpb_op1), intent(in) :: self
      !> Apply the transpose
      logical, intent(in) :: trans
      !> Input vector
      real(wp), contiguous, intent(in) :: x(:)
      !> Result vector
      real(wp), contiguous, intent(out) :: y(:)

      ! The transpose is the operator itself
      associate (unused1 => trans)
      end associate
      call gemv(self%c1, x, y)
   end subroutine lpb_op1_apply

   module subroutine lpb_op1_assemble(self, a, error)
      !> Operator
      class(lpb_op1), intent(in) :: self
      !> Dense operator matrix
      real(wp), contiguous, intent(out) :: a(:, :)
      !> Error handling
      type(error_type), allocatable, intent(out) :: error

      if (allocated(error)) return   ! nothing to allocate; error stays unset
      a = self%c1
   end subroutine lpb_op1_assemble

   module subroutine lpb_op1_assemble_block(self, idx, a, error)
      !> Operator
      class(lpb_op1), intent(in) :: self
      !> Point indices
      integer, contiguous, intent(in) :: idx(:)
      !> Operator matrix of the points
      real(wp), contiguous, intent(out) :: a(:, :)
      !> Error handling
      type(error_type), allocatable, intent(out) :: error

      integer :: nb
      integer :: stat
      real(wp), allocatable :: tmp1(:, :)

      nb = size(idx)
      if (any(shape(a) /= [nb, nb])) then
         call fatal_error(error, "[lpb_op1_assemble_block] a: wrong shape")
         return
      end if
      allocate (tmp1(nb, nb), stat=stat)
      if (stat /= 0) then
         call fatal_error(error, "[lpb_op1_assemble_block] allocation failed")
         return
      end if
      tmp1 = self%c1(idx, idx)
      a = tmp1
   end subroutine lpb_op1_assemble_block

   module subroutine lpb_op2_apply(self, trans, x, y)
      !> Operator
      class(lpb_op2), intent(in) :: self
      !> Apply the transpose
      logical, intent(in) :: trans
      !> Input vector
      real(wp), contiguous, intent(in) :: x(:)
      !> Result vector
      real(wp), contiguous, intent(out) :: y(:)

      if (trans) then
         call lpb_op2_apply_t(self, x, y)
      else
         call lpb_op2_apply_n(self, x, y)
      end if
   end subroutine lpb_op2_apply

   !> Apply the transpose of operator 2
   !>
   !> @param[in]  self  operator
   !> @param[in]  x     input vector
   !> @param[out] y     result vector
   subroutine lpb_op2_apply_t(self, x, y)
      !> Operator
      class(lpb_op2), intent(in) :: self
      !> Input vector
      real(wp), contiguous, intent(in) :: x(:)
      !> Result vector
      real(wp), contiguous, intent(out) :: y(:)

      real(wp), allocatable :: tmp1(:), tmp2(:), tmp3(:), tmp4(:), tmp5(:), tmp6(:), tmp7(:), &
                               tmp8(:), tmp9(:), tmp10(:), tmp11(:), tmp12(:)

      allocate (tmp1(self%npt))
      allocate (tmp2(self%npt))
      allocate (tmp3(self%npt))
      allocate (tmp4(self%npt))
      allocate (tmp5(self%npt))
      allocate (tmp6(self%npt))
      allocate (tmp7(self%npt))
      allocate (tmp8(self%npt))
      allocate (tmp9(self%npt))
      allocate (tmp10(self%npt))
      allocate (tmp11(self%npt))
      allocate (tmp12(self%npt))
      call gemv(self%c3, x, tmp1, trans="t")
      tmp2 = self%a*tmp1
      tmp3 = (-0.15915494309189535_wp)*tmp2
      tmp4 = x + tmp3
      call gemv(self%c2, tmp4, tmp5, trans="t")
      tmp6 = self%c1*tmp5
      call gemv(self%c5, x, tmp7, trans="t")
      tmp8 = self%a*tmp7
      call gemv(self%c6, tmp8, tmp9)
      tmp10 = 0.15915494309189535_wp*tmp9
      tmp11 = tmp7 + tmp10
      tmp12 = self%c4*tmp11
      y = tmp6 + tmp12
   end subroutine lpb_op2_apply_t

   !> Apply operator 2
   !>
   !> @param[in]  self  operator
   !> @param[in]  x     input vector
   !> @param[out] y     result vector
   subroutine lpb_op2_apply_n(self, x, y)
      !> Operator
      class(lpb_op2), intent(in) :: self
      !> Input vector
      real(wp), contiguous, intent(in) :: x(:)
      !> Result vector
      real(wp), contiguous, intent(out) :: y(:)

      real(wp), allocatable :: tmp1(:), tmp2(:), tmp3(:), tmp4(:), tmp5(:), tmp6(:), tmp7(:), &
                               tmp8(:), tmp9(:), tmp10(:), tmp11(:), tmp12(:)

      allocate (tmp1(self%npt))
      allocate (tmp2(self%npt))
      allocate (tmp3(self%npt))
      allocate (tmp4(self%npt))
      allocate (tmp5(self%npt))
      allocate (tmp6(self%npt))
      allocate (tmp7(self%npt))
      allocate (tmp8(self%npt))
      allocate (tmp9(self%npt))
      allocate (tmp10(self%npt))
      allocate (tmp11(self%npt))
      allocate (tmp12(self%npt))
      call gemv(self%c2, x, tmp1)
      tmp2 = self%a*tmp1
      call gemv(self%c3, tmp2, tmp3)
      tmp4 = (-0.15915494309189535_wp)*tmp3
      tmp5 = tmp1 + tmp4
      tmp6 = self%c1*tmp5
      call gemv(self%c6, x, tmp7, trans="t")
      tmp8 = self%a*tmp7
      tmp9 = 0.15915494309189535_wp*tmp8
      tmp10 = x + tmp9
      call gemv(self%c5, tmp10, tmp11)
      tmp12 = self%c4*tmp11
      y = tmp6 + tmp12
   end subroutine lpb_op2_apply_n

   module subroutine lpb_op2_assemble(self, a, error)
      !> Operator
      class(lpb_op2), intent(in) :: self
      !> Dense operator matrix
      real(wp), contiguous, intent(out) :: a(:, :)
      !> Error handling
      type(error_type), allocatable, intent(out) :: error

      integer :: stat
      real(wp), allocatable :: tmp1(:, :), tmp2(:, :), tmp3(:, :), tmp4(:, :), tmp5(:, :), &
                               tmp6(:, :), tmp7(:, :), tmp8(:, :), tmp9(:, :), tmp10(:, :)
      integer :: i

      allocate (tmp1(self%npt, self%npt), stat=stat)
      if (stat == 0) allocate (tmp2(self%npt, self%npt), stat=stat)
      if (stat == 0) allocate (tmp3(self%npt, self%npt), stat=stat)
      if (stat == 0) allocate (tmp4(self%npt, self%npt), stat=stat)
      if (stat == 0) allocate (tmp5(self%npt, self%npt), stat=stat)
      if (stat == 0) allocate (tmp6(self%npt, self%npt), stat=stat)
      if (stat == 0) allocate (tmp7(self%npt, self%npt), stat=stat)
      if (stat == 0) allocate (tmp8(self%npt, self%npt), stat=stat)
      if (stat == 0) allocate (tmp9(self%npt, self%npt), stat=stat)
      if (stat == 0) allocate (tmp10(self%npt, self%npt), stat=stat)
      if (stat /= 0) then
         call fatal_error(error, "[lpb_op2_assemble] allocation failed")
         return
      end if
      do i = 1, self%npt
         tmp1(:, i) = self%a(i)*self%c3(:, i)
      end do
      call gemm(tmp1, self%c2, tmp2)
      tmp3 = (-0.15915494309189535_wp)*tmp2
      tmp4 = self%c2 + tmp3
      tmp5 = self%c1*tmp4
      do i = 1, self%npt
         tmp6(:, i) = self%a(i)*self%c5(:, i)
      end do
      call gemm(tmp6, self%c6, tmp7, transb="t")
      tmp8 = 0.15915494309189535_wp*tmp7
      tmp9 = self%c5 + tmp8
      tmp10 = self%c4*tmp9
      a = tmp5 + tmp10
   end subroutine lpb_op2_assemble

   module subroutine lpb_op2_assemble_block(self, idx, a, error)
      !> Operator
      class(lpb_op2), intent(in) :: self
      !> Point indices
      integer, contiguous, intent(in) :: idx(:)
      !> Operator matrix of the points
      real(wp), contiguous, intent(out) :: a(:, :)
      !> Error handling
      type(error_type), allocatable, intent(out) :: error

      integer :: nb
      integer :: stat
      real(wp), allocatable :: tmp1(:)
      real(wp), allocatable :: tmp2(:, :), tmp3(:, :), tmp4(:, :), tmp5(:, :), tmp6(:, :), &
                               tmp7(:, :), tmp8(:, :), tmp9(:, :), tmp10(:, :), tmp11(:, :), &
                               tmp12(:, :), tmp13(:, :), tmp14(:, :), tmp15(:, :)
      integer :: i

      nb = size(idx)
      if (any(shape(a) /= [nb, nb])) then
         call fatal_error(error, "[lpb_op2_assemble_block] a: wrong shape")
         return
      end if
      allocate (tmp1(nb), stat=stat)
      if (stat == 0) allocate (tmp2(nb, nb), stat=stat)
      if (stat == 0) allocate (tmp3(nb, nb), stat=stat)
      if (stat == 0) allocate (tmp4(nb, nb), stat=stat)
      if (stat == 0) allocate (tmp5(nb, nb), stat=stat)
      if (stat == 0) allocate (tmp6(nb, nb), stat=stat)
      if (stat == 0) allocate (tmp7(nb, nb), stat=stat)
      if (stat == 0) allocate (tmp8(nb, nb), stat=stat)
      if (stat == 0) allocate (tmp9(nb, nb), stat=stat)
      if (stat == 0) allocate (tmp10(nb, nb), stat=stat)
      if (stat == 0) allocate (tmp11(nb, nb), stat=stat)
      if (stat == 0) allocate (tmp12(nb, nb), stat=stat)
      if (stat == 0) allocate (tmp13(nb, nb), stat=stat)
      if (stat == 0) allocate (tmp14(nb, nb), stat=stat)
      if (stat == 0) allocate (tmp15(nb, nb), stat=stat)
      if (stat /= 0) then
         call fatal_error(error, "[lpb_op2_assemble_block] allocation failed")
         return
      end if
      tmp1 = self%a(idx)
      tmp2 = self%c2(idx, idx)
      tmp3 = self%c3(idx, idx)
      tmp4 = self%c5(idx, idx)
      tmp5 = self%c6(idx, idx)
      do i = 1, nb
         tmp6(:, i) = tmp1(i)*tmp3(:, i)
      end do
      call gemm(tmp6, tmp2, tmp7)
      tmp8 = (-0.15915494309189535_wp)*tmp7
      tmp9 = tmp2 + tmp8
      tmp10 = self%c1*tmp9
      do i = 1, nb
         tmp11(:, i) = tmp1(i)*tmp4(:, i)
      end do
      call gemm(tmp11, tmp5, tmp12, transb="t")
      tmp13 = 0.15915494309189535_wp*tmp12
      tmp14 = tmp4 + tmp13
      tmp15 = self%c4*tmp14
      a = tmp10 + tmp15
   end subroutine lpb_op2_assemble_block

end submodule pcmgen_gauss_lpb_operators
