!> - Procedures of pcmgen_gauss_conductor: conductor_assemble, conductor_medium, conductor_solve
submodule(pcmgen_gauss_conductor) pcmgen_gauss_conductor_energy
   implicit none(type, external)

contains

   module subroutine conductor_assemble(state, r, xi, F, error, solver)
      !> State of conductor
      type(conductor_state), target, intent(inout) :: state
      !> Positions of the surface points
      real(wp), contiguous, intent(in) :: r(:, :)
      !> Gaussian widths of the surface charges (ISWIG: xi_Born/(R_I sqrt(w_i)))
      real(wp), contiguous, intent(in) :: xi(:)
      !> Switching function (1 where the grid is not switched)
      real(wp), contiguous, intent(in) :: F(:)
      !> Error handling
      type(error_type), allocatable, intent(out) :: error
      !> Linear solver
      class(pcm_solver), intent(in), optional :: solver

      integer :: npt
      integer :: stat
      real(wp) :: tmp121, tmp122, tmp123
      real(wp), allocatable :: tmp5(:)
      integer :: i, j

      if (present(solver)) then
         if (solver%matrix_free(size(r, 2), 1)) then
            call conductor_mf_assemble(state, r, xi, F, error, solver)
            return
         end if
      end if
      stat = 0
      npt = size(r, 2)
      if (npt < 1) then
         call fatal_error(error, "[conductor_assemble] empty discretization")
         return
      end if
      if (any(shape(r) /= [3, npt])) then
         call fatal_error(error, "[conductor_assemble] r: wrong shape")
         return
      end if
      if (any(shape(xi) /= [npt])) then
         call fatal_error(error, "[conductor_assemble] xi: wrong shape")
         return
      end if
      if (any(shape(F) /= [npt])) then
         call fatal_error(error, "[conductor_assemble] F: wrong shape")
         return
      end if
      state%ready = 0
      if (allocated(state%solver)) deallocate (state%solver)
      if (allocated(state%v)) deallocate (state%v)
      if (allocated(state%xi)) deallocate (state%xi)
      if (allocated(state%r)) deallocate (state%r)
      if (allocated(state%s2)) deallocate (state%s2)
      if (allocated(state%s3)) deallocate (state%s3)
      if (allocated(state%s4)) deallocate (state%s4)
      if (allocated(state%F)) deallocate (state%F)
      if (allocated(state%s5)) deallocate (state%s5)
      if (allocated(state%s6)) deallocate (state%s6)
      if (allocated(state%s8)) deallocate (state%s8)
      if (allocated(state%s9)) deallocate (state%s9)
      if (allocated(state%s10)) deallocate (state%s10)
      if (allocated(state%s11)) deallocate (state%s11)
      state%npt = npt
      if (present(solver)) then
         allocate (state%solver, source=solver, stat=stat)
      else
         allocate (pcm_dense_solver :: state%solver, stat=stat)
      end if
      if (stat == 0) allocate (state%v(npt), stat=stat)
      if (stat == 0) allocate (state%xi(npt), stat=stat)
      if (stat == 0) allocate (state%r(3, npt), stat=stat)
      if (stat == 0) allocate (state%s2(npt), stat=stat)
      if (stat == 0) allocate (state%s3(npt), stat=stat)
      if (stat == 0) allocate (state%s4(npt), stat=stat)
      if (stat == 0) allocate (state%F(npt), stat=stat)
      if (stat == 0) allocate (state%s5(npt, npt), stat=stat)
      if (stat == 0) allocate (state%s6(npt), stat=stat)
      if (stat == 0) allocate (state%s8(npt), stat=stat)
      if (stat == 0) allocate (state%s9(npt), stat=stat)
      if (stat == 0) allocate (state%s10(npt), stat=stat)
      if (stat == 0) allocate (state%s11(npt), stat=stat)
      if (stat /= 0) then
         call fatal_error(error, "[conductor_assemble] allocation failed")
         return
      end if
      state%s6 = 0.0_wp
      call state%solver%reset(conductor_n_operators)
      state%matrix_free = .false.

      state%xi = xi
      state%r = r
      state%F = F
      state%op1%npt = npt
      state%op1%npoint = npt
      state%op1%id = 1
      state%op1%points => state%r
      state%op1%symmetric = .true.
      state%op1%positive_definite = .true.
      block
         real(wp) :: tmp1, tmp2, tmp3, tmp4, tmp6, tmp7, tmp10, tmp14, tmp8, tmp9, tmp11, tmp12, &
                     tmp13, tmp15, tmp16, tmp17, tmp18, tmp19, tmp20, tmp21, tmp22, tmp23, tmp24, &
                     tmp25, tmp26, tmp27, tmp28, tmp29, tmp30, tmp31, tmp32, tmp33, tmp34, tmp35, &
                     tmp36, tmp37, tmp38, tmp39, tmp40, tmp41, tmp42, tmp43, tmp44, tmp45, tmp46, &
                     tmp47, tmp48, tmp49, tmp50, tmp51, tmp52, tmp53, tmp54, tmp55, tmp56, tmp57, &
                     tmp58, tmp59, tmp60, tmp61, tmp62, tmp63, tmp64, tmp65, tmp66, tmp67, tmp68, &
                     tmp69, tmp70, tmp71, tmp72, tmp73, tmp74, tmp75, tmp76, tmp77, tmp78, tmp79, &
                     tmp80, tmp81, tmp82, tmp83, tmp84, tmp85, tmp86, tmp87, tmp88, tmp89, tmp90, &
                     tmp91, tmp92, tmp93, tmp94, tmp95, tmp96, tmp97, tmp98, tmp99, tmp100, tmp101
         real(wp) :: tmp102, tmp103, tmp104, tmp105, tmp106, tmp107, tmp108, tmp109, tmp110, &
                     tmp111, tmp112, tmp113, tmp114, tmp115, tmp116, tmp117, tmp118, tmp119, &
                     tmp120

         !$omp parallel &
         !$omp& private(i, j, tmp5) &
         !$omp& shared(npt, state) &
         !$omp& default(private)
         allocate (tmp5(npt))
         !$omp do schedule(dynamic, 16)
         do j = 2, npt
            tmp1 = state%xi(j)
            tmp2 = state%r(1, j)
            tmp3 = state%r(2, j)
            tmp4 = state%r(3, j)
            tmp6 = tmp1**(2)
            tmp7 = -tmp2
            tmp10 = -tmp3
            tmp14 = -tmp4
            !$omp simd &
            !$omp& private(tmp8, tmp9, tmp11, tmp12, tmp13, tmp15, tmp16, tmp17) &
            !$omp& private(tmp18, tmp19, tmp20, tmp21, tmp22, tmp23, tmp24, tmp25) &
            !$omp& private(tmp26)
            do i = 1, j - 1
               tmp8 = state%r(1, i) + tmp7
               tmp9 = tmp8**(2)
               tmp11 = state%r(2, i) + tmp10
               tmp12 = tmp11**(2)
               tmp13 = tmp9 + tmp12
               tmp15 = state%r(3, i) + tmp14
               tmp16 = tmp15**(2)
               tmp17 = tmp13 + tmp16
               tmp18 = tmp6*tmp17
               tmp19 = state%xi(i)**(2)
               tmp20 = tmp18*tmp19
               tmp21 = tmp19 + tmp6
               tmp22 = (-81.0_wp)*tmp21
               tmp23 = tmp20 + tmp22
               tmp5(i) = tmp23
               tmp24 = 1.0_wp + (0.0_wp - 1.0_wp)*(0.5_wp + sign(0.5_wp, tmp23))
               tmp25 = tmp17 + tmp24
               tmp26 = 1.0_wp/sqrt(tmp25)
               state%s5(i, j) = tmp26
               state%s5(j, i) = tmp26
            end do
            do i = 1, j - 1
               if (tmp5(i) < 0.0_wp) then
                  tmp27 = state%xi(i)**(2)
                  tmp28 = tmp27 + tmp6
                  tmp29 = 0.25_wp*tmp28
                  tmp30 = state%r(1, i) + tmp7
                  tmp31 = tmp30**(2)
                  tmp32 = state%r(2, i) + tmp10
                  tmp33 = tmp32**(2)
                  tmp34 = tmp31 + tmp33
                  tmp35 = state%r(3, i) + tmp14
                  tmp36 = tmp35**(2)
                  tmp37 = tmp34 + tmp36
                  tmp38 = tmp6*tmp37
                  tmp39 = tmp38*tmp27
                  tmp40 = -tmp39
                  tmp41 = tmp29 + tmp40
                  if (tmp41 >= 0.0_wp) then
                     tmp44 = 1.0_wp/sqrt(tmp28)
                     tmp45 = tmp44*state%xi(i)
                     tmp46 = tmp44**(2)
                     tmp47 = tmp38*tmp46
                     tmp48 = tmp47*tmp27
                     tmp49 = 9.422759064650411e-11_wp*tmp48
                     tmp50 = (-1.2290555301717926e-09_wp) + tmp49
                     tmp51 = tmp50*tmp6
                     tmp52 = tmp51*tmp37
                     tmp53 = tmp52*tmp46
                     tmp54 = tmp53*tmp27
                     tmp55 = 1.4807192815879218e-08_wp + tmp54
                     tmp56 = tmp38*tmp55
                     tmp57 = tmp56*tmp46
                     tmp58 = tmp57*tmp27
                     tmp59 = (-1.6365844691234924e-07_wp) + tmp58
                     tmp60 = tmp48*tmp59
                     tmp61 = 1.6462114365889246e-06_wp + tmp60
                     tmp62 = tmp38*tmp61
                     tmp63 = tmp62*tmp46
                     tmp64 = tmp63*tmp27
                     tmp65 = (-1.492565035840625e-05_wp) + tmp64
                     tmp66 = tmp38*tmp65
                     tmp67 = tmp66*tmp46
                     tmp68 = tmp67*tmp27
                     tmp69 = 0.00012055332981789664_wp + tmp68
                     tmp70 = tmp47*tmp69
                     tmp71 = tmp70*tmp27
                     tmp72 = (-0.0008548327023450852_wp) + tmp71
                     tmp73 = tmp38*tmp72
                     tmp74 = tmp73*tmp46
                     tmp75 = tmp74*tmp27
                     tmp76 = 0.005223977625442188_wp + tmp75
                     tmp77 = tmp48*tmp76
                     tmp78 = (-0.026866170645131252_wp) + tmp77
                     tmp79 = tmp38*tmp78
                     tmp80 = tmp79*tmp46
                     tmp81 = tmp80*tmp27
                     tmp82 = 0.11283791670955126_wp + tmp81
                     tmp83 = tmp48*tmp82
                     tmp84 = (-0.37612638903183754_wp) + tmp83
                     tmp85 = tmp38*tmp84
                     tmp86 = tmp85*tmp46
                     tmp87 = tmp86*tmp27
                     tmp88 = 1.1283791670955126_wp + tmp87
                     tmp89 = tmp45*tmp88
                     tmp42 = tmp89*tmp1
                     tmp43 = tmp42
                  else
                     tmp90 = 1.0_wp/sqrt(tmp37)
                     tmp91 = 1.0_wp/sqrt(tmp28)
                     tmp92 = tmp91*state%xi(i)
                     tmp93 = sqrt(tmp37)
                     tmp94 = tmp92*tmp93
                     tmp95 = tmp94*tmp1
                     ! erf(x): Laikov (2026) Eq. (10)
                     tmp96 = min(max(tmp95, -27.0_wp), 27.0_wp)
                     tmp97 = tmp96*tmp96
                     tmp104 = -tmp97
                     tmp105 = min(max(tmp104, -709.09_wp), 709.0_wp)
                     tmp106 = tmp105*1.4426950408889634_wp
                     tmp106 = real(int(tmp106 + sign(0.5_wp, tmp106)), wp)
                     tmp105 = tmp105 - tmp106*0.6931471805598903_wp
                     tmp105 = tmp105 - tmp106*5.497923018708371e-14_wp
                     tmp107 = tmp105*tmp105
                     tmp108 = tmp107*tmp107
                     tmp109 = tmp108*tmp108
                     tmp112 = 1.0_wp + tmp105
                     tmp113 = 0.5000000000000001_wp + 0.16666666666666669_wp*tmp105
                     tmp112 = tmp112 + tmp107*tmp113
                     tmp113 = 0.041666666666624164_wp + 0.008333333333330065_wp*tmp105
                     tmp114 = 0.0013888888917196719_wp + 0.00019841269863040545_wp*tmp105
                     tmp113 = tmp113 + tmp107*tmp114
                     tmp112 = tmp112 + tmp108*tmp113
                     tmp113 = 2.4801521322368692e-05_wp + 2.7557268480310024e-06_wp*tmp105
                     tmp114 = 2.7620075879983367e-07_wp + 2.5100375832561234e-08_wp*tmp105
                     tmp113 = tmp113 + tmp107*tmp114
                     tmp110 = tmp112 + tmp109*tmp113
                     tmp111 = tmp110*transfer(ishft(int(int(tmp106), int64) + 1023_int64, 52), &
                                              1.0_wp)
                     tmp111 = tmp111 + (tmp95 - tmp95)
                     tmp98 = tmp97*tmp97
                     tmp99 = tmp98*tmp98
                     tmp100 = tmp99*tmp99
                     tmp115 = 0.6168502750680849_wp + 0.6779639980363701_wp*tmp97
                     tmp116 = 0.3553712533710437_wp + 0.1172490624654413_wp*tmp97
                     tmp115 = tmp115 + tmp98*tmp116
                     tmp116 = 0.02711246243412699_wp + 0.004646627179193606_wp*tmp97
                     tmp117 = 0.0006112629461186801_wp + 6.311361332797385e-05_wp*tmp97
                     tmp116 = tmp116 + tmp98*tmp117
                     tmp115 = tmp115 + tmp99*tmp116
                     tmp116 = 5.1324815918880575e-06_wp + 3.2134117178934646e-07_wp*tmp97
                     tmp117 = 1.525137867566814e-08_wp + 5.488629374567074e-10_wp*tmp97
                     tmp116 = tmp116 + tmp98*tmp117
                     tmp101 = tmp115 + tmp100*tmp116
                     tmp118 = 1.0_wp + 0.31221959210397726_wp*tmp97
                     tmp119 = 0.12212905451906655_wp + 0.022924009252132765_wp*tmp97
                     tmp118 = tmp118 + tmp98*tmp119
                     tmp119 = 0.004276684363418426_wp + 0.000515222367885319_wp*tmp97
                     tmp120 = 5.394727095325834e-05_wp + 4.261018300827443e-06_wp*tmp97
                     tmp119 = tmp119 + tmp98*tmp120
                     tmp118 = tmp118 + tmp99*tmp119
                     tmp119 = 2.6426511286051213e-07_wp + 1.2407855437294409e-08_wp*tmp97
                     tmp119 = tmp119 + tmp98*4.3107594303542656e-10_wp
                     tmp102 = tmp118 + tmp100*tmp119
                     tmp103 = tmp96/sqrt(tmp97 + sqrt(tmp101/tmp102)*tmp111)
                     tmp103 = tmp103 + (tmp95 - tmp95)
                     tmp42 = tmp90*tmp103
                     tmp43 = tmp42
                  end if
                  state%s5(i, j) = tmp42
                  state%s5(j, i) = tmp43
               end if
            end do
         end do
         !$omp end do
         deallocate (tmp5)
         !$omp end parallel
      end block
      do i = 1, npt
         tmp121 = 1.0_wp/state%F(i)
         tmp122 = state%xi(i)*tmp121
         tmp123 = 0.7978845608028654_wp*tmp122
         state%s5(i, i) = tmp123
      end do
      state%op1%c1 => state%s5
      call state%solver%setup(state%op1, error)
      if (allocated(error)) return
      state%s2 = state%r(1, :)
      state%s3 = state%r(2, :)
      state%s4 = state%r(3, :)

      state%ready = 1
      state%assembled = state%assembled + 1
   end subroutine conductor_assemble

   module subroutine conductor_medium(state, feps, error)
      !> State of conductor
      type(conductor_state), target, intent(inout) :: state
      !> Dielectric factor of a conductor-like model, e.g. (eps - 1)/eps
      real(wp), intent(in) :: feps
      !> Error handling
      type(error_type), allocatable, intent(out) :: error

      integer :: npt
      integer :: stat

      if (state%matrix_free) then
         call conductor_mf_medium(state, feps, error)
         return
      end if
      stat = 0
      npt = state%npt
      if (state%ready < 1) then
         call fatal_error(error, "[conductor_medium] call conductor_assemble first")
         return
      end if
      state%ready = 1

      state%op1%points => state%r
      state%op1%c1 => state%s5
      state%feps = feps
      state%s1 = -state%feps

      state%ready = 2
   end subroutine conductor_medium

   module subroutine conductor_solve(state, v, energy, q, grad_v, error)
      !> State of conductor
      type(conductor_state), target, intent(inout) :: state
      !> Solute electrostatic potential at the surface points
      real(wp), contiguous, intent(in) :: v(:)
      !> Solvation energy
      real(wp), intent(out) :: energy
      !> Apparent surface charges
      real(wp), contiguous, intent(out) :: q(:)
      !> Partial derivative of the energy with respect to v
      real(wp), contiguous, intent(out) :: grad_v(:)
      !> Error handling
      type(error_type), allocatable, intent(out) :: error

      integer :: npt
      integer :: stat
      real(wp), allocatable :: tmp3(:), tmp4(:), tmp5(:), tmp6(:)
      real(wp) :: tmp1, tmp2, tmp7

      if (state%matrix_free) then
         call conductor_mf_solve(state, v, energy, q, grad_v, error)
         return
      end if
      stat = 0
      npt = state%npt
      if (state%ready < 2) then
         call fatal_error(error, "[conductor_solve] call conductor_medium first")
         return
      end if
      if (any(shape(v) /= [npt])) then
         call fatal_error(error, "[conductor_solve] v: wrong shape")
         return
      end if
      if (any(shape(q) /= [npt])) then
         call fatal_error(error, "[conductor_solve] q: wrong shape")
         return
      end if
      if (any(shape(grad_v) /= [npt])) then
         call fatal_error(error, "[conductor_solve] grad_v: wrong shape")
         return
      end if
      allocate (tmp3(npt), stat=stat)
      if (stat == 0) allocate (tmp4(npt), stat=stat)
      if (stat == 0) allocate (tmp5(npt), stat=stat)
      if (stat == 0) allocate (tmp6(npt), stat=stat)
      if (stat /= 0) then
         call fatal_error(error, "[conductor_solve] allocation failed")
         return
      end if
      state%ready = 2

      state%op1%points => state%r
      state%op1%c1 => state%s5
      state%v = v
      call state%solver%solve(state%op1, .false., state%v, state%s6, error)
      if (allocated(error)) return
      q = state%s1*state%s6
      tmp1 = dot(state%v, q)
      energy = 0.5_wp*tmp1
      grad_v = q
      if (state%solver%inexact()) then
         ! First-order correction for the residuals of the solves
         tmp2 = (-0.5_wp)*state%feps
         tmp3 = tmp2*state%s6
         call gemv(state%s5, state%s6, tmp4)
         tmp5 = -tmp4
         tmp6 = state%v + tmp5
         tmp7 = dot(tmp3, tmp6)
         energy = energy + tmp7
      end if

      state%ready = 3
   end subroutine conductor_solve

end submodule pcmgen_gauss_conductor_energy
