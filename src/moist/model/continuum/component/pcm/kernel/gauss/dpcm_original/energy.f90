   module subroutine dpcm_original_medium(state, eps, error)
      !> State of dpcm_original
      type(dpcm_original_state), target, intent(inout) :: state
      !> Relative permittivity of the solvent (inf for a conductor)
      real(wp), intent(in) :: eps
      !> Error handling
      type(error_type), allocatable, intent(out) :: error

      integer :: npt
      integer :: stat
      real(wp) :: tmp1, tmp2

      if (state%matrix_free) then
         call dpcm_original_mf_medium(state, eps, error)
         return
      end if
      stat = 0
      npt = state%npt
      if (state%ready < 1) then
         call fatal_error(error, "[dpcm_original_medium] call dpcm_original_assemble first")
         return
      end if
      state%ready = 1
      ! Inputs that do not enter these outputs
      associate (unused1 => eps)
      end associate

      state%op1%npt = npt
      state%op1%npoint = npt
      state%op1%id = 1
      state%op1%points => state%r
      state%op1%c1 => state%s3
      state%s1 = eps + 1.0_wp
      tmp1 = 1.0_wp/state%s1
      tmp2 = (-2.0_wp)*tmp1
      state%s2 = 1.0_wp + tmp2
      state%s4 = -state%s2
      state%op1%c2 = state%s4
      state%op1%c3 => state%s11
      call state%solver%setup(state%op1, error)
      if (allocated(error)) return
      state%s13 = 0.5_wp*state%s2

      state%ready = 2
   end subroutine dpcm_original_medium

