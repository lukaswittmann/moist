      if (stat == 0) allocate (tmp38(npt), stat=stat)
      if (stat == 0) allocate (tmp40(npt), stat=stat)
      if (stat == 0) allocate (tmp51(npt), stat=stat)
      if (stat == 0) allocate (tmp52(npt), stat=stat)
      if (stat /= 0) then
         call fatal_error(error, "[slic_solve] allocation failed")
         return
      end if
      state%ready = 2

      state%op1%npt = npt
      state%op1%npoint = npt
      state%op1%id = 1
      state%op1%points => state%r
      state%op1%a => state%a
      nl1%npt = npt
      nl1%solver => state%solver
      nl1%r => state%r
      nl1%a => state%a
      nl1%vn => vn
      nl1%alpha = state%alpha
      nl1%beta = state%beta
      nl1%mu = state%mu
      nl1%c1 => state%s7
      nl1%c2 = state%s8
      nl1%c3 = state%s10
      nl1%c4 = state%s11
      call nl1%solve(state%s12, error)
      if (allocated(error)) return
      state%s13 = state%a*state%s12
      call gemv(state%s7, state%s13, tmp1, trans="t")
      state%s14 = vn + tmp1
      tmp2 = 6.283185307179586_wp*state%s12
      tmp3 = state%s14 + tmp2
      state%s15 = -tmp3
      do i = 1, npt
         tmp4 = state%s15(i)*state%beta
         tmp5 = tmp4 + state%s8
         tmp6 = tanh(tmp5)
         tmp7 = tmp6**(2)
         tmp8 = -tmp7
         tmp9 = 1.0_wp + tmp8
         tmp10 = tmp9*state%s10
         tmp11 = tmp10*state%alpha
         tmp12 = tmp11*state%beta
         tmp13 = tmp12*state%s12(i)
         tmp14 = (-12.566370614359172_wp)*tmp13
         state%s16(i) = tmp14
      end do
      state%op1%c1 => state%s16
      state%op1%c2 => state%s7
      do i = 1, npt
         tmp15 = state%s15(i)*state%beta
         tmp16 = tmp15 + state%s8
         tmp17 = tanh(tmp16)
         tmp18 = state%alpha*tmp17
         tmp19 = tmp18 + state%mu
         tmp20 = state%s10*tmp19
         tmp21 = (-2.0_wp)*tmp20
         tmp22 = 1.0_wp + tmp21
         tmp23 = 6.283185307179586_wp*tmp22
         state%s17(i) = tmp23
      end do
      state%op1%c3 => state%s17
      state%op1%c4 = state%s11
      call state%solver%setup(state%op1, error)
      if (allocated(error)) return
      state%s18 = 0.5_wp*v
      tmp24 = state%s18*state%a
      call state%solver%solve(state%op1, .true., tmp24, state%s19, error)
      if (allocated(error)) return
      do i = 1, npt
         tmp25 = state%s12(i)*state%s10
         tmp26 = tmp25*state%alpha
         tmp27 = tmp26*state%beta
         tmp28 = state%s15(i)*state%beta
         tmp29 = tmp28 + state%s8
         tmp30 = tanh(tmp29)
         tmp31 = tmp30**(2)
         tmp32 = -tmp31
         tmp33 = 1.0_wp + tmp32
         tmp34 = tmp27*tmp33
         tmp35 = (-12.566370614359172_wp)*tmp34
         state%s20(i) = tmp35
      end do
      tmp36 = state%s11*state%s19
      tmp37 = state%s19*state%s20
      tmp38 = -tmp37
      state%s21 = tmp36 + tmp38
      state%s22 = -state%s21
      tmp39 = dot(v, state%s13)
      energy = 0.5_wp*tmp39
      q = state%s13
      grad_v = 0.5_wp*state%s13
      grad_vn = state%s22
      if (state%solver%inexact()) then
         ! First-order correction for the residuals of the solves
         do i = 1, npt
            tmp41 = state%s15(i)*state%beta
            tmp42 = tmp41 + state%s8
            tmp43 = tanh(tmp42)
            tmp44 = state%alpha*tmp43
            tmp45 = tmp44 + state%mu
            tmp46 = state%s10*tmp45
            tmp47 = (-2.0_wp)*tmp46
            tmp48 = 1.0_wp + tmp47
            tmp49 = tmp48*state%s12(i)
            tmp50 = 6.283185307179586_wp*tmp49
            tmp40(i) = tmp50
         end do
         tmp51 = state%s11*state%s14
         tmp52 = tmp40 + tmp51
         tmp53 = dot(state%s19, tmp52)
         tmp54 = -tmp53
         energy = energy + tmp54
      end if

      state%ready = 3
   end subroutine slic_solve

