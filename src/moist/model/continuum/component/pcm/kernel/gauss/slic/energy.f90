   module subroutine slic_medium(state, eps, alpha, beta, gamma, mu, error)
      !> State of slic
      type(slic_state), target, intent(inout) :: state
      !> Relative permittivity of the solvent (inf for a conductor)
      real(wp), intent(in) :: eps
      !> SLIC amplitude of the solvation-layer perturbation h
      real(wp), intent(in) :: alpha
      !> SLIC steepness of h in the normal field (inverse field units)
      real(wp), intent(in) :: beta
      !> SLIC offset of the transition of h
      real(wp), intent(in) :: gamma
      !> SLIC shift of h
      real(wp), intent(in) :: mu
      !> Error handling
      type(error_type), allocatable, intent(out) :: error

      integer :: npt
      integer :: stat
      real(wp) :: tmp1, tmp2

      if (state%matrix_free) then
         call slic_mf_medium(state, eps, alpha, beta, gamma, mu, error)
         return
      end if
      stat = 0
      npt = state%npt
      if (state%ready < 1) then
         call fatal_error(error, "[slic_medium] call slic_assemble first")
         return
      end if
      state%s12 = 0.0_wp
      state%ready = 1
      ! Inputs that do not enter these outputs
      associate (unused1 => eps, unused2 => gamma)
      end associate

      state%beta = beta
      state%alpha = alpha
      state%mu = mu
      state%s8 = -gamma
      state%s9 = eps + 1.0_wp
      tmp1 = 1.0_wp/state%s9
      tmp2 = (-2.0_wp)*tmp1
      state%s10 = 1.0_wp + tmp2
      state%s11 = -state%s10
      state%s27 = state%beta**(2)

      state%ready = 2
   end subroutine slic_medium

