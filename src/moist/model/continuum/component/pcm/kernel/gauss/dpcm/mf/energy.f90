                     tmp63 = tmp123*tmp157
                  end if
                  tmp158 = state%s11(i)*tmp63
                  tmp9 = tmp9 + tmp158
               end if
            end do
            tmp2(j) = tmp2(j) + tmp9
         end do
         !$omp end do
         deallocate (tmp8)
         !$omp end parallel
      end block
      state%s15 = tmp2
      q = state%s2*state%s11
      tmp159 = dot(state%v, q)
      energy = 0.5_wp*tmp159
      grad_v = state%s12*state%s11
      grad_vn = state%s14*state%a
      if (state%solver%inexact()) then
         ! First-order correction for the residuals of the solves
         tmp160 = 6.283185307179586_wp*state%s11
         tmp161 = state%a*state%s15
         tmp162 = state%s3*tmp161
         tmp163 = tmp160 + tmp162
         tmp164 = -tmp163
         tmp165 = tmp1 + tmp164
         tmp166 = dot(state%s14, tmp165)
         energy = energy + tmp166
      end if

      state%ready = 3
   end subroutine dpcm_mf_solve

