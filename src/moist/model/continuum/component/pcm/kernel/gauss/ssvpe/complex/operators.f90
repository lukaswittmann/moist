!> - Procedures of pcmgen_gauss_ssvpe: ssvpe_op3_apply, ssvpe_op3_assemble, ssvpe_op3_assemble_block
submodule(pcmgen_gauss_ssvpe) pcmgen_gauss_ssvpe_complex_operators
   implicit none(type, external)

contains

   module subroutine ssvpe_op3_apply(self, trans, x, y)
      !> Operator
      class(ssvpe_op3), intent(in) :: self
      !> Apply the transpose
      logical, intent(in) :: trans
      !> Input vector
      complex(wp), contiguous, intent(in) :: x(:)
      !> Result vector
      complex(wp), contiguous, intent(out) :: y(:)

      ! The transpose is the operator itself
      associate (unused1 => trans)
      end associate
      block
         real(wp), allocatable :: tmp2(:), tmp3(:), tmp6(:), tmp7(:), tmp9(:), tmp10(:), tmp13(:), &
                                  tmp14(:)
         complex(wp), allocatable :: tmp1(:), tmp4(:), tmp5(:), tmp8(:), tmp11(:), tmp12(:), &
                                     tmp15(:), tmp16(:)

         allocate (tmp1(self%npt))
         allocate (tmp2(self%npt))
         allocate (tmp3(self%npt))
         allocate (tmp4(self%npt))
         allocate (tmp5(self%npt))
         allocate (tmp6(self%npt))
         allocate (tmp7(self%npt))
         allocate (tmp8(self%npt))
         allocate (tmp9(self%npt))
         allocate (tmp10(self%npt))
         allocate (tmp11(self%npt))
         allocate (tmp12(self%npt))
         allocate (tmp13(self%npt))
         allocate (tmp14(self%npt))
         allocate (tmp15(self%npt))
         allocate (tmp16(self%npt))
         call gemv(self%c1, real(x, wp), tmp2)
         call gemv(self%c1, aimag(x), tmp3)
         tmp1 = cmplx(tmp2, tmp3, wp)
         tmp4 = self%a*tmp1
         call gemv(self%c3, real(tmp4, wp), tmp6)
         call gemv(self%c3, aimag(tmp4), tmp7)
         tmp5 = cmplx(tmp6, tmp7, wp)
         call gemv(self%c3, real(x, wp), tmp9, trans="t")
         call gemv(self%c3, aimag(x), tmp10, trans="t")
         tmp8 = cmplx(tmp9, tmp10, wp)
         tmp11 = self%a*tmp8
         call gemv(self%c1, real(tmp11, wp), tmp13, trans="t")
         call gemv(self%c1, aimag(tmp11), tmp14, trans="t")
         tmp12 = cmplx(tmp13, tmp14, wp)
         tmp15 = tmp5 + tmp12
         tmp16 = self%c2*tmp15
         y = tmp1 + tmp16
      end block
   end subroutine ssvpe_op3_apply

   module subroutine ssvpe_op3_assemble(self, a, error)
      !> Operator
      class(ssvpe_op3), intent(in) :: self
      !> Dense operator matrix
      complex(wp), contiguous, intent(out) :: a(:, :)
      !> Error handling
      type(error_type), allocatable, intent(out) :: error

      integer :: stat
      real(wp), allocatable :: tmp1(:, :), tmp2(:, :), tmp3(:, :), tmp4(:, :)
      complex(wp), allocatable :: tmp5(:, :)
      integer :: i

      allocate (tmp1(self%npt, self%npt), stat=stat)
      if (stat == 0) allocate (tmp2(self%npt, self%npt), stat=stat)
      if (stat == 0) allocate (tmp3(self%npt, self%npt), stat=stat)
      if (stat == 0) allocate (tmp4(self%npt, self%npt), stat=stat)
      if (stat == 0) allocate (tmp5(self%npt, self%npt), stat=stat)
      if (stat /= 0) then
         call fatal_error(error, "[ssvpe_op3_assemble] allocation failed")
         return
      end if
      do i = 1, self%npt
         tmp1(:, i) = self%a(i)*self%c3(:, i)
      end do
      call gemm(tmp1, self%c1, tmp2)
      tmp3 = transpose(tmp2)
      tmp4 = tmp2 + tmp3
      tmp5 = self%c2*tmp4
      a = self%c1 + tmp5
   end subroutine ssvpe_op3_assemble

   module subroutine ssvpe_op3_assemble_block(self, idx, a, error)
      !> Operator
      class(ssvpe_op3), intent(in) :: self
      !> Point indices
      integer, contiguous, intent(in) :: idx(:)
      !> Operator matrix of the points
      complex(wp), contiguous, intent(out) :: a(:, :)
      !> Error handling
      type(error_type), allocatable, intent(out) :: error

      integer :: nb
      integer :: stat
      real(wp), allocatable :: tmp1(:)
      real(wp), allocatable :: tmp2(:, :), tmp3(:, :), tmp4(:, :), tmp5(:, :), tmp6(:, :), &
                               tmp7(:, :)
      complex(wp), allocatable :: tmp8(:, :)
      integer :: i

      nb = size(idx)
      if (any(shape(a) /= [nb, nb])) then
         call fatal_error(error, "[ssvpe_op3_assemble_block] a: wrong shape")
         return
      end if
      allocate (tmp1(nb), stat=stat)
      if (stat == 0) allocate (tmp2(nb, nb), stat=stat)
      if (stat == 0) allocate (tmp3(nb, nb), stat=stat)
      if (stat == 0) allocate (tmp4(nb, nb), stat=stat)
      if (stat == 0) allocate (tmp5(nb, nb), stat=stat)
      if (stat == 0) allocate (tmp6(nb, nb), stat=stat)
      if (stat == 0) allocate (tmp7(nb, nb), stat=stat)
      if (stat == 0) allocate (tmp8(nb, nb), stat=stat)
      if (stat /= 0) then
         call fatal_error(error, "[ssvpe_op3_assemble_block] allocation failed")
         return
      end if
      tmp1 = self%a(idx)
      tmp2 = self%c1(idx, idx)
      tmp3 = self%c3(idx, idx)
      do i = 1, nb
         tmp4(:, i) = tmp1(i)*tmp3(:, i)
      end do
      call gemm(tmp4, tmp2, tmp5)
      tmp6 = transpose(tmp5)
      tmp7 = tmp5 + tmp6
      tmp8 = self%c2*tmp7
      a = tmp2 + tmp8
   end subroutine ssvpe_op3_assemble_block

end submodule pcmgen_gauss_ssvpe_complex_operators
